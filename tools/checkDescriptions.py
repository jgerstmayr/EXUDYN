import argparse
import datetime
import hashlib
import io
import json
import os
import re
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
recordFile = os.path.join(root, 'definitions', 'descriptionChecks.json')
kinds = ['nodes', 'objects', 'markers', 'loads', 'sensors']
implementationFolder = {'nodes': 'ImplNodes', 'objects': 'ImplObjects', 'markers': 'ImplMarkers', 'loads': None,
                        'sensors': None}


def Items():
    """[(name, kind)] of every item, from the generated headers"""
    found = []
    for kind in kinds:
        folder = os.path.join(root, 'src', 'Autogenerated', kind)
        for fileName in sorted(os.listdir(folder)):
            if fileName.startswith('C') and fileName.endswith('.h'):
                found.append((fileName[1:-2], kind))
    return found


def WithoutComments(text):
    """C++ without comments and with one blank between tokens; strings are kept"""
    result = []
    i = 0
    while i < len(text):
        if text.startswith('//', i):
            end = text.find('\n', i)
            i = len(text) if end < 0 else end
        elif text.startswith('/*', i):
            end = text.find('*/', i + 2)
            i = len(text) if end < 0 else end + 2
        elif text[i] == '"':
            match = re.compile(r'"(?:[^"\\\n]|\\.)*"').match(text, i)
            end = match.end() if match else i + 1
            result.append(text[i:end])
            i = end
        else:
            result.append(text[i])
            i += 1
    return ' '.join(''.join(result).split())


def SharedSources():
    """the hand-written sources in which several items are implemented: (path, text without comments)"""
    sources = []
    for folder in ['System', 'Main', 'Graphics']:
        directory = os.path.join(root, 'src', folder)
        for fileName in sorted(os.listdir(directory)):
            if fileName.endswith('.cpp'):
                with io.open(os.path.join(directory, fileName), encoding='utf-8', errors='replace') as file:
                    sources.append(WithoutComments(file.read()))
    return sources


def MemberDefinitions(text, className):
    """the definitions of the member functions of className (and of its Visualization class) in text"""
    def Matching(i, opening, closing):
        """the index of the bracket that closes the one at i"""
        depth = 0
        while i < len(text):
            if text[i] == opening:
                depth += 1
            elif text[i] == closing:
                depth -= 1
                if depth == 0:
                    return i
            i += 1
        return len(text) - 1

    found = []
    for match in re.finditer(r'(?<![A-Za-z0-9_])(?:Visualization)?' + re.escape(className) + r'::[A-Za-z_~][A-Za-z0-9_]*\s*\(', text):
        endArguments = Matching(match.end() - 1, '(', ')')
        after = re.match(r'\s*(const\s*)?(override\s*)?(:[^{;]*)?\{', text[endArguments + 1:])
        if after is None: #a call or a declaration, not a definition
            continue
        start = max(text.rfind(';', 0, match.start()), text.rfind('}', 0, match.start())) + 1
        end = Matching(endArguments + after.end(), '{', '}')
        definition = text[start:end + 1].strip()
        definition = re.sub(r'^(\s*#\s*\w+\s*(<[^>]*>|"[^"]*"|\S+))+', '', definition).strip() #no preprocessor line before it
        found.append(definition)
    return found


def Fingerprint(name, kind, sharedSources=None):
    """the fingerprint of the implementation of item name: 12 hexadecimal digits"""
    className = 'C' + name
    parts = []
    with io.open(os.path.join(root, 'src', 'Autogenerated', kind, className + '.h'), encoding='utf-8', errors='replace') as file:
        parts.append(WithoutComments(file.read()))
    folder = implementationFolder[kind]
    source = os.path.join(root, 'src', folder, className + '.cpp') if folder else None
    if source and os.path.isfile(source):
        with io.open(source, encoding='utf-8', errors='replace') as file:
            parts.append(WithoutComments(file.read()))
    #and its functions elsewhere: the loads and sensors, and e.g. the user function calls in evaluateUserFunctions.cpp
    for text in (sharedSources if sharedSources is not None else SharedSources()):
        parts += MemberDefinitions(text, className)
    return hashlib.sha256('\n'.join(parts).encode('utf-8')).hexdigest()[:12]


def ReadRecords():
    if not os.path.isfile(recordFile):
        return {}
    return json.load(io.open(recordFile, encoding='utf-8'))['items']


def WriteRecords(records):
    data = {'generatedBy': 'tools/checkDescriptions.py --mark - do not edit by hand (#2717)',
            'items': {name: records[name] for name in sorted(records)}}
    io.open(recordFile, 'w', encoding='utf-8', newline='\n').write(json.dumps(data, indent=1) + '\n')


def Main(argv=None):
    parser = argparse.ArgumentParser(description='the descriptions of the items, checked against their implementation (#2717)')
    parser.add_argument('--check', action='store_true', help='exit 1 if the implementation of a checked item changed')
    parser.add_argument('--mark', nargs='+', default=[], metavar='ITEM', help='record that these items were checked')
    parser.add_argument('--mark-kind', nargs='+', default=[], dest='markKind', choices=kinds,
                        help='record that every item of these kinds was checked')
    parser.add_argument('--by', default='Claude-JG', help='who checked (default Claude-JG)')
    args = parser.parse_args(argv)

    items = Items()
    known = dict(items)
    shared = SharedSources()
    records = ReadRecords()

    toMark = list(args.mark) + [name for (name, kind) in items if kind in args.markKind]
    if toMark:
        for name in toMark:
            if name not in known:
                print('checkDescriptions: no item ' + name)
                return 1
            records[name] = {'checked': datetime.date.today().isoformat(), 'by': args.by,
                             'fingerprint': Fingerprint(name, known[name], shared)}
        WriteRecords(records)
        print('checkDescriptions: recorded ' + str(len(toMark)) + ' item(s) as checked against their implementation')
        return 0

    changed = []
    counts = {kind: [0, 0] for kind in kinds} #checked, all
    for (name, kind) in items:
        counts[kind][1] += 1
        if name in records:
            counts[kind][0] += 1
            fingerprint = Fingerprint(name, kind, shared)
            if fingerprint != records[name]['fingerprint']:
                changed.append((name, records[name], fingerprint))
    if not args.check:
        for kind in kinds:
            print('%-8s %3d of %3d checked' % (kind, counts[kind][0], counts[kind][1]))
    for (name, record, fingerprint) in changed:
        print('checkDescriptions: the implementation of ' + name + ' changed since its description was checked ('
              + record['checked'] + ', ' + record['by'] + '): fingerprint ' + record['fingerprint'] + ' -> '
              + fingerprint + '; look at the description again, then: python tools/checkDescriptions.py --mark ' + name)
    unknown = [name for name in records if name not in known]
    for name in unknown:
        print('checkDescriptions: ' + name + ' is recorded, but there is no such item')
    if args.check:
        print('checkDescriptions: ' + str(len(records)) + ' checked item(s), ' + str(len(changed)) + ' changed since')
    return 1 if args.check and (changed or unknown) else 0


if __name__ == '__main__':
    sys.exit(Main())
