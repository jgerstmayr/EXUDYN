# This is an EXUDYN tool
#
# Details:  Each item description, checked once against its implementation, and the record of what it
#           was checked against (#2717). A description in definitions/itemDefs*.py says what an item does;
#           the C++ does it. When someone has read both and made them agree, this tool records it in
#           definitions/descriptionChecks.json: who, when, and a fingerprint of the implementation as it
#           was then. When the implementation changes afterwards, the fingerprint no longer matches and
#           --check names the item, with the old and the new fingerprint - the description has to be
#           looked at again, and --mark records the new state. Nobody edits a fingerprint by hand.
#
#           The implementation of an item C<Name> is
#           - its hand-written source src/Impl<Kind>s/C<Name>.cpp, if it has one, and every function
#             definition C<Name>::... and VisualizationC<Name>::... in src/System, src/Main and
#             src/Graphics - the loads in CLoad.cpp, the sensors in CSensor.cpp, the calls of the user
#             functions in evaluateUserFunctions.cpp;
#           - its generated header src/Autogenerated/<kind>s/C<Name>.h without its comments, which are
#             the descriptions themselves: a change of a description does not change the fingerprint,
#             a change of a parameter, a declaration or generated code does.
#           Comments and white space of the sources do not count either.
#
# Usage:    python tools/checkDescriptions.py                     the state of every item
#           python tools/checkDescriptions.py --check             exit 1 if a checked item changed since
#           python tools/checkDescriptions.py --mark NodePoint ... record the check of these items, now
#           python tools/checkDescriptions.py --mark-kind nodes   record the check of every node
#
