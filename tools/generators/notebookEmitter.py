# This is an EXUDYN maintainer tool
#
# Details:  Emits, from each notebook of python/Notebooks/, the two views of it (#2831):
#           - the page of the documentation, docs/generated/notebooks/<name>.md: the Markdown cells as
#             they are, the code cells as Python blocks, and the outputs the notebook stores - text, and
#             images in docs/generated/notebooks/images/;
#           - the example script, python/Examples/<name>.py: the code cells, the Markdown cells as
#             comments, so that a notebook is also an example that runTestExamples.py runs.
#           A code cell tagged 'remove-cell' (Jupyter's cell tags) runs but is not shown on the page, and
#           one tagged 'remove-input' shows only its output: the setup a snippet needs, without showing it.
#           The notebook is the one place a tutorial is written; its outputs are stored by
#           tools/runNotebooks.py, so this emitter only converts and its output is the same on every run.
#
# Usage:    python tools/generators/notebookEmitter.py
#
# Author:   Johannes Gerstmayr
