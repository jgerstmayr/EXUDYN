import base64
import glob
import io
import json
import os
import re
import sys

toolsDirectory = os.path.dirname(os.path.abspath(__file__))
repositoryRoot = os.path.dirname(os.path.dirname(toolsDirectory))
notebookDirectory = 'python/Notebooks'
pageDirectory = 'docs/generated/notebooks'
scriptDirectory = 'python/Examples'


def Source(cell):
    return ''.join(cell['source']) if isinstance(cell['source'], list) else cell['source']


def Text(value):
    return ''.join(value) if isinstance(value, list) else value


def Notebooks():
    return sorted(glob.glob(os.path.join(repositoryRoot, notebookDirectory, '*.ipynb')))


def Write(path, content, binary=False):
    """write only what changed, so that an unchanged notebook leaves its outputs untouched"""
    full = os.path.join(repositoryRoot, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    old = None
    if os.path.exists(full):
        old = open(full, 'rb' if binary else 'r', **({} if binary else {'encoding': 'utf-8', 'newline': ''})).read()
    if old != content:
        with open(full, 'wb' if binary else 'w', **({} if binary else {'encoding': 'utf-8', 'newline': '\n'})) as file:
            file.write(content)


def Page(name, notebook):
    """the Markdown page of a notebook, and the images it refers to as {file name: bytes}"""
    origin = notebookDirectory + '/' + name + '.ipynb'
    lines = ['<!-- GENERATED by tools/generators/notebookEmitter.py from ' + origin + ' - do not edit -->',
             '(notebook-' + name.lower() + ')=']
    images = {}
    first = True
    for cell in notebook['cells']:
        source = Source(cell).rstrip()
        if cell['cell_type'] == 'markdown':
            lines += [source, '']
            if first:   #below the title: where the notebook is
                lines += ['*This page is the notebook `' + origin + '`; the same code is the example `'
                          + scriptDirectory + '/' + name + '.py`.*', '']
            first = False
            continue
        if cell['cell_type'] != 'code' or source == '':
            continue
        tags = cell.get('metadata', {}).get('tags', [])
        if 'remove-cell' in tags:   #code the reader needs not see: it runs, its output is not shown either
            continue
        if 'remove-input' not in tags:
            lines += ['```python', source, '```', '']
        for output in cell.get('outputs', []):
            if output['output_type'] == 'stream':
                lines += ['```text', Text(output['text']).rstrip(), '```', '']
            elif output['output_type'] in ['execute_result', 'display_data']:
                data = output.get('data', {})
                if 'image/png' in data:
                    imageName = name + '_' + str(len(images)) + '.png'
                    images[imageName] = base64.b64decode(Text(data['image/png']))
                    lines += ['![](images/' + imageName + ')', '']
                elif 'text/plain' in data:
                    lines += ['```text', Text(data['text/plain']).rstrip(), '```', '']
            elif output['output_type'] == 'error':
                lines += ['```text', output['ename'] + ': ' + output['evalue'], '```', '']
    return ('\n'.join(lines).rstrip() + '\n', images)


def Script(name, notebook):
    """the example script of a notebook: its code, its text as comments"""
    origin = notebookDirectory + '/' + name + '.ipynb'
    cells = notebook['cells']
    title = ''
    details = ''
    if cells and cells[0]['cell_type'] == 'markdown':
        text = Source(cells[0]).strip().split('\n')
        title = text[0].lstrip('#').strip()
        details = ' '.join(line.strip() for line in text[1:] if line.strip() != '')
    #the details in lines of about 100 characters, as the headers of the examples are
    words = (title + ': ' + details).split()
    detailLines = ['']
    for word in words:
        if len(detailLines[-1]) + len(word) > 100:
            detailLines.append('')
        detailLines[-1] += ('' if detailLines[-1] == '' else ' ') + word
    out = ['#generated by tools/generators/notebookEmitter.py from ' + origin + ' - edit the notebook, not this file',
           '#' + '+'*77, '# This is an EXUDYN example', '#',
           '# Details:  ' + detailLines[0]] + ['#           ' + line for line in detailLines[1:]] + [
           '#', '# Author:   Johannes Gerstmayr', '# Date:     2026-10-04', '#',
           "# Copyright:This file is part of Exudyn. Exudyn is free software. You can redistribute it and/or modify it under the terms of the Exudyn license. See 'LICENSE.txt' for more details.",
           '#', '#' + '+'*77, '']
    for (i, cell) in enumerate(cells):
        source = Source(cell).rstrip()
        if source == '' or (i == 0 and cell['cell_type'] == 'markdown'):
            continue
        if cell['cell_type'] == 'markdown':
            out += ['#%%' + '+'*60] + ['#' + (' ' + line if line.strip() != '' else '') for line in source.split('\n')]
        elif cell['cell_type'] == 'code':
            out += [source, '']
    return '\n'.join(out).rstrip() + '\n'


def main():
    written = set()
    for path in Notebooks():
        name = os.path.splitext(os.path.basename(path))[0]
        notebook = json.load(open(path, encoding='utf-8'))
        (page, images) = Page(name, notebook)
        Write(pageDirectory + '/' + name + '.md', page)
        written.add(name + '.md')
        for (imageName, data) in images.items():
            Write(pageDirectory + '/images/' + imageName, data, binary=True)
            written.add('images/' + imageName)
        Write(scriptDirectory + '/' + name + '.py', Script(name, notebook))
    #what no notebook writes any more goes, so that a removed notebook leaves no page behind
    for full in glob.glob(os.path.join(repositoryRoot, pageDirectory, '**', '*'), recursive=True):
        relative = os.path.relpath(full, os.path.join(repositoryRoot, pageDirectory)).replace(os.sep, '/')
        if os.path.isfile(full) and relative not in written:
            os.remove(full)
    print('notebookEmitter: ' + str(len(Notebooks())) + ' notebook(s)')


if __name__ == '__main__':
    sys.exit(main())
