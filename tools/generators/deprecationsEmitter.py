import io
import os

import deprecationModel

sourceTitles = [('library', 'Functions and arguments of the Python library'),
                ('functions', 'Functions of the C++ module'),
                ('items', 'Item parameters'),
                ('settings', 'Settings')]


def Cell(text):
    return str(text).replace('|', '\\|').replace('\n', ' ')


def main():
    entries = deprecationModel.Collect()
    text = ('<!-- GENERATED by tools/generators/deprecationsEmitter.py from definitions/ and python/exudyn - do not edit -->\n'
            '(sec-dev-deprecations)=\n# Deprecations\n\n'
            'Every name of Exudyn that is deprecated, with the version it was deprecated in and the year it is removed. '
            'A use warns once per session and is counted in `exudyn.sys[\'deprecationUse\']`; '
            '`tools/checkDeprecations.py` fails for a deprecation whose year has come, which then has to be removed. '
            'How to deprecate something: `CODING_STYLE.md` §10.5. The version is 1.11.0 for what was deprecated before '
            'the history of this repository begins.\n')
    for (source, title) in sourceTitles:
        selected = [entry for entry in entries if entry['source'] == source]
        if len(selected) == 0:
            continue
        text += '\n## ' + title + ' (' + str(len(selected)) + ')\n\n'
        text += '| name | since | removed in | instead | declared in |\n|---|---|---|---|---|\n'
        for entry in sorted(selected, key=lambda entry: (entry['expires'] if isinstance(entry['expires'], int) else 0,
                                                         entry['name'])):
            text += ('| `' + Cell(entry['name']) + '` | ' + Cell(entry['since']) + ' | ' + Cell(entry['expires']) + ' | '
                     + Cell(entry['use']) + ' | ' + Cell(entry['where'].split(':')[0]) + ' |\n')
    fileName = os.path.join(deprecationModel.repositoryRoot, 'docs', 'generated', 'deprecations.md')
    with io.open(fileName, 'w', encoding='utf-8', newline='\n') as file:
        file.write(text)
    print('deprecationsEmitter: ' + str(len(entries)) + ' deprecations written')


if __name__ == '__main__':
    main()
