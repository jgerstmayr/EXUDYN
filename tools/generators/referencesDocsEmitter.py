#
# Details:  Emits the references page, docs/generated/references.md, from docs/bibliographyDoc.bib,
#           and the citation keys as data for conf.py in tools/generators/generated/
#           confHelperCitations.py (revision2026b step RG3.5, #2550).
#
#           WHY a generator and not a hand-written page: the .bib is the bibliography of the
#           project and outlived the LaTeX build (revision2026 step R7.1.7 moved it to docs/).
#           The chapters cite with [Key2021] in the running text, which the LaTeX build resolved
#           and nothing has resolved since - the keys were printed and pointed nowhere.
#
#           HOW the citation becomes a link without touching a single source text: every entry
#           gets a target (ref-<key in lower case>) here, and conf.py appends one Markdown link
#           definition per key to every document it reads. CommonMark then resolves [Key2021] as
#           a shortcut reference link - and only where it IS text, never inside a code fence or
#           inline code, because the Markdown parser itself decides that. See conf.py,
#           AppendCitationDefinitions().
#
#           The page lists the WHOLE bibliography, not only what is cited today: the input is the
#           .bib alone, so the output never depends on the state of another generated page. The
#           report at the end of a run says how many of the entries are cited and names a key that
#           is cited but missing from the .bib - such a key renders as plain text, and nothing
#           else would notice.
#
