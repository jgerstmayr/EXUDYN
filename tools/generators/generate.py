class Stage:
    """one generator script with the paths it reads and writes (repository-relative)"""
    def __init__(self, script, reads, writes, writesOnlyWhenChanged=False):
        self.script = script
        self.name = os.path.splitext(os.path.basename(script))[0]
        self.reads = reads
        self.writes = writes
        #two generators compare before they write (WriteTextIfDifferent), so an unchanged run
        #touches nothing. That is fine and it has to be declared, or the check below reads it as
        #a generator that has stopped writing - which is the failure it exists to catch (#2526)
        self.writesOnlyWhenChanged = writesOnlyWhenChanged


