def _Overlaps(readPath, writePath):
    """True if a written path and a read path meet: equal, one inside the other (directories), or
    one matching the other as a pattern with '*'"""
    return (fnmatch.fnmatchcase(writePath, readPath) or fnmatch.fnmatchcase(readPath, writePath)
            or writePath.startswith(readPath.rstrip('/') + '/')
            or readPath.startswith(writePath.rstrip('/') + '/'))


def RunOrder(stageList=None):
    """stages sorted so that each runs after the stages writing what it reads; raises on a cycle"""
    stageList = stages if stageList is None else stageList
    after = {s.name: set() for s in stageList}
    for reader in stageList:
        for writer in stageList:
            if writer is reader:
                continue
            if any(_Overlaps(r, w) for r in reader.reads for w in writer.writes):
                after[reader.name].add(writer.name)
    ordered = []
    remaining = list(stageList)
    while remaining:
        for stage in remaining:  #the first stage in declaration order whose inputs are ready
            if after[stage.name] <= set(s.name for s in ordered):
                ordered.append(stage)
                remaining.remove(stage)
                break
        else:
            raise RuntimeError('generate.py: cyclic stage dependencies among '
                               + ', '.join(s.name for s in remaining))
    return ordered


def _WriteTimes(stage):
    """modification time of every declared output that exists, keyed by path; a directory counts as
    the newest file below it"""
    times = {}
    for pattern in stage.writes:
        for path in glob.glob(os.path.join(repositoryRoot, pattern)):
            if os.path.isdir(path):
                for (directory, _, files) in os.walk(path):
                    for name in files:
                        fullPath = os.path.join(directory, name)
                        times[fullPath] = os.path.getmtime(fullPath)
            else:
                times[path] = os.path.getmtime(path)

    return times


def RunStages(pythonExecutable=sys.executable, only=None, verbose=True):
    """run the stages in order from the repository root; returns the list of failed stage names"""
    failed = []
    ordered = RunOrder()
    if verbose:
        print('running ' + str(len(ordered) if not only else len(only)) + ' generators ...')
    for stage in ordered:
        if only and stage.name not in only:
            continue
        if verbose:
            print('  running ' + stage.script + ' ...', flush=True)
        before = _WriteTimes(stage)
        result = subprocess.run([pythonExecutable, os.path.join(repositoryRoot, stage.script)],
                                cwd=repositoryRoot, capture_output=True, text=True)
        if result.returncode != 0:
            failed.append(stage.name)
            print('  ERROR: ' + stage.script + ' failed with exit code ' + str(result.returncode))
            for line in (result.stdout.splitlines()[-15:] + result.stderr.splitlines()[-15:]):
                print('    | ' + line)
            continue

        #A STAGE THAT WRITES NOTHING IS A FAILURE, even though it exits 0 (#2526, revision2026 step
        #R4.3.1). mainSystemExtensionDocsEmitter.py ended in the middle of main() for five days:
        #it ran, printed nothing, produced nothing, and the regeneration check could not see it,
        #because a generator that writes nothing always agrees with the commit. Five documentation
        #files were frozen at their committed content the whole time.
        #The test is deliberately crude - did ANY declared output change its modification time -
        #because the generators rewrite their outputs unconditionally; it catches a stage that
        #writes none of them, which is the failure that hides.
        after = _WriteTimes(stage)
        missing = [pattern for pattern in stage.writes
                   if not glob.glob(os.path.join(repositoryRoot, pattern))]
        touched = [path for path in after if after[path] != before.get(path)]

        if missing or (stage.writes and not touched and not stage.writesOnlyWhenChanged):
            failed.append(stage.name)
            print('  ERROR: ' + stage.script + ' exited 0 but produced no output:')
            for pattern in (missing if missing else stage.writes):
                print('    | ' + pattern + ('  (does not exist)' if missing else ''))
            print('    | a generator that writes nothing always agrees with the commit, so the')
            print('    | regeneration check cannot see this - hence the check here')
    return failed


def main(argv=None):
    parser = argparse.ArgumentParser(description='Run the Exudyn code generators in dependency order.')
    parser.add_argument('--list', action='store_true', help='print the stages in run order and exit')
    parser.add_argument('--only', action='append', help='run only this stage (repeatable)')
    parser.add_argument('--python', default=sys.executable, help='python executable for the stages')
    args = parser.parse_args(argv)

    if args.list:
        for stage in RunOrder():
            print(stage.name)
        return 0

    sys.path.insert(0, toolsDirectory)
    from definitionValidator import ValidateDefinitions
    if ValidateDefinitions():
        print('definitions/ are inconsistent - nothing generated')
        return 3

    return 1 if RunStages(args.python, args.only) else 0


if __name__ == '__main__':
    sys.exit(main())
