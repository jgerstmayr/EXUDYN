import io
import json
import os
import sys

toolsDirectory = os.path.dirname(os.path.abspath(__file__))
if toolsDirectory not in sys.path:
    sys.path.insert(0, toolsDirectory)

import generatorPaths as paths                                                  # noqa: E402

historyFile = paths.pythonDir + 'logs/performance/performanceHistory.json'
outputFile = paths.repositoryRoot + 'docs/generated/performanceReleases.md'


def VersionKey(version):
    return tuple(int(part) for part in version.split('.')[:3])


def ReleaseEntries(history, module):
    """the release entries of one module on Windows, of the computer of the newest release run, by version"""
    entries = [entry for entry in history['entries'] if entry['system'] == 'win32' and entry['module'] == module
               and 'dev' not in entry['version']]
    if not entries:
        return []
    newest = max(entries, key=lambda entry: VersionKey(entry['version']))
    entries = [entry for entry in entries if entry['machine'] == newest['machine'] and entry['python'] == newest['python']]
    return sorted(entries, key=lambda entry: VersionKey(entry['version']))


def Table(entries):
    """a Markdown table: one row per model, one column per release, and the total of the models in every release"""
    names = sorted(set(name for entry in entries for name in entry['files']), key=str.lower)
    common = [name for name in names if all(name in entry['files'] for entry in entries)]
    lines = ['| model | ' + ' | '.join(entry['version'] for entry in entries) + ' |',
             '|---|' + '---:|'*len(entries)]
    for name in names:
        lines.append('| `' + name + '` | ' + ' | '.join('%.2f' % entry['files'][name] if name in entry['files'] else ''
                                                       for entry in entries) + ' |')
    lines.append('| total of the models in every release | '
                 + ' | '.join('%.2f' % sum(entry['files'][name] for name in common) for entry in entries) + ' |')
    return '\n'.join(lines) + '\n'


def main():
    with io.open(historyFile, encoding='utf-8') as file:
        history = json.load(file)
    text = ('<!-- GENERATED by tools/generators/performanceReleasesEmitter.py from '
            'python/logs/performance/performanceHistory.json - do not edit -->\n')
    tables = 0
    for (module, title) in [('regular', 'the regular module'), ('fast', 'the fast module (`exudynCPPfast`)')]:
        entries = ReleaseEntries(history, module)
        if not entries:
            continue
        text += ('\n**' + title[0].upper() + title[1:] + '**, Windows, Python ' + entries[-1]['python'] + ', '
                 + entries[-1]['cpu'].strip() + ':\n\n' + Table(entries))
        tables += 1
    with io.open(outputFile, 'w', encoding='utf8', newline='\n') as file:
        file.write(text)
    print('performanceReleasesEmitter: ' + str(tables) + ' tables written')
    return 0


if __name__ == '__main__':
    sys.exit(main())
