import importlib.util
import io
import os
import re
import sys

toolsDirectory = os.path.dirname(os.path.abspath(__file__))
if toolsDirectory not in sys.path:
    sys.path.insert(0, toolsDirectory)

import generatorPaths as paths                                                  # noqa: E402

bindingsModuleFile = paths.pythonPackageDir + 'misc/keyBindings.py'
glfwClientFile = paths.repositoryRoot + 'src/Graphics/GlfwClient.cpp'


def Banner():
    return ('<!-- GENERATED by tools/generators/keyBindingsEmitter.py from '
            'python/exudyn/misc/keyBindings.py - do not edit -->\n')


def BindingsModule():
    """the table, loaded from the file rather than imported as exudyn.misc.keyBindings

    The generators run without the compiled module being importable, and this one needs no more
    than a list of tuples; the module itself imports nothing but textwrap and collections.
    """
    specification = importlib.util.spec_from_file_location('keyBindings', bindingsModuleFile)
    module = importlib.util.module_from_spec(specification)
    specification.loader.exec_module(module)
    return module


def MarkdownTable(bindings, firstColumn):
    """the bindings as the three column table the manual had by hand"""
    table = '| **' + firstColumn + '** | action | **remarks** |\n|---|---|---|\n'
    for binding in bindings:
        table += ('| **' + binding.keys + '** | ' + binding.action + ' | '
                  + binding.remarks + ' |\n')
    return table


def DocumentedKeys(bindings):
    """{(GLFW key name, modifier)} of the table; 'GLFW_KEY_1..5' is a range, '+CONTROL' a modifier"""
    keys = set()
    for binding in bindings:
        for name in binding.glfw.split(','):
            name = name.strip()
            if name == '':
                continue
            modifier = 'CONTROL' if name.endswith('+CONTROL') else ''
            name = name.replace('+CONTROL', '')
            rangeMatch = re.match(r'^GLFW_KEY_(\d)\.\.(\d)$', name)
            if rangeMatch:
                for digit in range(int(rangeMatch.group(1)), int(rangeMatch.group(2)) + 1):
                    keys.add(('GLFW_KEY_' + str(digit), modifier))
            else:
                keys.add((name, modifier))
    return keys


def ImplementedKeys(text):
    """{(GLFW key name, modifier)} of the key tests in GlfwClient.cpp

    The implementation is one 'if (key == GLFW_KEY_X && action == ... && mods == ...)' per
    binding, so the pair can be read out of it - per LINE, because one condition may hold two
    keys and two modifier cases ('mods == 0 || mods == GLFW_MOD_CONTROL' for the zoom keys).
    SHIFT is not distinguished: it is a variant of a binding, never one of its own.
    """
    keys = set()
    for line in text.split('\n'):
        names = re.findall(r'key\s*==\s*GLFW_KEY_(\w+)', line)
        if names == []:
            continue
        modifiers = set()
        if 'GLFW_MOD_CONTROL' in line:
            modifiers.add('CONTROL')
        if 'mods == 0' in line or 'GLFW_MOD' not in line:
            modifiers.add('')
        for name in names:
            for modifier in modifiers:
                keys.add(('GLFW_KEY_' + name, modifier))
    return keys


def Report(bindings):
    """what the table and the implementation say about each other"""
    if not os.path.exists(glfwClientFile):
        return
    with io.open(glfwClientFile, encoding='utf-8', errors='replace') as file:
        implemented = ImplementedKeys(file.read())
    documented = DocumentedKeys(bindings)

    def Name(key):
        return key[0] + ('+CONTROL' if key[1] == 'CONTROL' else '')

    missing = sorted(Name(key) for key in implemented - documented)
    extra = sorted(Name(key) for key in documented - implemented)
    if missing != []:
        print('   NOTE: handled in GlfwClient.cpp and not in the table: ' + ', '.join(missing))
    if extra != []:
        print('   WARNING: in the table and not handled in GlfwClient.cpp: ' + ', '.join(extra))


def main():
    module = BindingsModule()
    pages = [('mouseBindings.md', MarkdownTable(module.mouseBindings, 'Button')),
             ('keyBindings.md', MarkdownTable(module.keyBindings, 'Key(s)'))]
    for (name, table) in pages:
        with io.open(paths.repositoryRoot + 'docs/generated/' + name, 'w', encoding='utf8',
                     newline='\n') as file:
            file.write(Banner() + table)

    print('keyBindingsEmitter: ' + str(len(module.mouseBindings)) + ' mouse and '
          + str(len(module.keyBindings)) + ' keyboard bindings written')
    Report(module.keyBindings)
    return 0


if __name__ == '__main__':
    sys.exit(main())
