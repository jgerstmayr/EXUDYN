# Details:  Emits the mouse and keyboard tables of the documentation,
#           docs/generated/mouseBindings.md and docs/generated/keyBindings.md, from the one table
#           in python/exudyn/misc/keyBindings.py (#2591).
#
#           WHY: what the render window does when a key is pressed was written down three times -
#           src/Graphics/GlfwClient.cpp implements it, docs/manual/GUI.md tabulated it, and the
#           help dialog printed its own text. Nothing kept the two prose copies in step with the
#           implementation, and both had drifted: four bindings that exist were documented
#           nowhere, and the keypad rotation keys were named wrongly in both.
#
#           The help dialog and these two pages now come from the same table. The third copy - the
#           implementation - cannot be generated, so it is COMPARED: every binding of the table
#           carries the GLFW key names it is implemented with, this tool reads the key tests out
#           of GlfwClient.cpp, and the report at the end names what one side has and the other
#           does not. That is a warning, not a failure: a key can legitimately be handled without
#           being worth documenting, and the report says which one it is.
#
#           The two pages are FRAGMENTS - no heading, no label - because docs/manual/GUI.md
#           includes them where its tables stood; they are excluded from the document tree in
#           conf.py, or Sphinx reads them as pages of their own and reports them as orphans.
