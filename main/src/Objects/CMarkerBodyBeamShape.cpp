//very specific marker for Cable2D shape; this is not the usual way to compute markerdata!
void CMarkerBodyBeamShape::ComputeMarkerData(const CSystemData& cSystemData, bool computeJacobian, MarkerData& markerData) const
{
	//the following code could be adapted to different beam elements!
	CObjectANCFCable* cable = ((CObjectANCFCable*)(cSystemData.GetCObjects()[parameters.bodyNumber]));
	Index nCoordinatesCable = cable->GetODE2Size();
	const Index nnc = CObjectANCFCable::nNodalCoordinates;   //number of shape functions


	ConstSizeVector<nnc> q0DisplRef; //coordinates (displacement+reference) node 0
	ConstSizeVector<nnc> q1DisplRef; //coordinates (displacement+reference) node 1

	markerData.GetHelper() = cable->GetLength(); //WORKAROUND

	markerData.vectorValue.SetNumberOfItems(nCoordinatesCable); //stores beam element coordinates
	markerData.vectorValue_t.SetNumberOfItems(nCoordinatesCable); //stores coordinates velocities

	cable->ComputeCurrentNodeCoordinates(q0DisplRef, q1DisplRef);
	markerData.vectorValue.CopyFrom(q0DisplRef, 0, 0, nnc);
	markerData.vectorValue.CopyFrom(q1DisplRef, 0, nnc, nnc);

	cable->ComputeCurrentNodeVelocities(q0DisplRef, q1DisplRef);
	markerData.vectorValue_t.CopyFrom(q0DisplRef, 0, 0, nnc);
	markerData.vectorValue_t.CopyFrom(q1DisplRef, 0, nnc, nnc);
	markerData.velocityAvailable = true;

	if (computeJacobian)
	{
		//markerData.jacobian.SetNumberOfRowsAndColumns(nCoordinatesCable, nCoordinatesCable); //stores the shape functions; very specific for ANCF cable
		//the following might not be necessary as the SlidingJoint2D anyway needs to communicate with the ANCF cable
		markerData.jacobian.SetScalarMatrix(nCoordinatesCable, 1.); //8 forces act on 8 coordinates ==> could be made more efficient!!
	}


}

