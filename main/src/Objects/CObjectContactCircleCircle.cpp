static int g_logCounter = 0;

//compute the properties which are needed for computation of LHS and needed for OutputVariables
// NOTE: All contact calculations are performed in 2D (XY plane), ignoring Z coordinates.
// This allows circles at different Z positions to contact correctly (e.g., bearings).
void CObjectContactCircleCircle::ComputeContactProperties(const MarkerDataStructure& markerData, Index itemIndex, LinkedDataVector& data, bool useDataStates) const
{
    // Get marker data - extract only XY components for 2D contact calculation
    const Vector3D& pos1 = markerData.GetMarkerData(0).position;
    const Vector3D& pos2 = markerData.GetMarkerData(1).position;
    const Vector3D& v1_3d = markerData.GetMarkerData(0).velocity;
    const Vector3D& v2_3d = markerData.GetMarkerData(1).velocity;
    
    // 2D circle centers (ignore Z)
    Real c1x = pos1[0], c1y = pos1[1];
    Real c2x = pos2[0], c2y = pos2[1];
    
    Real r1 = parameters.radius1;
    Real r2_signed = parameters.radius2;
    Real r2 = fabs(r2_signed);
    bool marker2Concave = (r2_signed < 0.0);
    
    // Compute distance and direction in 2D
    Real dx = c2x - c1x;
    Real dy = c2y - c1y;
    Real dist_sq = dx * dx + dy * dy;
    Real dist = sqrt(dist_sq);

    Real nx, ny;  // 2D normal direction
    if (dist > 1e-12) {
        Real invDist = 1.0 / dist;
        nx = dx * invDist;
        ny = dy * invDist;
    } else {
        nx = 1.0;
        ny = 0.0;
    }
    
    // Convert to 3D normal (Z = 0)
    Vector3D normalDir({nx, ny, 0.0});

    // Concave contact: radius2 < 0 means marker1 is a cavity (not distance-dependent!)
    if (marker2Concave) {
        // Concave contact: normal points from circle center towards cavity wall
        contactNormal = normalDir;  // from c1 towards c2 (cavity center)
        gap = r2 - (dist + r1);     // gap < 0 when circle pushes into cavity wall
    } else {
        // Convex contact: normal points from c1 away from c2
        contactNormal = -normalDir; // push c1 away from c2
        gap = dist - (r1 + r2);
    }
    
    // Contact point in 2D (Z = 0)
    // Contact point is on the surface of circle 1
    // For convex-convex, it's towards circle 2 (nx)
    // For concave (internal), it's AWAY from circle 2 (-nx)
    Real dirSign = marker2Concave ? -1.0 : 1.0;
    Real cpx = c1x + r1 * nx * dirSign;
    Real cpy = c1y + r1 * ny * dirSign;
    contactPoint = Vector3D({cpx, cpy, 0.0});
    
    // Relative velocity in 2D (only XY components matter for normal force)
    Real v1x = v1_3d[0], v1y = v1_3d[1];
    Real v2x = v2_3d[0], v2y = v2_3d[1];
    Real vrel_x = v1x - v2x;
    Real vrel_y = v1y - v2y;
    gapVelocity = vrel_x * contactNormal[0] + vrel_y * contactNormal[1];
    
    // Contact force (normal)
    contactForce = 0.0;
    Real contactState = 0.0;
    
    if (gap <= 0.0) {
        contactState = 1.0;
        constexpr Real contactExponent = 10.0 / 9.0;
        Real penetration = -gap;
        
        // Smooth damping coefficient (matching paper's c_c approach)
        // Prevents attractive forces and ensures smooth force transition
        Real h0 = 0;  // Damping starts to take effect
        Real h1 = 1e-6;  // Damping fully effective
        Real c_c = 0.0;
        if (penetration >= h1) {
            c_c = 1.0;
        } else if (penetration > h0) {
            c_c = (penetration - h0) / (h1 - h0);
        }
        
        Real nonLinearForce = parameters.contactStiffness * pow(penetration, contactExponent);
        Real dampingForce = c_c * parameters.contactDamping * gapVelocity;
        contactForce = nonLinearForce - dampingForce;
        
        // Safety check (should rarely trigger with smooth damping)
        // if (contactForce < 0.0) contactForce = 0.0;
    }
    
    // Friction force (velocity penalty + regularized Coulomb model)
    frictionForce = Vector3D({0.0, 0.0, 0.0});
    tangentialVelocity = 0.0;
    
    if (contactForce > 0.0 && (parameters.frictionCoefficient > 0.0 || parameters.frictionVelocityPenalty > 0.0)) {
        // Get angular velocities (only Z component matters for 2D)
        Real omegaZ1 = 0.0, omegaZ2 = 0.0;
        if (markerData.GetMarkerData(0).velocityAvailable) {
            omegaZ1 = markerData.GetMarkerData(0).angularVelocityLocal[2];
        }
        if (markerData.GetMarkerData(1).velocityAvailable) {
            omegaZ2 = markerData.GetMarkerData(1).angularVelocityLocal[2];
        }
        
        // Contact point velocity in 2D: v_contact = v_center + omega_z × r_contact
        // omega × r = (-omega_z * ry, omega_z * rx, 0) for 2D
        Real r1x = contactPoint[0] - pos1[0], r1y = contactPoint[1] - pos1[1];
        Real r2x = contactPoint[0] - pos2[0], r2y = contactPoint[1] - pos2[1];
        Real v1c_x = v1x + (-omegaZ1 * r1y);
        Real v1c_y = v1y + (omegaZ1 * r1x);
        Real v2c_x = v2x + (-omegaZ2 * r2y);
        Real v2c_y = v2y + (omegaZ2 * r2x);
        
        // Tangential relative velocity at contact point (marker1 relative to marker0)
        Real vrel_cx = v2c_x - v1c_x;
        Real vrel_cy = v2c_y - v1c_y;
        // Remove normal component
        Real vrel_n = vrel_cx * contactNormal[0] + vrel_cy * contactNormal[1];
        Real vtang_x = vrel_cx - vrel_n * contactNormal[0];
        Real vtang_y = vrel_cy - vrel_n * contactNormal[1];
        tangentialVelocity = sqrt(vtang_x * vtang_x + vtang_y * vtang_y);
        
        // Compute friction force using Bristle model (if enabled) or velocity penalty
        Real maxFrictionForce = parameters.frictionCoefficient * contactForce;
        
        if (parameters.frictionStiffness > 0.0 && parameters.frictionCoefficient > 0.0) {
            // ========== BRISTLE MODEL (静摩擦) ==========
            // Get previous contact state and stick position
            Real lastContactState = data[dataIndexContactState];
            Real stickPosX = data[dataIndexStickPosX];
            Real stickPosY = data[dataIndexStickPosY];
            
            // Current contact point (tangential position)
            Real currentPosX = contactPoint[0];
            Real currentPosY = contactPoint[1];
            
            // If new contact, initialize stick position
            if (lastContactState < 0.5) {
                stickPosX = currentPosX;
                stickPosY = currentPosY;
            }
            
            // Compute stick displacement (tangential only)
            Real deltaX = currentPosX - stickPosX;
            Real deltaY = currentPosY - stickPosY;
            // Remove normal component to get pure tangential displacement
            Real deltaNormal = deltaX * contactNormal[0] + deltaY * contactNormal[1];
            Real deltaTangX = deltaX - deltaNormal * contactNormal[0];
            Real deltaTangY = deltaY - deltaNormal * contactNormal[1];
            Real deltaMag = sqrt(deltaTangX * deltaTangX + deltaTangY * deltaTangY);
            
            // Compute stick force
            Real stickForce = parameters.frictionStiffness * deltaMag;
            
            if (stickForce <= maxFrictionForce || maxFrictionForce <= 0.0) {
                // STICKING: friction = spring force
                frictionForce = Vector3D({-parameters.frictionStiffness * deltaTangX,
                                          -parameters.frictionStiffness * deltaTangY, 0.0});
            } else {
                // SLIDING: friction = Coulomb limit, update stick position
                Real scale = maxFrictionForce / stickForce;
                frictionForce = Vector3D({-parameters.frictionStiffness * deltaTangX * scale,
                                          -parameters.frictionStiffness * deltaTangY * scale, 0.0});
                // Update stick position to follow sliding
                Real maxDisp = maxFrictionForce / parameters.frictionStiffness;
                if (deltaMag > 1e-12) {
                    stickPosX = currentPosX - (deltaTangX / deltaMag) * maxDisp;
                    stickPosY = currentPosY - (deltaTangY / deltaMag) * maxDisp;
                }
            }
            
            // Store updated stick position
            if (!useDataStates) {
                data[dataIndexStickPosX] = stickPosX;
                data[dataIndexStickPosY] = stickPosY;
            }
        }
        else if (parameters.frictionVelocityPenalty > 0.0) {
            // Velocity penalty friction model
            Real frictionForceMagnitude = tangentialVelocity * parameters.frictionVelocityPenalty;
            if (frictionForceMagnitude > maxFrictionForce && maxFrictionForce > 0.0) {
                frictionForceMagnitude = maxFrictionForce;
            }
            if (tangentialVelocity > 1e-12 && frictionForceMagnitude > 0.0) {
                Real invNorm = 1.0 / tangentialVelocity;
                frictionForce = Vector3D({-frictionForceMagnitude * vtang_x * invNorm, 
                                          -frictionForceMagnitude * vtang_y * invNorm, 0.0});
            }
        }
        else if (parameters.frictionProportionalZone > 0.0 && parameters.frictionCoefficient > 0.0) {
            // Regularized Coulomb friction model
            Real frictionForceMagnitude = 0.0;
            if (tangentialVelocity < parameters.frictionProportionalZone) {
                frictionForceMagnitude = (maxFrictionForce / parameters.frictionProportionalZone) * tangentialVelocity;
            } else {
                frictionForceMagnitude = maxFrictionForce;
            }
            if (tangentialVelocity > 1e-12 && frictionForceMagnitude > 0.0) {
                Real invNorm = 1.0 / tangentialVelocity;
                frictionForce = Vector3D({-frictionForceMagnitude * vtang_x * invNorm, 
                                          -frictionForceMagnitude * vtang_y * invNorm, 0.0});
            }
        }
    }
    
    // ========== DEBUG LOG ==========
    if (DEBUG_LOG_ENABLED) {
        if (!g_logInitialized) {
            g_contactLog.open("contact_debug.log");
            g_contactLog << "===== Circle-Circle Contact Debug Log =====" << std::endl;
            g_logInitialized = true;
        }
        
        // 获取角速度
        Real omega0_z = 0.0, omega1_z = 0.0;
        if (markerData.GetMarkerData(0).velocityAvailable) {
            omega0_z = markerData.GetMarkerData(0).angularVelocityLocal[2];
        }
        if (markerData.GetMarkerData(1).velocityAvailable) {
            omega1_z = markerData.GetMarkerData(1).angularVelocityLocal[2];
        }
        
        // 计算接触点处的线速度
        Real r0x = contactPoint[0] - pos1[0], r0y = contactPoint[1] - pos1[1];
        Real r1x = contactPoint[0] - pos2[0], r1y = contactPoint[1] - pos2[1];
        Real v0_contact_x = v1x + (-omega0_z * r0y);
        Real v0_contact_y = v1y + (omega0_z * r0x);
        Real v1_contact_x = v2x + (-omega1_z * r1y);
        Real v1_contact_y = v2y + (omega1_z * r1x);

        Vector3D force1 = contactForce * contactNormal + frictionForce;
        Real force1_x = force1[0];
        Real force1_y = force1[1];
        
        Real torque0_z = r0x * (-force1_y) - r0y * (-force1_x); // r0 × (-forceOnMarker1)
        Real torque1_z = r1x * force1_y - r1y * force1_x;  // r1 × forceOnMarker1
        
        g_contactLog << std::fixed << std::setprecision(6);
        g_contactLog << "--- Step " << g_logCounter << " ---" << std::endl;
        g_contactLog << "  omega0_z=" << omega0_z << " rad/s (主动圆), omega1_z=" << omega1_z << " rad/s (从动圆)" << std::endl;
        g_contactLog << "  v0_contact=(" << v0_contact_x << ", " << v0_contact_y << ") m/s" << std::endl;
        g_contactLog << "  v1_contact=(" << v1_contact_x << ", " << v1_contact_y << ") m/s" << std::endl;
        g_contactLog << "  vrel_tang=" << tangentialVelocity << " m/s" << std::endl;
        g_contactLog << "  friction=(" << frictionForce[0] << ", " << frictionForce[1] << ") N, |F|=" << frictionForce.GetL2Norm() << " N" << std::endl;
        g_contactLog << "  forceOnMarker1=(" << force1_x << ", " << force1_y << ") N" << std::endl;
        g_contactLog << "  torque0_z=" << torque0_z << " Nm, torque1_z=" << torque1_z << " Nm" << std::endl;
        g_contactLog << "  r0=(" << r0x << ", " << r0y << "), r1=(" << r1x << ", " << r1y << ")" << std::endl;
        g_contactLog << "  contactForce=" << contactForce << " N" << std::endl;
        g_logCounter++;
    }
    // ========== END DEBUG LOG ==========
    
    // Store data for discontinuous iteration
    if (!useDataStates) {
        data[dataIndexGap] = gap;
        data[dataIndexGapVelocity] = gapVelocity;
        data[dataIndexContactForce] = contactForce;
        data[dataIndexFrictionForceX] = frictionForce[0];
        data[dataIndexFrictionForceY] = frictionForce[1];
        data[dataIndexContactState] = contactState;
    }
}

//! Computational function: compute left-hand-side (LHS) of second order ordinary differential equations (ODE) to "ode2Lhs"
void CObjectContactCircleCircle::ComputeODE2LHS(Vector& ode2Lhs, const MarkerDataStructure& markerData, Index objectNumber) const
{
    CHECKandTHROW(markerData.GetMarkerData(0).velocityAvailable && markerData.GetMarkerData(1).velocityAvailable,
        "CObjectContactCircleCircle::ComputeODE2LHS: markers do not provide velocity information");

    LinkedDataVector data = GetCNode(0)->GetCurrentCoordinateVector();
    const bool useDataStates = true;
    
    // Compute contact properties
    ComputeContactProperties(markerData, objectNumber, data, useDataStates);
    
    // Initialize result vector
    Index nODE2_0 = markerData.GetMarkerData(0).positionJacobian.NumberOfColumns();
    Index nODE2_1 = markerData.GetMarkerData(1).positionJacobian.NumberOfColumns();
    ode2Lhs.SetNumberOfItems(nODE2_0 + nODE2_1);
    ode2Lhs.SetAll(0.);
    
    if (parameters.activeConnector && (contactForce != 0.0 || frictionForce.GetL2Norm() > 0.0)) {
        // contactNormal direction depends on contact type:
        // - Convex-convex: contactNormal = -normalDir (away from marker1)
        // - Convex-concave: contactNormal = +normalDir (towards cavity center)
        // 
        // Repulsive force should PUSH marker1 AWAY from marker0:
        // - Convex-convex: push in +normalDir direction = -contactNormal
        // - Convex-concave: push in -normalDir direction = -contactNormal
        // In both cases: repulsive force on marker1 = -contactForce * contactNormal
        Vector3D normalForceOnMarker1 = -contactForce * contactNormal;
        Vector3D forceOnMarker1 = normalForceOnMarker1 + frictionForce;
        Vector3D forceOnMarker0 = -forceOnMarker1;

        // Compute torques from forces applied at contact point
        // r = contactPoint - markerPosition
        Vector3D r0 = contactPoint - markerData.GetMarkerData(0).position;
        Vector3D r1 = contactPoint - markerData.GetMarkerData(1).position;
        
        // Torque = r × F
        // Each marker uses its own force for torque calculation
        // r points FROM marker center TO contact point
        Vector3D torqueOnMarker0 = r0.CrossProduct(forceOnMarker0);
        Vector3D torqueOnMarker1 = r1.CrossProduct(forceOnMarker1);
        

        // EXUDYN convention: systemODE2Rhs -= ODE2LHS
        // So to apply force F, we need ODE2LHS = -F
        // To apply torque T, we need ODE2LHS = -T
        Vector3D negForce0 = -forceOnMarker0;
        Vector3D negForce1 = -forceOnMarker1;
        Vector3D negTorque0 = -torqueOnMarker0;
        Vector3D negTorque1 = -torqueOnMarker1;

        // Apply forces and torques to marker0
        if (nODE2_0 > 0) {
            LinkedDataVector ldv0(ode2Lhs, 0, nODE2_0);
            EXUmath::MultMatrixTransposedVector(markerData.GetMarkerData(0).positionJacobian, negForce0, ldv0);
            if (markerData.GetMarkerData(0).rotationJacobian.NumberOfColumns() > 0) {
                EXUmath::MultMatrixTransposedVectorAdd(markerData.GetMarkerData(0).rotationJacobian, negTorque0, ldv0);
            }
        }

        // Apply forces and torques to marker1
        if (nODE2_1 > 0) {
            LinkedDataVector ldv1(ode2Lhs, nODE2_0, nODE2_1);
            EXUmath::MultMatrixTransposedVector(markerData.GetMarkerData(1).positionJacobian, negForce1, ldv1);
            if (markerData.GetMarkerData(1).rotationJacobian.NumberOfColumns() > 0) {
                EXUmath::MultMatrixTransposedVectorAdd(markerData.GetMarkerData(1).rotationJacobian, negTorque1, ldv1);
            }
        }
    }
}

//! provide according output variable in "value"
void CObjectContactCircleCircle::GetOutputVariableConnector(OutputVariableType variableType, const MarkerDataStructure& markerData, Index itemIndex, Vector& value) const
{
    LinkedDataVector data = GetCNode(0)->GetCurrentCoordinateVector();
    const bool useDataStates = true;
    
    // Compute current contact properties
    ComputeContactProperties(markerData, itemIndex, data, useDataStates);
    
    switch (variableType)
    {
    case OutputVariableType::DisplacementLocal:
        value.SetNumberOfItems(1);
        value[0] = gap;
        break;
    case OutputVariableType::VelocityLocal:
        value.SetNumberOfItems(1);
        value[0] = gapVelocity;
        break;
    case OutputVariableType::ForceLocal:
    value.SetNumberOfItems(3);
    value[0] = contactForce * contactNormal[0] + frictionForce[0];
    value[1] = contactForce * contactNormal[1] + frictionForce[1];
    value[2] = contactForce * contactNormal[2] + frictionForce[2];
        break;
    default:
        SysError("CObjectContactCircleCircle::GetOutputVariableConnector failed");
    }
}

//! function called after Newton method; returns a residual error (force)
Real CObjectContactCircleCircle::PostNewtonStep(const MarkerDataStructure& markerDataCurrent, Index itemIndex, PostNewtonFlags::Type& flags, Real& recommendedStepSize)
{
    Real discontinuousError = 0.0;
    flags = PostNewtonFlags::_None;
    
    LinkedDataVector dataStartofStepState = ((CNodeData*)GetCNode(0))->GetCoordinateVector(ConfigurationType::StartOfStep);
    LinkedDataVector data = ((CNodeData*)GetCNode(0))->GetCoordinateVector(ConfigurationType::Current);
    
    const bool useDataStates = false;
    ComputeContactProperties(markerDataCurrent, itemIndex, data, useDataStates);
    
    // Store current values
    data[dataIndexGap] = gap;
    data[dataIndexGapVelocity] = gapVelocity;
    data[dataIndexContactForce] = contactForce;
    data[dataIndexFrictionForceX] = frictionForce[0];
    data[dataIndexFrictionForceY] = frictionForce[1];
    data[dataIndexContactState] = (gap <= 0.0) ? 1.0 : 0.0;
    
    // Check for contact state change
    Real lastContactState = dataStartofStepState[dataIndexContactState];
    Real currentContactState = data[dataIndexContactState];
    if (lastContactState != currentContactState) {
        discontinuousError = fabs(contactForce);
        flags = PostNewtonFlags::UpdateJacobian;
    }
    
    return discontinuousError;
}

