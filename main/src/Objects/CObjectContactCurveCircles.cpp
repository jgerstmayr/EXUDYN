// ========== FLEXIBLE BODY DEFORMATION CACHE ==========
// Cache structure for flexible body deformed positions
// Avoids redundant computation when multiple contact objects share the same flexible body
// Update frequency can be configured to reduce computation (e.g., every N steps)

static constexpr Index g_flexCacheUpdateInterval = 100;  // Update deformation every N steps (1 = every step)

struct FlexibleBodyCache {
    Index bodyIndex;                    // Which body this cache is for
    Real lastComputeTime;               // Time step when cache was last updated
    Index lastUpdateStep;               // Step counter when cache was last updated
    ResizableMatrix deformedPositions;  // Cached deformed node positions (global frame)
    bool isValid;                       // Whether cache is valid
    
    FlexibleBodyCache() : bodyIndex(EXUstd::InvalidIndex), lastComputeTime(-1.0), lastUpdateStep(0), isValid(false) {}
    
    void Invalidate() { isValid = false; lastUpdateStep = 0; }
};

// Global cache - supports multiple flexible bodies (indexed by body number)
static std::unordered_map<Index, FlexibleBodyCache> g_flexBodyCache;
static Real g_lastGlobalTime = -1.0;  // Track global simulation time
static Index g_globalStepCounter = 0; // Global step counter

// Clear all caches when simulation restarts or time goes backward
static void CheckAndClearCache(Real currentTime) {
    if (currentTime < g_lastGlobalTime || currentTime == 0.0) {
        g_flexBodyCache.clear();
        g_globalStepCounter = 0;
    }
    // Increment step counter when time advances
    if (currentTime > g_lastGlobalTime) {
        g_globalStepCounter++;
    }
    g_lastGlobalTime = currentTime;
}

// Check if cache needs update based on step interval
static bool NeedsCacheUpdate(const FlexibleBodyCache& cache) {
    return (g_globalStepCounter - cache.lastUpdateStep) >= g_flexCacheUpdateInterval;
}
