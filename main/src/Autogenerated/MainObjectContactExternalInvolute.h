    static void UpdateExternalProfileFromDict(const py::dict& src, ExternalInvoluteProfile& dst)
    {
        if (src.is_none()) { return; }

        if (EPyUtils::DictItemExists(src, "numberOfTeeth")) { dst.numberOfTeeth = py::cast<Index>(src["numberOfTeeth"]); }
        if (EPyUtils::DictItemExists(src, "module")) { dst.module = py::cast<Real>(src["module"]); }
        if (EPyUtils::DictItemExists(src, "alpha")) { dst.alpha = py::cast<Real>(src["alpha"]); }
        if (EPyUtils::DictItemExists(src, "haStar")) { dst.haStar = py::cast<Real>(src["haStar"]); }
        if (EPyUtils::DictItemExists(src, "cStar")) { dst.cStar = py::cast<Real>(src["cStar"]); }
        if (EPyUtils::DictItemExists(src, "x")) { dst.addendumModification = py::cast<Real>(src["x"]); }
        if (EPyUtils::DictItemExists(src, "baseRotation")) { dst.baseRotation = py::cast<Real>(src["baseRotation"]); }
        if (EPyUtils::DictItemExists(src, "flankSign")) { dst.flankMirror = py::cast<Real>(src["flankSign"]); }
        if (EPyUtils::DictItemExists(src, "reverseParam")) { dst.reverseParam = py::cast<bool>(src["reverseParam"]); }
        if (EPyUtils::DictItemExists(src, "replicateAllTeeth")) { dst.replicateAllTeeth = py::cast<bool>(src["replicateAllTeeth"]); }
        if (EPyUtils::DictItemExists(src, "singleToothIndex")) { dst.singleToothIndex = py::cast<Index>(src["singleToothIndex"]); }

        dst.InvalidateDerived();
    }

    static py::dict BuildExternalProfileDict(const ExternalInvoluteProfile& src)
    {
        auto d = py::dict();
        d["numberOfTeeth"] = src.numberOfTeeth;
        d["module"] = src.module;
        d["alpha"] = src.alpha;
        d["haStar"] = src.haStar;
        d["cStar"] = src.cStar;
        d["x"] = src.addendumModification;
        d["baseRotation"] = src.baseRotation;
        d["flankSign"] = src.flankMirror;
        d["reverseParam"] = src.reverseParam;
        d["replicateAllTeeth"] = src.replicateAllTeeth;
        d["singleToothIndex"] = (int)src.singleToothIndex;
        return d;
    }

