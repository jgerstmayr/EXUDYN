inline bool MainObjectContactExternalInvolute::CheckPreAssembleConsistency(const MainSystem& mainSystem, STDstring& errorString) const
{
    const auto& params = cObjectContactExternalInvolute->GetParameters();
    if (params.markerNumbers.NumberOfItems() != 2)
    {
        errorString = "ContactExternalInvolute requires exactly two marker numbers";
        return false;
    }
    if (params.gear1Analytic.numberOfTeeth <= 0 || params.gear2Analytic.numberOfTeeth <= 0)
    {
        errorString = "External involute contact requires valid teeth counts for both gear profiles";
        return false;
    }
    return true;
}

