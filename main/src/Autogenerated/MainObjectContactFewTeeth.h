inline bool MainObjectContactFewTeeth::CheckPreAssembleConsistency(const MainSystem& mainSystem, STDstring& errorString) const
{
    const auto& params = cObjectContactFewTeeth->GetParameters();
    if (params.markerNumbers.NumberOfItems() != 2)
    {
        errorString = "ContactFewTeeth requires exactly two marker numbers";
        return false;
    }
    if (params.outerAnalytic.numberOfTeeth <= 0 || params.innerAnalytic.numberOfTeeth <= 0)
    {
        errorString = "Analytic few-teeth contact requires valid teeth counts for both outer and inner profiles";
        return false;
    }
    return true;
}

