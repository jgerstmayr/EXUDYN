//! transform vertex 'in' with modelViewMatrix
//! column-major (openGL version)
inline void TransformVertexCM(const Float3& in, const Matrix4DF& modelViewMatrix, Float3& out)
{
	//openGL is column-major!
	//state->modelRotation.GetDataPointer()
	const float* modelview = modelViewMatrix.GetDataPointer();
	float x = in[0];
	float y = in[1];
	float z = in[2];
	out[0] = modelview[0] * x + modelview[4] * y + modelview[8] * z + modelview[12];
	out[1] = modelview[1] * x + modelview[5] * y + modelview[9] * z + modelview[13];
	out[2] = modelview[2] * x + modelview[6] * y + modelview[10] * z + modelview[14];
}

//! transform vertex 'in' with modelViewMatrix
//! row-major (Exudyn HomogeneousTransformation "compatible")
inline void TransformVertexRM(const Float3& in, const Matrix4DF& modelViewMatrix, Float3& out)
{
	//openGL is column-major!
	//state->modelRotation.GetDataPointer()
	const float* modelview = modelViewMatrix.GetDataPointer();
	float x = in[0];
	float y = in[1];
	float z = in[2];
	out[0] = modelview[0] * x + modelview[1] * y + modelview[2] * z + modelview[3];
	out[1] = modelview[4] * x + modelview[5] * y + modelview[6] * z + modelview[7];
	out[2] = modelview[8] * x + modelview[9] * y + modelview[10] * z + modelview[11];
}

//! transform vertex 'in' with modelViewMatrix to only Z-coordinate
//! column-major version (OpenGL matrix)
inline float TransformVertexZ_CM(const Float3& in, const Matrix4DF& modelViewMatrix)
{
	//state->modelRotation.GetDataPointer()
	const float* modelview = modelViewMatrix.GetDataPointer();
	return modelview[2] * in[0] + modelview[6] * in[1] + modelview[10] * in[2] + modelview[14];
}

