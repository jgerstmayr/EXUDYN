void VisualizationObjectContactCurveCircles::UpdateGraphics(const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemNumber)
{
	Index itemID = Index2ItemID(itemNumber, ItemType::Object, vSystem->GetSystemID());
	Float4 currentColor = visualizationSettings.connectors.defaultColor;
	if (color[0] != -1.f) { currentColor = color; }

	CObjectContactCurveCircles* cItem = (CObjectContactCurveCircles*)vSystem->systemData->GetCObjects()[itemNumber];

	//marker coordinate system:
	Vector3D refPos;
	Matrix3D refRot;
	vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[0]]->GetPosition(*vSystem->systemData, refPos, ConfigurationType::Visualization);
	vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[0]]->GetRotationMatrix(*vSystem->systemData, refRot, ConfigurationType::Visualization);
	refRot = refRot * cItem->GetParameters().rotationMarker0;

	//draw segments:
	Index nSegments = cItem->GetNumberOfSegments();
	const ResizableMatrix& segData = cItem->GetParameters().segmentsData.GetInternalDenseMatrix();
	const ResizableMatrix& polyData = cItem->GetParameters().polynomialData.GetInternalDenseMatrix();

	Float4 contactColor = Float4({ 1.,0.,0.,1. });//red color means contact ...
	Real rDraw = 0.5f * visualizationSettings.connectors.contactPointsDefaultSize;
	Vector3D firstItemPos({ 0,0,0 });

	LinkedDataVector data = ((CNodeData*)cItem->GetCNode(0))->GetVisualizationCoordinateVector();

	if (visualizationSettings.connectors.showContact)
	{
		for (Index jSeg = 0; jSeg < nSegments; jSeg++)
		{
			Vector3D p0base({ segData(jSeg,0), segData(jSeg,1), 0 });
			Vector3D p1base({ segData(jSeg,2), segData(jSeg,3), 0 });
			Vector3D p0 = refPos + refRot * p0base;
			Vector3D p1 = refPos + refRot * p1base;

			Float4* lineColor = &currentColor;
			if (data[jSeg * CObjectContactCurveCircles::nDataVariablesPerSegment + CObjectContactCurveCircles::dataIndexCircle] >= 0)
			{
				lineColor = &contactColor;
			}
			if (polyData.NumberOfColumns() != 0)
			{
				Vector3D pLast = p0;
				Vector3D t = (p1base - p0base);
				Real c = t.GetL2Norm();
				Vector3D n({ -t[1],t[0],0 });
				n.Normalize();
				Real nTile = visualizationSettings.contact.tilingCurves;
				for (Index i = 0; i < visualizationSettings.contact.tilingCurves; i++)
				{
					Real x = c * (Real)(i + 1) / nTile;
					Real y = cItem->ComputePolynomials(x, c, jSeg, polyData);
					Vector3D p = -y*n + EXUstd::LinearInterpolateVector(p0base, p1base, 0, c, x);
					p = refPos + refRot * p;
					vSystem->graphicsData.AddLine(pLast, p, *lineColor, *lineColor, itemID);

					pLast = p;
				}
			}
			else 
			{ 
				vSystem->graphicsData.AddLine(p0, p1, *lineColor, *lineColor, itemID);
			}
			EXUvis::DrawSphere(p0, rDraw, currentColor, vSystem->graphicsData, itemID, visualizationSettings.general.sphereTiling);

			if (jSeg == 0) { firstItemPos = p0; }
			if (jSeg == 0 || jSeg == nSegments - 1)
			{
				EXUvis::DrawSphere(p1, rDraw, currentColor, vSystem->graphicsData, itemID, visualizationSettings.general.sphereTiling);
			}
		}

		for (Index jCircle = 0; jCircle < cItem->GetNumberOfCircles(); jCircle++)
		{
			Vector3D pMarker;
			vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[1+jCircle]]->GetPosition(*vSystem->systemData, pMarker, ConfigurationType::Visualization);
			//note: everything is done in plane of marker0! the distance is measured from the circle marker points to the segments, but in the plane of marker0!!!
			//vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[1 + jCircle]]->GetRotationMatrix(*vSystem->systemData, rotMarker, ConfigurationType::Visualization);
			EXUvis::DrawCircle(pMarker, refRot, cItem->GetParameters().circlesRadii[jCircle], currentColor, vSystem->graphicsData, itemID, visualizationSettings.general.cylinderTiling);
		}
	}

	if (visualizationSettings.connectors.showNumbers) { EXUvis::DrawItemNumber(refPos + refRot * firstItemPos, vSystem, itemID, "", currentColor); }
}





