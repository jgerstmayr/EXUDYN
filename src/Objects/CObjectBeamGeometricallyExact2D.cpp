// Return shape functions N_i(x) for ns = GetNumberOfNodes()
// Linear (2-node): N1 = (L/2 - x)/L, N2 = (L/2 + x)/L
// Quadratic (3-node, nodes at x = {-L/2, 0, L/2}): Lagrange at xi = 2x/L with nodes at xi = {-1,0,1}
ConstSizeVector<CObjectBeamGeometricallyExact2D::maxNNodes> CObjectBeamGeometricallyExact2D::ComputeShapeFunctions(Real x) const
{
    Real L = parameters.physicsLength;
    const Index ns = GetNumberOfNodes();
    ConstSizeVector<CObjectBeamGeometricallyExact2D::maxNNodes> SV(ns);
    if (IsLinear())
    {
        // 2-node linear
        SV[0] = (0.5 * L - x) / L;
        SV[1] = (0.5 * L + x) / L;
    }
    else
    {
        // 3-node quadratic
        const Real xi = 2.0 * x / L; // maps x in [-L/2, L/2] to xi in [-1, 1]
        SV[0] = 0.5 * xi * (xi - 1.0);       // N1
        SV[1] = 1.0 - xi * xi;               // N2
        SV[2] = 0.5 * xi * (xi + 1.0);       // N3
    }
    return SV;
}

// Return dN_i/dx for ns = GetNumberOfNodes()
ConstSizeVector<CObjectBeamGeometricallyExact2D::maxNNodes> CObjectBeamGeometricallyExact2D::ComputeShapeFunctions_x(Real x) const
{
    const Real L = parameters.physicsLength;
    const Index ns = GetNumberOfNodes();
    ConstSizeVector<CObjectBeamGeometricallyExact2D::maxNNodes> SVx(ns);
    if (IsLinear())
    {
        SVx[0] = -1.0 / L;
        SVx[1] = 1.0 / L;
    }
    else
    {
        const Real xi = 2.0 * x / L;
        const Real dxi_dx = 2.0 / L;
        // d/dxi for quadratic:
        // N1 = 0.5*(xi^2 - xi)   => dN1/dxi = xi - 0.5
        // N2 = 1 - xi^2          => dN2/dxi = -2*xi
        // N3 = 0.5*(xi^2 + xi)   => dN3/dxi = xi + 0.5
        SVx[0] = (xi - 0.5) * dxi_dx;
        SVx[1] = (-2.0 * xi) * dxi_dx;
        SVx[2] = (xi + 0.5) * dxi_dx;
    }
    return SVx;
}

//! templated map of element coordinate vector to  [u0,u1,theta0]; works for linear and quadratic
template<class TReal, Index nODE2> SlimVectorBase<TReal, 3> CObjectBeamGeometricallyExact2D::MapCoordinates(const ConstSizeVector<maxNNodes>& SV, const ConstSizeVectorBase<TReal, nODE2>& qBeam) const
{
    SlimVectorBase<TReal, 3> v;
    v[0] = 0;
    v[1] = 0;
    v[2] = 0;
    for (Index i = 0; i < SV.NumberOfItems(); i++)
    {
        v[0] += SV[i] * qBeam[3 * i];
        v[1] += SV[i] * qBeam[3 * i + 1];
        v[2] += SV[i] * qBeam[3 * i + 2];
    }
    return v;
}


//! map element coordinates (position or velocity level) given by nodal vectors q0 and q1 onto compressed shape function vector to compute position, etc.; if SV=SV(x), it returns Vector of coordinates at certain position x: [p0,p1,theta0]
