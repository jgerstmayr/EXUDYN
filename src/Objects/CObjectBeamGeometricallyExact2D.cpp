// Compute mass matrix for ns-node element (each node: 3 DOFs)
void CObjectBeamGeometricallyExact2D::ComputeMassMatrix(EXUmath::MatrixContainer& massMatrixC, const ArrayIndex& ltg, Index objectNumber, bool computeInverse) const
{
    CHECKandTHROW(!computeInverse, "CObjectBeamGeometricallyExact2D::ComputeMassMatrix: computeMassMatrixInversePerBody=True is not possible for this type of element; change solver settings");

    Matrix& massMatrix = massMatrixC.GetInternalDenseMatrix();
    if (massMatrixComputed)
    {
        massMatrix.CopyFrom(precomputedMassMatrix);
    }
    else
    {
        const Index ns = GetNumberOfNodes();
        massMatrix.SetScalarMatrix(GetODE2Size(), 0.0);

        const Real a = -0.5 * parameters.physicsLength;
        const Real b = 0.5 * parameters.physicsLength;
        const Real rhoA = parameters.physicsMassPerLength;
        const Real rhoJ = parameters.physicsCrossSectionInertia;

        ConstSizeVector<3> integrationPoints;
        ConstSizeVector<3> integrationWeights;
        if (IsLinear())
        {
            integrationPoints.CopyFrom(EXUmath::gaussRuleOrder3Points);
            integrationWeights.CopyFrom(EXUmath::gaussRuleOrder3Weights);
        }
        else
        {
            integrationPoints.CopyFrom(EXUmath::gaussRuleOrder5Points);
            integrationWeights.CopyFrom(EXUmath::gaussRuleOrder5Weights);
        }

        Index cnt = 0;
        for (auto item : integrationPoints)
        {
            const Real x = 0.5 * (b - a) * item + 0.5 * (b + a);
            const ConstSizeVector<maxNNodes> SV = ComputeShapeFunctions(x);
            const Real factInt = (0.5 * (b - a) * integrationWeights[cnt++]); // integration factor

            for (Index i = 0; i < ns; ++i)
            {
                for (Index j = 0; j < ns; ++j)
                {
                    massMatrix(i * 3 + 0, j * 3 + 0) += SV[i] * SV[j] * rhoA * factInt;
                    massMatrix(i * 3 + 1, j * 3 + 1) += SV[i] * SV[j] * rhoA * factInt;
                    massMatrix(i * 3 + 2, j * 3 + 2) += SV[i] * SV[j] * rhoJ * factInt;
                }
            }
        }
        precomputedMassMatrix.CopyFrom(massMatrix);
        massMatrixComputed = true;
    }
}


