// Compute strains and variation of strains (delta vectors) for ns-node element
template<class TReal>
void CObjectBeamGeometricallyExact2D::ComputeGeneralizedStrains(Real x, TReal& theta, 
    const ConstSizeVectorBase<TReal, maxODE2coordinates>& qBeamTotal, const ConstSizeVectorBase<TReal, maxODE2coordinates>& qBeam_t,  
    const ConstSizeVectorBase<Real, maxODE2coordinates>& qBeamRef,
    ConstSizeVectorBase<Real,maxNNodes>& SV, ConstSizeVectorBase<Real, maxNNodes>& SV_x,
    TReal& gamma1, TReal& gamma2, TReal& theta_x, TReal& gamma1_t, TReal& gamma2_t, TReal& theta_xt,
    ConstSizeVectorBase<TReal, maxODE2coordinates>& deltaGamma1, ConstSizeVectorBase<TReal, maxODE2coordinates>& deltaGamma2) const
{
    //const Index indRot = 2;
    SV = ComputeShapeFunctions(x);
    SV_x = ComputeShapeFunctions_x(x);

    //const Index ns = GetNumberOfNodes();
    //const Index nodeSize = 3;
    //const Index nODE2 = ns * nodeSize;


    SlimVectorBase<Real, 3> slopeVectorRef = MapCoordinates<Real, maxODE2coordinates>(SV_x, qBeamRef); //Ref: rx_x, ry_x, theta_x
    SlimVectorBase<Real, 3> pRef = MapCoordinates<Real, maxODE2coordinates>(SV, qBeamRef); //Ref: rx, ry, theta

    //adjust reference rotation if requested
    //this allows to connect nodes at arbitrary angles
    theta = 0;
    if (!parameters.includeReferenceRotations)
    {
        theta = atan2(slopeVectorRef[1], slopeVectorRef[0]); //this is the reference rotation at x!
        theta -= pRef[2]; //ideally, we would set pRef[2] to 0 => but it is added in pTotal[2] later! => substract here!
    }

    SlimVectorBase<TReal, 3> pTotal = MapCoordinates<TReal, maxODE2coordinates>(SV, qBeamTotal); //Ref: rx, ry, theta
    theta += pTotal[2]; //theta either computed from reference values or based on slope without reference values
    
    SlimVectorBase<TReal, 3> slopeVectorTotal = MapCoordinates<TReal, maxODE2coordinates>(SV_x, qBeamTotal); //Total: r_x, r_y, theta_x
    TReal u1_x = slopeVectorTotal[0] - slopeVectorRef[0];
    TReal u2_x = slopeVectorTotal[1] - slopeVectorRef[1];
    theta_x = slopeVectorTotal[2] - parameters.physicsReferenceCurvature; //in precurved case, reference values shall not contribute to curvature

    //+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    TReal cosTheta = cos(theta);
    TReal sinTheta = sin(theta);
    const SlimVectorBase<Real, 3>& RS = slopeVectorRef;
    gamma1 = cosTheta * (RS[0] + u1_x - cosTheta) + sinTheta * (RS[1] + u2_x - sinTheta);
    
    TReal termGamma1 = (-sinTheta * (RS[0] + u1_x - cosTheta) + cosTheta * sinTheta + cosTheta * (RS[1] + u2_x - sinTheta) - sinTheta * cosTheta);
    
    gamma2 = -sinTheta * (RS[0] + u1_x - cosTheta) + cosTheta * (RS[1] + u2_x - sinTheta);

    TReal termGamma2 = (-cosTheta * (RS[0] + u1_x - cosTheta) - sinTheta * sinTheta - sinTheta * (RS[1] + u2_x - sinTheta) - cosTheta * cosTheta);


    if (IsLinear())
    {
        deltaGamma1.SetVector({ cosTheta * SV_x[0], sinTheta * SV_x[0], termGamma1 * SV[0],
            cosTheta * SV_x[1], sinTheta * SV_x[1], termGamma1 * SV[1] });

        deltaGamma2.SetVector({ -sinTheta * SV_x[0], cosTheta * SV_x[0], termGamma2 * SV[0],
                -sinTheta * SV_x[1], cosTheta * SV_x[1], termGamma2 * SV[1] });
    }
    else
    {
        deltaGamma1.SetVector({ cosTheta * SV_x[0], sinTheta * SV_x[0], termGamma1 * SV[0],
            cosTheta* SV_x[1], sinTheta* SV_x[1], termGamma1* SV[1],
            cosTheta* SV_x[2], sinTheta* SV_x[2], termGamma1* SV[2]} );

        deltaGamma2.SetVector({ -sinTheta * SV_x[0], cosTheta * SV_x[0], termGamma2 * SV[0],
                -sinTheta * SV_x[1], cosTheta* SV_x[1], termGamma2* SV[1],
                -sinTheta * SV_x[2], cosTheta* SV_x[2], termGamma2* SV[2]} );
    }

    //not always needed, but not costly:
    theta_xt = MapCoordinates<TReal, maxODE2coordinates>(SV_x, qBeam_t)[2]; //Total: r_xt, r_yt, theta_xt
    gamma1_t = deltaGamma1 * qBeam_t;
    gamma2_t = deltaGamma2 * qBeam_t;
}

