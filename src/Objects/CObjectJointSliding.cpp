//! compute the (local) sliding coordinate within the current cable element
Real CObjectJointSliding::ComputeLocalSlidingCoordinate() const
{
	Real slidingPos = GetCurrentAEcoordinate(slidingCoordinateIndex); //this is only the small changed solved in Newton

	Index slidingMarkerIndex = (Index)GetCNode(0)->GetCurrentCoordinate(0); //this contains the current index in the cable marker list; slidingMarkerIndex will always be in valid range!
	slidingPos += GetCNode(0)->GetCurrentCoordinate(1); //this contains the startOfStep value of the sliding coordinate (or initial value); ranges from 0 to total length of sliding cables

	slidingPos -= parameters.slidingMarkerOffsets[slidingMarkerIndex]; //slidingPos now ranges from 0 to L in current cable element

	return slidingPos;
}

//! Computational function: compute algebraic equations and write residual into "algebraicEquations"
void CObjectJointSliding::ComputeAlgebraicEquations(Vector& algebraicEquations, const MarkerDataStructure& markerData, Real t, Index itemIndex, bool velocityLevel) const
{
	//markerData.GetMarkerData(1).vectorValue/_t:cable (refCoordinates+coordinates)/velocities
	//markerData.GetMarkerData(1).GetHelper():cable Length (current cable)
	//markerData.GetMarkerData(0).position:   position on other body (e.g. rigid body or mass point)

	//CObjectJointSliding: contains NodeGenericData: for current Cable marker number in marker list
	// 1 equation: force*slope + forceX = 0
	// 3 equations for force residuum
	// 3 equations for torque residuum
	// 7 alg. unknowns: sliding coordinate, forces, torques

	if (parameters.activeConnector)
	{
		algebraicEquations.SetNumberOfItems(GetAlgebraicEquationsSize());

		Real lBeam = markerData.GetMarkerData(1).GetHelper(); //kind of hack ...
		Real slidingCoordinate = ComputeLocalSlidingCoordinate();
		Vector3D position;
		Vector3D slopeVector, slopeVector_x;
		bool beamHasTorsion;

		//change to:
		//const CMarkerBodyBeamShape& beamMarker = (const CMarkerBodyBeamShape &)cSystemData->GetCMarker(parameters.markerNumbers[1]);
		//beamMarker.ComputeSlidingJointData(slidingCoordinate, lBeam,
		//	markerData.GetMarkerData(1).vectorValue, markerData.GetMarkerData(1).vectorValue_t,
		//	position, slopeVector, slopeVector_x);

		CMarkerBodyBeamShape::ComputeSlidingJointData(slidingCoordinate, lBeam, 
			markerData.GetMarkerData(1).vectorValue, markerData.GetMarkerData(1).vectorValue_t,
			position, slopeVector, slopeVector_x, beamHasTorsion);


		if (velocityLevel)
		{
			CHECKandTHROWstring("CObjectJointSliding::ComputeAlgebraicEquations: velocityLevel not possible now!");
		}

		if (true) //(parameters.classicalFormulation)
		{
			Vector3D vPos = (position - markerData.GetMarkerData(0).position); //this is the difference between the sliding position and the position of marker0

			//TODO: vPos should be transformed into local frame of marker0

			Vector3D force({ GetCurrentAEcoordinate(forcesStartIndex), GetCurrentAEcoordinate(forcesStartIndex+1), GetCurrentAEcoordinate(forcesStartIndex+2) });
			algebraicEquations[slidingCoordinateIndex] = slopeVector * force; //force in sliding direction must be zero
			if (parameters.axialForce != 0)
			{
				algebraicEquations[slidingCoordinateIndex] -= slopeVector.GetL2Norm() * parameters.axialForce;
			}

			for (Index i = 0; i < EXUstd::dim3D; i++)
			{
				algebraicEquations[forcesStartIndex + i] = parameters.constrainTranslations[i] ? vPos[i] : GetCurrentAEcoordinate(forcesStartIndex + i);
			}

		}
		//else //new formulation
		//{
		//	//check SlidingJoint2D
		//}
		CHECKandTHROW(!HasRotationConstraints(), "CObjectJointSliding::ComputeAlgebraicEquations: constrainRotations must be all zero for now!");
		if (HasRotationConstraints())
		{
			CHECKandTHROW(beamHasTorsion || !parameters.constrainRotations[0], "CObjectJointSliding::ComputeAlgebraicEquations: for torsion-free beam elements, constrainRotations[0] must be zero!");

			algebraicEquations[torquesStartIndex + 0] = GetCurrentAEcoordinate(torquesStartIndex);
			if (parameters.constrainRotations[1]) //rotation around y-axis
			{
				Vector3D nZ({
				markerData.GetMarkerData(0).orientation(0,2),
				markerData.GetMarkerData(0).orientation(1,2),
				markerData.GetMarkerData(0).orientation(2,2),
					});
				algebraicEquations[torquesStartIndex + 1] = slopeVector * nZ;
			}
			else
			{
				algebraicEquations[torquesStartIndex + 1] = GetCurrentAEcoordinate(torquesStartIndex + 1);
			}
			if (parameters.constrainRotations[2]) //rotation around z-axis
			{
				Vector3D nY({
					markerData.GetMarkerData(0).orientation(0,1),
					markerData.GetMarkerData(0).orientation(1,1),
					markerData.GetMarkerData(0).orientation(2,1),
					});
				algebraicEquations[torquesStartIndex + 2] = slopeVector * nY;
			}
			else
			{
				algebraicEquations[torquesStartIndex + 2] = GetCurrentAEcoordinate(torquesStartIndex+2);
			}
		}

	}
	else
	{
		algebraicEquations.SetNumberOfItems(GetAlgebraicEquationsSize());
		for (Index i = 0; i < GetAlgebraicEquationsSize(); i++)
		{
			algebraicEquations[i] = GetCurrentAEcoordinate(i);
		}
	}

}


