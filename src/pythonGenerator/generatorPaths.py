import os
import sys


def _Directory(*parts):
    return os.path.normpath(os.path.join(*parts)).replace(os.sep, '/') + '/'


generatorDir = _Directory(os.path.dirname(os.path.abspath(__file__)))
repositoryRoot = _Directory(generatorDir, '..', '..')

generatedDir = generatorDir + 'generated/'              #intermediate files between generators
autogeneratedDir = repositoryRoot + 'src/Autogenerated/'
theDocDir = repositoryRoot + 'docs/theDoc/'
rstDir = repositoryRoot + 'docs/RST/'
pythonDir = repositoryRoot + 'python/'
pythonPackageDir = pythonDir + 'exudyn/'
testModelsDir = pythonDir + 'TestModels/'
examplesDir = pythonDir + 'Examples/'
toolsGeneratorsDir = repositoryRoot + 'tools/generators/'

if toolsGeneratorsDir not in sys.path:
    sys.path.append(toolsGeneratorsDir)
