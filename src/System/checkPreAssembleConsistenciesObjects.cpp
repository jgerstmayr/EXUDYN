bool MainObjectConnectorReevingSystemSprings::CheckPreAssembleConsistency(const MainSystem& mainSystem, STDstring& errorString) const
{
	CObjectConnectorReevingSystemSprings* cObject = (CObjectConnectorReevingSystemSprings*)GetCObject();

	Index hasCoordinateMarkers = (Index)cObject->GetParameters().hasCoordinateMarkers;
	Index nRigidBodyMarkers = cObject->GetParameters().markerNumbers.NumberOfItems() - 2 * hasCoordinateMarkers;

	if (nRigidBodyMarkers < 2)
	{
		if (hasCoordinateMarkers)
		{
			errorString = "CObjectConnectorReevingSystemSprings: has " + EXUstd::ToString(nRigidBodyMarkers) + 
				" markers, but the minimum is 4 (2 rigid body markers and 2 coordinate markers)";
		}
		else
		{
			errorString = "CObjectConnectorReevingSystemSprings: has " + EXUstd::ToString(nRigidBodyMarkers) +
				" rigid body markers, but the minimum is 2";
		}
		return false;

	}

	Index npa = cObject->GetParameters().sheavesAxes.NumberOfItems();
	if (nRigidBodyMarkers != npa)
	{
		errorString = "CObjectConnectorReevingSystemSprings: number of rigid body markers is " + EXUstd::ToString(nRigidBodyMarkers);
		if (hasCoordinateMarkers) { errorString += " (note that two additional markers are expected to be coordinate markers)"; }
		errorString += ", but the number of sheavesAxes is different (" + EXUstd::ToString(npa) + ")";
		return false;
	}

	for (Index i = 0; i < npa; i++)
	{
		Vector3D v = cObject->GetParameters().sheavesAxes[i];
		if (fabs(v.GetL2Norm() - 1.) > toleranceNorm)
		{
			errorString = "CObjectConnectorReevingSystemSprings: axis " + EXUstd::ToString(i) +
				" in sheavesAxes has length which is considerably different from 1, which is not possible";
			return false;
		}
	}

    if (cObject->GetParameters().regularizationForce == 0.)
    {
        errorString = "CObjectConnectorReevingSystemSprings: regularizationForce may not be zero";
        return false;
    }


	Index npr = cObject->GetParameters().sheavesRadii.NumberOfItems();
	if (nRigidBodyMarkers != npr)
	{
		errorString = "CObjectConnectorReevingSystemSprings: number of rigid body markers is " + EXUstd::ToString(nRigidBodyMarkers);
		if (hasCoordinateMarkers) { errorString += " (note that two additional markers are expected to be coordinate markers)"; }
		errorString += ", but the number of sheavesRadii is different (" + EXUstd::ToString(npr) + ")";
		return false;
	}

	//check number of marker types
	const ArrayIndex& nMarkers = cObject->GetMarkerNumbers();
	for (Index i = 0; i < nRigidBodyMarkers; i++)
	{
		const CMarker& marker = mainSystem.GetCSystem().GetSystemData().GetCMarker(nMarkers[i]);

		if (!EXUstd::IsOfTypeAndNotNone((Index)marker.GetType(),(Index)Marker::Position + (Index)Marker::Orientation))
		{
			errorString = "CObjectConnectorReevingSystemSprings: marker " + EXUstd::ToString(i) + " must be a rigid body marker";
			return false;
		}
	}

	for (Index i = 0; i < 2* hasCoordinateMarkers; i++)
	{
		const CMarker& marker = mainSystem.GetCSystem().GetSystemData().GetCMarker(nMarkers[nRigidBodyMarkers + i]);

		if (!EXUstd::IsOfTypeAndNotNone(marker.GetType(), Marker::Coordinate))
		{
			errorString = "CObjectConnectorReevingSystemSprings: marker " + EXUstd::ToString(i) + " must be a coordinate marker; because hasCoordinateMarkers=True, the last two markers in markerNumbers are expected to provide coordinates";
			return false;
		}
	}

	return true;
}


