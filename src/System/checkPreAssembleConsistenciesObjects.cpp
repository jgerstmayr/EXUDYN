bool MainObjectContactCylinderCylinder::CheckPreAssembleConsistency(const MainSystem& mainSystem, STDstring& errorString) const
{
	const CObjectContactCylinderCylinder* cObject = (const CObjectContactCylinderCylinder*)GetCObject();
	const auto& parameters = cObject->GetParameters();
	for (Index i = 0; i < 2; i++)
	{
		if (!(parameters.cylindersRadii[i] > 0.) || !(parameters.cylindersLengths[i] > 0.))
		{
			errorString = "ObjectContactCylinderCylinder: cylindersRadii and cylindersLengths must be > 0 (found: radii " +
				EXUstd::ToString(parameters.cylindersRadii) + ", lengths " + EXUstd::ToString(parameters.cylindersLengths) + ")";
			return false;
		}
	}
	if (parameters.isHollowCylinder1 && !(parameters.cylindersRadii[0] <= parameters.cylindersRadii[1]))
	{
		errorString = "ObjectContactCylinderCylinder: with isHollowCylinder1, cylinder 0 is inside cylinder 1, so cylindersRadii[0] must not be larger than cylindersRadii[1] (found " +
			EXUstd::ToString(parameters.cylindersRadii) + ")";
		return false;
	}
	return CheckPreAssembleContactCylinder(mainSystem, cObject, "ObjectContactCylinderCylinder", errorString);
}

bool MainObjectContactCylinderTriangle::CheckPreAssembleConsistency(const MainSystem& mainSystem, STDstring& errorString) const
{
	const CObjectContactCylinderTriangle* cObject = (const CObjectContactCylinderTriangle*)GetCObject();
	const auto& points = cObject->GetParameters().trianglePoints;
	if (points.NumberOfItems() != 3)
	{
		errorString = "ObjectContactCylinderTriangle: trianglePoints must have 3 points (found: " + EXUstd::ToString(points.NumberOfItems()) + ")";
		return false;
	}
	Vector3D v1 = points[1] - points[0];
	Vector3D v2 = points[2] - points[0];
	if (!(v1.CrossProduct(v2).GetL2Norm() > 1e-12 * v1.GetL2Norm() * v2.GetL2Norm()))
	{
		errorString = "ObjectContactCylinderTriangle: the trianglePoints lie on a line or coincide; the triangle needs an area";
		return false;
	}
	return CheckPreAssembleContactCylinder(mainSystem, cObject, "ObjectContactCylinderTriangle", errorString);
}


//! the points and triangles of a convex shape: rows of 3, indices in range, every point on the inner side of every
//! triangle (convex, outward normals) (#3331)
bool CheckConvexShape(const Matrix& points, const MatrixI& triangles, const STDstring& name, STDstring& errorString)
{
	STDstring itemName = "ObjectContactConvexConvex: ";
	if (points.NumberOfRows() < 1 || points.NumberOfColumns() != 3)
	{
		errorString = itemName + "points" + name + " must be rows of 3 coordinates, at least one (found " +
			EXUstd::ToString(points.NumberOfRows()) + " x " + EXUstd::ToString(points.NumberOfColumns()) + ")";
		return false;
	}
	if (triangles.NumberOfRows() != 0 && triangles.NumberOfColumns() != 3)
	{
		errorString = itemName + "triangles" + name + " must be rows of 3 indices (found " + EXUstd::ToString(triangles.NumberOfColumns()) + " columns)";
		return false;
	}
	Real size = 0.;
	for (Index i = 0; i < points.NumberOfRows(); i++)
	{
		size = EXUstd::Maximum(size, Vector3D({ points(i, 0), points(i, 1), points(i, 2) }).GetL2Norm());
	}
	for (Index t = 0; t < triangles.NumberOfRows(); t++)
	{
		Vector3D p[3];
		for (Index k = 0; k < 3; k++)
		{
			Index index = triangles(t, k);
			if (index < 0 || index >= points.NumberOfRows())
			{
				errorString = itemName + "triangle " + EXUstd::ToString(t) + " of triangles" + name + " has the index " + EXUstd::ToString(index) +
					", but points" + name + " has " + EXUstd::ToString(points.NumberOfRows()) + " points";
				return false;
			}
			p[k] = Vector3D({ points(index, 0), points(index, 1), points(index, 2) });
		}
		Vector3D normal = (p[1] - p[0]).CrossProduct(p[2] - p[0]);
		if (!(normal.GetL2Norm() > 1e-14 * size * size))
		{
			errorString = itemName + "triangle " + EXUstd::ToString(t) + " of triangles" + name + " has no area";
			return false;
		}
		normal.Normalize();
		for (Index i = 0; i < points.NumberOfRows(); i++)
		{
			if (normal * (Vector3D({ points(i, 0), points(i, 1), points(i, 2) }) - p[0]) > 1e-8 * size)
			{
				errorString = itemName + "point " + EXUstd::ToString(i) + " of points" + name + " lies outside triangle " + EXUstd::ToString(t) +
					" of triangles" + name + ": the shape must be convex, and the order of the points of each triangle must give the normal out of the shape";
				return false;
			}
		}
	}
	return true;
}

