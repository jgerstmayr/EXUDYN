//the shape and coordinate markers of cables compute with the element's own shape functions: only the
//elements named can serve them (#2731)
static bool BodyIsOneOf(const MainSystem& mainSystem, Index bodyNumber, const std::vector<STDstring>& typeNames,
	const char* markerName, STDstring& errorString)
{
	STDstring typeName = mainSystem.GetMainSystemData().GetMainObjects()[bodyNumber]->GetTypeName();
	STDstring names;
	for (const STDstring& name : typeNames)
	{
		if (typeName == name) { return true; }
		names += (names.size() ? " or Object" : "Object") + name;
	}
	errorString = STDstring(markerName) + ": body number " + EXUstd::ToString(bodyNumber) + " must be an " + names +
		", but it is an Object" + typeName;
	return false;
}

