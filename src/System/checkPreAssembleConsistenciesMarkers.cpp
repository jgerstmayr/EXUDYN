//the relative coordinate markers compute with the position (and orientation) Jacobians of their two bodies;
//as coordinate markers they are not checked for them in CSystem::CheckSystemIntegrity (#2731)
static bool BodiesProvideRigidBodyAccess(const MainSystem& mainSystem, const ArrayIndex& bodyNumbers, bool needsOrientation0,
	bool needsOrientation1, const char* markerName, STDstring& errorString)
{
	for (Index i = 0; i < 2; i++)
	{
		const CObject* cObject = mainSystem.GetMainSystemData().GetMainObjects()[bodyNumbers[i]]->GetCObject();
		AccessFunctionType afType = cObject->GetAccessFunctionTypes();
		bool needsOrientation = (i == 0) ? needsOrientation0 : needsOrientation1;
		if (!EXUstd::IsOfType(afType, AccessFunctionType::TranslationalVelocity_qt) || EXUstd::IsOfType(afType, AccessFunctionType::OwnMarkersOnly) ||
			(needsOrientation && !EXUstd::IsOfType(afType, AccessFunctionType::AngularVelocity_qt)))
		{
			errorString = STDstring(markerName) + ": body " + EXUstd::ToString(i) + " (object number " + EXUstd::ToString(bodyNumbers[i]) +
				") must provide position" + (needsOrientation ? " and orientation" : "") + " at a local point, as a rigid body or mass point does";
			return false;
		}
	}
	return true;
}

