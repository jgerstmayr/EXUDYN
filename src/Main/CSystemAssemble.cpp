//! build ltg-coordinate lists for objects (used to build system ODE2RHS, MassMatrix, etc. vectors and matrices) 
//! and store special object lists (body, connector, constraint, ...)
void CSystem::AssembleLTGLists(const MainSystem& mainSystem)
{
	//pout << "Assemble LTG Lists\n";

	//build system-wide local to global lists for objects:
	ObjectContainer<ArrayIndex>& listODE2 = cSystemData.GetLocalToGlobalODE2();
	ObjectContainer<ArrayIndex>& listODE1 = cSystemData.GetLocalToGlobalODE1();
	ObjectContainer<ArrayIndex>& listAE = cSystemData.GetLocalToGlobalAE();
	ObjectContainer<ArrayIndex>& listData = cSystemData.GetLocalToGlobalData();
	listODE2.Flush();
	listODE1.Flush();
	listAE.Flush();
	listData.Flush();

	ObjectContainer<ArrayIndex>& listODE2numDiff = cSystemData.GetLocalToGlobalODE2NumDiff();
	listODE2numDiff.Flush();
	ObjectContainer<ArrayIndex>& listODE1numDiff = cSystemData.GetLocalToGlobalODE1NumDiff();
	listODE1numDiff.Flush();

    //reset load dependencies :
    cSystemData.GetLoadsODE2dependencies().Flush();
    cSystemData.GetLoadsODE1dependencies().Flush();
    cSystemData.GetLoadsAEdependencies().Flush();
    cSystemData.LoadsDependenciesInitialized() = false;

	//temporary lists per object:
	ArrayIndex ltgListODE2;
	ArrayIndex ltgListODE1;
	ArrayIndex ltgListAE;
	ArrayIndex ltgListData;

	ArrayIndex ltgListODE2numDiff;

	//compute localToGlobalODE2 coordinate indices
	for (Index i = 0; i < cSystemData.GetCObjects().NumberOfItems(); i++)
	{
		AssembleObjectLTGLists(i, ltgListODE2, ltgListODE1, ltgListAE, ltgListData);

		listODE2.Append(ltgListODE2);
		listODE1.Append(ltgListODE1);
		listAE.Append(ltgListAE);
		listData.Append(ltgListData);

		//the lists for numerical differentiation contain each coordinate once, as an object may address a
		//coordinate twice (two markers on the same node or object); AE does not use numDiff (#1424)
		for (Index k = 0; k < 2; k++)
		{
			ArrayIndex& ltgList = (k == 0) ? ltgListODE2 : ltgListODE1;
			ltgListODE2numDiff = ltgList;
			EXUstd::QuickSort(ltgListODE2numDiff); //additional overhead, but should not be too time critical!
			ltgList.SetNumberOfItems(0); //new list without duplicates

			//first item always added
			if (ltgListODE2numDiff.NumberOfItems() != 0) { ltgList.Append(ltgListODE2numDiff[0]); }

			//add only non-duplicates:
			for (Index j = 1; j < ltgListODE2numDiff.NumberOfItems(); j++)
			{
				if (ltgListODE2numDiff[j] != ltgListODE2numDiff[j - 1])
				{
					ltgList.Append(ltgListODE2numDiff[j]);
				}
			}
			((k == 0) ? listODE2numDiff : listODE1numDiff).Append(ltgList);
		}
	}
	//pout << "local to global ODE2 Indices:\n" << listODE2 << "\n\n";
	//pout << "local to global ODE1 Indices:\n" << listODE1 << "\n\n";
	//pout << "local to global AE Indices:\n" << listAE << "\n\n";
	//pout << "local to global Data Indices:\n" << listData << "\n\n";

	PreComputeItemLists();
	InitLieGroupLists();
}


//! build ltg-coordinate lists for object with 'objectIndex' and set indices in ltg lists
void CSystem::AssembleObjectLTGLists(Index objectIndex, ArrayIndex& ltgListODE2, ArrayIndex& ltgListODE1,
	ArrayIndex& ltgListAE, ArrayIndex& ltgListData)
{
	ltgListODE2.SetNumberOfItems(0);
	ltgListODE1.SetNumberOfItems(0);
	ltgListAE.SetNumberOfItems(0);
	ltgListData.SetNumberOfItems(0);

	CObject* object = cSystemData.GetCObjects()[objectIndex];

	//body not necessary here, works for all objects: if ((Index)object->GetType() & (Index)CObjectType::Body) //single and multinoded objects
	if (!EXUstd::IsOfType(object->GetType(), CObjectType::Connector))
	{
		//CObjectBody* objectBody = (CObjectBody*)object;

		//bool algebraicEquationsInNodes = false;
		//node-based elements (bodies, finite elements, ...)
		//for (Index nodeNumber : objectBody->GetCNode())
		for (Index j = 0; j < object->GetNumberOfNodes(); j++)
		{
			CNode* node = object->GetCNode(j);
			if (node->GetNumberOfODE2Coordinates())
			{
				Index gIndex = node->GetGlobalODE2CoordinateIndex();
				for (Index i = 0; i < node->GetNumberOfODE2Coordinates(); i++)
				{
					ltgListODE2.Append(gIndex + i);
				}
			}
			if (node->GetNumberOfODE1Coordinates())
			{
				Index gIndex = node->GetGlobalODE1CoordinateIndex();
				for (Index i = 0; i < node->GetNumberOfODE1Coordinates(); i++)
				{
					ltgListODE1.Append(gIndex + i);
				}
			}
			if (node->GetNumberOfAECoordinates()) //this is for algebraic nodes (e.g. Euler Parameters); but constraint equation handled by node!
			{
				Index gIndex = node->GetGlobalAECoordinateIndex();
				for (Index i = 0; i < node->GetNumberOfAECoordinates(); i++)
				{
					ltgListAE.Append(gIndex + i);
				}
			}
			if (node->GetNumberOfDataCoordinates()) //data/history variables - contact, friction, plasticity
			{
				Index gIndex = node->GetGlobalDataCoordinateIndex();
				for (Index i = 0; i < node->GetNumberOfDataCoordinates(); i++)
				{
					ltgListData.Append(gIndex + i);
				}
			}
		}
	}
	else
	{
		CObjectConnector* connector = (CObjectConnector*)object;

		//connector may also contain Data nodes
		for (Index j = 0; j < connector->GetNumberOfNodes(); j++)
		{
			CNode* node = connector->GetCNode(j);
			if (node->GetNumberOfDataCoordinates()) //data/history variables - contact, friction, plasticity
			{
				Index gIndex = node->GetGlobalDataCoordinateIndex();
				for (Index i = 0; i < node->GetNumberOfDataCoordinates(); i++)
				{
					ltgListData.Append(gIndex + i);
				}
			}
			if (node->GetNumberOfODE1Coordinates()) //controller: integrator; generic object with ODE1 coordinates
			{
				Index gIndex = node->GetGlobalODE1CoordinateIndex();
				for (Index i = 0; i < node->GetNumberOfODE1Coordinates(); i++)
				{
					ltgListODE1.Append(gIndex + i);
				}
			}
		}

		//+++++++++++++++++++++++++++++++++++++++
		//process markers --> they have associated coordinates
		for (Index markerNumber : connector->GetMarkerNumbers())
		{
			cSystemData.ComputeMarkerODE2LTGarray(markerNumber, ltgListODE2, false);

			cSystemData.ComputeMarkerODE1DataLTGarray(markerNumber, ltgListODE1, ltgListData, false);
		}

		//+++++++++++++++++++++++++++++++++++++++
		//now process algebraic equations of connector (algebraic variables are treated earlier!)
		//this is because LAGRANGE MULTIPLIERS DO NOT REQUIRE NODES
		if ((Index)object->GetType() & (Index)CObjectType::Constraint)
		{
			CObjectConstraint* constraint = (CObjectConstraint*)object;
			//build ltg-list directly from connector

			Index gIndex = constraint->GetGlobalAECoordinateIndex();
			for (Index i = 0; i < constraint->GetAlgebraicEquationsSize(); i++)
			{
				ltgListAE.Append(gIndex + i);
			}
		}
	}
	//else
	//{
	//	pout << "ERROR: ObjectType Nr. " << (Index)object->GetType() << " not implemented in CSystem::AssembleLTGLists!\n";
	//}

	//pout << "ltgODE1=" << ltgListODE1 << "\n";
	//pout << "ltgAE=" << ltgListAE << "\n";
}

//! true, if one of the user functions must be computed in the main thread (#2978)
static bool UserFunctionsInMainThread(const ResizableArray<const UserFunctionBase*>& functions)
{
	for (const UserFunctionBase* function : functions)
	{
		if (!function->ComputableInThreads()) { return true; }
	}
	return false;
}

//! the items computed in the main thread (#2978): those with a user function that cannot be computed in the threads -
//! a Python function, which holds the GIL, or a symbolic one without a flat program -, and those that compute the
//! access functions of such an item: the objects on such a node, the markers on such a node or object, the
//! connectors and loads on such a marker; the same dependencies as of the drawing in the main thread (#3003)
static void ComputeMainThreadItems(const CSystemData& data, std::vector<bool>& mainThreadObjects, std::vector<bool>& mainThreadLoads)
{
	Index nNodes = data.GetCNodes().NumberOfItems();
	Index nObjects = data.GetCObjects().NumberOfItems();
	Index nMarkers = data.GetCMarkers().NumberOfItems();
	Index nLoads = data.GetCLoads().NumberOfItems();
	std::vector<bool> mainThreadNodes(nNodes, false);
	std::vector<bool> mainThreadMarkers(nMarkers, false);
	mainThreadObjects.assign(nObjects, false);
	mainThreadLoads.assign(nLoads, false);

	ResizableArray<const UserFunctionBase*> functions;
	for (Index i = 0; i < nNodes; i++)
	{
		functions.SetNumberOfItems(0);
		data.GetCNodes()[i]->GetUserFunctions(functions);
		mainThreadNodes[i] = UserFunctionsInMainThread(functions);
	}
	for (Index i = 0; i < nObjects; i++)
	{
		const CObject* object = data.GetCObjects()[i];
		functions.SetNumberOfItems(0);
		object->GetUserFunctions(functions);
		//a user function the generated list does not name, of an item written by hand: in the main thread
		mainThreadObjects[i] = UserFunctionsInMainThread(functions) || (functions.NumberOfItems() == 0 && object->HasUserFunction());
		for (Index k = 0; k < object->GetNumberOfNodes() && !mainThreadObjects[i]; k++)
		{
			Index node = object->GetNodeNumber(k);
			mainThreadObjects[i] = (node >= 0 && node < nNodes && mainThreadNodes[node]);
		}
	}
	for (Index i = 0; i < nMarkers; i++)
	{
		const CMarker* marker = data.GetCMarkers()[i];
		functions.SetNumberOfItems(0);
		marker->GetUserFunctions(functions);
		if (UserFunctionsInMainThread(functions)) { mainThreadMarkers[i] = true; } //MarkerBodyUser
		else if (marker->GetType() & (Marker::Body + Marker::Object)) //a marker on one object
		{
			Index objectNumber = marker->GetObjectNumber();
			mainThreadMarkers[i] = (objectNumber >= 0 && objectNumber < nObjects && mainThreadObjects[objectNumber]);
		}
		else if (marker->GetType() & Marker::Node) //a marker on one node
		{
			Index nodeNumber = marker->GetNodeNumber();
			mainThreadMarkers[i] = (nodeNumber >= 0 && nodeNumber < nNodes && mainThreadNodes[nodeNumber]);
		}
	}
	for (Index i = 0; i < nObjects; i++) //the connectors and joints on these markers
	{
		const CObject* object = data.GetCObjects()[i];
		if (EXUstd::IsOfType(object->GetType(), CObjectType::Connector))
		{
			for (Index marker : ((const CObjectConnector*)object)->GetMarkerNumbers())
			{
				if (marker >= 0 && marker < nMarkers && mainThreadMarkers[marker]) { mainThreadObjects[i] = true; }
			}
		}
	}
	for (Index i = 0; i < nLoads; i++)
	{
		const CLoad* load = data.GetCLoads()[i];
		functions.SetNumberOfItems(0);
		load->GetUserFunctions(functions);
		Index marker = load->GetMarkerNumber();
		mainThreadLoads[i] = UserFunctionsInMainThread(functions) || (functions.NumberOfItems() == 0 && load->HasUserFunction())
			|| (marker >= 0 && marker < nMarkers && mainThreadMarkers[marker]);
	}
}

//! the copies of the symbolic user functions of the items for numberOfThreads threads (#2978)
static void PrepareUserFunctionsForThreads(const ResizableArray<const UserFunctionBase*>& functions, Index numberOfThreads)
{
	for (const UserFunctionBase* function : functions) { function->PrepareThreads(numberOfThreads); }
}

//! before the computation of the items: the lists and the copies of the user functions for the threads, then the
//! states that the objects share with their markers, so that the parallel loops only read them (#3229)
void CSystem::PreComputeItems()
{
	UpdateUserFunctionsForThreads();
	for (Index i : cSystemData.listPreComputeObjects) { cSystemData.GetCObjects()[i]->PreCompute(); }
}

void CSystem::UpdateUserFunctionsForThreads()
{
	Index nThreads = ExuThreading::TaskManager::GetNumThreads();
	if (nThreads <= 1) { return; }
	if (userFunctionAssignmentsOfLists != UserFunctionAssignmentCount()) { PreComputeItemLists(); }
	if (threadsOfUserFunctions >= nThreads) { return; }

	ResizableArray<const UserFunctionBase*> functions;
	for (const CNode* node : cSystemData.GetCNodes()) { functions.SetNumberOfItems(0); node->GetUserFunctions(functions); PrepareUserFunctionsForThreads(functions, nThreads); }
	for (const CObject* object : cSystemData.GetCObjects()) { functions.SetNumberOfItems(0); object->GetUserFunctions(functions); PrepareUserFunctionsForThreads(functions, nThreads); }
	for (const CMarker* marker : cSystemData.GetCMarkers()) { functions.SetNumberOfItems(0); marker->GetUserFunctions(functions); PrepareUserFunctionsForThreads(functions, nThreads); }
	for (const CLoad* load : cSystemData.GetCLoads()) { functions.SetNumberOfItems(0); load->GetUserFunctions(functions); PrepareUserFunctionsForThreads(functions, nThreads); }
	threadsOfUserFunctions = nThreads;
}

