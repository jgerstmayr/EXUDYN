py::array_t<uint8_t> MainRenderer::RedrawAndGetImage(bool useRaytracer, Index viewID)
{
	VisualizationSystemContainer& VSC = mainSystemContainer->GetVisualizationSystemContainer();
	RenderViewDataVSC& RVD = VSC.GetRenderViewData(viewID);

	//pout << "RedrawAndGetImage: useRaytracer=" << useRaytracer << "\n";
	if (!useRaytracer)
	{
		ViewDisabledError(viewID, "RedrawAndGetImage");
		RendererInActiveError("RedrawAndGetImage");
		RVD.saveImageAsData = true;
		VSC.RedrawAndSaveImage(viewID);
		RVD.saveImageAsData = false;
		return py::array_t<uint8_t>({ RVD.imageDataSize[1], RVD.imageDataSize[0], 3 }, //height, width, channels
			RVD.imageData.GetDataPointer());
	}
	else
	{
		if (!IsActive()) { VSC.InitializeRenderState(true, true); } //if first call to inactive renderer->initialize RenderState
		ViewDisabledError(viewID, "RedrawAndGetImage");

		//to adjust view, renderState can be used!
		RenderStateMachine stateMachine;
		stateMachine.Reset();

		//get up to date visualization state
		for (MainSystem* mainSystem : mainSystemContainer->GetMainSystems())
		{
			mainSystem->GetCSystem().UpdatePostProcessData();
		}

		VSC.UpdateGraphicsDataNow();
		VSC.UpdateGraphicsData();

		raytracer.SoftwareRenderer(viewID, &VSC, stateMachine, true, true); //storeImage=true

		return py::array_t<uint8_t>({ RVD.imageDataSize[1], RVD.imageDataSize[0], 3 }, //height, width, channels
			RVD.imageData.GetDataPointer());

	}
}

//! the item that drew a primitive as [system, itemType, itemIndex]; an ID that names no item - a
