//! restore the render state that exudyn.sys holds
bool MainRenderer::RestoreSavedState(Index viewID)
{
	//the key is the one PyStopOpenGLRenderer writes when the renderer stops: the main
	//view under "renderState", every other view under "renderState<viewID>"
	STDstring key = "renderState";
	if (viewID != VisualizationSystemContainer::mainViewID) { key += EXUstd::ToString(viewID); }

	py::dict systemVariables = py::module::import("exudyn").attr("sys");
	//NOTHING SAVED IS NOT AN ERROR: the first run of a script has no state, which is the
	//case the two Python lines this function replaces were guarding against
	if (!systemVariables.contains(key.c_str())) { return false; }

	SetState(py::cast<py::dict>(systemVariables[key.c_str()]), false, viewID);
	return true;
}

//! set render state dictionary
void MainRenderer::SetState(py::dict renderState, bool waitForRendererFullStartup, Index viewID)
{
	ViewDisabledError(viewID, "SetState");

	VisualizationSystemContainer& VSC = mainSystemContainer->GetVisualizationSystemContainer();
	RenderViewDataVSC& RVD = VSC.GetRenderViewData(viewID);

	if (!IsActive()) { VSC.InitializeRenderState(true, true); } //if first call to inactive renderer->initialize RenderState

	RenderState& state = RVD.renderState;
	try
	{
		if (waitForRendererFullStartup && EXUstd::compiledwithGLFW)
		{
			//to wait for image to have finished
			Index waitCnt = 0;
			while (!PyGetRendererUpdateCount() && waitCnt++ < 100) //this is equivalent to timeout of 2 seconds
			{
				PyDoRendererIdleTasks(0.02, false); //shortly wait to complete rendering
			}
		}


		if (renderState.contains("centerPoint"))
		{
			EPyUtils::FromPython(renderState["centerPoint"], state.centerPoint); //conversion to float works ...
		}
		if (renderState.contains("rotationCenterPoint"))
		{
			EPyUtils::FromPython(renderState["rotationCenterPoint"], state.rotationCenterPoint);
		}
		if (renderState.contains("maxSceneSize")) { state.maxSceneSize = py::cast<float>(renderState["maxSceneSize"]); }
		if (renderState.contains("zoom")) { state.zoom = py::cast<float>(renderState["zoom"]); }
		if (renderState.contains("displayScaling")) { state.displayScaling = py::cast<float>(renderState["displayScaling"]); }

		if (renderState.contains("currentWindowSize"))
		{
			Vector2D windowSize;
			EPyUtils::FromPython(renderState["currentWindowSize"], windowSize); //no effect when changing; maybe changes in future
			state.currentWindowSize[0] = (Index)windowSize[0];
			state.currentWindowSize[1] = (Index)windowSize[1];
			GetSettingsView(viewID, VSC.GetVisualizationSettings()).window.renderWindowSize = state.currentWindowSize;
		}
		if (renderState.contains("modelRotation"))
		{
			//check if all parts of modelRotation (translation part) shall be modified?
			Matrix4DF& A = state.modelRotation;
			Matrix3D R;
			EPyUtils::Conversion::NumpyToMatrix<Real>(renderState["modelRotation"], R);
			//map rotation matrix to part of 16 components in A; other components untouched!
			for (Index i = 0; i < 3; i++)
			{
				for (Index j = 0; j < 3; j++)
				{
					A(i, j) = (float)R(i, j);
				}
			}
		}

		//++++++++++++++++++++++++++++++++++++++++++++
		//current projection matrix:
		if (renderState.contains("projectionMatrix"))
		{
			Matrix4D m;
			EPyUtils::Conversion::NumpyToMatrix<Real>(renderState["projectionMatrix"], m);
			state.projectionMatrix.CopyFrom(m);
		}
		//++++++++++++++++++++++++++++++++++++++++++++

		if (renderState.contains("mouseSelectionMbsNumber"))
		{
			state.mouseSelectionMbsNumber = py::cast<Index>(renderState["mouseSelectionMbsNumber"]);
		}
		if (renderState.contains("mouseSelectionItemType"))
		{
			state.mouseSelectionItemType = py::cast<ItemType>(renderState["mouseSelectionItemType"]);
		}
		if (renderState.contains("mouseSelectionItemID"))
		{
			state.mouseSelectionItemID = py::cast<Index>(renderState["mouseSelectionItemID"]);
		}
		if (renderState.contains("mouseSelectionZdepth"))
		{
			state.mouseSelectionZdepth = py::cast<float>(renderState["mouseSelectionZdepth"]);
		}

	}
	catch (const EXUexception& ex)
	{
		SysError("EXUDYN raised internal error in SetRenderState(...):\n" + STDstring(ex.what()) + "\nCheck dictionary format.\n");
	}
	catch (...) //any other exception
	{
		SysError("Unexpected exception during SetRenderState(...)! Check dictionary format.\n");
	}
}

//! get OpenGL coordinates as list, faster than using render state
py::list MainRenderer::GetMouseCoordinates(bool useOpenGLcoordinates, Index viewID) const
{
	ViewDisabledError(viewID, "GetMouseCoordinates");

	RendererInActiveError("GetMouseCoordinates");
	if (!useOpenGLcoordinates)
	{
		return py::cast((std::array<Real, 2>)(mainSystemContainer->GetVisualizationSystemContainer().GetRenderViewData(viewID).renderState.mouseCoordinates));
	}
	else
	{
		return py::cast((std::array<Real, 2>)(mainSystemContainer->GetVisualizationSystemContainer().GetRenderViewData(viewID).renderState.openGLcoordinates));
	}
}

//! get info about item selection and reset selection if flag is set true
py::list MainRenderer::GetItemSelection(bool resetSelection, Index viewID)
{
	RendererInActiveError("GetItemSelection");
	ViewDisabledError(viewID, "GetItemSelection");

	RenderState& state = mainSystemContainer->GetVisualizationSystemContainer().GetRenderViewData(viewID).renderState;
	auto itemSelection = py::list();
	itemSelection.append(state.mouseSelectionMbsNumber);
	itemSelection.append(state.mouseSelectionItemType);
	itemSelection.append(state.mouseSelectionItemID);
	itemSelection.append(state.mouseSelectionZdepth);

	if (resetSelection) 
	{
		state.mouseSelectionMbsNumber = 0;
		state.mouseSelectionItemType = ItemType::_None;
		state.mouseSelectionItemID = 0;
		state.mouseSelectionZdepth = 0.f;
	}

	return itemSelection;
}


