//! a numpy array H x W, H x W x 1, H x W x 3 or H x W x 4 of uint8 or of floats in [0,1] into the store (#3029); the
//! channels converted to those of the interpretation and the rows from the bottom of the image, so that v=0 is its bottom
//! allowReserved: the textures of Exudyn itself, named 'exudyn.', e.g. by graphics.CheckerBoard (#3036)
void PyAddTexture(const STDstring& name, const py::object& image, TextureInterpretation interpretation,
	Index flags, bool allowReserved)
{
	if (name.size() == 0) { PyError("renderer.AddTexture: the name must not be empty", PyErrorType::valueError); }
	if (!allowReserved && name.rfind("exudyn.", 0) == 0) { PyError("renderer.AddTexture: names starting with 'exudyn.' are reserved for the textures of Exudyn; got '" + name + "'", PyErrorType::valueError); }
	py::array array = py::array::ensure(image);
	if (!array) { PyError("renderer.AddTexture: the image must be a numpy array or a nested list of numbers", PyErrorType::typeError); }
	if (array.ndim() != 2 && array.ndim() != 3) { PyError("renderer.AddTexture: the image must have the shape (height, width) or (height, width, channels), but has " + EXUstd::ToString((Index)array.ndim()) + " dimensions", PyErrorType::valueError); }
	Index height = (Index)array.shape(0);
	Index width = (Index)array.shape(1);
	Index channels = array.ndim() == 3 ? (Index)array.shape(2) : 1;
	if (height == 0 || width == 0) { PyError("renderer.AddTexture: the image is empty", PyErrorType::valueError); }
	if (channels != 1 && channels != 3 && channels != 4) { PyError("renderer.AddTexture: the image must have 1, 3 or 4 channels, but has " + EXUstd::ToString(channels), PyErrorType::valueError); }
	if (interpretation == TextureInterpretation::Grey && channels != 1) { PyError("renderer.AddTexture: TextureInterpretation.Grey needs an image with one channel, but it has " + EXUstd::ToString(channels) + "; convert the colors to brightness first", PyErrorType::valueError); }

	//the pixels as bytes, row by row from the top, with the channels of the image
	std::vector<unsigned char> pixels((size_t)(height * width * channels));
	char kind = array.dtype().kind();
	if (py::isinstance<py::array_t<uint8_t>>(array))
	{
		py::array_t<uint8_t, py::array::c_style | py::array::forcecast> bytes(array);
		std::copy(bytes.data(), bytes.data() + pixels.size(), pixels.begin());
	}
	else if (kind == 'f' || kind == 'i' || kind == 'u' || kind == 'b')
	{
		py::array_t<double, py::array::c_style | py::array::forcecast> values(array);
		const double* value = values.data();
		for (size_t i = 0; i < pixels.size(); i++)
		{
			if (!(value[i] >= 0. && value[i] <= 1.)) { PyError("renderer.AddTexture: an image of floats must have values in [0, 1], but has " + EXUstd::ToString(value[i]) + "; an image of uint8 has values in [0, 255]", PyErrorType::valueError); }
			pixels[i] = (unsigned char)std::lround(value[i] * 255.);
		}
	}
	else { PyError("renderer.AddTexture: the image must be of numbers, uint8 or floats in [0, 1]", PyErrorType::typeError); }

	const Index allFlags = (Index)TextureFlags::Nearest | (Index)TextureFlags::Clamp | (Index)TextureFlags::Replace;
	if (flags < 0 || (flags & ~allFlags) != 0) { PyError("renderer.AddTexture: flags must be TextureFlags combined with |, or 0, but got " + EXUstd::ToString(flags), PyErrorType::valueError); }
	Index flagBits = flags;

	Index targetChannels = Texture::Channels(interpretation);
	std::vector<unsigned char> data((size_t)(height * width * targetChannels));
	for (Index row = 0; row < height; row++)
	{
		const unsigned char* source = &pixels[(size_t)((height - 1 - row) * width * channels)];
		unsigned char* target = &data[(size_t)(row * width * targetChannels)];
		for (Index column = 0; column < width; column++, source += channels, target += targetChannels)
		{
			for (Index k = 0; k < targetChannels; k++)
			{
				if (k == 3) { target[k] = channels == 4 ? source[3] : 255; } //no alpha: opaque
				else { target[k] = channels == 1 ? source[0] : source[k]; } //grey: equal R, G and B
			}
		}
	}
	textureStore.Set(name, width, height, interpretation, flagBits, std::move(data));
}

