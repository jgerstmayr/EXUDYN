//! the image as AddTexture takes it: uint8, (height, width) for one channel and (height, width, channels) otherwise,
//! the first row at the top; the interpretation by its name, e.g. 'RGB', so that the dict can be saved as a file
py::dict PyGetTexture(const STDstring& name)
{
	Index id = textureStore.GetID(name);
	if (id == -1) { PyError("renderer.GetTexture: no texture has the name '" + name + "'", PyErrorType::valueError); }
	Texture texture = textureStore.GetCopy(id);
	std::vector<py::ssize_t> shape = { (py::ssize_t)texture.height, (py::ssize_t)texture.width };
	if (texture.channels != 1) { shape.push_back((py::ssize_t)texture.channels); }
	py::array_t<uint8_t> image(shape);
	const size_t rowSize = (size_t)(texture.width * texture.channels);
	for (Index row = 0; row < texture.height; row++) //the store holds the rows from the bottom
	{
		const unsigned char* source = texture.data.data() + (size_t)(texture.height - 1 - row) * rowSize;
		std::copy(source, source + rowSize, image.mutable_data() + (size_t)row * rowSize);
	}
	py::dict d;
	d["name"] = name;
	d["image"] = image;
	d["interpretation"] = EXUstd::ToString(texture.interpretation);
	d["flags"] = texture.flags;
	return d;
}

void PySetTexture(const py::object& textureDict)
{
	if (!py::isinstance<py::dict>(textureDict)) { PyError("SetTexture: a texture must be a dict with the keys name, image, interpretation and flags, as renderer.GetTexture gives it", PyErrorType::typeError); }
	py::dict d = py::reinterpret_borrow<py::dict>(textureDict);
	for (const char* key : { "name", "image", "interpretation", "flags" })
	{
		if (!d.contains(key)) { PyError(STDstring("SetTexture: the dict of a texture has no key '") + key + "'; the keys are name, image, interpretation and flags", PyErrorType::valueError); }
	}
	STDstring interpretationName = py::str(d["interpretation"]);
	if (interpretationName.rfind("TextureInterpretation.", 0) == 0) { interpretationName = interpretationName.substr(22); } //also the enum itself
	for (TextureInterpretation interpretation : { TextureInterpretation::Grey, TextureInterpretation::RGB, TextureInterpretation::RGBA, TextureInterpretation::RGBAMask })
	{
		if (EXUstd::ToString(interpretation) == interpretationName)
		{
			PyAddTexture(py::str(d["name"]), d["image"], interpretation, py::cast<Index>(d["flags"]), true);
			return;
		}
	}
	PyError("SetTexture: unknown interpretation '" + interpretationName + "'; it is Grey, RGB, RGBA or RGBAMask", PyErrorType::valueError);
}

py::list PyGetTextures()
{
	py::list textures;
	for (const STDstring& name : textureStore.GetNames()) { textures.append(PyGetTexture(name)); }
	return textures;
}

py::array_t<uint8_t> MainRenderer::RedrawAndGetImage(bool useRaytracer, Index viewID)
{
	VisualizationSystemContainer& VSC = mainSystemContainer->GetVisualizationSystemContainer();
	RenderViewDataVSC& RVD = VSC.GetRenderViewData(viewID);

	//pout << "RedrawAndGetImage: useRaytracer=" << useRaytracer << "\n";
	if (!useRaytracer)
	{
		ViewDisabledError(viewID, "RedrawAndGetImage");
		RendererInActiveError("RedrawAndGetImage");
		RVD.saveImageAsData = true;
		VSC.RedrawAndSaveImage(viewID);
		RVD.saveImageAsData = false;
		return py::array_t<uint8_t>({ RVD.imageDataSize[1], RVD.imageDataSize[0], 3 }, //height, width, channels
			RVD.imageData.GetDataPointer());
	}
	else
	{
		if (!IsActive()) { VSC.InitializeRenderState(true, true); } //if first call to inactive renderer->initialize RenderState
		ViewDisabledError(viewID, "RedrawAndGetImage");

		//to adjust view, renderState can be used!
		RenderStateMachine stateMachine;
		stateMachine.Reset();

		//get up to date visualization state
		for (MainSystem* mainSystem : mainSystemContainer->GetMainSystems())
		{
			mainSystem->GetCSystem().UpdatePostProcessData();
		}

		VSC.UpdateGraphicsDataNow();
		VSC.UpdateGraphicsData();

		raytracer.SoftwareRenderer(viewID, &VSC, stateMachine, true, true); //storeImage=true

		return py::array_t<uint8_t>({ RVD.imageDataSize[1], RVD.imageDataSize[0], 3 }, //height, width, channels
			RVD.imageData.GetDataPointer());

	}
}

//! the item that drew a primitive as [system, itemType, itemIndex]; an ID that names no item - a
//! static object of the scene - is [-1, 0, ID], so the kind of static object stays visible
inline void GraphicsDataItem(Index itemID, int* item)
{
	if (itemID < 0)
	{
		item[0] = -1; item[1] = (int)ItemType::_None; item[2] = (int)itemID;
		return;
	}
	Index index; ItemType type; Index mbsNumber;
	ItemID2IndexType(itemID, index, type, mbsNumber);
	item[0] = (int)mbsNumber; item[1] = (int)type; item[2] = (int)index;
}

//! the drawing elements of the scene as numpy arrays (#2700). The graphics data is built the way
//! RedrawAndGetImage(useRaytracer=True) builds it, so no window and no OpenGL is needed; nothing that
//! depends on a window - zoom, model view, screen size - is part of it. The 6-node triangles and quadratic
//! lines as they are, or with flatShapes by one fixed refinement among the flat ones (#2709)
py::dict MainRenderer::GetGraphicsData(bool flatShapes)
{
	VisualizationSystemContainer& VSC = mainSystemContainer->GetVisualizationSystemContainer();

	for (MainSystem* mainSystem : mainSystemContainer->GetMainSystems())
	{
		mainSystem->GetCSystem().UpdatePostProcessData();
	}
	VSC.UpdateGraphicsDataNow();
	VSC.UpdateGraphicsData();

	const ResizableArray<GraphicsData*>& list = VSC.GetGraphicsDataList();
	{
		//a running renderer may hold a lock while it waits for the GIL in a graphics user function
		py::gil_scoped_release release;
		for (auto data : list) { data->LockData(); }
	}

	//flat: each 6-node triangle into the 4 triangles on its nodes, each quadratic line into 2 lines - independent of the
	//tiling settings, which only the renderers apply (#2709)
	std::vector<ResizableArray<GLTriangle>> trianglesRefined(list.NumberOfItems());
	std::vector<ResizableArray<GLLine>> linesRefined(list.NumberOfItems());
	py::ssize_t nLines = 0, nSpheres = 0, nCircles = 0, nTexts = 0, nTriangles = 0, nTriangles6 = 0, nLines3 = 0;
	for (Index i = 0; i < list.NumberOfItems(); i++)
	{
		if (flatShapes)
		{
			for (const GLTriangle6& triangle : list[i]->glTriangles6) { EXUvis::SplitTriangle6Uniform(triangle, 2, trianglesRefined[i]); }
			for (const GLLine3& line : list[i]->glLines3) { EXUvis::SplitLine3Uniform(line, 2, linesRefined[i]); }
			nTriangles += trianglesRefined[i].NumberOfItems();
			nLines += linesRefined[i].NumberOfItems();
		}
		else
		{
			nTriangles6 += list[i]->glTriangles6.NumberOfItems();
			nLines3 += list[i]->glLines3.NumberOfItems();
		}
	}
	for (auto data : list)
	{
		nLines += data->glLines.NumberOfItems();
		nSpheres += data->glSpheres.NumberOfItems();
		nCircles += data->glCirclesXY.NumberOfItems();
		nTexts += data->glTexts.NumberOfItems();
		nTriangles += data->glTriangles.NumberOfItems();
	}

	py::array_t<int> lineItems({ nLines, (py::ssize_t)3 });
	py::array_t<float> linePoints({ nLines, (py::ssize_t)2, (py::ssize_t)3 });
	py::array_t<float> lineColors({ nLines, (py::ssize_t)2, (py::ssize_t)4 });
	py::array_t<int> sphereItems({ nSpheres, (py::ssize_t)3 });
	py::array_t<float> spherePoints({ nSpheres, (py::ssize_t)3 });
	py::array_t<float> sphereColors({ nSpheres, (py::ssize_t)4 });
	py::array_t<float> sphereRadii(nSpheres);
	py::array_t<int> sphereResolutions(nSpheres);
	py::array_t<int> circleItems({ nCircles, (py::ssize_t)3 });
	py::array_t<float> circlePoints({ nCircles, (py::ssize_t)3 });
	py::array_t<float> circleColors({ nCircles, (py::ssize_t)4 });
	py::array_t<float> circleRadii(nCircles);
	py::array_t<int> circleSegments(nCircles);
	py::array_t<int> textItems({ nTexts, (py::ssize_t)3 });
	py::array_t<float> textPoints({ nTexts, (py::ssize_t)3 });
	py::array_t<float> textColors({ nTexts, (py::ssize_t)4 });
	py::array_t<float> textFontSizes(nTexts);
	py::array_t<float> textOffsets({ nTexts, (py::ssize_t)2 });
	py::list textStrings;
	py::array_t<int> triangleItems({ nTriangles, (py::ssize_t)3 });
	py::array_t<float> trianglePoints({ nTriangles, (py::ssize_t)3, (py::ssize_t)3 });
	py::array_t<float> triangleNormals({ nTriangles, (py::ssize_t)3, (py::ssize_t)3 });
	py::array_t<float> triangleColors({ nTriangles, (py::ssize_t)3, (py::ssize_t)4 });
	py::array_t<int> triangle6Items({ nTriangles6, (py::ssize_t)3 });
	py::array_t<float> triangle6Points({ nTriangles6, (py::ssize_t)6, (py::ssize_t)3 });
	py::array_t<float> triangle6Normals({ nTriangles6, (py::ssize_t)6, (py::ssize_t)3 });
	py::array_t<float> triangle6Colors({ nTriangles6, (py::ssize_t)6, (py::ssize_t)4 });
	py::array_t<int> line3Items({ nLines3, (py::ssize_t)3 });
	py::array_t<float> line3Points({ nLines3, (py::ssize_t)3, (py::ssize_t)3 });
	py::array_t<float> line3Colors({ nLines3, (py::ssize_t)3, (py::ssize_t)4 });

	auto li = lineItems.mutable_unchecked<2>(); auto lp = linePoints.mutable_unchecked<3>(); auto lc = lineColors.mutable_unchecked<3>();
	auto si = sphereItems.mutable_unchecked<2>(); auto sp = spherePoints.mutable_unchecked<2>(); auto sc = sphereColors.mutable_unchecked<2>();
	auto sr = sphereRadii.mutable_unchecked<1>(); auto sres = sphereResolutions.mutable_unchecked<1>();
	auto ci = circleItems.mutable_unchecked<2>(); auto cp = circlePoints.mutable_unchecked<2>(); auto cc = circleColors.mutable_unchecked<2>();
	auto cr = circleRadii.mutable_unchecked<1>(); auto cs = circleSegments.mutable_unchecked<1>();
	auto ti = textItems.mutable_unchecked<2>(); auto tp = textPoints.mutable_unchecked<2>(); auto tc = textColors.mutable_unchecked<2>();
	auto tf = textFontSizes.mutable_unchecked<1>(); auto to = textOffsets.mutable_unchecked<2>();
	auto gi = triangleItems.mutable_unchecked<2>(); auto gp = trianglePoints.mutable_unchecked<3>();
	auto gn = triangleNormals.mutable_unchecked<3>(); auto gc = triangleColors.mutable_unchecked<3>();
	auto hi = triangle6Items.mutable_unchecked<2>(); auto hp = triangle6Points.mutable_unchecked<3>();
	auto hn = triangle6Normals.mutable_unchecked<3>(); auto hc = triangle6Colors.mutable_unchecked<3>();
	auto qi = line3Items.mutable_unchecked<2>(); auto qp = line3Points.mutable_unchecked<3>(); auto qc = line3Colors.mutable_unchecked<3>();

	py::ssize_t iLine = 0, iSphere = 0, iCircle = 0, iText = 0, iTriangle = 0, iTriangle6 = 0, iLine3 = 0;
	int item[3];
	Index iData = 0;
	std::array<Float3, 6> nodeNormals;
	for (auto data : list)
	{
		for (const ResizableArray<GLLine>* lineList : { &data->glLines, &linesRefined[iData] })
		for (const GLLine& line : *lineList)
		{
			GraphicsDataItem(line.itemID, item);
			for (Index k = 0; k < 3; k++) { li(iLine, k) = item[k]; lp(iLine, 0, k) = line.point1[k]; lp(iLine, 1, k) = line.point2[k]; }
			for (Index k = 0; k < 4; k++) { lc(iLine, 0, k) = line.color1[k]; lc(iLine, 1, k) = line.color2[k]; }
			iLine++;
		}
		for (const GLSphere& sphere : data->glSpheres)
		{
			GraphicsDataItem(sphere.itemID, item);
			for (Index k = 0; k < 3; k++) { si(iSphere, k) = item[k]; sp(iSphere, k) = sphere.point[k]; }
			for (Index k = 0; k < 4; k++) { sc(iSphere, k) = sphere.color[k]; }
			sr(iSphere) = sphere.radius;
			sres(iSphere) = (int)EXUvis::SphereResolution(sphere, VSC.GetVisualizationSettings()); //as drawn (#2877)
			iSphere++;
		}
		for (const GLCircleXY& circle : data->glCirclesXY)
		{
			GraphicsDataItem(circle.itemID, item);
			for (Index k = 0; k < 3; k++) { ci(iCircle, k) = item[k]; cp(iCircle, k) = circle.point[k]; }
			for (Index k = 0; k < 4; k++) { cc(iCircle, k) = circle.color[k]; }
			cr(iCircle) = circle.radius;
			cs(iCircle) = (int)circle.numberOfSegments;
			iCircle++;
		}
		for (const GLText& text : data->glTexts)
		{
			GraphicsDataItem(text.itemID, item);
			for (Index k = 0; k < 3; k++) { ti(iText, k) = item[k]; tp(iText, k) = text.point[k]; }
			for (Index k = 0; k < 4; k++) { tc(iText, k) = text.color[k]; }
			tf(iText) = text.fontSize;
			to(iText, 0) = text.offsetX;
			to(iText, 1) = text.offsetY;
			textStrings.append(py::str(text.text != nullptr ? text.text : ""));
			iText++;
		}
		for (const ResizableArray<GLTriangle>* triangleList : { &data->glTriangles, &trianglesRefined[iData] })
		for (const GLTriangle& trig : *triangleList)
		{
			GraphicsDataItem(trig.itemID, item);
			for (Index k = 0; k < 3; k++) { gi(iTriangle, k) = item[k]; }
			for (Index j = 0; j < 3; j++)
			{
				for (Index k = 0; k < 3; k++) { gp(iTriangle, j, k) = trig.points[j][k]; gn(iTriangle, j, k) = trig.normals[j][k]; }
				for (Index k = 0; k < 4; k++) { gc(iTriangle, j, k) = trig.colors[j][k]; }
			}
			iTriangle++;
		}
		if (!flatShapes)
		{
			for (const GLTriangle6& trig : data->glTriangles6)
			{
				GraphicsDataItem(trig.itemID, item);
				EXUvis::Triangle6NodeNormals(trig, nodeNormals); //the given ones, else those of the geometry
				for (Index k = 0; k < 3; k++) { hi(iTriangle6, k) = item[k]; }
				for (Index j = 0; j < 6; j++)
				{
					for (Index k = 0; k < 3; k++) { hp(iTriangle6, j, k) = trig.points[j][k]; hn(iTriangle6, j, k) = nodeNormals[j][k]; }
					for (Index k = 0; k < 4; k++) { hc(iTriangle6, j, k) = trig.colors[j][k]; }
				}
				iTriangle6++;
			}
			for (const GLLine3& line : data->glLines3)
			{
				GraphicsDataItem(line.itemID, item);
				for (Index k = 0; k < 3; k++) { qi(iLine3, k) = item[k]; }
				for (Index j = 0; j < 3; j++)
				{
					for (Index k = 0; k < 3; k++) { qp(iLine3, j, k) = line.points[j][k]; }
					for (Index k = 0; k < 4; k++) { qc(iLine3, j, k) = line.colors[j][k]; }
				}
				iLine3++;
			}
		}
		iData++;
	}

	//the textured triangles with the name of their texture and their texture coordinates (#3030)
	py::ssize_t nTextured = 0;
	for (auto data : list) { nTextured += data->glTexturedTriangles.NumberOfItems(); }
	py::array_t<int> texturedItems({ nTextured, (py::ssize_t)3 });
	py::array_t<float> texturedPoints({ nTextured, (py::ssize_t)3, (py::ssize_t)3 });
	py::array_t<float> texturedNormals({ nTextured, (py::ssize_t)3, (py::ssize_t)3 });
	py::array_t<float> texturedColors({ nTextured, (py::ssize_t)3, (py::ssize_t)4 });
	py::array_t<float> texturedCoordinates({ nTextured, (py::ssize_t)3, (py::ssize_t)2 });
	py::list textureNames;
	{
		auto xi = texturedItems.mutable_unchecked<2>(); auto xp = texturedPoints.mutable_unchecked<3>();
		auto xn = texturedNormals.mutable_unchecked<3>(); auto xc = texturedColors.mutable_unchecked<3>();
		auto xt = texturedCoordinates.mutable_unchecked<3>();
		py::ssize_t iTextured = 0;
		for (auto data : list)
		{
			for (const GLTexturedTriangle& trig : data->glTexturedTriangles)
			{
				GraphicsDataItem(trig.itemID, item);
				for (Index k = 0; k < 3; k++) { xi(iTextured, k) = item[k]; }
				for (Index j = 0; j < 3; j++)
				{
					for (Index k = 0; k < 3; k++) { xp(iTextured, j, k) = trig.points[j][k]; xn(iTextured, j, k) = trig.normals[j][k]; }
					for (Index k = 0; k < 4; k++) { xc(iTextured, j, k) = trig.colors[j][k]; }
					for (Index k = 0; k < 2; k++) { xt(iTextured, j, k) = trig.textureCoordinates[j][k]; }
				}
				textureNames.append(py::str(textureStore.GetName(trig.textureID)));
				iTextured++;
			}
		}
	}
	for (auto data : list) { data->ClearLock(); }

	py::dict lines, spheres, circles, texts, triangles;
	lines["items"] = lineItems; lines["points"] = linePoints; lines["colors"] = lineColors;
	spheres["items"] = sphereItems; spheres["points"] = spherePoints; spheres["colors"] = sphereColors;
	spheres["radius"] = sphereRadii; spheres["resolution"] = sphereResolutions;
	circles["items"] = circleItems; circles["points"] = circlePoints; circles["colors"] = circleColors;
	circles["radius"] = circleRadii; circles["numberOfSegments"] = circleSegments;
	texts["items"] = textItems; texts["points"] = textPoints; texts["colors"] = textColors;
	texts["fontSize"] = textFontSizes; texts["offset"] = textOffsets; texts["text"] = textStrings;
	triangles["items"] = triangleItems; triangles["points"] = trianglePoints;
	triangles["normals"] = triangleNormals; triangles["colors"] = triangleColors;
	py::dict triangles6, lines3;
	triangles6["items"] = triangle6Items; triangles6["points"] = triangle6Points;
	triangles6["normals"] = triangle6Normals; triangles6["colors"] = triangle6Colors;
	lines3["items"] = line3Items; lines3["points"] = line3Points; lines3["colors"] = line3Colors;
	py::dict texturedTriangles;
	texturedTriangles["items"] = texturedItems; texturedTriangles["points"] = texturedPoints;
	texturedTriangles["normals"] = texturedNormals; texturedTriangles["colors"] = texturedColors;
	texturedTriangles["textureCoordinates"] = texturedCoordinates; texturedTriangles["texture"] = textureNames;

	py::dict d;
	d["formatVersion"] = 1;
	d["lines"] = lines;
	d["spheres"] = spheres;
	d["circles"] = circles;
	d["texts"] = texts;
	d["triangles"] = triangles;
	d["triangles6"] = triangles6;
	d["lines3"] = lines3;
	d["texturedTriangles"] = texturedTriangles;
	return d;
}

//! add subview which is either only activated (for raytracing), or activated and visible
void MainRenderer::EnableView(Index viewID, bool createWindow)
{
	if (!EXUstd::IndexIsInRange(viewID, 1, MAX_VIEWS_GLFW))
	{
		PyError(STDstring("renderer.EnableView: viewID must lie in range 1..") + EXUstd::ToString(MAX_VIEWS_GLFW - 1)+"; main view 0 can only be enabled with renderer.Start()", PyErrorType::valueError);
	}

	VisualizationSystemContainer& VSC = mainSystemContainer->GetVisualizationSystemContainer();
	RenderViewDataVSC& RVD = VSC.GetRenderViewData(viewID);

	RVD.renderState.viewEnabled = true;

	if (createWindow)
	{
		if (!IsActive())
		{
			PyError("renderer.EnableView: renderer is not yet active; in case of createWindow=True, main view 0 has to be started first with renderer.Start()!", PyErrorType::modelError);
		}

		PyOpenViewWindow(viewID); //sets flag for GLFWClient thread to create window; further states only set when window is created!
	}
}

//! remove/close subview
void MainRenderer::DisableView(Index viewID)
{
	VisualizationSystemContainer& VSC = mainSystemContainer->GetVisualizationSystemContainer();
	RenderViewDataVSC& RVD = VSC.GetRenderViewData(viewID);

	ViewDisabledError(viewID, "DisableView");

	if (IsActive())
	{
		PyCloseViewWindow(viewID); //also changes renderState
	}
	else
	{
		RVD.renderState.viewEnabled = true; //without renderer
	}

}

