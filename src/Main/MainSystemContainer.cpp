//! send zoom all request for next scene redraw:
void MainRenderer::ZoomAll(bool computeMaxScene, Index viewID)
{
	ViewDisabledError(viewID, "ZoomAll");
	if (IsActive())
	{
		mainSystemContainer->GetVisualizationSystemContainer().GetRenderViewData(viewID).zoomAllRequest = true;
	}
	else //in this case, compute max scene (this is not allowed if renderer is active!)
	{
		VisualizationSystemContainer& VSC = mainSystemContainer->GetVisualizationSystemContainer();
		RenderViewDataVSC& RVD = VSC.GetRenderViewData(viewID);
		VSC.InitializeRenderState(true, true); //if first call to inactive renderer->initialize RenderState

		if (computeMaxScene)
		{
			//get up to date visualization state
			for (MainSystem* mainSystem : mainSystemContainer->GetMainSystems())
			{
				mainSystem->GetCSystem().UpdatePostProcessData();
			}

			VSC.UpdateGraphicsDataNow();
			VSC.UpdateGraphicsData();
			RVD.renderState.ComputeMaxSceneSize(VSC.GetVisualizationSettings(), &VSC.GetGraphicsDataList());
		}

		RVD.renderState.ComputeZoomAll(VSC.GetVisualizationSettings());
		//std::cout << "ZoomAll-inactive: zoom=" << VSC.GetRenderState().zoom << "\n";
	}
}

void MainRenderer::SetModelView(float zoom, const std::vector<Real>& rotationVector, const std::vector<Real>& centerPoint, Index viewID)
{
	ViewDisabledError(viewID, "SetModelView");

	VisualizationSystemContainer& VSC = mainSystemContainer->GetVisualizationSystemContainer();
	RenderViewDataVSC& RVD = VSC.GetRenderViewData(viewID);

	if (!IsActive() && RVD.renderState.validInitialization) //if not yet initialized, we also have to compute max scene size!
	{ 
		//VSC.InitializeRenderState(true, true); 
		ZoomAll(); //in fact, we only need to compute max scene size; zoom will then be overwritten ...
	} //if first call to inactive renderer->initialize RenderState

	RVD.renderState.zoom = zoom;

	CHECKandTHROW(centerPoint.size() == 3, "renderer.SetModelView: centerPoint must be a list of numpy array with 3 floats", ExudynValueError);
	CHECKandTHROW(rotationVector.size() == 3, "renderer.SetModelView: rotationVector must be a list of numpy array with 3 floats", ExudynValueError);

	RVD.renderState.centerPoint[0] = (float)centerPoint[0];
	RVD.renderState.centerPoint[1] = (float)centerPoint[1];
	RVD.renderState.centerPoint[2] = (float)centerPoint[2];

	Vector3D rot(rotationVector);

	Matrix3D Rot = EXUlie::ExpSO3(-rot); //transposed!

	Matrix4DF& MV = RVD.renderState.modelRotation;
	//MV.SetAll(1.f); //MV is already initialized!

	for (Index i = 0; i < 3; i++)
	{
		for (Index j = 0; j < 3; j++)
		{
			MV(i, j) = (float)Rot(i, j);
		}
	}
}

