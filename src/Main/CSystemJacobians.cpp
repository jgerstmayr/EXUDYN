//! the analytic ODE2 Jacobian of object j, factorODE2 d(LHS)/dq + factorODE2_t d(LHS)/dq_t, into temp.jacobianODE2Container:
//! its own (ComputeJacobianODE2_ODE2), or for a connector the one on the interface or on the path of the marker data; false
//! if it has none, then the caller differentiates numerically; used by
//! JacobianODE2RHS and mbs.ComputeItem (#2782)
bool CSystem::ComputeObjectJacobianODE2(TemporaryComputationData& temp, const NumericalDifferentiationSettings& numDiff, Index j,
	Real factorODE2, Real factorODE2_t)
{
	CObject* object = cSystemData.GetCObjects()[j];
	ArrayIndex& ltgODE2 = cSystemData.GetLocalToGlobalODE2()[j];
	JacobianType::Type jacType = object->GetAvailableJacobians();
	if (!(jacType & (JacobianType::ODE2_ODE2 + JacobianType::ODE2_ODE2_t + JacobianType::ODE2_ODE1))) { return false; } //no ODE2 dependency
	if ((jacType & (JacobianType::ODE2_ODE2_function + JacobianType::ODE2_ODE2_t_function)) == 0) { return false; }

	return object->ComputeLocalJacobianODE2(cSystemData, temp, numDiff, factorODE2, factorODE2_t, ltgODE2); //the object's own (#3201)
}


//! the local Jacobian of the ODE2 rows of object j (#3201): by the ODE2 coordinates and velocities the object's own -
//! analytic, automatic, on the connector interface (ComputeObjectJacobianODE2) - or else by numerical differentiation of
//! its LHS, with the Lie group nodes apart; by the ODE1 coordinates the object's own (ComputeJacobianODE2_ODE1) or else
//! numerical (#3143); the blocks in temp as local says
bool CSystem::ComputeLocalJacobianODE2(TemporaryComputationData& temp, const NumericalDifferentiationSettings& numDiff, Index j,
	Real factorODE2, Real factorODE2_t, Real factorODE1, LocalJacobian& local, bool analyticOnly)
{
	local = LocalJacobian();
	CObject* object = cSystemData.GetCObjects()[j];
	JacobianType::Type jacType = object->GetAvailableJacobians();
	if (!object->IsActive() || !(jacType & (JacobianType::ODE2_ODE2 + JacobianType::ODE2_ODE2_t + JacobianType::ODE2_ODE1))) { return false; }
	//a connector on the markers of a kinematic tree computes in the temporaries of the tree, so it is computed serially (#3229)
	if (analyticOnly && EXUstd::IsOfType(object->GetType(), CObjectType::Connector))
	{
		for (Index marker : ((const CObjectConnector*)object)->GetMarkerNumbers())
		{
			if (cSystemData.GetCMarkers()[marker]->GetType() & Marker::KinematicTree) { local.deferred = true; return false; }
		}
	}

	Vector& x = cSystemData.GetCData().currentState.ODE2Coords;			//current coordinates ==> this is what is differentiated for
	Vector& xRef = cSystemData.GetCData().referenceState.ODE2Coords;	//reference coordinates; might be important for numerical differentiation
	Vector& x_t = cSystemData.GetCData().currentState.ODE2Coords_t;		//for diff w.r.t. velocities
	Vector& xODE1 = cSystemData.GetCData().currentState.ODE1Coords;
	Vector& xRefODE1 = cSystemData.GetCData().referenceState.ODE1Coords;
	Vector emptyXRef; //for NumDiff template

	ResizableVector& f0 = temp.numericalJacobianf0;
	ResizableVector& f1 = temp.numericalJacobianf1;
	Index nLocalODE2 = cSystemData.GetLocalToGlobalODE2()[j].NumberOfItems();
	bool diffODE1 = (factorODE1 != 0.) && (jacType & JacobianType::ODE2_ODE1);

	//the block by the ODE1 coordinates, numerical: f0 is the LHS of the object at the current state
	auto NumericalODE1 = [&]()
	{
		ArrayIndex& ltgODE1 = cSystemData.GetLocalToGlobalODE1NumDiff()[j]; //columns without duplicates (#1424)
		temp.localJacobianODE1.SetNumberOfRowsAndColumns(nLocalODE2, ltgODE1.NumberOfItems()); //fully computed, needs no initialization
		AddNumDiffObject(numDiff, factorODE1, xODE1, xRefODE1, temp.localJacobianODE1, f0, f1, ltgODE1,
			[this, &temp, &object, &f1]
		{
			ComputeObjectODE2LHS(temp, object, f1);
		}, true); //true=set values
		local.ode1 = LocalJacobian::numerical;
	};

	if (analyticOnly && diffODE1 && !(jacType & JacobianType::ODE2_ODE1_function)) { local.deferred = true; return false; }

	//the object's own Jacobian, if it has one
	if (ComputeObjectJacobianODE2(temp, numDiff, j, -factorODE2, -factorODE2_t)) //minus (-): RHS = -LHS
	{
		local.ode2 = LocalJacobian::analytic;
		if (diffODE1 && (jacType & JacobianType::ODE2_ODE1_function))
		{
			object->ComputeJacobianODE2_ODE1(cSystemData, temp, temp.localJacobianODE1);
			local.ode1 = LocalJacobian::analytic;
		}
		else if (diffODE1)
		{
			f0.SetNumberOfItems(nLocalODE2);
			f1.SetNumberOfItems(nLocalODE2);
			if (ComputeObjectODE2LHS(temp, object, f0)) { NumericalODE1(); }
		}
		return true;
	}

	//else numerical differentiation
	if (analyticOnly) { local.deferred = true; return false; }
	ArrayIndex& ltgODE2numDiff = cSystemData.GetLocalToGlobalODE2NumDiff()[j]; //a possibly shorter list without duplicates
	f0.SetNumberOfItems(nLocalODE2); //size also correct for ODE1 derivatives
	f1.SetNumberOfItems(nLocalODE2);
	if (!ComputeObjectODE2LHS(temp, object, f0)) { return false; }

	ResizableMatrix& localJacobian = temp.localJacobian;
	localJacobian.SetNumberOfRowsAndColumns(nLocalODE2, ltgODE2numDiff.NumberOfItems()); //fully computed, needs no initialization
	if (factorODE2 != 0.)
	{
		SetNumDiffObjectLieGroup(numDiff, factorODE2, x, xRef, localJacobian, f0, f1, ltgODE2numDiff, cSystemData,
			[this, &temp, &object, &f1]
		{
			ComputeObjectODE2LHS(temp, object, f1);
		});
	}
	else { localJacobian.SetAll(0.); }

	if (factorODE2_t != 0. && EXUstd::IsOfType(jacType, JacobianType::ODE2_ODE2_t))
	{
		AddNumDiffObject(numDiff, factorODE2_t, x_t, emptyXRef, localJacobian, f0, f1, ltgODE2numDiff,
			[this, &temp, &object, &f1]
		{
			ComputeObjectODE2LHS(temp, object, f1);
		});
	}
	local.ode2 = LocalJacobian::numerical;

	if (diffODE1) { NumericalODE1(); }
	return true;
}

//! add the blocks of ComputeLocalJacobianODE2 of object j to the system Jacobian (#3201)
void CSystem::AddLocalJacobianODE2(TemporaryComputationData& temp, Index j, Real factorODE1, const LocalJacobian& local,
	GeneralMatrix& jacobianGM)
{
	ArrayIndex& ltgODE2 = cSystemData.GetLocalToGlobalODE2()[j];
	Index nODE2 = cSystemData.GetNumberOfCoordinatesODE2();
	if (local.ode2 == LocalJacobian::analytic)
	{
		if (temp.jacobianODE2Container.UseDenseMatrix())
		{
			jacobianGM.AddSubmatrix(temp.jacobianODE2Container.GetInternalDenseMatrix(), 1., ltgODE2, ltgODE2);
		}
		else
		{
			jacobianGM.AddSparseTriplets(temp.jacobianODE2Container.GetInternalSparseTripletMatrix().GetTriplets());
			temp.jacobianODE2Container.GetInternalSparseTripletMatrix().SetAllZero();
		}
	}
	else if (local.ode2 == LocalJacobian::numerical)
	{
		jacobianGM.AddSubmatrix(temp.localJacobian, 1., ltgODE2, cSystemData.GetLocalToGlobalODE2NumDiff()[j]);
	}

	if (local.ode1 == LocalJacobian::analytic) //fill into ODE2 rows, ODE1 columns
	{
		jacobianGM.AddSubmatrix(temp.localJacobianODE1, -factorODE1, ltgODE2, cSystemData.GetLocalToGlobalODE1()[j], 0, nODE2); //minus (-): RHS = -LHS
	}
	else if (local.ode1 == LocalJacobian::numerical)
	{
		jacobianGM.AddSubmatrix(temp.localJacobianODE1, 1., ltgODE2, cSystemData.GetLocalToGlobalODE1NumDiff()[j], 0, nODE2);
	}
}

//! append the blocks of ComputeLocalJacobianODE2 of object j as triplets of the system Jacobian, for the parallel
//! assembly (#3201): the dense blocks by their nonzero entries, the sparse container by its triplets
void CSystem::AppendLocalJacobianODE2(TemporaryComputationData& temp, Index j, Real factorODE1, const LocalJacobian& local,
	SparseTripletVector& triplets)
{
	const ArrayIndex& ltgODE2 = cSystemData.GetLocalToGlobalODE2()[j];
	Index nODE2 = cSystemData.GetNumberOfCoordinatesODE2();
	auto AppendDense = [&triplets](const ResizableMatrix& block, Real factor, const ArrayIndex& rows, const ArrayIndex& columns, Index columnOffset)
	{
		for (Index r = 0; r < block.NumberOfRows(); r++)
		{
			for (Index k = 0; k < block.NumberOfColumns(); k++)
			{
				Real value = block(r, k);
				if (value != 0.) { triplets.AppendPure(SparseTriplet(rows[r], columns[k] + columnOffset, factor*value)); }
			}
		}
	};

	if (local.ode2 == LocalJacobian::analytic)
	{
		if (temp.jacobianODE2Container.UseDenseMatrix())
		{
			AppendDense(temp.jacobianODE2Container.GetInternalDenseMatrix(), 1., ltgODE2, ltgODE2, 0);
		}
		else
		{
			triplets.AppendArray(temp.jacobianODE2Container.GetInternalSparseTripletMatrix().GetTriplets());
			temp.jacobianODE2Container.GetInternalSparseTripletMatrix().SetAllZero();
		}
	}
	CHECKandTHROW(local.ode2 != LocalJacobian::numerical && local.ode1 != LocalJacobian::numerical,
		"CSystem::AppendLocalJacobianODE2: a numerical block is assembled serially", ExudynInternalError);
	if (local.ode1 == LocalJacobian::analytic)
	{
		AppendDense(temp.localJacobianODE1, -factorODE1, ltgODE2, cSystemData.GetLocalToGlobalODE1()[j], nODE2); //minus (-): RHS = -LHS
	}
}

//! compute numerical differentiation of ODE2RHS w.r.t. ODE2 and ODE2_t quantities; 
//! multiply (before added to jacobianGM) ODE2 with factorODE2 and ODE2_t with factorODE2_t
//! the jacobian is ADDed to jacobianGM, which needs to have according size; set entries to zero beforehand in order to obtain only the jacobian
void CSystem::JacobianODE2RHS(TemporaryComputationDataArray& tempArray, const NumericalDifferentiationSettings& numDiff,
	GeneralMatrix& jacobianGM, Real factorODE2, Real factorODE2_t, Real factorODE1, Index computeLoadsJacobian)
{
	TemporaryComputationData& temp = tempArray[0]; //always exists
	temp.jacobianODE2Container.ClearAllMatrices();

	ResizableVector& f0 = temp.numericalJacobianf0;
	ResizableVector& f1 = temp.numericalJacobianf1;

	//Real relEps = numDiff.relativeEpsilon;			//relative differentiation parameter
	//Real minCoord = numDiff.minimumCoordinateSize;	//absolute differentiation parameter is limited to this minimum
	//Real eps, epsInv; //coordinate(column)-wise differentiation parameter; depends on size of coordinate

	Index nODE2 = cSystemData.GetNumberOfCoordinatesODE2();
	Index nODE1 = cSystemData.GetNumberOfCoordinatesODE1();

	Vector& x = cSystemData.GetCData().currentState.ODE2Coords;			//current coordinates ==> this is what is differentiated for
	Vector& xRef = cSystemData.GetCData().referenceState.ODE2Coords;	//reference coordinates; might be important for numerical differentiation
	Vector& xODE1 = cSystemData.GetCData().currentState.ODE1Coords;			//current coordinates ==> this is what is differentiated for
	Vector& xRefODE1 = cSystemData.GetCData().referenceState.ODE1Coords;	//reference coordinates; might be important for numerical differentiation

	//Real xStore; //store value of x; avoid roundoff error effects in numerical differentiation
	Vector& x_t = cSystemData.GetCData().currentState.ODE2Coords_t;		//for diff w.r.t. velocities

	bool diffODE2 = (factorODE2 != 0.);
	bool diffODE2_t = (factorODE2_t != 0.);
	bool diffODE1 = (factorODE1 != 0.);
	
	Vector emptyXRef; //for NumDiff template

	if (!numDiff.doSystemWideDifferentiation)
	{
		//the local Jacobian of each object, added to the system Jacobian (#3201)
		LocalJacobian local;
		auto ComputeAndAdd = [&](Index j)
		{
			if (ComputeLocalJacobianODE2(temp, numDiff, j, factorODE2, factorODE2_t, factorODE1, local))
			{
				AddLocalJacobianODE2(temp, j, factorODE1, local, jacobianGM);
			}
		};

		Index nItems = cSystemData.listComputeObjectODE2LhsNoUF.NumberOfItems();
		Index nThreads = ExuThreading::TaskManager::GetNumThreads();
		if (nThreads > 1 && nItems >= solverData.multithreadedLowerLimitJacobians)
		{
			//the analytic and automatic local Jacobians of the objects without Python functions in parallel, as triplets
			//per thread; the objects that need a numerical block and those with Python functions serially (#3201, #1203)
			outputBuffer.SetSuspendWriting(true); //may not write to python during parallel computation
			tempArray.SetNumberOfItems(nThreads); //only affected, if nThreads changed
			for (Index i = 0; i < nThreads; i++)
			{
				tempArray[i].sparseTriplets.SetNumberOfItems(0);
				tempArray[i].deferredObjects.SetNumberOfItems(0);
				tempArray[i].jacobianODE2Container.ClearAllMatrices();
			}
			Index taskSplit = GetTaskSplit(nItems, nThreads);
			ExuThreading::ParallelFor(nItems, [this, &tempArray, &numDiff, factorODE2, factorODE2_t, factorODE1](ParallelSizeType i)
			{
				Index j = cSystemData.listComputeObjectODE2LhsNoUF[(Index)i];
				TemporaryComputationData& threadTemp = tempArray[ExuThreading::TaskManager::GetThreadId()];
				LocalJacobian threadLocal;
				if (ComputeLocalJacobianODE2(threadTemp, numDiff, j, factorODE2, factorODE2_t, factorODE1, threadLocal, true))
				{
					AppendLocalJacobianODE2(threadTemp, j, factorODE1, threadLocal, threadTemp.sparseTriplets);
				}
				else if (threadLocal.deferred) { threadTemp.deferredObjects.Append(j); }
			}, taskSplit);
			outputBuffer.SetSuspendWriting(false);

			for (Index i = 0; i < nThreads; i++) { jacobianGM.AddSparseTriplets(tempArray[i].sparseTriplets); }
			for (Index i = 0; i < nThreads; i++)
			{
				for (Index j : tempArray[i].deferredObjects) { ComputeAndAdd(j); }
			}
			for (Index j : cSystemData.listComputeObjectODE2LhsUF) { ComputeAndAdd(j); }
		}
		else
		{
			for (Index j : cSystemData.listComputeObjectODE2Lhs) { ComputeAndAdd(j); }
		}
	}
	else
	{
		//done in solver: jacobian.SetNumberOfRowsAndColumns(nODE2, nODE2);

		//++++++++++++++++++++++++++++++++++++++++++++++++
		f0.SetNumberOfItems(nODE2);
		f1.SetNumberOfItems(nODE2);
		ComputeSystemODE2RHS(tempArray, f0); //compute nominal value for jacobian; same for Lie group and other nodes
        //Real xRefVal = 0;

		if (diffODE2)
		{
            if (!cSystemData.HasLieGroupDUNodes())
            {
                EXUmath::NumericalDifferentiation(0, nODE2, numDiff, factorODE2, x, xRef, jacobianGM, f0, f1, [this, &tempArray, &f1]
                {
                    ComputeSystemODE2RHS(tempArray, f1);
                });
            }
            else //Lie group derivatives need special treatment!
            {
				AddNumDiffLieGroup(0, nODE2, numDiff, factorODE2, x, xRef, jacobianGM, f0, f1, cSystemData,
					[this, &tempArray, &f1]
				{
					ComputeSystemODE2RHS(tempArray, f1);
                });
            }
		}

		if (diffODE2_t)
		{
            EXUmath::NumericalDifferentiation(0, nODE2, numDiff, factorODE2_t, x_t, jacobianGM, f0, f1, [this, &tempArray, &f1]
            {
                ComputeSystemODE2RHS(tempArray, f1);
            });
		}
		if (diffODE1 && nODE1 != 0)
		{
			//++++++++++++++++++++++++++++++++++++++++++++++++
			//for ODE2-ODE1:
            EXUmath::NumericalDifferentiation(0, nODE1, numDiff, factorODE1, xODE1, xRefODE1, jacobianGM, f0, f1, [this, &tempArray, &f1]
            {
                ComputeSystemODE2RHS(tempArray, f1);
            }, nODE2, 0); //columnOffset, rowOffset
		}
	}
	//pout << "ODE2jac=" << jacobian << "\n";
	//cSystemData.isODE2RHSjacobianComputation = false; //hack! only for debugging

    if (!numDiff.doSystemWideDifferentiation) //otherwise these parts would appear twice!
    {
        if (computeLoadsJacobian) //in case of doSystemWideDifferentiation it is done already above
        {
            Real loadsFactorODE2_t = (computeLoadsJacobian > 1) ? factorODE2_t : 0.;

            JacobianODE2Loads(tempArray, numDiff, jacobianGM, factorODE2, loadsFactorODE2_t, factorODE1);
        }


        //this part is anyway done in parallel:
        for (GeneralContact* gc : generalContacts) //usually only 1
        {
            STARTGLOBALTIMER(TScomputeGeneralContact);
            gc->JacobianODE2LHS(*this, tempArray, numDiff, jacobianGM, -factorODE2, -factorODE2_t); //negative sign, because contact computes LHS jacobian!
            STOPGLOBALTIMER(TScomputeGeneralContact);
        }
    }

}





//! the local Jacobian of the ODE1 rows of object j (#3201): the object's own (ComputeJacobianODE1RHS, #3143) if it
//! has one and is not a connector, else by numerical differentiation of its RHS; the blocks in temp as local says
bool CSystem::ComputeLocalJacobianODE1(TemporaryComputationData& temp, const NumericalDifferentiationSettings& numDiff, Index j,
	Real factorODE2, Real factorODE2_t, Real factorODE1, LocalJacobian& local)
{
	local = LocalJacobian();
	CObject* object = cSystemData.GetCObjects()[j];
	JacobianType::Type jacType = object->GetAvailableJacobians();
	Index nODE2 = cSystemData.GetNumberOfCoordinatesODE2();
	Index nLocalODE1 = cSystemData.GetLocalToGlobalODE1()[j].NumberOfItems();
	ArrayIndex& ltgODE2 = cSystemData.GetLocalToGlobalODE2NumDiff()[j];
	Index nLocalODE2 = ltgODE2.NumberOfItems();

	if (jacType & JacobianType::ODE1_ODE1_function)
	{
		if (!object->IsActive()) { return false; }
		bool analytic = true;
		if (!EXUstd::IsOfType(object->GetType(), CObjectType::Connector))
		{
			object->ComputeJacobianODE1RHS(temp.localJacobian, temp.tempMatrix, temp.tempMatrix2);
		}
		else //by the marker kinematics, or numerical (#3214)
		{
			analytic = ((const CObjectConnector*)object)->ComputeJacobianODE1RHSConnector(cSystemData, temp, temp.localJacobian,
				temp.tempMatrix, temp.tempMatrix2);
		}
		if (analytic)
		{
			local.ode1 = LocalJacobian::analytic;
			if (nLocalODE2 && (jacType & JacobianType::ODE1_ODE2_function)) { local.ode2 = LocalJacobian::analytic; }
			return true;
		}
	}

	ResizableVector& f0 = temp.numericalJacobianf0;
	ResizableVector& f1 = temp.numericalJacobianf1;
	f0.SetNumberOfItems(nLocalODE1);
	f1.SetNumberOfItems(nLocalODE1);
	if (!ComputeObjectODE1RHS(temp, object, f0)) { return false; }

	Vector& xODE1 = cSystemData.GetCData().currentState.ODE1Coords;			//current coordinates ==> this is what is differentiated for
	Vector& xODE2 = cSystemData.GetCData().currentState.ODE2Coords;
	Vector& xRefODE1 = cSystemData.GetCData().referenceState.ODE1Coords;	//reference coordinates; might be important for numerical differentiation
	Vector& xRefODE2 = cSystemData.GetCData().referenceState.ODE2Coords;
	Vector& xODE2_t = cSystemData.GetCData().currentState.ODE2Coords_t;		//for diff w.r.t. velocities
	auto ComputeF1 = [this, &temp, &object, &f1]
	{
		ComputeObjectODE1RHS(temp, object, f1);
	};

	//ODE1-ODE1
	ArrayIndex& ltgODE1numDiff = cSystemData.GetLocalToGlobalODE1NumDiff()[j]; //columns without duplicates (#1424)
	temp.localJacobian.SetNumberOfRowsAndColumns(nLocalODE1, ltgODE1numDiff.NumberOfItems()); //fully computed, needs no initialization
	AddNumDiffObject(numDiff, -factorODE1, xODE1, xRefODE1, temp.localJacobian, f0, f1, ltgODE1numDiff, ComputeF1, true); //set values
	local.ode1 = LocalJacobian::numerical;

	//ODE1-ODE2, the coupling
	if (nLocalODE2)
	{
		ResizableMatrix& localJacobian = temp.localJacobianODE2;
		localJacobian.SetNumberOfRowsAndColumns(nLocalODE1, nLocalODE2);
		localJacobian.SetAll(0.);
		if (factorODE2 != 0. && nODE2 != 0 && EXUstd::IsOfType(jacType, JacobianType::ODE1_ODE2))
		{
			AddNumDiffObject(numDiff, -factorODE2, xODE2, xRefODE2, localJacobian, f0, f1, ltgODE2, ComputeF1, true); //(-) sign because of RHS, f1-f0; set values
		}
		if (factorODE2_t != 0. && nODE2 != 0 && EXUstd::IsOfType(jacType, JacobianType::ODE1_ODE2_t))
		{
			AddNumDiffObject(numDiff, -factorODE2_t, xODE2_t, Vector(), localJacobian, f0, f1, ltgODE2, ComputeF1); //(-) sign because of RHS, f1-f0
		}
		local.ode2 = LocalJacobian::numerical;
	}
	return true;
}

//! add the blocks of ComputeLocalJacobianODE1 of object j to the system Jacobian (#3201)
void CSystem::AddLocalJacobianODE1(TemporaryComputationData& temp, Index j, Real factorODE2, Real factorODE2_t, Real factorODE1,
	const LocalJacobian& local, GeneralMatrix& jacobianGM)
{
	ArrayIndex& ltgODE1 = cSystemData.GetLocalToGlobalODE1()[j];
	Index nODE2 = cSystemData.GetNumberOfCoordinatesODE2();
	if (local.ode1 == LocalJacobian::analytic)
	{
		jacobianGM.AddSubmatrix(temp.localJacobian, factorODE1, ltgODE1, ltgODE1, nODE2, nODE2);
	}
	else if (local.ode1 == LocalJacobian::numerical)
	{
		jacobianGM.AddSubmatrix(temp.localJacobian, 1., ltgODE1, cSystemData.GetLocalToGlobalODE1NumDiff()[j], nODE2, nODE2);
	}

	if (local.ode2 == LocalJacobian::analytic && nODE2 != 0)
	{
		ArrayIndex& ltgODE2all = cSystemData.GetLocalToGlobalODE2()[j]; //analytic: the duplicates add up
		if (factorODE2 != 0.) { jacobianGM.AddSubmatrix(temp.tempMatrix, factorODE2, ltgODE1, ltgODE2all, nODE2, 0); }
		if (factorODE2_t != 0.) { jacobianGM.AddSubmatrix(temp.tempMatrix2, factorODE2_t, ltgODE1, ltgODE2all, nODE2, 0); }
	}
	else if (local.ode2 == LocalJacobian::numerical)
	{
		jacobianGM.AddSubmatrix(temp.localJacobianODE2, 1., ltgODE1, cSystemData.GetLocalToGlobalODE2NumDiff()[j], nODE2, 0);
	}
}

//! the Jacobian of ODE1RHS by the ODE1 coordinates, the ODE2 coordinates and velocities, multiplied with the factors: the
//! analytic one of an object that has it (ComputeJacobianODE1RHS, #3143), else by numerical differentiation;
//! the jacobian is ADDed to the given matrix, which needs to have according size; set entries to zero beforehand in order to obtain only the jacobian
void CSystem::JacobianODE1RHS(TemporaryComputationDataArray& tempArray, const NumericalDifferentiationSettings& numDiff,
	GeneralMatrix& jacobianGM, Real factorODE2, Real factorODE2_t, Real factorODE1, Index computeLoadsJacobian)
{
	//size needs to be set accordingly in the caller function; components are added to jacobian!
	TemporaryComputationData& temp = tempArray[0]; //first array does always exist!
	temp.jacobianODE2Container.ClearAllMatrices();

	ResizableVector& f0 = temp.numericalJacobianf0;
	ResizableVector& f1 = temp.numericalJacobianf1;


	//Real relEps = numDiff.relativeEpsilon;			//relative differentiation parameter
	//Real minCoord = numDiff.minimumCoordinateSize;	//absolute differentiation parameter is limited to this minimum

	Index nODE2 = cSystemData.GetNumberOfCoordinatesODE2();
	Index nODE1 = cSystemData.GetNumberOfCoordinatesODE1();
	Vector& xODE1 = cSystemData.GetCData().currentState.ODE1Coords;			//current coordinates ==> this is what is differentiated for
	Vector& xODE2 = cSystemData.GetCData().currentState.ODE2Coords;			//current coordinates ==> this is what is differentiated for
	Vector& xRefODE1 = cSystemData.GetCData().referenceState.ODE1Coords;	//reference coordinates; might be important for numerical differentiation
	Vector& xRefODE2 = cSystemData.GetCData().referenceState.ODE2Coords;	//reference coordinates; might be important for numerical differentiation
	Vector& xODE2_t = cSystemData.GetCData().currentState.ODE2Coords_t;		//for diff w.r.t. velocities

	bool diffODE1 = (factorODE1 != 0. && nODE1 != 0);
	bool diffODE2 = (factorODE2 != 0. && nODE2 != 0);
	bool diffODE2_t = (factorODE2_t != 0. && nODE2 != 0);
	//diffODE2 = false;
	//diffODE2_t = false;

	if (!numDiff.doSystemWideDifferentiation)
	{
		//the local Jacobian of each object, added to the system Jacobian (#3201)
		LocalJacobian local;
		for (Index j : cSystemData.listComputeObjectODE1Rhs)
		{
			if (ComputeLocalJacobianODE1(temp, numDiff, j, factorODE2, factorODE2_t, factorODE1, local))
			{
				AddLocalJacobianODE1(temp, j, factorODE2, factorODE2_t, factorODE1, local, jacobianGM);
			}
		}
		if (computeLoadsJacobian) //the system-wide differentiation includes the loads
		{
			JacobianODE1Loads(tempArray, numDiff, jacobianGM, factorODE2, (computeLoadsJacobian > 1) ? factorODE2_t : 0., factorODE1);
		}
	}
	else
	{
        //systemwide differentiation
		//++++++++++++++++++++++++++++++++++++++++++++++++
		f0.SetNumberOfItems(nODE1);
		f1.SetNumberOfItems(nODE1);
		ComputeSystemODE1RHS(temp, f0); //compute nominal value for jacobian
		Index rowOffset = nODE2;
		//Real xRefVal = 0;

		//for ODE1-ODE1:
		if (diffODE1)
		{
            EXUmath::NumericalDifferentiation(0, nODE1, numDiff, factorODE1, xODE1, xRefODE1, jacobianGM, f0, f1, [this, &temp, &f1]
            {
                ComputeSystemODE1RHS(temp, f1);
            }, nODE2, rowOffset); //columnOffset, rowOffset

		}
		//++++++++++++++++++++++++++++++++++++++++++++++++
		//for ODE1-ODE2:
		if (diffODE2)
		{
			if (!cSystemData.HasLieGroupDUNodes())
			{
				EXUmath::NumericalDifferentiation(0, nODE2, numDiff, factorODE2, xODE2, xRefODE2, jacobianGM, f0, f1, [this, &temp, &f1]
				{
					ComputeSystemODE1RHS(temp, f1);
				}, 0, rowOffset); //columnOffset, rowOffset
			}
			else //Lie group derivatives need special treatment!
			{
				AddNumDiffLieGroup(0, nODE2, numDiff, factorODE2, xODE2, xRefODE2, jacobianGM, f0, f1, cSystemData,
					[this, &temp, &f1]
				{
					ComputeSystemODE1RHS(temp, f1);
				}, 0, rowOffset);
			}
		}
		if (diffODE2_t)
		{
            EXUmath::NumericalDifferentiation(0, nODE2, numDiff, factorODE2_t, xODE2_t, jacobianGM, f0, f1, [this, &temp, &f1]
            {
                ComputeSystemODE1RHS(temp, f1);
            }, 0, rowOffset); //columnOffset, rowOffset
		}
	}
	//pout << "ODE2jac=" << jacobian << "\n";
	//cSystemData.isODE2RHSjacobianComputation = false; //hack! only for debugging
}





//! numerical computation of constraint jacobian with respect to ODE2 and ODE1 (fillIntoSystemMatrix=true: also w.r.t. AE) coordinates
//! factorODE2 is used to scale the ODE2-part of the jacobian (to avoid postmultiplication); 
//! velocityLevel = velocityLevel constraints are used, if available; 
//! fillIntoSystemMatrix=true: fill in g_q_ODE2, g_q_ODE2^T AND g_q_AE into system matrix at according positions
//! fillIntoSystemMatrix=false: fill in g_q_ODE2 into jacobian matrix at (0,0) ???REALLY
template<class TGeneralMatrix>
void CSystem::NumericalJacobianAE(TemporaryComputationDataArray& tempArray, const NumericalDifferentiationSettings& numDiff,
	Vector& f0, Vector& f1, TGeneralMatrix& jacobianGM, Real factorAE_ODE2, Real factorAE_ODE2_t, Real factorAE_ODE1,
	bool velocityLevel, Real factorODE2_AE, Real factorODE1_AE, Real factorAE_AE)
{
	//TemporaryComputationData& temp = tempArray[0];
	Real relEps = numDiff.relativeEpsilon;			//relative differentiation parameter
	Real minCoord = numDiff.minimumCoordinateSize;	//absolute differentiation parameter is limited to this minimum
	Real eps, epsInv; //coordinate(column)-wise differentiation parameter; depends on size of coordinate

	Index nAE = cSystemData.GetNumberOfCoordinatesAE();
	Index nODE2 = cSystemData.GetNumberOfCoordinatesODE2();
	Index nODE1 = cSystemData.GetNumberOfCoordinatesODE1();
	
	//DELETE: CHECKandTHROW(nODE1 == 0, "CSystem::NumericalJacobianAE: nODE1 must be zero"); //check that offsetAE is correctly added
	Index offsetAE = nODE2 + nODE1; //offset for algebraic equations in system jacobian

	Vector& x = cSystemData.GetCData().currentState.ODE2Coords;
	Vector& x_t = cSystemData.GetCData().currentState.ODE2Coords_t; //velocity coordinates
	Real xStore; //store value of x; avoid roundoff error effects in numerical differentiation

	Vector& y = cSystemData.GetCData().currentState.ODE1Coords;
	//Vector& y_t = cSystemData.GetCData().currentState.ODE1Coords_t; //velocity coordinates
	Real yStore; //store value of y; avoid roundoff error effects in numerical differentiation


	Vector& z = cSystemData.GetCData().currentState.AECoords;
	Real zStore; //store value of x; avoid roundoff error effects in numerical differentiation

	//++++++++++++++++++++++++++++++++++++++++++++++++
	//compute total jacobian ==> very time consuming ==> change this to local jacobian (use flag in numDiffParameters?)

	f0.SetNumberOfItems(nAE);
	f1.SetNumberOfItems(nAE);

	//the entries of the AE rows and columns as triplets, for dense and sparse matrices (#3205); the blocks are zero before
	SparseTripletVector triplets;
	auto Add = [&triplets](Index row, Index column, Real value)
	{
		if (value != 0.) { triplets.AppendPure(SparseTriplet(row, column, value)); }
	};

	ComputeAlgebraicEquations(tempArray, f0, velocityLevel); //compute nominal value for jacobian

	//THE REACTION FORCES in the ODE2 rows are those of the residual, linear in lambda: column j is the reaction forces of
	//the unit lambda_j (#3201) - the derivative the residual has, dC/dq^T at position level and dC/dq_t^T at velocity
	//level (#692), without the direction along the Euler parameters which dC/dq has and the reaction forces do not
	Vector lambda(nAE);
	Vector reactionForces(nODE2);
	lambda.SetAll(0.);
	for (Index j = 0; j < nAE; j++)
	{
		lambda[j] = 1.;
		reactionForces.SetAll(0.);
		ComputeODE2ProjectedReactionForces(tempArray, lambda, reactionForces);
		lambda[j] = 0.;
		for (Index i = 0; i < nODE2; i++) { Add(i, offsetAE + j, factorODE2_AE * reactionForces[i]); }
	}

	//differentiation w.r.t. ODE2 coordinates
	for (Index i = 0; i < nODE2; i++)
	{
		eps = relEps * (EXUstd::Maximum(minCoord, fabs(x[i])));
		//pout << "Jac i=" << i << ", diffEps = " << eps << "\n";

		xStore = x[i];
		x[i] += eps;
		ComputeAlgebraicEquations(tempArray, f1, velocityLevel);
		x[i] = xStore;

		epsInv = 1. / eps;

		for (Index j = 0; j < nAE; j++)
		{
			Real x = epsInv * (f1[j] - f0[j]);
			Add(offsetAE + j, i, factorAE_ODE2 * x); //add Cq ==> factor only used for Position constraints ...
		}
	}

	//differentiation w.r.t. ODE2_t coordinates
	for (Index i = 0; i < nODE2; i++)
	{
		eps = relEps * (EXUstd::Maximum(minCoord, fabs(x[i])));
		//pout << "Jac i=" << i << ", diffEps = " << eps << "\n";

		xStore = x_t[i];
		x_t[i] += eps;
		ComputeAlgebraicEquations(tempArray, f1, velocityLevel);
		x_t[i] = xStore;

		epsInv = 1. / eps;

		for (Index j = 0; j < nAE; j++)
		{
			Real x = epsInv * (f1[j] - f0[j]);
			Add(offsetAE + j, i, factorAE_ODE2_t * x); //add Cq ==> factor only used for Position constraints ...
		}
	}

	//differentiation w.r.t. ODE1 coordinates
	for (Index i = 0; i < nODE1; i++)
	{
		eps = relEps * (EXUstd::Maximum(minCoord, fabs(y[i])));
		//pout << "Jac i=" << i << ", diffEps = " << eps << "\n";

		yStore = y[i];
		y[i] += eps;
		ComputeAlgebraicEquations(tempArray, f1, velocityLevel);
		y[i] = yStore;

		epsInv = 1. / eps;

		for (Index j = 0; j < nAE; j++)
		{
			Real y = epsInv * (f1[j] - f0[j]);

			Add(offsetAE + j, i + nODE2, factorAE_ODE1 * y); //add Cq1
			Add(i + nODE2, offsetAE + j, factorODE1_AE * y); //add Cq1T
		}
	}

	//differentiation w.r.t. AE coordinates
	for (Index i = 0; i < nAE; i++)
	{
		eps = relEps * (EXUstd::Maximum(minCoord, fabs(z[i])));

		zStore = z[i];
		z[i] += eps;
		ComputeAlgebraicEquations(tempArray, f1, velocityLevel);
		z[i] = zStore;
		epsInv = 1. / eps;

		for (Index j = 0; j < nAE; j++)
		{
			Add(offsetAE + j, offsetAE + i, (factorAE_AE * epsInv) * (f1[j] - f0[j]));
		}
	}
	jacobianGM.AddSparseTriplets(triplets);
}

