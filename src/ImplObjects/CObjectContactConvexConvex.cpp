void VisualizationObjectContactConvexConvex::UpdateGraphics(const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemNumber)
{
	Index itemID = Index2ItemID(itemNumber, ItemType::Object, vSystem->GetSystemID());
	CObjectContactConvexConvex* cItem = (CObjectContactConvexConvex*)vSystem->systemData->GetCObjects()[itemNumber];
	const auto& parameters = cItem->GetParameters();

	Vector3D pos[2];
	for (Index i = 0; i < 2; i++)
	{
		vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[i]]->GetPosition(*vSystem->systemData, pos[i], ConfigurationType::Visualization);
	}
	if (visualizationSettings.contact.showTriangles)
	{
		Float4 triangleColor = visualizationSettings.contact.colorTriangles;
		if (color[0] != -1.f) { triangleColor = color; }
		std::array<Float4, 3> colors = { triangleColor, triangleColor, triangleColor };
		for (Index i = 0; i < 2; i++)
		{
			const Matrix& points = i == 0 ? parameters.points0 : parameters.points1;
			const MatrixI& triangles = i == 0 ? parameters.triangles0 : parameters.triangles1;
			Matrix3D A;
			vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[i]]->GetRotationMatrix(*vSystem->systemData, A, ConfigurationType::Visualization);
			for (Index t = 0; t < triangles.NumberOfRows(); t++)
			{
				std::array<Vector3D, 3> nodes;
				for (Index k = 0; k < 3; k++)
				{
					Index p = triangles(t, k);
					nodes[k] = pos[i] + A * Vector3D({ points(p, 0), points(p, 1), points(p, 2) });
				}
				Vector3D normal = EGeometry::ComputeTriangleNormal(nodes);
				std::array<Vector3D, 3> normals = { normal, normal, normal };
				vSystem->graphicsData.AddTriangle(nodes, normals, colors, itemID);
			}
		}
	}
	if (visualizationSettings.connectors.showNumbers)
	{
		Float4 currentColor = visualizationSettings.connectors.defaultColor;
		if (color[0] != -1.f) { currentColor = color; }
		EXUvis::DrawItemNumber(0.5 * (pos[0] + pos[1]), vSystem, itemID, "", currentColor);
	}
}
