void VisualizationObjectContactConvexConvex::UpdateGraphics(const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemNumber)
{
	Index itemID = Index2ItemID(itemNumber, ItemType::Object, vSystem->GetSystemID());
	CObjectContactConvexConvex* cItem = (CObjectContactConvexConvex*)vSystem->systemData->GetCObjects()[itemNumber];
	const auto& parameters = cItem->GetParameters();

	Vector3D pos[2];
	for (Index i = 0; i < 2; i++)
	{
		vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[i]]->GetPosition(*vSystem->systemData, pos[i], ConfigurationType::Visualization);
	}
	if (visualizationSettings.contact.show.triangles)
	{
		Float4 triangleColor = visualizationSettings.contact.color.triangles;
		if (color[0] != -1.f) { triangleColor = color; }
		ContactPoints::DrawPolytope(vSystem, cItem->GetMarkerNumbers()[0], parameters.points0, parameters.triangles0, triangleColor, itemID);
		ContactPoints::DrawPolytope(vSystem, cItem->GetMarkerNumbers()[1], parameters.points1, parameters.triangles1, triangleColor, itemID);
	}
	ContactPoints::DrawForces<CObjectContactConvexConvex, ContactConvex::Points>(*cItem, visualizationSettings, vSystem, itemID,
		"ObjectContactConvexConvex", ContactConvex::ComputePoints);
	if (visualizationSettings.connectors.showNumbers)
	{
		Float4 currentColor = visualizationSettings.connectors.defaultColor;
		if (color[0] != -1.f) { currentColor = color; }
		EXUvis::DrawItemNumber(0.5 * (pos[0] + pos[1]), vSystem, itemID, "", currentColor);
	}
}
