//! subtract the forces given per joint from the joint forces f: the constant joint forces, the P and D control and the
//! forceUserFunction; q includes the reference coordinates
void CObjectKinematicTree::AddJointForces(Vector& f, const LinkedDataVector& q, const LinkedDataVector& q_t, Index objectNumber) const
{
	Index n = NumberOfLinks();
	if (parameters.jointForceVector.NumberOfItems() != 0)
	{
		f -= parameters.jointForceVector; //constant forces per coordinate (RevoluteJoint: local torque in joint)
	}

	for (Index i = 0; i < n; i++)
	{
		if (parameters.jointPositionOffsetVector.NumberOfItems() != 0) //P control checked automatically
		{
			f[i] -= parameters.jointPControlVector[i] * (parameters.jointPositionOffsetVector[i] - q[i]);
		}
		if (parameters.jointVelocityOffsetVector.NumberOfItems() != 0) //P control checked automatically
		{
			f[i] -= parameters.jointDControlVector[i] * (parameters.jointVelocityOffsetVector[i] - q_t[i]);
		}
	}

	if (parameters.forceUserFunction)
	{
		Real t = GetCSystemData()->GetCData().GetCurrent().GetTime();
		Vector userForce;
		tempVector2.CopyFrom(q_t); //the joint velocities for the user function (#2845)

		EvaluateUserFunctionForce(userForce, cSystemData->GetMainSystemBacklink(), t, objectNumber, tempVector, tempVector2);
		CHECKandTHROW(userForce.NumberOfItems() == n, "CObjectKinematicTree: forceUserFunction return a vector with different size from ObjectKinematicTree system size", ExudynValueError);
		f -= userForce;
	}
}

//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
//+++++++++++++++     THE TREE ON HOMOGENEOUS TRANSFORMATIONS (#2829)     ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
//the recursive algorithms of Featherstone (the kinematics, the recursive Newton-Euler forces, the composite rigid body
//mass matrix), written on the placement of each link in its parent, H = (R, p) with x_parent = R x_link + p, instead of
//Featherstone's spatial transformation Xup = H^-1; motion vectors (omega, v) and force vectors (n, f) are pairs of
//Vector3D in link coordinates, at the link origin
namespace KinematicTreeHT
{
	//! the placement of link i in its parent: the constant joint transformation and offset, then the joint motion q
	void RelativePlacement(const CObjectKinematicTreeParameters& parameters, Index i, Real q, Matrix3D& R, Vector3D& p)
	{
		const Matrix3D& A = parameters.jointTransformations[i];
		p = parameters.jointOffsets[i];
		switch (parameters.jointTypes[i])
		{
		case Joint::RevoluteX: R = A * RigidBodyMath::RotationMatrix1(q); break;
		case Joint::RevoluteY: R = A * RigidBodyMath::RotationMatrix2(q); break;
		case Joint::RevoluteZ: R = A * RigidBodyMath::RotationMatrix3(q); break;
		case Joint::PrismaticX: R = A; p += q * A.GetColumnVector<3>(0); break;
		case Joint::PrismaticY: R = A; p += q * A.GetColumnVector<3>(1); break;
		case Joint::PrismaticZ: R = A; p += q * A.GetColumnVector<3>(2); break;
		default: SysError("KinematicTreeHT::RelativePlacement: illegal joint type"); //types are checked before
		}
	}

	//! the motion of the joint with speed qt in link coordinates: (omega, v)
	inline void JointMotion(Joint::Type jointType, Real qt, Vector3D& w, Vector3D& v)
	{
		w.SetAll(0.);
		v.SetAll(0.);
		if (Joint::IsRevolute(jointType)) { w[Joint::AxisNumber(jointType)] = qt; }
		else { v[Joint::AxisNumber(jointType)] = qt; }
	}

	//! the component of a force (n, f) along the motion subspace of the joint: MS^T F
	inline Real JointForce(Joint::Type jointType, const Vector3D& n, const Vector3D& f)
	{
		return Joint::IsRevolute(jointType) ? n[Joint::AxisNumber(jointType)] : f[Joint::AxisNumber(jointType)];
	}

	//! a motion of the parent in link coordinates: omega = R^T omegaParent, v = R^T (vParent + omegaParent x p)
	inline void MotionToLink(const Matrix3D& R, const Vector3D& p, const Vector3D& wParent, const Vector3D& vParent,
		Vector3D& w, Vector3D& v)
	{
		EXUmath::MultMatrixTransposedVectorTemplate(R, wParent, w);
		EXUmath::MultMatrixTransposedVectorTemplate(R, vParent + wParent.CrossProduct(p), v);
	}

	//! a force of the link in parent coordinates, added: fParent += R f, nParent += R n + p x (R f)
	inline void AddForceToParent(const Matrix3D& R, const Vector3D& p, const Vector3D& n, const Vector3D& f,
		Vector3D& nParent, Vector3D& fParent)
	{
		Vector3D Rf = R * f;
		fParent += Rf;
		nParent += R * n + p.CrossProduct(Rf);
	}

	//! the spatial inertia of a link at its origin: mass, mass times center of mass, inertia tensor at the origin
	struct Inertia
	{
		Real m;
		Vector3D mc;
		Matrix3D J;

		void Set(Real mass, const Vector3D& com, const Matrix3D& inertiaCOM)
		{
			Matrix3D skew(RigidBodyMath::Vector2SkewMatrix(com));
			m = mass;
			mc = mass * com;
			J = inertiaCOM - mass * skew * skew;
		}
		//! I * (omega, v) = (J omega + mc x v, m v - mc x omega)
		void Mult(const Vector3D& w, const Vector3D& v, Vector3D& n, Vector3D& f) const
		{
			n = J * w + mc.CrossProduct(v);
			f = m * v - mc.CrossProduct(w);
		}
		//! the inertia of a child at its origin added to this one, its origin placed by (R, p) in this one
		void AddChild(const Matrix3D& R, const Vector3D& p, const Inertia& child)
		{
			Vector3D mcChild = R * child.mc + child.m * p;
			Matrix3D skewChild(RigidBodyMath::Vector2SkewMatrix(child.mc));
			Matrix3D Jcom = child.J + (1. / child.m) * skewChild * skewChild;  //at the center of mass of the child
			Matrix3D skew(RigidBodyMath::Vector2SkewMatrix(mcChild));
			J += R * Jcom * R.GetTransposed() - (1. / child.m) * skew * skew;
			mc += mcChild;
			m += child.m;
		}
	};

	//! per link: the placement in the parent, motion, acceleration (bias), force, composite inertia; reused per thread
	struct Link
	{
		Matrix3D R;
		Vector3D p;
		Vector3D w, v;		//!< velocity
		Vector3D aw, av;	//!< acceleration; the bias acceleration (with gravity) in the dynamics
		Vector3D n, f;		//!< force
		Inertia inertia;
	};
	thread_local ResizableArray<Link> links;
	thread_local ResizableArray<HomogeneousTransformation> placements; //!< the global placements for the forces given per link
}

//! the placements of the links - in the base if computeAbsoluteTransformations, else in their parents - and, if
//! computeVelocitiesAccelerations, their velocities and accelerations as (omega, v) in link coordinates
void CObjectKinematicTree::ComputeTreeTransformations(ConfigurationType configuration, bool computeVelocitiesAccelerations,
	bool computeAbsoluteTransformations, Transformation66List& frames, Vector6DList& V, Vector6DList& A) const
{
	using namespace KinematicTreeHT;
	Index n = NumberOfLinks();
	ResizableArray<Link>& L = links;
	L.SetNumberOfItems(n);
	frames.SetNumberOfItems(n);
	V.SetNumberOfItems(computeVelocitiesAccelerations ? n : 0);
	A.SetNumberOfItems(computeVelocitiesAccelerations ? n : 0);

	LinkedDataVector q(GetCNode(0)->GetCoordinateVector(configuration));
	LinkedDataVector q_t;
	LinkedDataVector q_tt;
	if (computeVelocitiesAccelerations)
	{
		q_t.LinkDataTo(((CNodeODE2*)GetCNode(0))->GetCoordinateVector_t(configuration));
		q_tt.LinkDataTo(((CNodeODE2*)GetCNode(0))->GetCoordinateVector_tt(configuration));
	}
	LinkedDataVector qRef(GetCNode(0)->GetReferenceCoordinateVector());

	Vector3D wJ, vJ, awJ, avJ;
	for (Index i = 0; i < n; i++)
	{
		Real qTotal = q[i];
		if (configuration != ConfigurationType::Reference) { qTotal += qRef[i]; }
		RelativePlacement(parameters, i, qTotal, L[i].R, L[i].p);
		Index parent = parameters.linkParents[i];

		if (computeVelocitiesAccelerations)
		{
			JointMotion(parameters.jointTypes[i], q_t[i], wJ, vJ);
			JointMotion(parameters.jointTypes[i], q_tt[i], awJ, avJ);
			if (parent == noParent)
			{
				L[i].w = wJ; L[i].v = vJ;
				L[i].aw = awJ; L[i].av = avJ;
			}
			else
			{
				MotionToLink(L[i].R, L[i].p, L[parent].w, L[parent].v, L[i].w, L[i].v);
				MotionToLink(L[i].R, L[i].p, L[parent].aw, L[parent].av, L[i].aw, L[i].av);
				L[i].w += wJ;
				L[i].v += vJ;
				//the product of the motion vectors (v x vJ): (w x wJ, v x wJ + w x vJ)
				L[i].aw += L[i].w.CrossProduct(wJ) + awJ;
				L[i].av += L[i].v.CrossProduct(wJ) + L[i].w.CrossProduct(vJ) + avJ;
			}
			V[i] = Vector6D({ L[i].w[0], L[i].w[1], L[i].w[2], L[i].v[0], L[i].v[1], L[i].v[2] });
			A[i] = Vector6D({ L[i].aw[0], L[i].aw[1], L[i].aw[2], L[i].av[0], L[i].av[1], L[i].av[2] });
		}

		Matrix3D R = L[i].R;
		Vector3D p = L[i].p;
		if (computeAbsoluteTransformations)
		{
			if (parent != noParent) //the placement in the base: that of the parent times this one
			{
				p = L[parent].R * p + L[parent].p;
				R = L[parent].R * R;
			}
			else { p += parameters.baseOffset; }
			//the global placement is kept for the children; L[i].R, p are not needed afterwards in this function
			L[i].R = R;
			L[i].p = p;
		}
		frames[i] = HomogeneousTransformation(R, p);
	}
}

//! the mass matrix if computeMass, otherwise the forces of the left-hand side
void CObjectKinematicTree::ComputeMassMatrixAndODE2LHS(ResizableMatrix* massMatrix, Vector* ode2Lhs,
	Index objectNumber, bool computeMass) const
{
	using namespace KinematicTreeHT;
	Index n = NumberOfLinks();
	ResizableArray<Link>& L = links;
	L.SetNumberOfItems(n);

	tempVector.CopyFrom(GetCNode(0)->GetCurrentCoordinateVector());
	tempVector += GetCNode(0)->GetReferenceCoordinateVector();
	LinkedDataVector q(tempVector);
	LinkedDataVector q_t(((CNodeODE2*)GetCNode(0))->GetCurrentCoordinateVector_t());

	//from the base to the leaves: placements, velocities, bias accelerations (gravity as an acceleration of the base), forces
	Vector3D wJ, vJ;
	Vector3D zero(0.);
	for (Index i = 0; i < n; i++)
	{
		Link& link = L[i];
		RelativePlacement(parameters, i, q[i], link.R, link.p);
		JointMotion(parameters.jointTypes[i], q_t[i], wJ, vJ);
		Index parent = parameters.linkParents[i];
		if (parent == noParent)
		{
			link.w = wJ;
			link.v = vJ;
			MotionToLink(link.R, link.p, zero, -parameters.gravity, link.aw, link.av);
		}
		else
		{
			MotionToLink(link.R, link.p, L[parent].w, L[parent].v, link.w, link.v);
			MotionToLink(link.R, link.p, L[parent].aw, L[parent].av, link.aw, link.av);
			link.w += wJ;
			link.v += vJ;
			link.aw += link.w.CrossProduct(wJ);
			link.av += link.v.CrossProduct(wJ) + link.w.CrossProduct(vJ);
		}
		link.inertia.Set(parameters.linkMasses[i], parameters.linkCOMs[i], parameters.linkInertiasCOM[i]);
		if (!computeMass)
		{
			//F = I a + v x* (I v), the force product (w, v) x* (n, f) = (w x n + v x f, w x f)
			Vector3D nI, fI;
			link.inertia.Mult(link.aw, link.av, link.n, link.f);
			link.inertia.Mult(link.w, link.v, nI, fI);
			link.n += link.w.CrossProduct(nI) + link.v.CrossProduct(fI);
			link.f += link.w.CrossProduct(fI);
		}
	}

	if (!computeMass)
	{
		//the forces and torques given per link in global coordinates: in the frame of the link, without the base offset
		if (parameters.linkForces.NumberOfItems() != 0 || parameters.linkTorques.NumberOfItems() != 0)
		{
			ResizableArray<HomogeneousTransformation>& Ha = placements;
			Ha.SetNumberOfItems(n);
			for (Index i = 0; i < n; i++)
			{
				Index parent = parameters.linkParents[i];
				Ha[i] = HomogeneousTransformation(L[i].R, L[i].p);
				if (parent != noParent) { Ha[i] = Ha[parent] * Ha[i]; }
				Vector3D torque = parameters.linkTorques.NumberOfItems() ? (Vector3D)parameters.linkTorques[i] : Vector3D(0.);
				Vector3D force = parameters.linkForces.NumberOfItems() ? (Vector3D)parameters.linkForces[i] : Vector3D(0.);
				//(n, f) = (Ra^T (torque - pa x force), Ra^T force)
				Vector3D nLink, fLink;
				EXUmath::MultMatrixTransposedVectorTemplate(Ha[i].GetRotation(), torque - Ha[i].GetTranslation().CrossProduct(force), nLink);
				EXUmath::MultMatrixTransposedVectorTemplate(Ha[i].GetRotation(), force, fLink);
				L[i].n += nLink;
				L[i].f += fLink;
			}
		}

		//from the leaves to the base: the joint forces
		Vector& f = *ode2Lhs;
		f.SetNumberOfItems(n);
		for (Index i = n - 1; i >= 0; i--)
		{
			f[i] = JointForce(parameters.jointTypes[i], L[i].n, L[i].f);
			Index parent = parameters.linkParents[i];
			if (parent != noParent) { AddForceToParent(L[i].R, L[i].p, L[i].n, L[i].f, L[parent].n, L[parent].f); }
		}
		AddJointForces(f, q, q_t, objectNumber);
	}
	else
	{
		//the composite inertias, from the leaves to the base
		for (Index i = n - 1; i >= 0; i--)
		{
			Index parent = parameters.linkParents[i];
			if (parent != noParent) { L[parent].inertia.AddChild(L[i].R, L[i].p, L[i].inertia); }
		}
		ResizableMatrix& M = *massMatrix;
		M.SetScalarMatrix(n, 0.);
		Vector3D nh, fh, w, v;
		for (Index i = 0; i < n; i++)
		{
			JointMotion(parameters.jointTypes[i], 1., w, v);
			L[i].inertia.Mult(w, v, nh, fh);
			M(i, i) = JointForce(parameters.jointTypes[i], nh, fh);
			Index j = i;
			while (parameters.linkParents[j] != noParent)
			{
				Vector3D nParent(0.), fParent(0.);
				AddForceToParent(L[j].R, L[j].p, nh, fh, nParent, fParent);
				nh = nParent;
				fh = fParent;
				j = parameters.linkParents[j];
				M(i, j) = JointForce(parameters.jointTypes[j], nh, fh);
				M(j, i) = M(i, j);
			}
		}
	}
}

