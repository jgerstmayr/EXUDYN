//! d(J_pos^T force + J_rot^T torque)/dq by central differences of the Jacobian user functions; the step follows the rule
//! of newton.numericalDifferentiation with its defaults (relativeEpsilon 1e-7, minimumCoordinateSize 1e-2), as the
//! settings of the solver do not reach a marker (#2995)
bool CObjectUserBody::GetJacobianTransposedTimesVectorDerivative(const Vector3D& localPosition, const Vector6D& forceTorque, Matrix& value) const
{
	Vector3D force({ forceTorque[0], forceTorque[1], forceTorque[2] });
	Vector3D torque({ forceTorque[3], forceTorque[4], forceTorque[5] });
	bool hasForce = !(force == 0.);
	bool hasTorque = !(torque == 0.);
	if (!hasForce && !hasTorque) { return false; }

	ResizableConstVector qRef, q, q_t;
	GatherUserFunctionCoordinates(qRef, q, q_t, ConfigurationType::Current);
	Index n = q.NumberOfItems();
	Real t = GetCSystemData()->GetConfigurationTime(ConfigurationType::Current);
	value.SetNumberOfRowsAndColumns(n, n);

	static thread_local ResizableMatrix jacobian; //memory kept between the calls (#3046), per thread (#2978)
	static thread_local ResizableVector plus;
	static thread_local ResizableVector minus;
	plus.SetNumberOfItems(n);
	minus.SetNumberOfItems(n);
	//J^T force + J_rot^T torque at the coordinates q, varied
	auto ProjectedVector = [&](Vector& result)
	{
		result.SetAll(0.);
		if (hasForce)
		{
			EvaluatePositionJacobian(jacobian, t, localPosition, qRef, q, q_t);
			for (Index j = 0; j < n; j++) { for (Index i = 0; i < 3; i++) { result[j] += jacobian(i, j)*force[i]; } }
		}
		if (hasTorque)
		{
			EvaluateRotationJacobian(jacobian, t, localPosition, qRef, q, q_t);
			for (Index j = 0; j < n; j++) { for (Index i = 0; i < 3; i++) { result[j] += jacobian(i, j)*torque[i]; } }
		}
	};
	const Real relativeEpsilon = 1e-7;
	const Real minimumCoordinateSize = 1e-2;
	for (Index k = 0; k < n; k++)
	{
		Real qk = q[k];
		Real eps = relativeEpsilon*EXUstd::Maximum(minimumCoordinateSize, fabs(qk));
		q[k] = qk + eps;
		ProjectedVector(plus);
		q[k] = qk - eps;
		ProjectedVector(minus);
		q[k] = qk;
		for (Index j = 0; j < n; j++) { value(j, k) = (plus[j] - minus[j])/(2.*eps); }
	}
	return true;
}

Vector3D CObjectUserBody::GetPosition(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	ResizableConstVector qRef, q, q_t;
	GatherUserFunctionCoordinates(qRef, q, q_t, configuration);
	Vector3D position;
	EvaluatePosition(position, GetCSystemData()->GetConfigurationTime(configuration), localPosition, qRef, q, q_t);
	return position;
}

//! the position minus the reference position: two calls of the position user function, as the reference position
//! depends on the local position
Vector3D CObjectUserBody::GetDisplacement(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	return GetPosition(localPosition, configuration) - GetPosition(localPosition, ConfigurationType::Reference);
}

//! the position Jacobian or the rotation Jacobian times the velocity coordinates, in a configuration
Vector3D CObjectUserBody::JacobianTimesVelocity(bool rotation, const Vector3D& localPosition, ConfigurationType configuration) const
{
	ResizableConstVector qRef, q, q_t;
	GatherUserFunctionCoordinates(qRef, q, q_t, configuration);
	Real t = GetCSystemData()->GetConfigurationTime(configuration);
	static thread_local ResizableMatrix jacobian; //memory kept between the calls (#3046), per thread (#2978)
	if (rotation) { EvaluateRotationJacobian(jacobian, t, localPosition, qRef, q, q_t); }
	else { EvaluatePositionJacobian(jacobian, t, localPosition, qRef, q, q_t); }
	Vector3D result(0.);
	for (Index i = 0; i < 3; i++)
	{
		for (Index j = 0; j < q_t.NumberOfItems(); j++) { result[i] += jacobian(i, j)*q_t[j]; }
	}
	return result;
}

Vector3D CObjectUserBody::GetVelocity(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	return JacobianTimesVelocity(false, localPosition, configuration);
}

Matrix3D CObjectUserBody::GetRotationMatrix(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return EXUmath::unitMatrix3D; }
	ResizableConstVector qRef, q, q_t;
	GatherUserFunctionCoordinates(qRef, q, q_t, configuration);
	Matrix3D rotation;
	EvaluateRotationMatrix(rotation, GetCSystemData()->GetConfigurationTime(configuration), localPosition, qRef, q, q_t);
	return rotation;
}

Vector3D CObjectUserBody::GetAngularVelocity(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	return JacobianTimesVelocity(true, localPosition, configuration);
}

Vector3D CObjectUserBody::GetAngularVelocityLocal(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	return GetRotationMatrix(localPosition, configuration).GetTransposed()*GetAngularVelocity(localPosition, configuration);
}

void CObjectUserBody::GetOutputVariableBody(OutputVariableType variableType, const Vector3D& localPosition, ConfigurationType configuration, Vector& value) const
{
	switch (variableType)
	{
	case OutputVariableType::Position: value.CopyFrom(GetPosition(localPosition, configuration)); break;
	case OutputVariableType::Displacement: value.CopyFrom(GetDisplacement(localPosition, configuration)); break;
	case OutputVariableType::Velocity: value.CopyFrom(GetVelocity(localPosition, configuration)); break;
	case OutputVariableType::RotationMatrix: {
		Matrix3D rotation = GetRotationMatrix(localPosition, configuration);
		value.SetVector(9, rotation.GetDataPointer());
		break;
	}
	case OutputVariableType::AngularVelocity: value.CopyFrom(GetAngularVelocity(localPosition, configuration)); break;
	case OutputVariableType::AngularVelocityLocal: value.CopyFrom(GetAngularVelocityLocal(localPosition, configuration)); break;
	case OutputVariableType::Coordinates: {
		ResizableConstVector q_t;
		GatherCoordinates(value, q_t, configuration, false); //the displacement coordinates, without the reference
		break;
	}
	case OutputVariableType::Coordinates_t: {
		ResizableConstVector q;
		GatherCoordinates(q, value, configuration, false);
		break;
	}
	case OutputVariableType::KineticEnergy:
		CheckEnergyLocalPosition(localPosition, "ObjectUserBody");
		value.SetVector({ ComputeKineticEnergyFromMassMatrix(configuration, "ObjectUserBody") });
		break;
	case OutputVariableType::DisplacementLocal:
	case OutputVariableType::VelocityLocal:
	case OutputVariableType::Acceleration:
	case OutputVariableType::AccelerationLocal:
	case OutputVariableType::Rotation:
	case OutputVariableType::AngularAcceleration:
	case OutputVariableType::AngularAccelerationLocal:
	case OutputVariableType::Director1:
	case OutputVariableType::Director2:
	case OutputVariableType::Director3:
	case OutputVariableType::Force:
	case OutputVariableType::ForceLocal:
	case OutputVariableType::Torque:
	case OutputVariableType::TorqueLocal:
	case OutputVariableType::StrainLocal:
	case OutputVariableType::StressLocal:
	case OutputVariableType::CurvatureLocal:
	case OutputVariableType::PotentialEnergy:
	case OutputVariableType::UserType0:
	case OutputVariableType::UserType1:
	case OutputVariableType::UserType2:
	case OutputVariableType::UserType3: { //by the outputVariableUserFunction (#3057)
		if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { value.SetVector({ 0. }); break; }
		ResizableConstVector qRef, q, q_t, q_tt;
		GatherUserFunctionCoordinates(qRef, q, q_t, configuration);
		GatherAccelerations(q_tt, configuration);
		EvaluateUserFunctionOutputVariable(value, GetCSystemData()->GetConfigurationTime(configuration), variableType, localPosition, qRef, q, q_t, q_tt);
		if (value.NumberOfItems() == 0)
		{
			PyError(STDstring("ObjectUserBody: outputVariableUserFunction gives no value for OutputVariableType ") + GetOutputVariableTypeString(variableType),
				PyErrorType::valueError);
		}
		break;
	}
	default:
		SysError("CObjectUserBody::GetOutputVariableBody failed"); //error should not occur, because types are checked!
	}
}

//! graphicsData in local coordinates, every point mapped by the positionUserFunction in the visualization configuration
//! (#3064); in the main thread, as the user body is drawn there (#3003); the graphicsDataUserFunction, in global
//! coordinates, is drawn by CallUserFunction
void VisualizationObjectUserBody::UpdateGraphics(const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemNumber)
{
	const BodyGraphicsData& data = graphicsData;
	if (data.glLines.NumberOfItems() + data.glCirclesXY.NumberOfItems() + data.glTexts.NumberOfItems() + data.glTriangles.NumberOfItems()
		+ data.glSpheres.NumberOfItems() + data.glTriangles6.NumberOfItems() + data.glLines3.NumberOfItems()
		+ data.glTexturedTriangles.NumberOfItems() == 0) { return; }

	const CObjectUserBody* cObject = (const CObjectUserBody*)vSystem->systemData->GetCObjects()[itemNumber];
	if (!cObject->PythonCallPossible()) { return; }
	ResizableConstVector qRef, q, q_t, zero;
	cObject->GatherCoordinates(q, q_t, ConfigurationType::Visualization, true);
	cObject->GatherCoordinates(qRef, zero, ConfigurationType::Reference, true);
	Real t = vSystem->systemData->GetConfigurationTime(ConfigurationType::Visualization);
	Index itemID = Index2ItemID(itemNumber, ItemType::Object, vSystem->GetSystemID());

	auto Map = [&](const Float3& localPosition)
	{
		Vector3D position;
		cObject->EvaluatePosition(position, t, Vector3D({ localPosition[0], localPosition[1], localPosition[2] }), qRef, q, q_t);
		return Float3({ (float)position[0], (float)position[1], (float)position[2] });
	};
	EXUvis::AddBodyGraphicsDataMapped(graphicsData, vSystem->graphicsData, Map, itemID);
	if (visualizationSettings.bodies.showNumbers)
	{
		EXUvis::DrawItemNumber(Map(Float3(0.f)), vSystem, itemID, "", visualizationSettings.bodies.defaultColor);
	}
}
