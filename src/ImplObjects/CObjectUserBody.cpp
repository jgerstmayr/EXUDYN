//! the object coordinates including the reference values, and the velocity coordinates
void CObjectUserBody::ComputeObjectCoordinates(StdVector& coordinates, StdVector& coordinates_t, ConfigurationType configuration) const
{
	Index n = GetODE2Size();
	coordinates.resize(n);
	coordinates_t.assign(n, 0.);
	Index cnt = 0;
	for (Index nn = 0; nn < GetNumberOfNodes(); nn++)
	{
		const CNodeODE2* node = (const CNodeODE2*)GetCNode(nn);
		Index nc = node->GetNumberOfODE2Coordinates();
		LinkedDataVector reference(node->GetReferenceCoordinateVector());
		for (Index i = 0; i < nc; i++) { coordinates[cnt + i] = reference[i]; }
		if (configuration != ConfigurationType::Reference)
		{
			LinkedDataVector u(node->GetCoordinateVector(configuration));
			LinkedDataVector u_t(node->GetCoordinateVector_t(configuration));
			for (Index i = 0; i < nc; i++)
			{
				coordinates[cnt + i] += u[i];
				coordinates_t[cnt + i] = u_t[i];
			}
		}
		cnt += nc;
	}
}

Index CObjectUserBody::GetODE2Size() const
{
	Index n = 0;
	for (Index nn = 0; nn < GetNumberOfNodes(); nn++) { n += GetCNode(nn)->GetNumberOfODE2Coordinates(); }
	return n;
}

//! the number of this object, found once in the list of objects
Index CObjectUserBody::GetObjectNumber() const
{
	const ResizableArray<CObject*>& objects = GetCSystemData()->GetCObjects();
	if (ownObjectNumber < 0 || ownObjectNumber >= objects.NumberOfItems() || objects[ownObjectNumber] != this)
	{
		ownObjectNumber = -1;
		for (Index i = 0; i < objects.NumberOfItems(); i++)
		{
			if (objects[i] == this) { ownObjectNumber = i; break; }
		}
	}
	return ownObjectNumber;
}

//! the time of a configuration, which the user functions get
static Real ConfigurationTime(const CSystemData* systemData, ConfigurationType configuration)
{
	return systemData->GetCData().Get(configuration).GetTime();
}

void CObjectUserBody::ComputeMassMatrix(EXUmath::MatrixContainer& massMatrixC, const ArrayIndex& ltg, Index objectNumber, bool computeInverse) const
{
	CHECKandTHROW(!computeInverse, "ObjectUserBody: computeMassMatrixInversePerBody=True is not possible, change the solver settings", ExudynNotImplementedError);
	StdVector q, q_t;
	ComputeObjectCoordinates(q, q_t, ConfigurationType::Current);
	EvaluateUserFunctionMassMatrix(massMatrixC, ConfigurationTime(GetCSystemData(), ConfigurationType::Current), objectNumber, q, q_t, ltg);
}

//! the left-hand side is the negative force of the user function
void CObjectUserBody::ComputeODE2LHS(Vector& ode2Lhs, Index objectNumber) const
{
	Index n = GetODE2Size();
	ode2Lhs.SetNumberOfItems(n);
	ode2Lhs.SetAll(0.);
	if (parameters.forceUserFunction)
	{
		StdVector q, q_t;
		ComputeObjectCoordinates(q, q_t, ConfigurationType::Current);
		Vector force;
		EvaluateUserFunctionForce(force, ConfigurationTime(GetCSystemData(), ConfigurationType::Current), objectNumber, q, q_t);
		if (force.NumberOfItems() != n) { PyError("ObjectUserBody: forceUserFunction returned a vector of size " + EXUstd::ToString(force.NumberOfItems())
			+ ", but the body has " + EXUstd::ToString(n) + " coordinates", PyErrorType::valueError); }
		ode2Lhs -= force;
	}
}

//! the user function of a matrix at the current configuration
static void CurrentMatrix(const CObjectUserBody& body, Index which, const Vector3D& localPosition, Matrix& value)
{
	StdVector q, q_t;
	body.ComputeObjectCoordinates(q, q_t, ConfigurationType::Current);
	body.EvaluateMatrix(which, value, ConfigurationTime(body.GetCSystemData(), ConfigurationType::Current), localPosition, q);
}

void CObjectUserBody::GetPositionJacobian(const Vector3D& localPosition, Matrix& value) const
{
	CurrentMatrix(*this, 0, localPosition, value);
}

void CObjectUserBody::GetRotationJacobian(const Vector3D& localPosition, Matrix& value) const
{
	CurrentMatrix(*this, 2, localPosition, value);
}

//! d(J_pos^T force + J_rot^T torque)/dq by central differences of the Jacobian user functions
bool CObjectUserBody::GetJacobianTransposedTimesVectorDerivative(const Vector3D& localPosition, const Vector6D& forceTorque, Matrix& value) const
{
	Vector3D force({ forceTorque[0], forceTorque[1], forceTorque[2] });
	Vector3D torque({ forceTorque[3], forceTorque[4], forceTorque[5] });
	bool hasForce = !(force == 0.);
	bool hasTorque = !(torque == 0.);
	if (!hasForce && !hasTorque) { return false; }

	Index n = GetODE2Size();
	StdVector q, q_t;
	ComputeObjectCoordinates(q, q_t, ConfigurationType::Current);
	Real t = ConfigurationTime(GetCSystemData(), ConfigurationType::Current);
	value.SetNumberOfRowsAndColumns(n, n);

	Matrix jacobian;
	Vector plus(n), minus(n);
	//J^T force + J_rot^T torque at the coordinates qVaried
	auto ProjectedVector = [&](const StdVector& qVaried, Vector& result)
	{
		result.SetAll(0.);
		if (hasForce)
		{
			EvaluateMatrix(0, jacobian, t, localPosition, qVaried);
			for (Index j = 0; j < n; j++) { for (Index i = 0; i < 3; i++) { result[j] += jacobian(i, j)*force[i]; } }
		}
		if (hasTorque)
		{
			EvaluateMatrix(2, jacobian, t, localPosition, qVaried);
			for (Index j = 0; j < n; j++) { for (Index i = 0; i < 3; i++) { result[j] += jacobian(i, j)*torque[i]; } }
		}
	};

	for (Index k = 0; k < n; k++)
	{
		Real qk = q[k];
		Real eps = 1e-6*EXUstd::Maximum(1., fabs(qk));
		q[k] = qk + eps;
		ProjectedVector(q, plus);
		q[k] = qk - eps;
		ProjectedVector(q, minus);
		q[k] = qk;
		for (Index j = 0; j < n; j++) { value(j, k) = (plus[j] - minus[j])/(2.*eps); }
	}
	return true;
}

Vector3D CObjectUserBody::GetPosition(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible())
	{
		Vector3D position;
		Matrix3D rotation;
		visualizationCache.Get(localPosition, position, rotation);
		return position;
	}
	StdVector q, q_t;
	ComputeObjectCoordinates(q, q_t, configuration);
	Vector3D position;
	EvaluatePosition(position, ConfigurationTime(GetCSystemData(), configuration), localPosition, q);
	return position;
}

Vector3D CObjectUserBody::GetDisplacement(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	return GetPosition(localPosition, configuration) - GetPosition(localPosition, ConfigurationType::Reference);
}

//! the matrix times the velocity coordinates of the configuration
static Vector3D MatrixTimesVelocity(const CObjectUserBody& body, Index which, const Vector3D& localPosition, ConfigurationType configuration)
{
	StdVector q, q_t;
	body.ComputeObjectCoordinates(q, q_t, configuration);
	Matrix jacobian;
	body.EvaluateMatrix(which, jacobian, ConfigurationTime(body.GetCSystemData(), configuration), localPosition, q);
	Vector3D result(0.);
	for (Index i = 0; i < 3; i++)
	{
		for (Index j = 0; j < (Index)q_t.size(); j++) { result[i] += jacobian(i, j)*q_t[j]; }
	}
	return result;
}

Vector3D CObjectUserBody::GetVelocity(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	return MatrixTimesVelocity(*this, 0, localPosition, configuration);
}

Matrix3D CObjectUserBody::GetRotationMatrix(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible())
	{
		Vector3D position;
		Matrix3D rotation;
		visualizationCache.Get(localPosition, position, rotation);
		return rotation;
	}
	StdVector q, q_t;
	ComputeObjectCoordinates(q, q_t, configuration);
	Matrix rotation;
	EvaluateMatrix(1, rotation, ConfigurationTime(GetCSystemData(), configuration), localPosition, q);
	Matrix3D rotation3D;
	rotation3D.CopyFrom(rotation);
	return rotation3D;
}

Vector3D CObjectUserBody::GetAngularVelocity(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	return MatrixTimesVelocity(*this, 2, localPosition, configuration);
}

Vector3D CObjectUserBody::GetAngularVelocityLocal(const Vector3D& localPosition, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	return GetRotationMatrix(localPosition, configuration).GetTransposed()*GetAngularVelocity(localPosition, configuration);
}

void CObjectUserBody::GetOutputVariableBody(OutputVariableType variableType, const Vector3D& localPosition, ConfigurationType configuration, Vector& value, Index objectNumber) const
{
	switch (variableType)
	{
	case OutputVariableType::Position: value.CopyFrom(GetPosition(localPosition, configuration)); break;
	case OutputVariableType::Displacement: value.CopyFrom(GetDisplacement(localPosition, configuration)); break;
	case OutputVariableType::Velocity: value.CopyFrom(GetVelocity(localPosition, configuration)); break;
	case OutputVariableType::RotationMatrix: {
		Matrix3D rotation = GetRotationMatrix(localPosition, configuration);
		value.SetVector(9, rotation.GetDataPointer());
		break;
	}
	case OutputVariableType::AngularVelocity: value.CopyFrom(GetAngularVelocity(localPosition, configuration)); break;
	case OutputVariableType::AngularVelocityLocal: value.CopyFrom(GetAngularVelocityLocal(localPosition, configuration)); break;
	case OutputVariableType::Coordinates:
	case OutputVariableType::Coordinates_t: {
		StdVector q, q_t, qReference, q_tReference;
		ComputeObjectCoordinates(q, q_t, configuration);
		value.SetNumberOfItems((Index)q.size());
		if (variableType == OutputVariableType::Coordinates)
		{
			ComputeObjectCoordinates(qReference, q_tReference, ConfigurationType::Reference);
			for (Index i = 0; i < (Index)q.size(); i++) { value[i] = q[i] - qReference[i]; }
		}
		else
		{
			for (Index i = 0; i < (Index)q.size(); i++) { value[i] = q_t[i]; }
		}
		break;
	}
	case OutputVariableType::KineticEnergy:
		CheckEnergyLocalPosition(localPosition, "ObjectUserBody");
		value.SetVector({ ComputeKineticEnergyFromMassMatrix(configuration, objectNumber, "ObjectUserBody") });
		break;
	default:
		SysError("CObjectUserBody::GetOutputVariableBody failed"); //error should not occur, because types are checked!
	}
}

//! the positions and rotations of the local positions the renderer asked for, in the visualization configuration
void CObjectUserBody::UpdateVisualizationCache() const
{
	std::vector<Vector3D> localPositions = visualizationCache.GetLocalPositions();
	if (localPositions.size() == 0) { return; }

	StdVector q, q_t;
	ComputeObjectCoordinates(q, q_t, ConfigurationType::Visualization);
	Real t = ConfigurationTime(GetCSystemData(), ConfigurationType::Visualization);
	for (const Vector3D& localPosition : localPositions)
	{
		Vector3D position;
		EvaluatePosition(position, t, localPosition, q);
		Matrix3D rotation3D = EXUmath::unitMatrix3D;
		if (parameters.rotationMatrixUserFunction)
		{
			Matrix rotation;
			EvaluateMatrix(1, rotation, t, localPosition, q);
			rotation3D.CopyFrom(rotation);
		}
		visualizationCache.Set(localPosition, position, rotation3D);
	}
}

