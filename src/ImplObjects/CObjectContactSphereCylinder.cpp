void VisualizationObjectContactSphereCylinder::UpdateGraphics(const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemNumber)
{
	Index itemID = Index2ItemID(itemNumber, ItemType::Object, vSystem->GetSystemID());
	Float4 currentColor = visualizationSettings.connectors.defaultColor;

	CObjectContactSphereCylinder* cItem = (CObjectContactSphereCylinder*)vSystem->systemData->GetCObjects()[itemNumber];

	Vector3D pos[2];
	vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[0]]->GetPosition(*vSystem->systemData, pos[0], ConfigurationType::Visualization);
	vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[1]]->GetPosition(*vSystem->systemData, pos[1], ConfigurationType::Visualization);

	if (color[0] != -1.f) { currentColor = color; }

	if (visualizationSettings.contact.show.spheres)
	{
		Float4 sphereColor = visualizationSettings.contact.color.spheres;
		if (color[0] != -1.f) { sphereColor = color; }
		EXUvis::DrawSphere(pos[0], cItem->GetParameters().sphereRadius, sphereColor, vSystem->graphicsData, itemID, visualizationSettings.general.sphereTiling);
	}
	if (visualizationSettings.contact.show.cylinders)
	{
		Float4 cylinderColor = visualizationSettings.contact.color.cylinders;
		if (color[0] != -1.f) { cylinderColor = color; }
		Matrix3D A1;
		vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[1]]->GetRotationMatrix(*vSystem->systemData, A1, ConfigurationType::Visualization);
		Vector3D axis = cItem->GetParameters().cylinderLength * Vector3D({ A1(0, 2), A1(1, 2), A1(2, 2) });
		EXUvis::DrawCylinder(pos[1] - 0.5 * axis, axis, cItem->GetParameters().cylinderRadius, cylinderColor, vSystem->graphicsData, itemID,
			visualizationSettings.general.cylinderTiling);
	}

	if (DrawContactForces(visualizationSettings, cItem->GetParameters().contactForceUserFunction) && cItem->GetParameters().activeConnector) //fVec is the force on marker 0 (#3339)
	{
		MarkerDataStructure markerData;
		VisualizationMarkerData(*vSystem->systemData, cItem->GetMarkerNumbers(), markerData);
		Vector3D deltaP, deltaV, fVec, fFriction, n0;
		Real frictionCoeff, gap;
		cItem->ComputeConnectorProperties(markerData, cItem->GetCNode(0)->GetVisualizationCoordinateVector(), frictionCoeff, gap, deltaP, deltaV, fVec, fFriction, n0, false);
		Vector3D contactPoint = markerData.GetMarkerData(0).position + (cItem->GetParameters().sphereRadius + 0.5 * gap) * n0;
		DrawContactForce(visualizationSettings, vSystem, itemID, contactPoint, fVec);
	}
	if (visualizationSettings.connectors.showNumbers) { EXUvis::DrawItemNumber(0.5 * (pos[0] + pos[1]), vSystem, itemID, "", currentColor); }
}
