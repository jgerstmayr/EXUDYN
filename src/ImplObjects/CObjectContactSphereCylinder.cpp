//compute the properties which are needed for computation of LHS and needed for OutputVariables
void CObjectContactSphereCylinder::ComputeConnectorProperties(const MarkerDataStructure& markerData, const LinkedDataVector& data,
	Real& frictionCoeff, Real& gap, Vector3D& deltaP, Vector3D& deltaV,
	Vector3D& fVec, Vector3D& fFriction, Vector3D& n0, bool contactFromData) const
{
	//0=Sphere, 1=Cylinder
	const Matrix3D& A1 = markerData.GetMarkerData(1).orientation;
	const Vector3D& p1 = markerData.GetMarkerData(1).position;
	const Vector3D& v1 = markerData.GetMarkerData(1).velocity;
	const Vector3D& omega1 = markerData.GetMarkerData(1).angularVelocityLocal;

	const Vector3D& p0 = markerData.GetMarkerData(0).position;
	const Vector3D& v0 = markerData.GetMarkerData(0).velocity;

	EGeometry::ConvexShape cylinder;
	cylinder.type = EGeometry::ConvexShapeType::Cylinder;
	cylinder.radius = parameters.cylinderRadius;
	cylinder.length = parameters.cylinderLength;
	EGeometry::ConvexDistanceResult result;
	EGeometry::DistanceSphereCylinder(parameters.sphereRadius, p0, cylinder, HomogeneousTransformation(A1, p1), result);

	gap = result.distance;
	n0 = result.normal; //from the sphere towards the cylinder, also with the center inside
	const Vector3D& cylinderPoint = result.point1;
	deltaP = cylinderPoint - p0;

	//global cylinder velocity at the contact point
	Vector3D vCylinder = (A1 * omega1).CrossProduct(cylinderPoint - p1) + v1;
	//global sphere velocity at the contact point:
	Vector3D vSphere = v0;
	if (parameters.dynamicFriction != 0) //only in this case, the A0 and omega0 exist and velocity can be computed
	{
		const Matrix3D& A0 = markerData.GetMarkerData(0).orientation;
		const Vector3D& omega0 = markerData.GetMarkerData(0).angularVelocityLocal;
		vSphere += (A0 * omega0).CrossProduct(cylinderPoint - p0);
	}
	deltaV = vCylinder - vSphere;

	frictionCoeff = parameters.dynamicFriction;

	bool hasContact = contactFromData ? (data[dataIndexGap] < 0) : (gap < 0);
	if (hasContact)
	{
		Real deltaVnormal = n0 * deltaV; //relative velocity in normal direction
		//frictionRegularizedRegion is only used in case that contactFromData=true
		bool frictionRegularizedRegion = data[dataIndexVtangent] < parameters.frictionProportionalZone;
		if (parameters.contactForceUserFunction) //the force by the user function (#3324)
		{
			EvaluateUserFunctionForce(fVec, cSystemData->GetMainSystemBacklink(), markerData.GetTime(), gap, deltaVnormal, n0,
				deltaV - deltaVnormal * n0, data[dataIndexImpactVel]);
			fFriction = fVec - (fVec * n0) * n0;
		}
		else
		{
			ContactPrimitiveForce<Real>(parameters, data[dataIndexImpactVel], "ObjectContactSphereCylinder", gap, n0, deltaVnormal,
				deltaV, frictionCoeff, frictionRegularizedRegion, fVec, fFriction, contactFromData);
		}
	}
	else
	{
		fVec.SetAll(0.);
		fFriction.SetAll(0.);
	}
	//in case that it is inactive, we only compute kinematical quantities, but no forces
	if (!parameters.activeConnector)
	{
		fVec.SetAll(0.);
		fFriction.SetAll(0.);
	}
}

//! the forces and torques of the connector interface (#2745): the contact force on the cylinder at the contact point
//! and its reaction on the sphere, with friction its torque; a marker without orientation takes the force only
void CObjectContactSphereCylinder::ComputeConnectorForceRigid(const MarkerRigid<Real>* markers, Real t,
	Vector3D* forces, Vector3D* torques) const
{
	for (Index k = 0; k < 2; k++) { forces[k].SetAll(0.); torques[k].SetAll(0.); }
	if (!parameters.activeConnector) { return; }
	TemporaryMarkerDataStructure temporary; //the physics read a marker data structure, without Jacobians
	MarkerDataStructure& markerData = temporary.Get();
	MarkerDataFromKinematics(markers, t, markerData);
	LinkedDataVector data = GetCNode(0)->GetCurrentCoordinateVector();
	Vector3D deltaP, deltaV, fVec, fFriction, n0;
	Real frictionCoeff, gap;
	ComputeConnectorProperties(markerData, data, frictionCoeff, gap, deltaP, deltaV, fVec, fFriction, n0);
	Vector3D contactPoint = markerData.GetMarkerData(0).position + (parameters.sphereRadius + 0.5 * gap) * n0;
	forces[1] = fVec;
	torques[1] = (contactPoint - markerData.GetMarkerData(1).position).CrossProduct(fVec);
	forces[0] = -fVec;
	if (frictionCoeff != 0) { torques[0] = (-(parameters.sphereRadius + 0.5 * gap) * n0).CrossProduct(fVec); }
}

//! provide according output variable in "value"
void CObjectContactSphereCylinder::GetOutputVariableConnector(OutputVariableType variableType, const MarkerDataStructure& markerData, Vector& value) const
{
	LinkedDataVector data = GetCNode(0)->GetCurrentCoordinateVector();
	Vector3D deltaP, deltaV, fVec, fFriction, n0;
	Real frictionCoeff, gap;
	ComputeConnectorProperties(markerData, data, frictionCoeff, gap, deltaP, deltaV, fVec, fFriction, n0);

	switch (variableType)
	{
	case OutputVariableType::Position: value.CopyFrom(markerData.GetMarkerData(0).position + (parameters.sphereRadius + 0.5 * gap) * n0); break;
	case OutputVariableType::Displacement: value.CopyFrom(deltaP); break;
	case OutputVariableType::Distance: value.CopyFrom(Vector1D({ gap })); break;
	case OutputVariableType::DisplacementLocal: value.CopyFrom(Vector1D({ gap })); break;
	case OutputVariableType::Velocity: value.CopyFrom(deltaV); break;
	case OutputVariableType::Director1: value.CopyFrom(n0); break;
	case OutputVariableType::Force: value.CopyFrom(fVec); break;
	case OutputVariableType::Torque: value.CopyFrom(((parameters.sphereRadius + 0.5 * gap) * n0).CrossProduct(fVec)); break; //the torque on marker 0 (#3328)
	default:
		SysError("CObjectContactSphereCylinder::GetOutputVariableConnector failed"); //error should not occur, because types are checked!
	}
}

//! function called after Newton method; returns a residual error (force); the contact state and the friction regime
//! of the current configuration into the data node, as ObjectContactSphereTriangle
Real CObjectContactSphereCylinder::PostNewtonStep(const MarkerDataStructure& markerDataCurrent, PostNewtonFlags::Type& flags, Real& recommendedStepSize)
{
	Real discontinuousError = 0;
	flags = PostNewtonFlags::_None;

	LinkedDataVector dataStartofStepState = ((CNodeData*)GetCNode(0))->GetCoordinateVector(ConfigurationType::StartOfStep);
	LinkedDataVector data = ((CNodeData*)GetCNode(0))->GetCoordinateVector(ConfigurationType::Current);

	Vector3D deltaP, deltaV, fVec, fFriction, n0;
	Real frictionCoeff, currentGap;
	ComputeConnectorProperties(markerDataCurrent, data, frictionCoeff, currentGap, deltaP, deltaV, fVec, fFriction, n0, false);

	Real vGap = n0 * deltaV; //required for Hunt-Crossley and similar models
	Real lastGap = data[dataIndexGap];
	Real startofStepGap = dataStartofStepState[dataIndexGap];
	Real lastVtangent = data[dataIndexVtangent];

	data[dataIndexGap] = currentGap;
	data[dataIndexVtangent] = (deltaV - vGap * n0).GetL2Norm(); //tangent velocity norm

	//the error of the gap: the contact state switched
	if ((currentGap > 0 && lastGap <= 0) || (currentGap <= 0 && lastGap > 0))
	{
		discontinuousError = fabs(currentGap * parameters.contactStiffness);
		//the time to the switch, also where the contact ends (#2109)
		if (vGap != 0 && startofStepGap != 0) { recommendedStepSize = fabs(startofStepGap / vGap); }
		flags = PostNewtonFlags::UpdateJacobian;
	}

	//the error of the friction: switching between stick and slip
	if (currentGap < 0 && parameters.frictionProportionalZone != 0.)
	{
		if ((data[dataIndexVtangent] < parameters.frictionProportionalZone && lastVtangent > parameters.frictionProportionalZone) ||
			(data[dataIndexVtangent] > parameters.frictionProportionalZone && lastVtangent < parameters.frictionProportionalZone))
		{
			discontinuousError += fabs((parameters.dynamicFriction * (fVec * n0) / parameters.frictionProportionalZone) * (data[dataIndexVtangent] - parameters.frictionProportionalZone));
		}
	}

	//the impact velocity, if an impact occured; else that of the start of the step
	if (startofStepGap > 0 && currentGap <= 0) { data[dataIndexImpactVel] = -vGap; }
	else { data[dataIndexImpactVel] = dataStartofStepState[dataIndexImpactVel]; }

	return discontinuousError;
}

