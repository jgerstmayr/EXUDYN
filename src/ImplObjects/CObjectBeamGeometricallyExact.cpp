//! Computational function: compute left-hand-side (LHS) of second order ordinary differential equations (ODE) to 'ode2Lhs'
void CObjectBeamGeometricallyExact::ComputeODE2LHS(Vector& ode2Lhs, Index objectNumber) const
{
	ode2Lhs.SetNumberOfItems(GetODE2Size());
	ode2Lhs.SetAll(0.);

	const Index nDim3D = 3;
	//const Index nDisplacementCoordinates = 3;
	Index nNode0 = GetCNode(0)->GetNumberOfODE2Coordinates();
	Real L = parameters.physicsLength;
	//Real intFactL = 0.5*L; //integration weight, using 2 points Lobatto

	Vector6D h;
	Vector6D h0;
	ComputeIncrementalMotion(h, h0);
	Vector3D incDisp({ h[0], h[1], h[2] });
	Vector3D incRot({ h[3], h[4], h[5] });

	Matrix6D TexpInv[2];
	TexpInv[0] = -1.*EXUlie::TExpSE3Inv(-incDisp, -incRot);
	TexpInv[1] = EXUlie::TExpSE3Inv(incDisp, incRot);

#ifdef useAverageRotation
	Matrix3D A = ((CNodeRigidBody*)GetCNode(0))->GetRotationMatrix() * EXUlie::ExpSO3(0.5*incRot); //compute rotation at mid-span; is this correct?
#endif


	//pout << "incDisp=" << incDisp << ", ";
	//pout << "incRot=" << incRot << "\n";

	Vector6D K6D({
		parameters.physicsAxialShearStiffness[0],
		parameters.physicsAxialShearStiffness[1],
		parameters.physicsAxialShearStiffness[2],
		parameters.physicsTorsionalBendingStiffness[0],
		parameters.physicsTorsionalBendingStiffness[1],
		parameters.physicsTorsionalBendingStiffness[2]});

	Vector6D eps = 1. / L * (h - h0); //deformation as incremental motion

	ConstSizeVector<CNodeRigidBody::maxRotationCoordinates + nDim3D> res(nNode0);
	ConstSizeVector<CNodeRigidBody::maxRotationCoordinates + nDim3D> res2(nNode0);

	ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> G;
	ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> Glocal;
	Vector3D omegaLocal;
	Real intFactL = 0.5*L; //integration weight, for quadratic velocity vector (approximated!)

	for (Index i = 0; i < GetNumberOfNodes(); i++)
	{
		((CNodeRigidBody*)GetCNode(i))->CollectCurrentNodeData1(Glocal, omegaLocal);
		((CNodeRigidBody*)GetCNode(i))->GetG(G);
		//omegaLocal = ((CNodeRigidBody*)GetCNode(i))->GetAngularVelocityLocal();

		EXUmath::MultVectorComponents(K6D, eps, res);
		//EXUmath::MultMatrixVectorTemplate(K6D, eps, res);
		EXUmath::MultMatrixTransposedVectorTemplate(TexpInv[i], res, res2);

		Vector3D resPos({ res2[0], res2[1], res2[2] }); //this is the residual on incremental positions
		Vector3D resRot({ res2[3], res2[4], res2[5] }); //this is the residual on incremental rotations

		ConstSizeVector< CNodeRigidBody::maxRotationCoordinates> resRotPar; //residual on rotation parameters
#ifndef useAverageRotation
		Matrix3D A = ((CNodeRigidBody*)GetCNode(i))->GetRotationMatrix();
#endif
		//EXUmath::ApplyTransformation33(A.GetTransposed(), G); //not correct; K6D is in local coordinates => K6D*Glocal gives global equations

		//EXUmath::MultMatrixTransposedVectorTemplate(G, A*resRot, resRotPar);
		EXUmath::MultMatrixTransposedVectorTemplate(Glocal, resRot, resRotPar);
		resPos = (A*resPos); //resPos is transformed from local into global coordinates

		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		//compute quadratic velocity vector per node (lumped; the consistent one follows after the loop):
		Vector3D temp = intFactL * omegaLocal.CrossProduct(parameters.physicsCrossSectionInertia * omegaLocal);


		ConstSizeVector<CNodeRigidBody::maxRotationCoordinates> forcesQV; //forces acting on rotation coordinates
		EXUmath::MultMatrixTransposedVectorTemplate(Glocal, temp, forcesQV); //using Glocal because of omegaLocal

		Vector3D Glocal_tTheta_t(0.); //used twice!

		//additional term, if not Euler Parameters
		if ((((CNodeRigidBody*)GetCNode(i))->GetType() & Node::Type::RotationEulerParameters) == 0 &&
			(((CNodeRigidBody*)GetCNode(i))->GetType() & Node::Type::RotationRotationVector) == 0) //for Euler parameters or rotation vector, the following terms vanish
		{
			ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> Glocal_t; //store this term for case with COM!=0
			LinkedDataVector rot_t = ((CNodeRigidBody*)GetCNode(i))->GetRotationParameters_t();//store this term for case with COM!=0

			//compute: forces2 = Glocal^T * localInertia * Glocal_t * rot_t
			ConstSizeVector<CNodeRigidBody::maxRotationCoordinates> forces2;
			Vector3D temp2;

			((CNodeRigidBody*)GetCNode(i))->GetGlocal_t(Glocal_t);
			EXUmath::MultMatrixVector(Glocal_t, rot_t, Glocal_tTheta_t); //Glocal_tTheta_t stored for later usage!
			EXUmath::MultMatrixVector(intFactL*parameters.physicsCrossSectionInertia, Glocal_tTheta_t, temp2); //the inertia of half the element, as in the mass matrix (#1273)

			EXUmath::MultMatrixTransposedVectorTemplate(Glocal, temp2, forces2);
			forcesQV += forces2;

		}
		if (!pyExperimental.beamGeometricallyExactConsistentMass) { resRotPar += forcesQV; }
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

		for (Index j = 0; j < nDim3D; j++)
		{
			ode2Lhs[j + i * nNode0] += resPos[j];
		}
		for (Index j = 0; j < resRotPar.NumberOfItems(); j++)
		{
			ode2Lhs[j + nDim3D + i * nNode0] += resRotPar[j];
		}
	}

	if (pyExperimental.beamGeometricallyExactConsistentMass)
	{
		//element-consistent quadratic velocity vector (#1273): d/dt(Theta*omega) = Theta*omega_t + omega x Theta*omega at each Gauss
		//point, with omega = SV_0*omega_0 + SV_1*omega_1 and omega_i = G_i*theta_i_t, omega_i_t = G_i*theta_i_tt + G_i_t*theta_i_t
		Vector2D SV[2];
		Matrix3D Theta[2];
		Real weight;
		BeamGEInertiaAtGaussPoints(*this, SV, Theta, weight);
		ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> G[2];
		Vector3D omegaNode[2];
		Vector3D GtThetat[2];
		for (Index i = 0; i < 2; i++)
		{
			const CNodeRigidBody* node = (const CNodeRigidBody*)GetCNode(i);
			ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> G_t;
			LinkedDataVector rot_t = node->GetRotationParameters_t();
			node->GetG(G[i]);
			node->GetG_t(G_t);
			EXUmath::MultMatrixVector(G[i], rot_t, omegaNode[i]);
			EXUmath::MultMatrixVector(G_t, rot_t, GtThetat[i]);
		}
		for (Index g = 0; g < 2; g++)
		{
			Vector3D omega = SV[g][0] * omegaNode[0] + SV[g][1] * omegaNode[1];
			Vector3D force = weight * (omega.CrossProduct(Theta[g] * omega) + Theta[g] * (SV[g][0] * GtThetat[0] + SV[g][1] * GtThetat[1]));
			for (Index i = 0; i < 2; i++)
			{
				ConstSizeVector<CNodeRigidBody::maxRotationCoordinates> forceRot;
				EXUmath::MultMatrixTransposedVectorTemplate(G[i], SV[g][i] * force, forceRot);
				for (Index j = 0; j < forceRot.NumberOfItems(); j++) { ode2Lhs[j + nDim3D + i * nNode0] += forceRot[j]; }
			}
		}
	}
	
}

//! Computational function: compute jacobian (dense or sparse mode, see parent CObject function)
//! the elastic forces of node i are Q_i = B_i^T r_i, r_i = TexpInv_i^T s, s = K6D*(h-h0)/L, where h is the relative motion
//! of the nodes, B_i = diag(A_i^T, Glocal_i) maps the coordinate variation of node i to its body-fixed variation, and
//! dh/dq_i = TexpInv_i B_i; the Jacobian is the full derivative of Q_i (#1100, #1550):
//!   rows of node i:  B_i^T (TexpInv_i^T K6D/L + d(TexpInv_i^T s)/dh) dh/dq    - the stiffness and the change of TexpInv_i
//!                  + d(B_i^T r_i)/dq_i with r_i fixed                         - the change of A_i and Glocal_i
//! d(TexpInv_i^T s)/dh is computed by central differences of the closed-form TExpSE3Inv; the derivative of the
//! quadratic velocity vector with respect to the velocities is added with factorODE2_t, its derivative with respect to
//! the coordinates is neglected, as the one of the mass matrix
void CObjectBeamGeometricallyExact::ComputeJacobianODE2_ODE2(EXUmath::MatrixContainer& jacobianODE2, JacobianTemp& temp, Real factorODE2, Real factorODE2_t,
	Index objectNumber, const ArrayIndex& ltg) const
{
	const Index nDim3D = 3;
	const Index maxNodeCoordinates = CNodeRigidBody::maxRotationCoordinates + nDim3D;
	Index dimJacobian = ltg.NumberOfItems();
	Index nNode0 = GetCNode(0)->GetNumberOfODE2Coordinates();

	//put this check into checkPreAssembleConsistencies.cpp
	CHECKandTHROW( (nNode0 + GetCNode(1)->GetNumberOfODE2Coordinates() == dimJacobian) &&
		(nNode0 <= maxNodeCoordinates) && (GetCNode(1)->GetNumberOfODE2Coordinates() <= maxNodeCoordinates),
		"CObjectBeamGeometricallyExact::ComputeJacobianODE2_ODE2: nodal coordinates mismatch; the nodes cannot be used with this beam element");

	jacobianODE2.SetUseDenseMatrix(true);
	Matrix& jac = jacobianODE2.GetInternalDenseMatrix();
	jac.SetScalarMatrix(dimJacobian, 0.);

	Index offset[2] = { 0, nNode0 };
	Real L = parameters.physicsLength;

	Vector6D h;
	Vector6D h0;
	ComputeIncrementalMotion(h, h0);

	Vector6D KL; //the diagonal of K6D/L
	for (Index k = 0; k < nDim3D; k++)
	{
		KL[k] = parameters.physicsAxialShearStiffness[k] / L;
		KL[k + nDim3D] = parameters.physicsTorsionalBendingStiffness[k] / L;
	}
	Vector6D s; //the section forces and moments
	for (Index k = 0; k < 6; k++) { s[k] = KL[k] * (h[k] - h0[k]); }

	//TexpInv_i as a function of h; node 0 enters with the inverse relative motion
	auto TexpInvNode = [](Index i, const Vector6D& hh)
	{
		Vector3D hDisp({ hh[0], hh[1], hh[2] });
		Vector3D hRot({ hh[3], hh[4], hh[5] });
		if (i == 0) { return Matrix6D(-1.*EXUlie::TExpSE3Inv(-hDisp, -hRot)); }
		return Matrix6D(EXUlie::TExpSE3Inv(hDisp, hRot));
	};

	ConstSizeMatrix<6 * maxNodeCoordinates> B[2];               //body-fixed variation of node i
	ConstSizeMatrix<6 * 2 * maxNodeCoordinates> P(6, dimJacobian, 0.); //dh/dq
	Matrix6D TexpInv[2];
	ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> Glocal[2];
	Matrix3D A[2];
	for (Index i = 0; i < 2; i++)
	{
		const CNodeRigidBody* node = (const CNodeRigidBody*)GetCNode(i);
		Index nCoords = node->GetNumberOfODE2Coordinates();
		A[i] = node->GetRotationMatrix();
		node->GetGlocal(Glocal[i]);
		B[i].SetNumberOfRowsAndColumns(6, nCoords);
		B[i].SetAll(0.);
		B[i].SetSubmatrix(A[i].GetTransposed(), 0, 0);
		B[i].SetSubmatrix(Glocal[i], nDim3D, nDim3D);

		TexpInv[i] = TexpInvNode(i, h);
		for (Index k = 0; k < 6; k++)
		{
			for (Index j = 0; j < nCoords; j++)
			{
				Real sum = 0.;
				for (Index m = 0; m < 6; m++) { sum += TexpInv[i](k, m) * B[i](m, j); }
				P(k, offset[i] + j) = sum;
			}
		}
	}

	for (Index i = 0; i < 2; i++)
	{
		const CNodeRigidBody* node = (const CNodeRigidBody*)GetCNode(i);
		Index nCoords = node->GetNumberOfODE2Coordinates();

		//C = TexpInv_i^T K6D/L + d(TexpInv_i^T s)/dh
		Matrix6D C(6, 6);
		for (Index k = 0; k < 6; k++)
		{
			for (Index m = 0; m < 6; m++) { C(k, m) = TexpInv[i](m, k) * KL[m]; }
		}
		for (Index m = 0; m < 6; m++)
		{
			Real delta = 1e-6 * (1. + fabs(h[m]));
			Vector6D hPlus = h;
			Vector6D hMinus = h;
			hPlus[m] += delta;
			hMinus[m] -= delta;
			Matrix6D TPlus = TexpInvNode(i, hPlus);
			Matrix6D TMinus = TexpInvNode(i, hMinus);
			for (Index k = 0; k < 6; k++)
			{
				Real sum = 0.;
				for (Index l = 0; l < 6; l++) { sum += (TPlus(l, k) - TMinus(l, k)) * s[l]; }
				C(k, m) += sum / (2. * delta);
			}
		}

		//rows of node i: B_i^T C P
		ConstSizeMatrix<6 * 2 * maxNodeCoordinates> CP(6, dimJacobian, 0.);
		EXUmath::MultMatrixMatrixTemplate(C, P, CP);
		for (Index a = 0; a < nCoords; a++)
		{
			for (Index j = 0; j < dimJacobian; j++)
			{
				Real sum = 0.;
				for (Index m = 0; m < 6; m++) { sum += B[i](m, a) * CP(m, j); }
				jac(offset[i] + a, j) += factorODE2 * sum;
			}
		}

		//d(B_i^T r_i)/dq_i with r_i = TexpInv_i^T s fixed: d(A_i*rPos)/dtheta_i = -A_i*rPosTilde*Glocal_i, d(Glocal_i^T*rRot)/dtheta_i
		Vector3D rPos(0.);
		Vector3D rRot(0.);
		for (Index k = 0; k < nDim3D; k++)
		{
			for (Index l = 0; l < 6; l++)
			{
				rPos[k] += TexpInv[i](l, k) * s[l];
				rRot[k] += TexpInv[i](l, k + nDim3D) * s[l];
			}
		}
		Matrix3D ArTilde = A[i] * RigidBodyMath::Vector2SkewMatrix(rPos);
		Index nRot = nCoords - nDim3D;
		for (Index k = 0; k < nDim3D; k++)
		{
			for (Index j = 0; j < nRot; j++)
			{
				Real sum = 0.;
				for (Index m = 0; m < nDim3D; m++) { sum += ArTilde(k, m) * Glocal[i](m, j); }
				jac(offset[i] + k, offset[i] + nDim3D + j) -= factorODE2 * sum;
			}
		}
		ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * CNodeRigidBody::maxRotationCoordinates> GlocalTv_q;
		node->GetGlocalTv_q(rRot, GlocalTv_q);
		for (Index k = 0; k < nRot; k++)
		{
			for (Index j = 0; j < nRot; j++) { jac(offset[i] + nDim3D + k, offset[i] + nDim3D + j) += factorODE2 * GlocalTv_q(k, j); }
		}

		//quadratic velocity vector 0.5*L*Glocal^T*(omega x J*omega + J*Glocal_t*theta_t), derivative with respect to theta_t (lumped)
		if (factorODE2_t != 0. && !pyExperimental.beamGeometricallyExactConsistentMass)
		{
			Real intFactL = 0.5 * L;
			const Matrix3D& J = parameters.physicsCrossSectionInertia;
			ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> GlocalCurrent;
			Vector3D omegaLocal;
			node->CollectCurrentNodeData1(GlocalCurrent, omegaLocal);

			//d(omega x J*omega)/domega = omegaTilde*J - (J*omega)Tilde
			Matrix3D Momega = RigidBodyMath::Vector2SkewMatrix(omegaLocal) * J - RigidBodyMath::Vector2SkewMatrix(J * omegaLocal);
			ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> dQ(nDim3D, nRot, 0.); //the derivative before the projection with Glocal^T
			for (Index k = 0; k < nDim3D; k++)
			{
				for (Index j = 0; j < nRot; j++)
				{
					for (Index m = 0; m < nDim3D; m++) { dQ(k, j) += Momega(k, m) * Glocal[i](m, j); }
				}
			}
			if (node->GetType() & Node::Type::RotationRxyz) //Glocal_t*theta_t vanishes for Euler parameters and the rotation vector
			{
				//d(Glocal_t*theta_t)/dtheta_t = Glocal_t + [Glocal_t(theta, e_j)*theta_t]_j, as Glocal_t is linear in theta_t
				ConstSizeVector<CNodeRigidBody::maxRotationCoordinates> rot = node->GetRotationParameters();
				LinkedDataVector rot_t = node->GetRotationParameters_t();
				ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> dGtheta =
					RigidBodyMath::RotXYZ2Glocal_tTemplate<ConstSizeVector<CNodeRigidBody::maxRotationCoordinates>, LinkedDataVector>(rot, rot_t);
				for (Index j = 0; j < nRot; j++)
				{
					Vector3D ej(0.);
					ej[j] = 1.;
					ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> Glocal_tj =
						RigidBodyMath::RotXYZ2Glocal_tTemplate<ConstSizeVector<CNodeRigidBody::maxRotationCoordinates>, Vector3D>(rot, ej);
					for (Index k = 0; k < nDim3D; k++)
					{
						for (Index m = 0; m < nRot; m++) { dGtheta(k, j) += Glocal_tj(k, m) * rot_t[m]; }
					}
				}
				for (Index k = 0; k < nDim3D; k++)
				{
					for (Index j = 0; j < nRot; j++)
					{
						for (Index m = 0; m < nDim3D; m++) { dQ(k, j) += J(k, m) * dGtheta(m, j); }
					}
				}
			}
			for (Index k = 0; k < nRot; k++)
			{
				for (Index j = 0; j < nRot; j++)
				{
					Real sum = 0.;
					for (Index m = 0; m < nDim3D; m++) { sum += Glocal[i](m, k) * dQ(m, j); }
					jac(offset[i] + nDim3D + k, offset[i] + nDim3D + j) += factorODE2_t * intFactL * sum;
				}
			}
		}
	}

	if (factorODE2_t != 0. && pyExperimental.beamGeometricallyExactConsistentMass)
	{
		//derivative of the element-consistent quadratic velocity vector with respect to theta_t (#1273):
		//G_i^T * sum_g w*SV_i*SV_j*[(omegaTilde*Theta - (Theta*omega)Tilde)*G_j + Theta*d(G_j_t*theta_j_t)/dtheta_j_t]
		Vector2D SV[2];
		Matrix3D Theta[2];
		Real weight;
		BeamGEInertiaAtGaussPoints(*this, SV, Theta, weight);
		ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> G[2];
		ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> dGtThetat[2]; //d(G_t*theta_t)/dtheta_t
		Vector3D omegaNode[2];
		for (Index i = 0; i < 2; i++)
		{
			const CNodeRigidBody* node = (const CNodeRigidBody*)GetCNode(i);
			LinkedDataVector rot_t = node->GetRotationParameters_t();
			node->GetG(G[i]);
			EXUmath::MultMatrixVector(G[i], rot_t, omegaNode[i]);
			Index nRot = G[i].NumberOfColumns();
			dGtThetat[i].SetNumberOfRowsAndColumns(nDim3D, nRot);
			dGtThetat[i].SetAll(0.);
			if (node->GetType() & Node::Type::RotationRxyz) //G_t*theta_t is zero for Euler parameters
			{
				//G_t is linear in theta_t: d(G_t*theta_t)/dtheta_t = G_t + [G_t(theta, e_m)*theta_t]_m
				ConstSizeVector<CNodeRigidBody::maxRotationCoordinates> rot = node->GetRotationParameters();
				node->GetG_t(dGtThetat[i]);
				for (Index m = 0; m < nRot; m++)
				{
					Vector3D em(0.);
					em[m] = 1.;
					ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * nDim3D> G_tm =
						RigidBodyMath::RotXYZ2G_tTemplate<ConstSizeVector<CNodeRigidBody::maxRotationCoordinates>, Vector3D>(rot, em);
					for (Index k = 0; k < nDim3D; k++)
					{
						for (Index l = 0; l < nRot; l++) { dGtThetat[i](k, m) += G_tm(k, l) * rot_t[l]; }
					}
				}
			}
			else if (!(node->GetType() & Node::Type::RotationEulerParameters))
			{
				node->GetG_t(dGtThetat[i]); //rotation vector: the part of G_t only
			}
		}
		for (Index g = 0; g < 2; g++)
		{
			Vector3D omega = SV[g][0] * omegaNode[0] + SV[g][1] * omegaNode[1];
			Matrix3D Momega = RigidBodyMath::Vector2SkewMatrix(omega) * Theta[g] - RigidBodyMath::Vector2SkewMatrix(Theta[g] * omega);
			for (Index i = 0; i < 2; i++)
			{
				for (Index j = 0; j < 2; j++)
				{
					Real factor = factorODE2_t * weight * SV[g][i] * SV[g][j];
					Index nRotI = G[i].NumberOfColumns();
					Index nRotJ = G[j].NumberOfColumns();
					for (Index b = 0; b < nRotJ; b++)
					{
						Vector3D column(0.); //(Momega*G_j + Theta*dGtThetat_j) e_b
						for (Index k = 0; k < nDim3D; k++)
						{
							for (Index m = 0; m < nDim3D; m++) { column[k] += Momega(k, m) * G[j](m, b) + Theta[g](k, m) * dGtThetat[j](m, b); }
						}
						for (Index a = 0; a < nRotI; a++)
						{
							Real sum = 0.;
							for (Index k = 0; k < nDim3D; k++) { sum += G[i](k, a) * column[k]; }
							jac(offset[i] + nDim3D + a, offset[j] + nDim3D + b) += factor * sum;
						}
					}
				}
			}
		}
	}
}


//! provide Jacobian at localPosition in 'value' according to object access
void CObjectBeamGeometricallyExact::GetAccessFunctionBody(AccessFunctionType accessType, const Vector3D& localPosition, Matrix& value) const
{
	//the Jacobians of the velocities as GetVelocity and GetAngularVelocity compute them: the nodal velocities and
	//angular velocities interpolated linearly along the axis, x = localPosition[0] in [-L/2, L/2] (#2730);
	//node i has 3 displacement coordinates, followed by its rotation parameters
	const Index nDim3D = 3;
	Vector2D SV = ComputeShapeFunctions(localPosition[0]);
	Index nCoordinates[2] = { GetCNode(0)->GetNumberOfODE2Coordinates(), GetCNode(1)->GetNumberOfODE2Coordinates() };
	Index offset[2] = { 0, nCoordinates[0] };

	switch (accessType)
	{
	case AccessFunctionType::TranslationalVelocity_qt:
	{
		value.SetNumberOfRowsAndColumns(nDim3D, GetODE2Size());
		value.SetAll(0.);
		for (Index i = 0; i < 2; i++)
		{
			for (Index k = 0; k < nDim3D; k++) { value(k, offset[i] + k) = SV[i]; }
		}
		//a point off the axis: v += R(x) * (omegaLocal(x) x pCS), omegaLocal interpolated from Glocal*theta_t of the nodes
		Vector3D pCS({ 0., localPosition[1], localPosition[2] });
		if (pCS[1] != 0. || pCS[2] != 0.)
		{
			Matrix3D A = GetLocalPositionFrame(localPosition, ConfigurationType::Current).GetRotation();
			ConstSizeMatrix<9> pTilde = RigidBodyMath::Vector2SkewMatrix(-pCS); //omega x p = -pTilde*omega
			ConstSizeMatrix<9> ApTilde;
			EXUmath::MultMatrixMatrix(A, pTilde, ApTilde);
			for (Index i = 0; i < 2; i++)
			{
				ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * 3> Glocal;
				((CNodeRigidBody*)GetCNode(i))->GetGlocal(Glocal);
				for (Index k = 0; k < nDim3D; k++)
				{
					for (Index j = 0; j < Glocal.NumberOfColumns(); j++)
					{
						Real sum = 0.;
						for (Index m = 0; m < nDim3D; m++) { sum += ApTilde(k, m) * Glocal(m, j); }
						value(k, offset[i] + nDim3D + j) += SV[i] * sum;
					}
				}
			}
		}
		break;
	}
	case AccessFunctionType::AngularVelocity_qt:
	{
		value.SetNumberOfRowsAndColumns(nDim3D, GetODE2Size());
		value.SetAll(0.);
		for (Index i = 0; i < 2; i++)
		{
			ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates * 3> G;
			((CNodeRigidBody*)GetCNode(i))->GetG(G);
			for (Index k = 0; k < nDim3D; k++)
			{
				for (Index j = 0; j < G.NumberOfColumns(); j++) { value(k, offset[i] + nDim3D + j) = SV[i] * G(k, j); }
			}
		}
		break;
	}
	case AccessFunctionType::JacobianTtimesVector_q:
	{
		//the derivative of the Jacobians is not computed: taken as zero, which is exact for the position
		//part on the axis and an approximation for rotation parameters with a configuration dependent G
		value.SetNumberOfRowsAndColumns(0, 0); //indicates that all entries are zero
		break;
	}
	case AccessFunctionType::DisplacementMassIntegral_q:
	{
		//the mass of the element at its two nodes, half each, as the lumped mass matrix: a distributed
		//load gives no nodal torques
		value.SetNumberOfRowsAndColumns(nDim3D, GetODE2Size());
		value.SetAll(0.);
		Real halfMass = 0.5 * parameters.physicsMassPerLength * parameters.physicsLength;
		for (Index i = 0; i < 2; i++)
		{
			for (Index k = 0; k < nDim3D; k++) { value(k, offset[i] + k) = halfMass; }
		}
		break;
	}
	default:
		SysError("CObjectBeamGeometricallyExact:GetAccessFunctionBody illegal accessType");
	}
}

//! provide according output variable in 'value'
void CObjectBeamGeometricallyExact::GetOutputVariableBody(OutputVariableType variableType, const Vector3D& localPosition, ConfigurationType configuration, Vector& value, Index objectNumber) const
{
	//CHECKandTHROWstring("CObjectBeamGeometricallyExact::GetOutputVariableBody not implemented!");

	switch (variableType)
	{
	case OutputVariableType::Position:	value.CopyFrom(GetPosition(localPosition, configuration)); break;
	case OutputVariableType::Displacement:	value.CopyFrom(GetPosition(localPosition, configuration) - GetPosition(localPosition, ConfigurationType::Reference)); break;
	case OutputVariableType::Velocity:	value.CopyFrom(GetVelocity(localPosition, configuration)); break;
	case OutputVariableType::Rotation:	value.CopyFrom(RigidBodyMath::RotationMatrix2RotXYZ(GetRotationMatrix(localPosition, configuration))); break;
	case OutputVariableType::RotationMatrix:
	{
		Matrix3D rotationMatrix = GetRotationMatrix(localPosition, configuration);
		value.SetVector(9, rotationMatrix.GetDataPointer());
		break;
	}
	case OutputVariableType::AngularVelocity:	value.CopyFrom(GetAngularVelocity(localPosition, configuration)); break;
	case OutputVariableType::AngularVelocityLocal:	value.CopyFrom(GetAngularVelocityLocal(localPosition, configuration)); break;
	case OutputVariableType::StrainLocal:
	case OutputVariableType::CurvatureLocal:
	case OutputVariableType::ForceLocal:
	case OutputVariableType::TorqueLocal:
	{
		//the strains (h-h0)/L are constant in the element, the section forces and moments K*(h-h0)/L (#2753)
		Vector6D h;
		Vector6D h0;
		ComputeIncrementalMotion(h, h0, configuration);
		Real L = parameters.physicsLength;
		Vector6D strain;
		for (Index k = 0; k < 6; k++) { strain[k] = (h[k] - h0[k]) / L; }
		const Vector3D& kAS = parameters.physicsAxialShearStiffness;
		const Vector3D& kTB = parameters.physicsTorsionalBendingStiffness;
		switch (variableType)
		{
		case OutputVariableType::StrainLocal:		value.SetVector({ strain[0], 0., 0., 0., strain[2], strain[1] }); break;
		case OutputVariableType::CurvatureLocal:	value.SetVector({ strain[3], strain[4], strain[5] }); break;
		case OutputVariableType::ForceLocal:		value.SetVector({ kAS[0] * strain[0], kAS[1] * strain[1], kAS[2] * strain[2] }); break;
		default:									value.SetVector({ kTB[0] * strain[3], kTB[1] * strain[4], kTB[2] * strain[5] }); break; //TorqueLocal
		}
		break;
	}
	default:
		SysError("CObjectBeamGeometricallyExact::GetOutputVariableBody failed"); //error should not occur, because types are checked!
	}
}

//! use matrix logarithm to compute relative frame position
HomogeneousTransformation CObjectBeamGeometricallyExact::GetLocalPositionFrame(const Vector3D& localPosition, 
	ConfigurationType configuration) const
{
	Vector2D SV = ComputeShapeFunctions(localPosition[0]); //SV[1] goes from 0 at node 0 (x=-L/2) to 1 at node 1 (x=L/2)

	const CNodeRigidBody* node0 = (CNodeRigidBody*)GetCNode(0);
	const CNodeRigidBody* node1 = (CNodeRigidBody*)GetCNode(1);
	HomogeneousTransformation HT0(node0->GetRotationMatrix(configuration), node0->GetPosition(configuration));
	HomogeneousTransformation HT1(node1->GetRotationMatrix(configuration), node1->GetPosition(configuration));

	Vector3D incDisp;
	Vector3D incRot;
	HT0.GetRelativeMotionTo(HT1, incDisp, incRot);

	//compute incremental rotation/displacement at some intermediate position:
	//the fraction of the way from node 0 to node 1 (#2730)
	incDisp *= SV[1];
	incRot *= SV[1];

	//HT at local position x:
	return HT0 * EXUlie::ExpSE3(incDisp, incRot);
}



//! return the (global) position of 'localPosition' according to configuration type
Vector3D CObjectBeamGeometricallyExact::GetPosition(const Vector3D& localPosition, ConfigurationType configuration) const
{
	HomogeneousTransformation HTlocalPosition = GetLocalPositionFrame(localPosition, configuration);

	Vector3D p = HTlocalPosition.GetTranslation();
	
	if (localPosition[1] != 0. || localPosition[2] != 0.)
	{
		p += HTlocalPosition.GetRotation() * Vector3D({0.,localPosition[1],localPosition[2]});
	}

	return p;

}

//! return the (global) displacemnet of 'localPosition' according to configuration type
Vector3D CObjectBeamGeometricallyExact::GetDisplacement(const Vector3D& localPosition, ConfigurationType configuration) const
{
	return GetPosition(localPosition, configuration) - GetPosition(localPosition, ConfigurationType::Reference);
}

//! return the (global) velocity of 'localPosition' according to configuration type
Vector3D CObjectBeamGeometricallyExact::GetVelocity(const Vector3D& localPosition, ConfigurationType configuration) const
{
	Vector2D SV = ComputeShapeFunctions(localPosition[0]); //SV[0] weights node 0, SV[1] node 1

	//Matrix3D A[2];
	Vector3D vel[2];
	Vector3D omegaLoc[2];
	for (Index i = 0; i < 2; i++)
	{
		const CNodeRigidBody* node = (CNodeRigidBody*)GetCNode(i);
		omegaLoc[i] = node->GetAngularVelocityLocal(configuration);
		vel[i] = node->GetVelocity(configuration);
	}

	Vector3D v = MapVectors(SV, vel[0], vel[1]); //interpolated at midline, not consistent with position ...

	//add velocity due to cross section rotation:
	Vector3D pCS({ 0.,localPosition[1],localPosition[2] });
	v += GetLocalPositionFrame(localPosition, configuration).GetRotation()*
		MapVectors(SV, omegaLoc[0], omegaLoc[1]).CrossProduct(pCS);

	return v;
}

//! return configuration dependent rotation matrix of node; returns always a 3D Matrix, independent of 2D or 3D object; for rigid bodies, the argument localPosition has no effect
Matrix3D CObjectBeamGeometricallyExact::GetRotationMatrix(const Vector3D& localPosition, ConfigurationType configuration) const
{
	return 	GetLocalPositionFrame(localPosition, configuration).GetRotation();
}

//! return configuration dependent angular velocity of node; returns always a 3D Vector, independent of 2D or 3D object; for rigid bodies, the argument localPosition has no effect
Vector3D CObjectBeamGeometricallyExact::GetAngularVelocity(const Vector3D& localPosition, ConfigurationType configuration) const
{
	Vector2D SV = ComputeShapeFunctions(localPosition[0]); //SV[0] weights node 0, SV[1] node 1

	Vector3D omegaLoc[2];
	for (Index i = 0; i < 2; i++)
	{
		omegaLoc[i] = ((CNodeRigidBody*)GetCNode(i))->GetAngularVelocity(configuration);
	}

	return MapVectors(SV, omegaLoc[0], omegaLoc[1]); //interpolated
}

//! the angular velocity in the frame of the cross section at localPosition, as MarkerBodyRigid needs it (#2730)
Vector3D CObjectBeamGeometricallyExact::GetAngularVelocityLocal(const Vector3D& localPosition, ConfigurationType configuration) const
{
	return GetLocalPositionFrame(localPosition, configuration).GetRotation().GetTransposed() * GetAngularVelocity(localPosition, configuration);
}

