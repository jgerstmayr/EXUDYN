//! the relative motion h of node 1 to node 0 in the given configuration, and h0, the one of the stress-free configuration,
//! which is the reference configuration of the nodes: a pre-curved or pre-twisted element is stress-free there (#1494)
void CObjectBeamGeometricallyExact::ComputeIncrementalMotion(Vector6D& h, Vector6D& h0, ConfigurationType configuration) const
{
	const CNodeRigidBody* node0 = (CNodeRigidBody*)GetCNode(0);
	const CNodeRigidBody* node1 = (CNodeRigidBody*)GetCNode(1);
	Vector3D incDisp;
	Vector3D incRot;
	ConfigurationType configurations[2] = { configuration, ConfigurationType::Reference };
	for (Index k = 0; k < 2; k++)
	{
		HomogeneousTransformation HT0(node0->GetRotationMatrix(configurations[k]), node0->GetPosition(configurations[k]));
		HomogeneousTransformation HT1(node1->GetRotationMatrix(configurations[k]), node1->GetPosition(configurations[k]));
		HT0.GetRelativeMotionTo(HT1, incDisp, incRot);
		Vector6D& hk = (k == 0) ? h : h0;
		hk = Vector6D({ incDisp[0], incDisp[1], incDisp[2], incRot[0], incRot[1], incRot[2] });
	}
}

//! the element-consistent inertia (#1273): the velocity field of the element is the linear interpolation of the nodal
//! velocities and angular velocities (as GetVelocity and GetAngularVelocity compute it); the rotational inertia of the
//! cross section, Theta = R(x)*J*R(x)^T, is integrated with two Gauss points; returns SV, R*J*R^T and the weight per point
static void BeamGEInertiaAtGaussPoints(const CObjectBeamGeometricallyExact& beam, Vector2D SV[2], Matrix3D Theta[2], Real& weight)
{
	Real L = beam.GetParameters().physicsLength;
	weight = 0.5 * L;
	Real xGauss = 0.5 * L / sqrt(3.);
	for (Index g = 0; g < 2; g++)
	{
		Real x = (g == 0) ? -xGauss : xGauss;
		SV[g] = beam.ComputeShapeFunctions(x);
		Matrix3D R = beam.GetLocalPositionFrame(Vector3D({ x, 0., 0. }), ConfigurationType::Current).GetRotation();
		Theta[g] = R * beam.GetParameters().physicsCrossSectionInertia * R.GetTransposed();
	}
}

