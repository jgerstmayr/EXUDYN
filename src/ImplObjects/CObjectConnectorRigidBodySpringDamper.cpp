//! compute joint frame, relative displacement, relative rotation, relative velocity and relative angular velocity; for Real
//! and AutoDiff (#2745), except the intrinsic formulation and the user function, which are Real only
template<class TReal>
void CObjectConnectorRigidBodySpringDamper::ComputeSpringForceTorque(const MarkerRigid<TReal>* markers, Real t, Index itemIndex,
	ConstSizeMatrixBase<TReal, 9>& Ajoint, SlimVectorBase<TReal, 3>& vLocPos, SlimVectorBase<TReal, 3>& vLocVel,
	SlimVectorBase<TReal, 3>& vLocRot, SlimVectorBase<TReal, 3>& vLocAngVel, SlimVectorBase<TReal, 6>& fLocVec6D,
	bool computeForceTorque) const
{
	//spring is measured relative to marker0:

	const ConstSizeMatrixBase<TReal, 9>& A0 = markers[0].frame.GetRotation();
	const ConstSizeMatrixBase<TReal, 9>& A1 = markers[1].frame.GetRotation();
	const SlimVectorBase<TReal, 3>& p0 = markers[0].frame.GetTranslation();
	const SlimVectorBase<TReal, 3>& p1 = markers[1].frame.GetTranslation();
	//the marker frame times rotationMarker0, as for all joints and as documented; it was rotationMarker0 times the frame (#2801)
	ConstSizeMatrixBase<TReal, 9> A0all = ApplyRotationMarker(A0, parameters.rotationMarker0);
	ConstSizeMatrixBase<TReal, 9> A1all = ApplyRotationMarker(A1, parameters.rotationMarker1);

	if (parameters.intrinsicFormulation)
	{
		if constexpr (std::is_same<TReal, Real>::value)
		{
			HomogeneousTransformation HT0(A0all, p0);
			HomogeneousTransformation HT1(A1all, p1);

			HT0.GetRelativeMotionTo(HT1, vLocPos, vLocRot);

			//HT1 = relative homogeneous transformation to mid point/rotation!
			HT1 = EXUlie::ExpSE3(0.5*vLocPos, 0.5*vLocRot);
			HT0 *= HT1; //HT0 = SE3 mid-frame
			Ajoint = HT0.GetRotation();
		}
		else
		{
			CHECKandTHROWstring("ObjectConnectorRigidBodySpringDamper: the intrinsic formulation has no Jacobian by automatic differentiation");
		}
	}
	else
	{
		Ajoint = A0all;
		vLocPos = Ajoint.GetTransposed() * (p1 - p0); //vLocPos transformed to marker0 local coordinate system, where springs are defined
		ConstSizeMatrixBase<TReal, 9> relRot = Ajoint.GetTransposed() * A1all;
		vLocRot = RigidBodyMath::RotationMatrix2RotXYZTemplate(relRot);
	}

	//relative velocities: same in all formulations
	vLocVel = Ajoint.GetTransposed() * (markers[1].velocity - markers[0].velocity);
	vLocAngVel = Ajoint.GetTransposed()*(A1*markers[1].angularVelocityLocal - A0 * markers[0].angularVelocityLocal);


	if (vLocRot[0] > EXUstd::pi) { vLocRot[0] -= 2.*EXUstd::pi; }
	if (vLocRot[1] > EXUstd::pi) { vLocRot[1] -= 2.*EXUstd::pi; }
	if (vLocRot[2] > EXUstd::pi) { vLocRot[2] -= 2.*EXUstd::pi; }

	//compute resulting displacement vector:
	SlimVectorBase<TReal, 6> uLoc6D;
	SlimVectorBase<TReal, 6> vLoc6D;
	for (Index i = 0; i < 3; i++)
	{
		uLoc6D[i] = vLocPos[i];
		uLoc6D[i + 3] = vLocRot[i];
		vLoc6D[i] = vLocVel[i];
		vLoc6D[i + 3] = vLocAngVel[i];
	}

	if (computeForceTorque)
	{
		//+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		//evaluate force-torque vector:
		//compute resulting force vector:
		if (!parameters.springForceTorqueUserFunction)
		{
			for (Index i = 0; i < 6; i++) { uLoc6D[i] -= parameters.offset[i]; }
			for (Index i = 0; i < 6; i++) //stiffness * u + damping * v
			{
				TReal springForce = parameters.stiffness(i, 0) * uLoc6D[0];
				TReal damperForce = parameters.damping(i, 0) * vLoc6D[0];
				for (Index j = 1; j < 6; j++)
				{
					springForce += parameters.stiffness(i, j) * uLoc6D[j];
					damperForce += parameters.damping(i, j) * vLoc6D[j];
				}
				fLocVec6D[i] = springForce + damperForce;
			}
		}
		else
		{
			if constexpr (std::is_same<TReal, Real>::value)
			{
				EvaluateUserFunctionForce(fLocVec6D, cSystemData->GetMainSystemBacklink(), t, itemIndex, uLoc6D, vLoc6D);
			}
			else
			{
				CHECKandTHROWstring("ObjectConnectorRigidBodySpringDamper: the user function has no Jacobian by automatic differentiation");
			}
		}
	}
}

//! the forces and torques of the connector interface on rigid markers (#2745), as ComputeODE2LHS projects them: the
//! intrinsic formulation adds the same torque of the offset force on both markers
template<class TReal>
void CObjectConnectorRigidBodySpringDamper::ComputeConnectorForceRigidTemplate(const MarkerRigid<TReal>* markers, Real t, Index itemIndex,
	SlimVectorBase<TReal, 3>* forces, SlimVectorBase<TReal, 3>* torques) const
{
	for (Index k = 0; k < 2; k++) { forces[k].SetAll(0.); torques[k].SetAll(0.); }
	if (!parameters.activeConnector) { return; }

	SlimVectorBase<TReal, 3> vLocPos, vLocVel, vLocRot, vLocAngVel;
	SlimVectorBase<TReal, 6> fLocVec6D;
	ConstSizeMatrixBase<TReal, 9> Ajoint;
	ComputeSpringForceTorque(markers, t, itemIndex, Ajoint, vLocPos, vLocVel, vLocRot, vLocAngVel, fLocVec6D);

	SlimVectorBase<TReal, 3> fPos = Ajoint * SlimVectorBase<TReal, 3>({ fLocVec6D[0], fLocVec6D[1], fLocVec6D[2] });
	SlimVectorBase<TReal, 3> fRot = Ajoint * SlimVectorBase<TReal, 3>({ fLocVec6D[3], fLocVec6D[4], fLocVec6D[5] });
	SlimVectorBase<TReal, 3> torque;
	torque.SetAll(0.);
	if (parameters.intrinsicFormulation)
	{
		SlimVectorBase<TReal, 3> halfPos;
		for (Index i = 0; i < 3; i++) { halfPos[i] = -0.5*vLocPos[i]; }
		torque = (Ajoint * halfPos).CrossProduct(fPos);
	}
	forces[1] = fPos;
	torques[1] = fRot + torque;
	forces[0] = -fPos;
	torques[0] = -fRot + torque;
}

//! the Jacobian by automatic differentiation (ComputeConnectorForceRigidDiff), unless a user function defines the force (#2745)
