//! compute joint frame, relative displacement, relative rotation, relative velocity and relative angular velocity
void CObjectConnectorRigidBodySpringDamper::ComputeSpringForceTorque(const MarkerRigid<Real>* markers, Real t, Index itemIndex,
	Matrix3D& Ajoint, Vector3D& vLocPos, Vector3D& vLocVel, Vector3D& vLocRot, Vector3D& vLocAngVel, Vector6D& fLocVec6D,
	bool computeForceTorque) const
{
	//spring is measured relative to marker0:

	const Matrix3D& A0 = markers[0].frame.GetRotation();
	const Matrix3D& A1 = markers[1].frame.GetRotation();
	const Vector3D& p0 = markers[0].frame.GetTranslation();
	const Vector3D& p1 = markers[1].frame.GetTranslation();
	const Matrix3D& A0off = parameters.rotationMarker0;
	const Matrix3D& A1off = parameters.rotationMarker1;
	Matrix3D A0all = A0off * A0;
	Matrix3D A1all = A1 * A1off;

	if (parameters.intrinsicFormulation)
	{
		HomogeneousTransformation HT0(A0all, p0);
		HomogeneousTransformation HT1(A1all, p1);

		HT0.GetRelativeMotionTo(HT1, vLocPos, vLocRot);

		//HT1 = relative homogeneous transformation to mid point/rotation!
		HT1 = EXUlie::ExpSE3(0.5*vLocPos, 0.5*vLocRot); 
		HT0 *= HT1; //HT0 = SE3 mid-frame
		Ajoint = HT0.GetRotation();
	}
	else
	{
		Ajoint = A0all;
		vLocPos = Ajoint.GetTransposed() * (p1 - p0); //vLocPos transformed to marker0 local coordinate system, where springs are defined
		Matrix3D relRot = Ajoint.GetTransposed() * A1all;
		vLocRot = RigidBodyMath::RotationMatrix2RotXYZ(relRot);
	}

	//relative velocities: same in all formulations
	vLocVel = Ajoint.GetTransposed() * (markers[1].velocity - markers[0].velocity);
	vLocAngVel = Ajoint.GetTransposed()*(A1*markers[1].angularVelocityLocal - A0 * markers[0].angularVelocityLocal);


	if (vLocRot[0] > EXUstd::pi) { vLocRot[0] -= 2.*EXUstd::pi; }
	if (vLocRot[1] > EXUstd::pi) { vLocRot[1] -= 2.*EXUstd::pi; }
	if (vLocRot[2] > EXUstd::pi) { vLocRot[2] -= 2.*EXUstd::pi; }

	//compute resulting displacement vector:
	Vector6D uLoc6D;
	Vector6D vLoc6D;
	for (Index i = 0; i < 3; i++)
	{
		uLoc6D[i] = vLocPos[i];
		uLoc6D[i + 3] = vLocRot[i];
		vLoc6D[i] = vLocVel[i];
		vLoc6D[i + 3] = vLocAngVel[i];
	}

	if (computeForceTorque)
	{
		//+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		//evaluate force-torque vector:
		//compute resulting force vector:
		if (!parameters.springForceTorqueUserFunction)
		{
			uLoc6D -= parameters.offset;

			EXUmath::MultMatrixVector(parameters.stiffness, uLoc6D, fLocVec6D);

			Vector6D temp;
			EXUmath::MultMatrixVector(parameters.damping, vLoc6D, temp);
			fLocVec6D += temp;
		}
		else
		{
			EvaluateUserFunctionForce(fLocVec6D, cSystemData->GetMainSystemBacklink(), t, itemIndex, uLoc6D, vLoc6D);
		}
	}
}

//! the forces and torques of the connector interface on rigid markers (#2745), as ComputeODE2LHS projects them: the
//! intrinsic formulation adds the same torque of the offset force on both markers
void CObjectConnectorRigidBodySpringDamper::ComputeConnectorForceRigid(const MarkerRigid<Real>* markers, Real t, Index itemIndex,
	Vector3D* forces, Vector3D* torques) const
{
	forces[0].SetAll(0.); forces[1].SetAll(0.); torques[0].SetAll(0.); torques[1].SetAll(0.);
	if (!parameters.activeConnector) { return; }

	Vector3D vLocPos, vLocVel, vLocRot, vLocAngVel;
	Vector6D fLocVec6D;
	Matrix3D Ajoint;
	ComputeSpringForceTorque(markers, t, itemIndex, Ajoint, vLocPos, vLocVel, vLocRot, vLocAngVel, fLocVec6D);

	LinkedDataVector fPosLoc(fLocVec6D, 0, 3);
	LinkedDataVector fRotLoc(fLocVec6D, 3, 3);
	Vector3D fPos, fRot;
	EXUmath::MultMatrixVector(Ajoint, fPosLoc, fPos);
	EXUmath::MultMatrixVector(Ajoint, fRotLoc, fRot);
	Vector3D torque(0.);
	if (parameters.intrinsicFormulation)
	{
		torque = (Ajoint * (-0.5*vLocPos)).CrossProduct(fPos);
	}
	forces[1] = fPos;
	torques[1] = fRot + torque;
	forces[0] = -fPos;
	torques[0] = -fRot + torque;
}


//! Computational function: compute left-hand-side (LHS) of second order ordinary differential equations (ODE) to "ode2Lhs"
void CObjectConnectorRigidBodySpringDamper::ComputeODE2LHS(Vector& ode2Lhs, const MarkerDataStructure& markerData, Index objectNumber) const
{
	CHECKandTHROW(markerData.GetMarkerData(1).velocityAvailable && markerData.GetMarkerData(0).velocityAvailable,
		"CObjectConnectorRigidBodySpringDamper::ComputeODE2LHS: marker do not provide velocityLevel information");

	//link separate vectors to result (ode2Lhs) vector
	ode2Lhs.SetNumberOfItems(markerData.GetMarkerData(0).positionJacobian.NumberOfColumns() + markerData.GetMarkerData(1).positionJacobian.NumberOfColumns());
	ode2Lhs.SetAll(0.);

	//pout << "test\n";
	if (parameters.activeConnector)
	{
		Vector3D vLocPos;
		Vector3D vLocVel;
		Vector3D vLocRot;
		Vector3D vLocAngVel;
		Vector6D fLocVec6D;
		Matrix3D Ajoint;
		MarkerRigid<Real> markers[2];
		GetMarkersRigid(markerData, markers);
		ComputeSpringForceTorque(markers, markerData.GetTime(), objectNumber, Ajoint, vLocPos, vLocVel, vLocRot, vLocAngVel, fLocVec6D);

		LinkedDataVector fPosLoc(fLocVec6D, 0, 3);
		LinkedDataVector fRotLoc(fLocVec6D, 3, 3);

		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		//transform to global coordinates (application of forces/torques always global):
		Vector3D fPos;
		Vector3D fRot;
		EXUmath::MultMatrixVector(Ajoint, fPosLoc, fPos);
		EXUmath::MultMatrixVector(Ajoint, fRotLoc, fRot);
		Vector3D torque(0.);
		if (parameters.intrinsicFormulation)
		{
			//additional torque due to distance of connector center-pos to marker location
			//this torque is the same on both sides
			//HomogeneousTransformation HTrel = EXUlie::ExpSE3(0.5 * vLocPos, 0.5 * vLocRot);

			//torque = (Ajoint * (HTrel.GetTranslation())).CrossProduct(fPos); //vLocPos is in Lie-algebra and can be halfed
			torque = (Ajoint * (-0.5*vLocPos)).CrossProduct(fPos); //vLocPos is in Lie-algebra and can be halfed
			//pout << "vLocPos=" << vLocPos << "\n";
		}

		//now link ode2Lhs Vector to partial result using the two jacobians
		if (markerData.GetMarkerData(1).positionJacobian.NumberOfColumns()) //special case: COGround has (0,0) Jacobian
		{
			//positionJacobian.NumberOfColumns() == rotationJacobian.NumberOfColumns()
			LinkedDataVector ldv1(ode2Lhs, markerData.GetMarkerData(0).positionJacobian.NumberOfColumns(), markerData.GetMarkerData(1).positionJacobian.NumberOfColumns());
			EXUmath::MultMatrixTransposedVector(markerData.GetMarkerData(1).positionJacobian, fPos, ldv1);
			EXUmath::MultMatrixTransposedVectorAdd(markerData.GetMarkerData(1).rotationJacobian, fRot+torque, ldv1);
		}

		if (markerData.GetMarkerData(0).positionJacobian.NumberOfColumns()) //special case: COGround has (0,0) Jacobian
		{
			fPos *= -1.;
			fRot *= -1.;
			LinkedDataVector ldv0(ode2Lhs, 0, markerData.GetMarkerData(0).positionJacobian.NumberOfColumns());
			EXUmath::MultMatrixTransposedVector(markerData.GetMarkerData(0).positionJacobian, fPos, ldv0);
			EXUmath::MultMatrixTransposedVectorAdd(markerData.GetMarkerData(0).rotationJacobian, fRot+torque, ldv0);
		}
		//pout << "  ode2Lhs=" << ode2Lhs << "\n";
	}

}



//! provide according output variable in "value"
void CObjectConnectorRigidBodySpringDamper::GetOutputVariableConnector(OutputVariableType variableType, const MarkerDataStructure& markerData, Index itemIndex, Vector& value) const
{
	Vector3D vLocPos;
	Vector3D vLocVel;
	Vector3D vLocRot;
	Vector3D vLocAngVel;
	Vector6D fLocVec6D;
	Matrix3D Ajoint;
	MarkerRigid<Real> markers[2];
	GetMarkersRigid(markerData, markers);
	ComputeSpringForceTorque(markers, markerData.GetTime(), itemIndex, Ajoint, vLocPos, vLocVel, vLocRot, vLocAngVel, fLocVec6D,
		(variableType == OutputVariableType::ForceLocal ||
		variableType == OutputVariableType::TorqueLocal));

	LinkedDataVector fPosLoc(fLocVec6D, 0, 3);
	LinkedDataVector fRotLoc(fLocVec6D, 3, 3);

	switch (variableType)
	{
	case OutputVariableType::DisplacementLocal: value.CopyFrom(vLocPos); break;
	case OutputVariableType::VelocityLocal: value.CopyFrom(vLocVel); break;
	case OutputVariableType::Rotation: value.CopyFrom(vLocRot); break;
	case OutputVariableType::AngularVelocityLocal: value.CopyFrom(vLocAngVel); break;
	case OutputVariableType::ForceLocal: value.CopyFrom(fPosLoc); break;
	case OutputVariableType::TorqueLocal: value.CopyFrom(fRotLoc); break;
	case OutputVariableType::PotentialEnergy: {
		//1/2 u^T K u of the six relative displacements and rotations in the joint frame, as the force law uses them
		if (parameters.springForceTorqueUserFunction) { EnergyNotAvailable("ObjectConnectorRigidBodySpringDamper", "its springForceTorqueUserFunction defines the force and torque"); }
		Vector6D u;
		for (Index i = 0; i < 3; i++) { u[i] = vLocPos[i]; u[i + 3] = vLocRot[i]; }
		u -= parameters.offset;
		Vector6D Ku;
		EXUmath::MultMatrixVector(parameters.stiffness, u, Ku);
		value.SetVector({ parameters.activeConnector ? 0.5*(u*Ku) : 0. }); break; }
	default:
		SysError("CObjectConnectorRigidBodySpringDamper::GetOutputVariableConnector failed"); //error should not occur, because types are checked!
	}
}


