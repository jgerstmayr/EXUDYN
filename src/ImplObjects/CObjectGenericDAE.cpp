void CObjectGenericDAE::ComputeObjectCoordinates(Vector& q, Vector& q_t, Vector& y, ConfigurationType configuration) const
{
	q.SetNumberOfItems(GetODE2Size());
	q_t.SetNumberOfItems(q.NumberOfItems());
	y.SetNumberOfItems(GetODE1Size());
	Index k = 0;
	for (Index i = 0; i < parameters.nodeNumbersODE2.NumberOfItems(); i++)
	{
		const CNodeODE2* node = (const CNodeODE2*)GetCNode(i);
		LinkedDataVector u(node->GetCoordinateVector(configuration));
		LinkedDataVector u_t(node->GetCoordinateVector_t(configuration));
		for (Index j = 0; j < u.NumberOfItems(); j++) { q[k] = u[j]; q_t[k] = u_t[j]; k++; }
	}
	k = 0;
	Index offset = parameters.nodeNumbersODE2.NumberOfItems();
	for (Index i = 0; i < parameters.nodeNumbersODE1.NumberOfItems(); i++)
	{
		LinkedDataVector v(GetCNode(offset + i)->GetCoordinateVector(configuration));
		for (Index j = 0; j < v.NumberOfItems(); j++) { y[k++] = v[j]; }
	}
}

//! the derivatives of the ODE1 coordinates, for the algebraic equations at velocity level
static void ComputeODE1Velocities(const CObjectGenericDAE& object, Vector& y_t)
{
	y_t.SetNumberOfItems(object.GetODE1Size());
	Index k = 0;
	Index offset = object.GetParameters().nodeNumbersODE2.NumberOfItems();
	for (Index i = 0; i < object.GetParameters().nodeNumbersODE1.NumberOfItems(); i++)
	{
		LinkedDataVector v(((const CNodeODE1*)object.GetCNode(offset + i))->GetCoordinateVector_t(ConfigurationType::Current));
		for (Index j = 0; j < v.NumberOfItems(); j++) { y_t[k++] = v[j]; }
	}
}

