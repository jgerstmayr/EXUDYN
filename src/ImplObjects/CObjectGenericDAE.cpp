//! node localIndex of the list ODE2 nodes, ODE1 nodes, AE nodes
Index CObjectGenericDAE::GetNodeNumber(Index localIndex) const
{
	Index n2 = parameters.nodeNumbersODE2.NumberOfItems();
	Index n1 = parameters.nodeNumbersODE1.NumberOfItems();
	if (localIndex < n2) { return parameters.nodeNumbersODE2[localIndex]; }
	if (localIndex < n2 + n1) { return parameters.nodeNumbersODE1[localIndex - n2]; }
	return parameters.nodeNumbersAE[localIndex - n2 - n1];
}

