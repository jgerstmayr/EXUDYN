	ode2Lhs.SetAll(0.);
	if (parameters.stiffnessMatrix.NumberOfRows() != 0) { EXUmath::MultMatrixVectorAdd(parameters.stiffnessMatrix, tempCoordinates, ode2Lhs); }
	if (parameters.dampingMatrix.NumberOfRows() != 0) { EXUmath::MultMatrixVectorAdd(parameters.dampingMatrix, tempCoordinates_t, ode2Lhs); }
