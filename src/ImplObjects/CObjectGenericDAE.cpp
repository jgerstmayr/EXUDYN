	Index n1 = parameters.nodeNumbersODE1.NumberOfItems();
	if (localIndex < n2) { parameters.nodeNumbersODE2[localIndex] = nodeNumber; }
	else if (localIndex < n2 + n1) { parameters.nodeNumbersODE1[localIndex - n2] = nodeNumber; }
