//! the coordinates of the object; localPosition is not used
void CObjectGenericDAE::GetOutputVariableBody(OutputVariableType variableType, const Vector3D& localPosition, ConfigurationType configuration, Vector& value) const
{
	Vector q, q_t, y; //local, as the renderer thread may ask during a step
	ComputeObjectCoordinates(q, q_t, y, configuration);
	switch (variableType)
	{
	case OutputVariableType::Coordinates: value.CopyFrom(q); break;
	case OutputVariableType::Coordinates_t: value.CopyFrom(q_t); break;
	default: SysError("CObjectGenericDAE::GetOutputVariableBody failed"); //the types are checked before
	}
}
