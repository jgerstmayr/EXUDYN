//! the access functions by automatic differentiation of the templated position and rotation (#2744): the same results
//! as the hand-written ones, which are used - measured in revision2026b step RG9.3.5, the implicit solve of a chain of
//! rigid-body connectors is 25-35 % slower with them (4 differentiated rotation parameters); kept for comparison
static const bool accessFunctionsByAD = false;

//! the rotation matrix of a rigid body as a template of the number type, for the access functions by automatic
//! differentiation (#2744): theta are the rotation parameters (reference + current); Euler parameters normalized - the
//! matrix then does not change along them, as Glocal theta = 0 says -, or Tait-Bryan angles as RotXYZ2RotationMatrix
template<class TReal, class TMatrix>
static void RigidBodyRotationMatrixAD(bool eulerParameters, const TReal* theta, TMatrix& A)
{
	using std::sin; using std::cos; using std::sqrt;
	if (eulerParameters)
	{
		TReal norm = sqrt(theta[0] * theta[0] + theta[1] * theta[1] + theta[2] * theta[2] + theta[3] * theta[3]);
		TReal ep[4] = { theta[0] / norm, theta[1] / norm, theta[2] / norm, theta[3] / norm };
		A(0, 0) = 1. - 2. * ep[3] * ep[3] - 2. * ep[2] * ep[2];
		A(0, 1) = -2. * ep[3] * ep[0] + 2. * ep[2] * ep[1];
		A(0, 2) = 2. * ep[3] * ep[1] + 2. * ep[2] * ep[0];
		A(1, 0) = 2. * ep[3] * ep[0] + 2. * ep[2] * ep[1];
		A(1, 1) = 1. - 2. * ep[3] * ep[3] - 2. * ep[1] * ep[1];
		A(1, 2) = 2. * ep[3] * ep[2] - 2. * ep[1] * ep[0];
		A(2, 0) = -2. * ep[2] * ep[0] + 2. * ep[3] * ep[1];
		A(2, 1) = 2. * ep[3] * ep[2] + 2. * ep[1] * ep[0];
		A(2, 2) = 1. - 2. * ep[2] * ep[2] - 2. * ep[1] * ep[1];
	}
	else
	{
		TReal c0 = cos(theta[0]), s0 = sin(theta[0]);
		TReal c1 = cos(theta[1]), s1 = sin(theta[1]);
		TReal c2 = cos(theta[2]), s2 = sin(theta[2]);
		A(0, 0) = c1 * c2; A(0, 1) = -c1 * s2; A(0, 2) = s1;
		A(1, 0) = s0 * s1 * c2 + c0 * s2; A(1, 1) = -s0 * s1 * s2 + c0 * c2; A(1, 2) = -s0 * c1;
		A(2, 0) = -c0 * s1 * c2 + s0 * s2; A(2, 1) = c0 * s1 * s2 + s0 * c2; A(2, 2) = c0 * c1;
	}
}

//! the position p = q_pos + A(theta) localPosition as a generic function of the coordinates q (#2744)
static auto RigidBodyPositionAD(bool eulerParameters, const Vector3D& localPosition)
{
	return [eulerParameters, localPosition](const auto* q, auto* p)
	{
		using TReal = typename std::remove_const<typename std::remove_reference<decltype(q[0])>::type>::type;
		ConstSizeMatrixBase<TReal, 9> A(3, 3);
		RigidBodyRotationMatrixAD(eulerParameters, q + 3, A);
		for (Index r = 0; r < 3; r++) { p[r] = q[r] + A(r, 0) * localPosition[0] + A(r, 1) * localPosition[1] + A(r, 2) * localPosition[2]; }
	};
}

//! the rotation matrix A(theta) as a generic function of the coordinates q (#2744)
static auto RigidBodyRotationAD(bool eulerParameters)
{
	return [eulerParameters](const auto* q, auto& A) { RigidBodyRotationMatrixAD(eulerParameters, q + 3, A); };
}

//! true if the access functions are computed by automatic differentiation (#2744): accessFunctionsByAD, and a node whose
//! coordinate velocities are the time derivatives of its coordinates - Euler parameters or Tait-Bryan angles, not the
//! Lie group nodes; q are then its coordinates, reference + current
static bool RigidBodyUsesAD(const CNode* node, bool& eulerParameters, ConstSizeVector<7>& q)
{
	if (!accessFunctionsByAD) { return false; }
	Node::Type type = node->GetType();
	eulerParameters = (type & Node::RotationEulerParameters) != 0;
	if (!eulerParameters && (type & Node::RotationRxyz) == 0) { return false; }
	Index n = node->GetNumberOfODE2Coordinates();
	q.SetNumberOfItems(n);
	LinkedDataVector reference = node->GetCoordinateVector(ConfigurationType::Reference);
	for (Index i = 0; i < n; i++) { q[i] = reference[i] + node->GetCurrentCoordinate(i); }
	return true;
}

