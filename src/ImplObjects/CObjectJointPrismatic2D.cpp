JacobianType::Type CObjectJointPrismatic2D::GetAvailableJacobians() const
{
	if (parameters.activeConnector)
	{
		if (parameters.constrainRotation)
		{ return (JacobianType::Type)(JacobianType::AE_ODE2 + JacobianType::AE_ODE2_function);}
		else
		{ return (JacobianType::Type)(JacobianType::AE_ODE2 + JacobianType::AE_ODE2_function + JacobianType::AE_AE + JacobianType::AE_AE_function);}
	}
	else //deactivated constraint means that only the lagrange multiplier needs to be set to zero
	{
		return (JacobianType::Type)(JacobianType::AE_AE + JacobianType::AE_AE_function);
	}
}


//! provide according output variable in "value"
void CObjectJointPrismatic2D::GetOutputVariableConnector(OutputVariableType variableType, const MarkerDataStructure& markerData, Index itemIndex, Vector& value) const
{
	const Matrix3D& A0 = markerData.GetMarkerData(0).orientation;
	const Matrix3D& A1 = markerData.GetMarkerData(1).orientation;
	const Vector3D& p0 = markerData.GetMarkerData(0).position;
	const Vector3D& p1 = markerData.GetMarkerData(1).position;
	switch (variableType)
	{
		//the joint frames are the marker frames (#2870)
		case OutputVariableType::Position: value.CopyFrom(p0); break;
		case OutputVariableType::Velocity: value.CopyFrom(markerData.GetMarkerData(0).velocity); break;
		case OutputVariableType::DisplacementLocal: value.CopyFrom(A0.GetTransposed() * (p1 - p0)); break;
		case OutputVariableType::HomogeneousTransformation: ConnectorOutputVariableFrame(A0, p0, value); break;
		case OutputVariableType::HomogeneousTransformationLocal: ConnectorOutputVariableFrameLocal(A0, p0, A1, p1, value); break;
		case OutputVariableType::ForceLocal: //the force normal to the axis from the first multiplier, on marker 0 as for the other joints (#2870)
		{
			Vector3D n1 = A1 * parameters.normalMarker1;
			value.CopyFrom(A0.GetTransposed() * (GetCurrentAEcoordinate(0) * n1));
			break;
		}
		case OutputVariableType::Distance: //the position of marker 1 along the (normalized) prismatic axis (#2735)
		{
			Vector3D t0 = A0 * parameters.axisMarker0;
			Real axisLength = t0.GetL2Norm();
			CHECKandTHROW(axisLength != 0., "CObjectJointPrismatic2D: axisMarker0 must not be zero");
			value.SetVector({ (markerData.GetMarkerData(1).position - markerData.GetMarkerData(0).position) * t0 / axisLength });
			break;
		}
		case OutputVariableType::Rotation: //the rotation of marker 1 relative to marker 0 about z (#2735)
		{
			Matrix3D A01 = A0.GetTransposed() * A1;
			value.SetVector({ atan2(A01(1, 0), A01(0, 0)) });
			break;
		}
		default:
			SysError("CObjectJointPrismatic2D::GetOutputVariable failed"); //error should not occur, because types are checked!
	}
}

