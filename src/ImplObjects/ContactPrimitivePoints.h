	//! the data coordinates of a point: gap, tangential velocity, impact velocity, and the plastic overlap with the
	//! adhesive elasto-plastic model (#3336)
	template<class TParameters>
	Index BlockSize(const TParameters& parameters) { return parameters.contactPlasticityRatio != 0. ? 4 : 3; }

	//! the parameters of the adhesive elasto-plastic model of an item, with the plastic overlap of a point
	template<class TParameters>
	ContactPlasticity Plasticity(const TParameters& parameters, Real deltaPlastic)
	{
		ContactPlasticity plasticity;
		plasticity.plasticityRatio = parameters.contactPlasticityRatio;
		plasticity.adhesionCoefficient = parameters.adhesionCoefficient;
		plasticity.adhesionExponent = parameters.adhesionExponent;
		plasticity.pullOffForce = parameters.constantPullOffForce;
		plasticity.deltaPlastic = deltaPlastic;
		return plasticity;
	}

	//! a contact point: point0 on shape 0, point1 on shape 1, the normal from shape 0 to shape 1, the gap
	struct Point
	{
		Vector3D point0, point1, normal;
		Real gap;
	};

	constexpr Real faceTolerance = 1e-6;	//!< a normal within this of the normal of a face is along it

	//! a convex polytope: its points and triangles in the frame of its marker, and the frame
	struct ConvexPolytope
	{
		const Matrix& points;
		const MatrixI& triangles;
		Matrix3D rotation;
		Vector3D position;
		ConvexPolytope(const Matrix& pointsInit, const MatrixI& trianglesInit, const MarkerData& marker) :
			points(pointsInit), triangles(trianglesInit), rotation(marker.orientation), position(marker.position) {}

		Vector3D LocalPoint(Index i) const { return Vector3D({ points(i, 0), points(i, 1), points(i, 2) }); }
		Vector3D Point(Index i) const { return position + rotation * LocalPoint(i); }
		//! the global unit normal of triangle t, by the order of its points
		Vector3D TriangleNormal(Index t) const
		{
			Vector3D p0 = LocalPoint(triangles(t, 0));
			Vector3D normal = (LocalPoint(triangles(t, 1)) - p0).CrossProduct(LocalPoint(triangles(t, 2)) - p0);
			normal.Normalize();
			return rotation * normal;
		}
		EGeometry::ConvexShape Convex() const
		{
			EGeometry::ConvexShape shape;
			shape.type = EGeometry::ConvexShapeType::Points;
			shape.pointRows = points.GetDataPointer();
			shape.numberOfPointRows = points.NumberOfRows();
			return shape;
		}

		//! the face whose outward normal is the direction within the tolerance: its normal and a point of it; false if there is none
		bool Face(const Vector3D& direction, Vector3D& faceNormal, Vector3D& facePoint, Real tolerance = faceTolerance) const
		{
			Real best = -2.;
			for (Index t = 0; t < triangles.NumberOfRows(); t++)
			{
				Vector3D normal = TriangleNormal(t);
				Real along = normal * direction;
				if (along > best) { best = along; faceNormal = normal; facePoint = Point(triangles(t, 0)); }
			}
			return best > 1. - tolerance;
		}

		//! true if x, projected along the faceNormal, lies in a triangle of the face with this normal
		bool OverFace(const Vector3D& faceNormal, const Vector3D& x) const
		{
			for (Index t = 0; t < triangles.NumberOfRows(); t++)
			{
				if (TriangleNormal(t) * faceNormal <= 1. - faceTolerance) { continue; }
				Vector3D p[3] = { Point(triangles(t, 0)), Point(triangles(t, 1)), Point(triangles(t, 2)) };
				bool inside = true;
				for (Index i = 0; i < 3 && inside; i++)
				{
					Vector3D edgeNormal = faceNormal.CrossProduct(p[(i + 1) % 3] - p[i]); //towards the inside for an outward normal
					Real size = (p[(i + 1) % 3] - p[i]).GetL2NormSquared();
					inside = edgeNormal * (x - p[i]) >= -1e-12 * size;
				}
				if (inside) { return true; }
			}
			return false;
		}
	};

	//! the triangles of a polytope in the frame of a marker
	inline void DrawPolytope(VisualizationSystem* vSystem, Index markerNumber, const Matrix& points, const MatrixI& triangles,
		const Float4& color, Index itemID)
	{
		Vector3D position;
		Matrix3D A;
		vSystem->systemData->GetCMarkers()[markerNumber]->GetPosition(*vSystem->systemData, position, ConfigurationType::Visualization);
		vSystem->systemData->GetCMarkers()[markerNumber]->GetRotationMatrix(*vSystem->systemData, A, ConfigurationType::Visualization);
		std::array<Float4, 3> colors = { color, color, color };
		for (Index t = 0; t < triangles.NumberOfRows(); t++)
		{
			std::array<Vector3D, 3> nodes;
			for (Index k = 0; k < 3; k++)
			{
				Index p = triangles(t, k);
				nodes[k] = position + A * Vector3D({ points(p, 0), points(p, 1), points(p, 2) });
			}
			Vector3D normal = EGeometry::ComputeTriangleNormal(nodes);
			std::array<Vector3D, 3> normals = { normal, normal, normal };
			vSystem->graphicsData.AddTriangle(nodes, normals, colors, itemID);
		}
	}

	//! the contact points of the current configuration and the distance of the shapes
	template<Index N>
	struct Points
	{
		static constexpr Index capacity = N;
		Point point[N];
		Index count = 0;
		EGeometry::ConvexDistanceResult closest; //!< the signed distance, the closest points and the normal by GJK and EPA
		void Add(const Vector3D& point0, const Vector3D& point1, const Vector3D& normal, Real gap)
		{
			if (count < N) { point[count++] = Point({ point0, point1, normal, gap }); }
		}
		void AddClosest() { Add(closest.point0, closest.point1, closest.normal, closest.distance); }
	};

	//! the force on marker 0 of a contact point by the law or the user function; the contact state of the point from
	//! its data block (contactFromData) or from its gap
	template<class TItem>
	void PointForce(const TItem& item, const MarkerDataStructure& markerData, const LinkedDataVector& data, Index block,
		const Point& point, const char* itemName, Vector3D& contactPoint, Vector3D& deltaV, Vector3D& fVec, bool contactFromData)
	{
		const auto& parameters = item.GetParameters();
		contactPoint = 0.5 * (point.point0 + point.point1);
		Vector3D velocity[2];
		for (Index i = 0; i < 2; i++)
		{
			const MarkerData& marker = markerData.GetMarkerData(i);
			velocity[i] = marker.velocity + (marker.orientation * marker.angularVelocityLocal).CrossProduct(contactPoint - marker.position);
		}
		deltaV = velocity[1] - velocity[0];

		fVec.SetAll(0.);
		Index blockSize = BlockSize(parameters);
		Index index = block * blockSize;
		bool hasContact = contactFromData ? (data[index] < 0) : (point.gap < 0);
		if (hasContact && parameters.activeConnector)
		{
			Real deltaVnormal = point.normal * deltaV; //relative velocity in normal direction
			if (parameters.contactForceUserFunction) //the force by the user function (#3324)
			{
				item.EvaluateUserFunctionForce(fVec, item.GetCSystemData()->GetMainSystemBacklink(), markerData.GetTime(), point.gap,
					deltaVnormal, point.normal, deltaV - deltaVnormal * point.normal, data[index + 2]);
			}
			else
			{
				//frictionRegularizedRegion is only used in case that contactFromData=true
				bool frictionRegularizedRegion = data[index + 1] < parameters.frictionProportionalZone;
				Vector3D fFriction;
				ContactPlasticity plasticity = Plasticity(parameters, blockSize == 4 ? data[index + 3] : 0.);
				ContactPrimitiveForce<Real>(parameters, data[index + 2], itemName, point.gap, point.normal, deltaVnormal,
					deltaV, parameters.dynamicFriction, frictionRegularizedRegion, fVec, fFriction, contactFromData, &plasticity);
			}
		}
	}

	//! the generalized forces of all contact points, in the sign of the left-hand side (#2745): the force fVec on
	//! marker 0 at each contact point and its negative on marker 1
	template<class TItem, class TPoints>
	void ForcesRigid(const TItem& item, const MarkerDataStructure& markerData, const TPoints& points, const char* itemName,
		FlatArray<Vector3D> forces, FlatArray<Vector3D> torques)
	{
		LinkedDataVector data = item.GetCNode(0)->GetCurrentCoordinateVector();
		for (Index i = 0; i < points.count; i++)
		{
			Vector3D contactPoint, deltaV, fVec;
			PointForce(item, markerData, data, i, points.point[i], itemName, contactPoint, deltaV, fVec, true);
			forces[0] -= fVec;
			torques[0] -= (contactPoint - markerData.GetMarkerData(0).position).CrossProduct(fVec);
			forces[1] += fVec;
			torques[1] += (contactPoint - markerData.GetMarkerData(1).position).CrossProduct(fVec);
		}
	}

	//! the output variables: the distance and normal of GJK and EPA, the force and torque of all points, the position
	//! their center weighted by the normal forces, else the middle of the closest points
	template<class TItem, class TPoints>
	void OutputVariable(const TItem& item, OutputVariableType variableType, const MarkerDataStructure& markerData,
		const TPoints& points, const char* itemName, Vector& value)
	{
		LinkedDataVector data = item.GetCNode(0)->GetCurrentCoordinateVector();
		Vector3D force({ 0., 0., 0. }), torque({ 0., 0., 0. }), center({ 0., 0., 0. });
		Real normalForces = 0.;
		for (Index i = 0; i < points.count; i++)
		{
			Vector3D contactPoint, deltaV, fVec;
			PointForce(item, markerData, data, i, points.point[i], itemName, contactPoint, deltaV, fVec, true);
			force += fVec;
			torque += (contactPoint - markerData.GetMarkerData(0).position).CrossProduct(fVec);
			Real normalForce = fabs(fVec * points.point[i].normal);
			center += normalForce * contactPoint;
			normalForces += normalForce;
		}
		Vector3D position = 0.5 * (points.closest.point0 + points.closest.point1);
		if (normalForces > 0.) { position = (1. / normalForces) * center; }
		Vector3D velocity[2];
		for (Index i = 0; i < 2; i++)
		{
			const MarkerData& marker = markerData.GetMarkerData(i);
			velocity[i] = marker.velocity + (marker.orientation * marker.angularVelocityLocal).CrossProduct(position - marker.position);
		}
		switch (variableType)
		{
		case OutputVariableType::Position: value.CopyFrom(position); break;
		case OutputVariableType::Displacement: value.CopyFrom(points.closest.point1 - points.closest.point0); break;
		case OutputVariableType::Distance: value.CopyFrom(Vector1D({ points.closest.distance })); break;
		case OutputVariableType::DisplacementLocal: value.CopyFrom(Vector1D({ points.closest.distance })); break;
		case OutputVariableType::Velocity: value.CopyFrom(velocity[1] - velocity[0]); break;
		case OutputVariableType::Director1: value.CopyFrom(points.closest.normal); break;
		case OutputVariableType::Force: value.CopyFrom(force); break;
		case OutputVariableType::Torque: value.CopyFrom(torque); break;
		default: SysError(STDstring(itemName) + "::GetOutputVariableConnector failed"); //error should not occur, because types are checked!
		}
	}

	//! the forces of the contact points in the visualization configuration, drawn with contact.showContactForces: the
	//! contact state from the gaps, the data of the visualization state (#3339)
	template<class TItem, class TPoints>
	void DrawForces(const TItem& item, const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemID,
		const char* itemName, void (*computePoints)(const TItem&, const MarkerDataStructure&, TPoints&))
	{
		if (!DrawContactForces(visualizationSettings, item.GetParameters().contactForceUserFunction)) { return; }
		MarkerDataStructure markerData;
		VisualizationMarkerData(*vSystem->systemData, item.GetMarkerNumbers(), markerData);
		TPoints points;
		computePoints(item, markerData, points);
		LinkedDataVector data = item.GetCNode(0)->GetVisualizationCoordinateVector();
		for (Index i = 0; i < points.count; i++)
		{
			Vector3D contactPoint, deltaV, fVec;
			PointForce(item, markerData, data, i, points.point[i], itemName, contactPoint, deltaV, fVec, false);
			DrawContactForce(visualizationSettings, vSystem, itemID, contactPoint, fVec);
		}
	}

	//! the post Newton step: the gap, the tangential velocity and the impact velocity of each contact point of the
	//! current configuration into its data block, as ObjectContactSphereCylinder; the error of a switch
	template<class TItem, class TPoints>
	Real PostNewtonStep(const TItem& item, const MarkerDataStructure& markerData, const TPoints& points, const char* itemName,
		PostNewtonFlags::Type& flags, Real& recommendedStepSize)
	{
		const auto& parameters = item.GetParameters();
		Real discontinuousError = 0;
		flags = PostNewtonFlags::_None;

		LinkedDataVector dataStartofStepState = ((CNodeData*)item.GetCNode(0))->GetCoordinateVector(ConfigurationType::StartOfStep);
		LinkedDataVector data = ((CNodeData*)item.GetCNode(0))->GetCoordinateVector(ConfigurationType::Current);

		Index blockSize = BlockSize(parameters);
		Index blocks = EXUstd::Minimum(TPoints::capacity, data.NumberOfItems() / blockSize); //the data node holds the blocks of the item
		for (Index i = 0; i < blocks; i++)
		{
			Index index = i * blockSize;
			Real currentGap = 1.; //a point that is not there is apart
			Real vGap = 0., vTangent = 0., normalForce = 0.;
			if (i < points.count)
			{
				Vector3D contactPoint, deltaV, fVec;
				PointForce(item, markerData, data, i, points.point[i], itemName, contactPoint, deltaV, fVec, false);
				currentGap = points.point[i].gap;
				vGap = points.point[i].normal * deltaV;
				vTangent = (deltaV - vGap * points.point[i].normal).GetL2Norm();
				normalForce = fVec * points.point[i].normal;
			}
			Real lastGap = data[index];
			Real startofStepGap = dataStartofStepState[index];
			Real lastVtangent = data[index + 1];
			data[index] = currentGap;
			data[index + 1] = vTangent;

			//the error of the gap: the contact state switched
			if ((currentGap > 0 && lastGap <= 0) || (currentGap <= 0 && lastGap > 0))
			{
				discontinuousError += fabs(currentGap * parameters.contactStiffness);
				//the time to the switch, also where the contact ends (#2109)
				if (vGap != 0 && startofStepGap != 0 && i < points.count)
				{
					recommendedStepSize = EXUstd::Minimum(recommendedStepSize >= 0 ? recommendedStepSize : EXUstd::MAXREAL, fabs(startofStepGap / vGap));
				}
				flags = PostNewtonFlags::UpdateJacobian;
			}

			//the error of the friction: switching between stick and slip
			if (currentGap < 0 && parameters.frictionProportionalZone != 0.)
			{
				if ((vTangent < parameters.frictionProportionalZone && lastVtangent > parameters.frictionProportionalZone) ||
					(vTangent > parameters.frictionProportionalZone && lastVtangent < parameters.frictionProportionalZone))
				{
					discontinuousError += fabs((parameters.dynamicFriction * normalForce / parameters.frictionProportionalZone) * (vTangent - parameters.frictionProportionalZone));
				}
			}

			//the plastic overlap: the largest of the current contact, kept from the start of the step (#3336)
			if (blockSize == 4)
			{
				Real deltaPlastic = 0.;
				if (currentGap < 0)
				{
					Real n = parameters.contactStiffnessExponent;
					deltaPlastic = (n != 1. ? EM::Pow(parameters.contactPlasticityRatio, 1. / n) : parameters.contactPlasticityRatio) * (-currentGap);
					deltaPlastic = EXUstd::Maximum(deltaPlastic, dataStartofStepState[index + 3]);
				}
				data[index + 3] = deltaPlastic;
			}

			//the impact velocity, if an impact occured; else that of the start of the step
			if (startofStepGap > 0 && currentGap <= 0) { data[index + 2] = -vGap; }
			else { data[index + 2] = dataStartofStepState[index + 2]; }
		}
		return discontinuousError;
	}
