	constexpr Real standingBlend = 1e-3;	//!< below this tilt (in rad) the points of a standing cylinder turn with it, not with the tilt
	constexpr Real parallelTolerance = 1e-3; //!< a normal within this of an axis or of a face normal is along it, also with the accuracy of EPA


	//! a cylinder or a truncated cone in global coordinates: center, unit axis, the radius at -halfLength and at
	//! +halfLength along the axis (radiusTop), half length, and a unit vector normal to the axis
	struct Cylinder
	{
		Vector3D center, axis, side;
		Real radius, radiusTop, halfLength;
		HomogeneousTransformation frame;	//!< the frame of the marker, for GJK and EPA
		Cylinder(const MarkerData& marker, Real radiusInit, Real length, Real radiusTopInit = -1.) : frame(marker.orientation, marker.position)
		{
			center = marker.position;
			axis = Vector3D({ marker.orientation(0, 2), marker.orientation(1, 2), marker.orientation(2, 2) });
			side = Vector3D({ marker.orientation(0, 0), marker.orientation(1, 0), marker.orientation(2, 0) });
			radius = radiusInit;
			radiusTop = radiusTopInit < 0. ? radiusInit : radiusTopInit;
			halfLength = 0.5 * length;
		}
		bool IsCone() const { return radiusTop != radius; }
		//! the radius at the end of the axis in the direction sign (+1: the top)
		Real RadiusAt(Real sign) const { return sign > 0. ? radiusTop : radius; }
		EGeometry::ConvexShape Shape() const
		{
			EGeometry::ConvexShape shape;
			shape.type = IsCone() ? EGeometry::ConvexShapeType::Cone : EGeometry::ConvexShapeType::Cylinder;
			shape.radius = radius;
			shape.radius1 = radiusTop;
			shape.length = 2. * halfLength;
			return shape;
		}
		//! the signed distance of a global point to the shape, the nearest point of the surface and its outward normal
		Real SignedDistance(const Vector3D& x, Vector3D& nearest, Vector3D& outward) const
		{
			Vector3D local = frame.RotateVectorTransposed(x - center);
			Real rho = sqrt(local[0] * local[0] + local[1] * local[1]);
			Vector3D e({ 1., 0., 0. });
			if (rho > 0.) { e = Vector3D({ local[0] / rho, local[1] / rho, 0. }); }
			Real z = local[2], h = halfLength;
			Real sr = radiusTop - radius, sz = 2. * h, sideLength = sqrt(sr * sr + sz * sz);
			Real nRho = sz / sideLength, nZ = -sr / sideLength; //the outward normal of the side in (rho, z)
			Real rz = radius + sr * (z + h) / sz;
			if (fabs(z) <= h && rho <= rz) //inside: the nearest of the caps and the side
			{
				Real depthSide = (rz - rho) * nRho;
				Real depth = h - z, nearestRho = rho, nearestZ = h, normalRho = 0., normalZ = 1.;
				if (z + h < depth) { depth = z + h; nearestZ = -h; normalZ = -1.; }
				if (depthSide < depth) { depth = depthSide; nearestRho = rho + depthSide * nRho; nearestZ = z + depthSide * nZ; normalRho = nRho; normalZ = nZ; }
				nearest = center + frame.GetRotation() * Vector3D({ nearestRho * e[0], nearestRho * e[1], nearestZ });
				outward = frame.GetRotation() * Vector3D({ normalRho * e[0], normalRho * e[1], normalZ });
				return -depth;
			}
			nearest = EGeometry::ClosestPointCore(Shape(), frame, x);
			outward = x - nearest;
			Real distance = outward.GetL2Norm();
			outward *= 1. / distance;
			return distance;
		}
	};

	//! a face for the contact points of a cylinder: infinite, a triangle or a disc (the cap of a cylinder)
	struct Face
	{
		enum class Type { Infinite, Triangle, Disc } type = Type::Infinite;
		Vector3D vertex[3];		//!< Triangle: the points; Disc: vertex[0] the center
		Vector3D inward[3];		//!< Triangle: the normal of each edge in the plane, towards the inside
		Vector3D discAxis;		//!< Disc: its normal
		Real discRadius = 0.;

		void SetTriangle(const Vector3D& p0, const Vector3D& p1, const Vector3D& p2)
		{
			type = Type::Triangle;
			vertex[0] = p0; vertex[1] = p1; vertex[2] = p2;
			Vector3D normal = (p1 - p0).CrossProduct(p2 - p0);
			for (Index i = 0; i < 3; i++)
			{
				inward[i] = normal.CrossProduct(vertex[(i + 1) % 3] - vertex[i]);
				if (inward[i] * (vertex[(i + 2) % 3] - vertex[i]) < 0.) { inward[i] *= -1.; }
			}
		}
		void SetDisc(const Vector3D& center, const Vector3D& axis, Real radius)
		{
			type = Type::Disc;
			vertex[0] = center;
			discAxis = axis;
			discRadius = radius;
		}

		//! the part [t0, t1] of the segment from x1 to x2 over the face, projected along its normal; false if none
		bool Clip(const Vector3D& x1, const Vector3D& x2, Real& t0, Real& t1) const
		{
			t0 = 0.; t1 = 1.;
			Vector3D dx = x2 - x1;
			if (type == Type::Triangle)
			{
				for (Index i = 0; i < 3; i++)
				{
					Real f0 = inward[i] * (x1 - vertex[i]); //f0 + t*df >= 0
					Real df = inward[i] * dx;
					if (df == 0.) { if (f0 < 0.) { return false; } }
					else if (df > 0.) { t0 = EXUstd::Maximum(t0, -f0 / df); }
					else { t1 = EXUstd::Minimum(t1, -f0 / df); }
				}
			}
			else if (type == Type::Disc)
			{
				Vector3D q1 = x1 - vertex[0];
				q1 -= (q1 * discAxis) * discAxis;
				Vector3D dq = dx - (dx * discAxis) * discAxis;
				Real a = dq * dq, b = 2. * (q1 * dq), c = q1 * q1 - discRadius * discRadius; //a t^2 + b t + c <= 0
				if (a == 0.) { if (c > 0.) { return false; } }
				else
				{
					Real discriminant = b * b - 4. * a * c;
					if (discriminant < 0.) { return false; }
					Real root = sqrt(discriminant);
					t0 = EXUstd::Maximum(t0, (-b - root) / (2. * a));
					t1 = EXUstd::Minimum(t1, (-b + root) / (2. * a));
				}
			}
			return t0 <= t1;
		}
		bool Inside(const Vector3D& x) const
		{
			Real t0, t1;
			return Clip(x, x, t0, t1);
		}
	};

	//! the contact points of a cylinder against a face with the point faceCenter and the unit normal faceNormal
	//! towards the cylinder: the deepest point of the lower rim and the other end of the side line through it,
	//! clipped to the face, and two points of the lower rim at +-120 degrees; a rim point beyond the face moves
	//! along its radius of the lower cap to the border of the face, so that a cap over the border of a face rests on
	//! the part over it; point0 is on the cylinder, the normal from the cylinder to the face; swap gives the points
	//! of the face first
	inline void FacePoints(const Cylinder& cylinder, const Vector3D& faceCenter, const Vector3D& faceNormal, const Face& face,
		Points& points, bool swap = false)
	{
		Vector3D down = -1. * faceNormal;
		Real axial = cylinder.axis * down;
		//the radial direction towards the face; for a standing cylinder, whose tilt gives no direction, it goes over
		//continuously into the local x axis of its marker, so that the points do not jump at small tilts; the share of
		//the x axis is standingBlend at no tilt and standingBlend^2 at a tilt of 1 rad
		Vector3D radial = down - axial * cylinder.axis;
		Real tilt = radial.GetL2Norm();
		radial += (standingBlend * standingBlend / (standingBlend + tilt)) * cylinder.side;
		if (radial.GetL2Norm() == 0.) { radial = cylinder.side; }
		radial.Normalize();
		Real lowerSign = axial >= 0. ? 1. : -1.;
		Vector3D lower = cylinder.center + (lowerSign * cylinder.halfLength) * cylinder.axis;
		Vector3D upper = 2. * cylinder.center - lower;
		Real radiusLower = cylinder.RadiusAt(lowerSign);
		Vector3D p1 = lower + radiusLower * radial;
		Vector3D p2 = upper + cylinder.RadiusAt(-lowerSign) * radial;
		Vector3D tangent = cylinder.axis.CrossProduct(radial);

		Vector3D candidate[maxPoints];
		Index n = 0;
		Real t0, t1;
		auto RimPoint = [&](const Vector3D& p) //the farthest point towards p of the radius of the lower cap over the face
		{
			if (face.Clip(lower, p, t0, t1)) { candidate[n++] = lower + t1 * (p - lower); }
		};
		if (face.Clip(p1, p2, t0, t1))
		{
			candidate[n++] = p1 + t0 * (p2 - p1);
			if (t1 > t0) { candidate[n++] = p1 + t1 * (p2 - p1); }
		}
		else { RimPoint(p1); }
		for (Real sign : {1., -1.})
		{
			if (radiusLower > 0.) { RimPoint(lower + radiusLower * (-0.5 * radial + sign * 0.5 * sqrt(3.) * tangent)); } //no rim at a tip
		}
		for (Index i = 0; i < n; i++)
		{
			Real gap = faceNormal * (candidate[i] - faceCenter);
			Vector3D onFace = candidate[i] - gap * faceNormal;
			if (swap) { points.Add(onFace, candidate[i], faceNormal, gap); }
			else { points.Add(candidate[i], onFace, down, gap); }
		}
	}

	//! the side of cylinder 0 against the side of cylinder 1: the closest point of the axes and the ends of the
	//! interval of axis 0 where the sides penetrate, which carry a line contact; the closest point carries the
	//! penetration beyond the line between the ends, so that a line contact and a point contact go over into each
	//! other continuously
	inline void SidePoints(const Cylinder& c0, const Cylinder& c1, Real s, Real distanceAxes, Real lo, Real hi, Points& points)
	{
		Real radii = c0.radius + c1.radius;
		auto AxisPoint = [&](Real sAxis, Vector3D& x0, Vector3D& x1, Vector3D& normal) -> Real
		{
			x0 = c0.center + sAxis * c0.axis;
			Real t = EXUstd::Minimum(c1.halfLength, EXUstd::Maximum(-c1.halfLength, (x0 - c1.center) * c1.axis));
			x1 = c1.center + t * c1.axis;
			normal = x1 - x0;
			Real d = normal.GetL2Norm();
			if (d > 0.) { normal *= 1. / d; }
			else { normal = points.closest.normal; }
			return d - radii;
		};
		//the ends of an interval of penetration have the gap 0 and the closest point of parallel sides carries nothing,
		//up to rounding: these gaps get the small offset zeroGap, so that rounding does not switch the contact state
		Real zeroGap = 1e-10 * radii;
		auto Apart = [&](Real gap) -> Real { return gap + zeroGap; }; //continuous, unlike a switch at zeroGap
		Vector3D x0, x1, normal;
		if (hi > lo)
		{
			Real gapEnd[2];
			Real sEnd[2] = { lo, hi };
			for (Index i = 0; i < 2; i++)
			{
				gapEnd[i] = AxisPoint(sEnd[i], x0, x1, normal);
				points.Add(x0 + c0.radius * normal, x1 - c1.radius * normal, normal, Apart(gapEnd[i]));
			}
			Real gap = AxisPoint(s, x0, x1, normal);
			Real gapLine = gapEnd[0] + (gapEnd[1] - gapEnd[0]) * (s - lo) / (hi - lo);
			gap -= EXUstd::Minimum(0., gapLine); //the penetration beyond the line of the ends
			points.Add(x0 + c0.radius * normal, x1 - c1.radius * normal, normal, Apart(gap));
		}
		else
		{
			Real gap = AxisPoint(s, x0, x1, normal);
			points.Add(x0 + c0.radius * normal, x1 - c1.radius * normal, normal, gap);
		}
		(void)distanceAxes;
	}

