	//! the contact points of two capsules, by the closest points of their segments in closed form: the points of the sides
	//! with the interval of penetration along segment 0, clipped to both segments (#3365)
	inline void CapsuleCapsulePoints(const Cylinder& c0, const Cylinder& c1, Points& points)
	{
		points.count = 0;
		auto Clamp = [](Real x, Real limit) -> Real { return EXUstd::Minimum(limit, EXUstd::Maximum(-limit, x)); };
		Vector3D w = c0.center - c1.center;
		Real c = c0.axis * c1.axis;
		Real sine2 = 1. - c * c;
		Real tau = w * c1.axis, wa0 = w * c0.axis;
		Real h0 = c0.halfLength, h1 = c1.halfLength;
		Real sLo = -h0, sHi = h0; //the interval of segment 0 over segment 1, for parallel segments
		if (c != 0.)
		{
			Real sA = (-h1 - tau) / c, sB = (h1 - tau) / c;
			sLo = EXUstd::Maximum(sLo, EXUstd::Minimum(sA, sB));
			sHi = EXUstd::Minimum(sHi, EXUstd::Maximum(sA, sB));
		}
		const bool parallel = !(sine2 > 1e-12);
		Real s = parallel ? (sHi > sLo ? 0.5 * (sLo + sHi) : 0.) : Clamp((c * tau - wa0) / sine2, h0);
		Real t = Clamp(tau + c * s, h1);
		s = Clamp(c * t - wa0, h0);
		t = Clamp(tau + c * s, h1);
		Vector3D x0 = c0.center + s * c0.axis, x1 = c1.center + t * c1.axis;
		Vector3D normal = x1 - x0;
		Real distanceAxes = normal.GetL2Norm();
		if (distanceAxes > 0.) { normal *= 1. / distanceAxes; }
		else
		{
			normal = c0.axis.CrossProduct(c1.axis);
			if (normal.GetL2Norm() == 0.) { normal = c0.side; }
			normal.Normalize();
		}
		Real radii = c0.radius + c1.radius;
		points.closest.distance = distanceAxes - radii;
		points.closest.point0 = x0 + c0.radius * normal;
		points.closest.point1 = x1 - c1.radius * normal;
		points.closest.normal = normal;
		Real lo = s, hi = s;
		if (distanceAxes < radii)
		{
			if (!parallel)
			{
				Real halfWidth = sqrt((radii * radii - distanceAxes * distanceAxes) / sine2);
				lo = EXUstd::Maximum(-h0, s - halfWidth);
				hi = EXUstd::Minimum(h0, s + halfWidth);
			}
			else if (sHi > sLo) { lo = sLo; hi = sHi; }
		}
		SidePoints(c0, c1, s, distanceAxes, lo, hi, points);
	}

	//! the contact points of shape 0 inside the hollow shape 1, a bore or a conical seat with its radii at the ends of its
	//! length (#3334): on each rim of shape 0 - clipped to the axial range of the hollow shape -, the point farthest
	//! from the axis of shape 1, in the direction of the eccentricity of the rim, and the points at +-120 degrees, so that
	//! a centered shape rests on all sides; the gap normal to the wall of the hollow shape
	inline void HollowPoints(const Cylinder& c0, const Cylinder& c1, Points& points)
	{
		points.count = 0;
		Real H = c1.halfLength;
		Real slope = (c1.radiusTop - c1.radius) / (2. * H); //dR/dt of the wall
		Real scale = 1. / sqrt(1. + slope * slope);
		Real a01 = c0.axis * c1.axis;
		Real deepest = EXUstd::MAXREAL;
		for (Real sign : { -1., 1. })
		{
			Real s = sign * c0.halfLength;
			Vector3D center = c0.center + s * c0.axis;
			Real t = (center - c1.center) * c1.axis;
			if (fabs(t) > H) //the rim is outside the hollow shape: the rim where shape 0 leaves it
			{
				if (a01 == 0.) { continue; }
				s += ((t > 0. ? H : -H) - t) / a01;
				if (fabs(s) > c0.halfLength) { continue; }
				center = c0.center + s * c0.axis;
				t = (center - c1.center) * c1.axis;
			}
			Real r = c0.radius + (c0.radiusTop - c0.radius) * (s + c0.halfLength) / (2. * c0.halfLength);
			//the eccentricity in the plane of the rim; for a centered rim it goes over into the local x axis of marker 0
			Vector3D e = center - (c1.center + t * c1.axis);
			e -= (e * c0.axis) * c0.axis;
			Real eccentricity = e.GetL2Norm() / c1.radius;
			e *= 1. / c1.radius;
			e += (standingBlend * standingBlend / (standingBlend + eccentricity)) * c0.side;
			if (e.GetL2Norm() == 0.) { e = c0.side; }
			e.Normalize();
			Vector3D tangent = c0.axis.CrossProduct(e);
			for (Real angle : { 0., 2. * EXUstd::pi / 3., -2. * EXUstd::pi / 3. })
			{
				Vector3D point = center + r * (EM::Cos(angle) * e + EM::Sin(angle) * tangent);
				Vector3D d = point - c1.center;
				Real tPoint = d * c1.axis;
				Vector3D radial = d - tPoint * c1.axis;
				Real rho = radial.GetL2Norm();
				if (rho > 0.) { radial *= 1. / rho; }
				else { radial = e; }
				Real R = c1.radius + slope * (tPoint + H);
				Real gap = (R - rho) * scale;
				Vector3D normal = scale * (radial - slope * c1.axis); //the wall of shape 1, outwards
				points.Add(point, point + gap * normal, normal, gap);
				if (gap < deepest)
				{
					deepest = gap;
					points.closest.distance = gap; points.closest.point0 = point; points.closest.point1 = point + gap * normal; points.closest.normal = normal;
				}
			}
		}
		if (points.count == 0) //shape 0 is outside the hollow shape along its axis
		{
			points.closest.distance = c1.radius; points.closest.point0 = c0.center; points.closest.point1 = c1.center; points.closest.normal = c1.axis;
		}
	}


	//! the contact points of two cylinders
	inline void CylinderCylinderPoints(const Cylinder& c0, const Cylinder& c1, Points& points)
	{
		if (c0.isCapsule && c1.isCapsule) { CapsuleCapsulePoints(c0, c1, points); return; }
		points.count = 0;
		EGeometry::ConvexShape shape0 = c0.Shape();
		EGeometry::ConvexShape shape1 = c1.Shape();
		EGeometry::ConvexDistance(shape0, c0.frame, shape1, c1.frame, points.closest);
		const Vector3D& normal = points.closest.normal;

		//the sides: the closest points of the axes inside both cylinders
		Vector3D w = c0.center - c1.center;
		Real c = c0.axis * c1.axis;
		Real sine2 = 1. - c * c;
		Real tau = w * c1.axis; //the parameter on axis 1 of the point s on axis 0: tau + c*s
		Real sLo = -c0.halfLength, sHi = c0.halfLength;
		if (c != 0.) //axis 1 limits the interval of axis 0: |tau + c*s| <= h1
		{
			Real sA = (-c1.halfLength - tau) / c, sB = (c1.halfLength - tau) / c;
			sLo = EXUstd::Maximum(sLo, EXUstd::Minimum(sA, sB));
			sHi = EXUstd::Minimum(sHi, EXUstd::Maximum(sA, sB));
		}
		else if (fabs(tau) > c1.halfLength) { sHi = sLo - 1.; } //empty
		Real radii = c0.radius + c1.radius;
		if (sine2 > 1e-12)
		{
			Real wa0 = w * c0.axis;
			Real s = (c * tau - wa0) / sine2; //the closest points of the two lines
			Real t = tau + c * s;
			if (fabs(s) <= c0.halfLength && fabs(t) <= c1.halfLength)
			{
				Vector3D d = (c1.center + t * c1.axis) - (c0.center + s * c0.axis);
				Real distanceAxes = d.GetL2Norm();
				Real halfWidth = sqrt(EXUstd::Maximum(0., radii * radii - distanceAxes * distanceAxes) / sine2);
				Real lo = EXUstd::Maximum(sLo, s - halfWidth), hi = EXUstd::Minimum(sHi, s + halfWidth);
				SidePoints(c0, c1, s, distanceAxes, lo, hi, points);
				return;
			}
		}
		else if (sHi > sLo && fabs(normal * c0.axis) < parallelTolerance && fabs(normal * c1.axis) < parallelTolerance)
		{
			//parallel sides: their distance is the same along the overlap
			Real s = 0.5 * (sLo + sHi);
			Vector3D d = w - (w * c0.axis) * c0.axis;
			Real distanceAxes = d.GetL2Norm();
			if (distanceAxes < radii) { SidePoints(c0, c1, s, distanceAxes, sLo, sHi, points); }
			else { SidePoints(c0, c1, s, distanceAxes, s, s, points); }
			return;
		}

		//a cap: the face of cylinder 1, or of cylinder 0
		CapPoints(c0, c1, points);
		if (points.count == 0) { points.AddClosest(); }
	}

	//! the points of a cap: where the normal is along the axis of one shape, the other against its cap as a face
	inline bool CapPoints(const Cylinder& c0, const Cylinder& c1, Points& points)
	{
		const Vector3D& normal = points.closest.normal;
		if (!c1.isCapsule && fabs(normal * c1.axis) > 1. - parallelTolerance) //a capsule has no cap
		{
			Real sign = normal * c1.axis < 0. ? 1. : -1.;
			Vector3D faceNormal = sign * c1.axis; //from the cap of 1 towards shape 0
			Vector3D faceCenter = c1.center + c1.halfLength * faceNormal;
			Face face;
			face.SetDisc(faceCenter, c1.axis, c1.RadiusAt(sign));
			if (c0.isCapsule) { CapsuleFacePoints(c0, faceCenter, faceNormal, face, points); }
			else { FacePoints(c0, faceCenter, faceNormal, face, points); }
			return true;
		}
		if (!c0.isCapsule && fabs(normal * c0.axis) > 1. - parallelTolerance)
		{
			Real sign = normal * c0.axis > 0. ? 1. : -1.;
			Vector3D faceNormal = sign * c0.axis; //from the cap of 0 towards shape 1
			Vector3D faceCenter = c0.center + c0.halfLength * faceNormal;
			Face face;
			face.SetDisc(faceCenter, c0.axis, c0.RadiusAt(sign));
			if (c1.isCapsule) { CapsuleFacePoints(c1, faceCenter, faceNormal, face, points, true); }
			else { FacePoints(c1, faceCenter, faceNormal, face, points, true); }
			return true;
		}
		return false;
	}

	//! the contact points of two truncated cones: on a cap as for the cylinders; else along the side line of cone 0
	//! through its closest point - the ends of the interval where it penetrates cone 1 (by bisection of the signed
	//! distance, a convex function along the line) and the closest point, which carries the penetration beyond the
	//! line of the ends, as SidePoints
	inline void ConeConePoints(const Cylinder& c0, const Cylinder& c1, Points& points)
	{
		points.count = 0;
		EGeometry::ConvexDistance(c0.Shape(), c0.frame, c1.Shape(), c1.frame, points.closest);
		if (CapPoints(c0, c1, points)) { if (points.count == 0) { points.AddClosest(); } return; }
		//the side: decided by the signed distance along the side line, not by GJK and EPA, whose penetration is less exact

		//the side line of cone 0 in the half-plane towards the axis of cone 1: through the point of the axis of cone 1
		//closest to the center of cone 0, smooth in the configuration (the closest point of EPA is not exact; the
		//closest points of the two axes jump where the axes intersect, as for cones rolling on each other)
		Real t = EXUstd::Minimum(c1.halfLength, EXUstd::Maximum(-c1.halfLength, (c0.center - c1.center) * c1.axis));
		Vector3D between = c1.center + t * c1.axis - c0.center;
		Vector3D radial = between - (between * c0.axis) * c0.axis;
		if (radial.GetL2Norm() <= 1e-12 * (c0.halfLength + c1.halfLength))
		{
			radial = points.closest.normal - (points.closest.normal * c0.axis) * c0.axis;
		}
		if (radial.GetL2Norm() == 0.) { points.AddClosest(); return; }
		radial.Normalize();
		Vector3D lineStart = c0.center - c0.halfLength * c0.axis + c0.radius * radial;
		Vector3D lineEnd = c0.center + c0.halfLength * c0.axis + c0.radiusTop * radial;
		Vector3D line = lineEnd - lineStart;
		auto Gap = [&](Real u, Vector3D& x, Vector3D& nearest, Vector3D& outward) -> Real
		{
			x = lineStart + u * line;
			return c1.SignedDistance(x, nearest, outward);
		};
		//the deepest point of the line: the minimum of the signed distance, convex along the line, by golden section;
		//the closest point of GJK and EPA is not the deepest one along a line contact
		Vector3D xs, ns, os;
		Real ua = 0., ub = 1., golden = 0.5 * (sqrt(5.) - 1.);
		Real uc = ub - golden * (ub - ua), ud = ua + golden * (ub - ua);
		Real gc = Gap(uc, xs, ns, os), gd = Gap(ud, xs, ns, os);
		for (Index k = 0; k < 60; k++)
		{
			if (gc < gd) { ub = ud; ud = uc; gd = gc; uc = ub - golden * (ub - ua); gc = Gap(uc, xs, ns, os); }
			else { ua = uc; uc = ud; gc = gd; ud = ua + golden * (ub - ua); gd = Gap(ud, xs, ns, os); }
		}
		Real uStar = 0.5 * (ua + ub);
		Vector3D x, nearest, outward;
		Real gapStar = Gap(uStar, x, nearest, outward);
		if (gapStar >= 0.) { points.Add(x, nearest, -1. * outward, gapStar); return; } //apart: the one point of the line
		auto End = [&](Real uOut) -> Real //the end of the penetration between uStar and uOut
		{
			Vector3D xe, ne, oe;
			if (Gap(uOut, xe, ne, oe) <= 0.) { return uOut; } //clipped by the end of the line
			Real a = uStar, b = uOut;
			for (Index k = 0; k < 60; k++)
			{
				Real m = 0.5 * (a + b);
				if (Gap(m, xe, ne, oe) <= 0.) { a = m; } else { b = m; }
			}
			return a;
		};
		Real lo = End(0.), hi = End(1.);
		Real zeroGap = 1e-10 * (c0.halfLength + c1.halfLength);
		auto Apart = [&](Real gap) -> Real { return gap + zeroGap; }; //continuous, unlike a switch at zeroGap
		Real gapEnd[2];
		Real uEnd[2] = { lo, hi };
		for (Index i = 0; i < 2; i++)
		{
			gapEnd[i] = Gap(uEnd[i], x, nearest, outward);
			points.Add(x, nearest, -1. * outward, Apart(gapEnd[i]));
		}
		Real gap = Gap(uStar, x, nearest, outward);
		if (hi > lo) { gap -= EXUstd::Minimum(0., gapEnd[0] + (gapEnd[1] - gapEnd[0]) * (uStar - lo) / (hi - lo)); }
		points.Add(x, nearest, -1. * outward, Apart(gap));
	}

	//! the contact points of a cylinder and a triangle, or its infinite plane
	inline void CylinderTrianglePoints(const Cylinder& cylinder, const Vector3D* trianglePoints, bool infinitePlane, Points& points)
	{
		points.count = 0;
		Vector3D triangleNormal = EXUmath::ComputeTriangleNormal(trianglePoints[0], trianglePoints[1], trianglePoints[2]);
		Face face;
		if (infinitePlane)
		{
			FacePoints(cylinder, trianglePoints[0], triangleNormal, face, points);
			//the distance: the lowest point of the cylinder along the normal, its support point
			Vector3D lowest = cylinder.frame.GetTranslation() + cylinder.frame.GetRotation() *
				cylinder.Shape().SupportCore(cylinder.frame.GetRotation().GetTransposed() * (-1. * triangleNormal));
			points.closest.distance = triangleNormal * (lowest - trianglePoints[0]);
			points.closest.point0 = lowest;
			points.closest.point1 = lowest - points.closest.distance * triangleNormal;
			points.closest.normal = -1. * triangleNormal;
			return;
		}
		EGeometry::ConvexShape shape0 = cylinder.Shape();
		EGeometry::ConvexShape triangle;
		triangle.type = EGeometry::ConvexShapeType::Triangle;
		for (Index i = 0; i < 3; i++) { triangle.triangle[i] = trianglePoints[i]; }
		EGeometry::ConvexDistance(shape0, cylinder.frame, triangle, HomogeneousTransformation(), points.closest); //the triangle points are global
		Real alongNormal = points.closest.normal * triangleNormal;
		if (fabs(alongNormal) > 1. - parallelTolerance) //the face of the triangle, from the side of the cylinder
		{
			face.SetTriangle(trianglePoints[0], trianglePoints[1], trianglePoints[2]);
			FacePoints(cylinder, trianglePoints[0], (alongNormal < 0. ? 1. : -1.) * triangleNormal, face, points);
		}
		if (points.count == 0) { points.AddClosest(); }
	}


