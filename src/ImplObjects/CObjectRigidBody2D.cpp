//! the access functions by automatic differentiation of the templated position and rotation (#2744): the same results
//! as the hand-written ones, which are used - measured in revision2026b step RG9.3.5, the implicit solve of a chain of
//! 2D rigid bodies is about 20 % slower with them (the angle differentiated); kept for comparison
static const bool accessFunctionsByAD = false;

//! the position [x, y, 0] + A(phi) localPosition as a generic function of the coordinates [x, y, phi] (#2744)
static auto RigidBody2DPositionAD(const Vector3D& localPosition)
{
	return [localPosition](const auto* q, auto* p)
	{
		using std::sin; using std::cos;
		p[0] = q[0] + cos(q[2]) * localPosition[0] - sin(q[2]) * localPosition[1];
		p[1] = q[1] + sin(q[2]) * localPosition[0] + cos(q[2]) * localPosition[1];
		p[2] = 0. * q[0] + localPosition[2];
	};
}

//! the rotation matrix about z as a generic function of the coordinates [x, y, phi] (#2744)
static auto RigidBody2DRotationAD()
{
	return [](const auto* q, auto& A)
	{
		using std::sin; using std::cos;
		A(0, 0) = cos(q[2]); A(0, 1) = -sin(q[2]); A(0, 2) = 0. * q[2];
		A(1, 0) = sin(q[2]); A(1, 1) = cos(q[2]); A(1, 2) = 0. * q[2];
		A(2, 0) = 0. * q[2]; A(2, 1) = 0. * q[2]; A(2, 2) = 0. * q[2] + 1.;
	};
}

//! the coordinates [x, y, phi], reference + current (#2744)
static ConstSizeVector<3> RigidBody2DCoordinates(const CNode* node)
{
	LinkedDataVector reference = node->GetCoordinateVector(ConfigurationType::Reference);
	return ConstSizeVector<3>({ reference[0] + node->GetCurrentCoordinate(0), reference[1] + node->GetCurrentCoordinate(1),
		reference[2] + node->GetCurrentCoordinate(2) });
}

