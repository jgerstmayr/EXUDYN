//! Map coordinates using shape functions: map_coordinates_element_jax(sf, q)
//! Returns the 3D vector resulting from q @ sf, where q is reshaped as (12, 3)
template<class TReal>
SlimVectorBase<TReal, 3> CObjectANCFThinPlate::MapCoordinates(const Vector12D& sf, const ConstSizeVectorBase<TReal,nODE2coordinates>& q) const
{
    SlimVectorBase<TReal, 3> result;

    //use 
    //LinkedDataMatrix qMat(q.GetDataPointer(), nSF, EXUstd::dim3D);
    //EXUmath::MultMatrixTransposedVector(qMat, sf, result);
    
    result[0] = TReal(0.0);
    result[1] = TReal(0.0);
    result[2] = TReal(0.0);
    
    // q is in node-major format: [node0(r,sx,sy), node1(r,sx,sy), ...]
    // Each node has 9 entries: r(3), sx(3), sy(3)
    // Need to multiply by 12 shape functions corresponding to [r0, sx0, sy0, r1, sx1, sy1, ...]
    for (Index i = 0; i < 12; i++)
    {
        Index nodeIdx = i / 3;  // 0,0,0,1,1,1,2,2,2,3,3,3
        Index vecIdx = i % 3;   // 0,1,2,0,1,2,0,1,2,0,1,2
        Index qOffset = nodeIdx * 9 + vecIdx * 3;
        
        result[0] += q[qOffset + 0] * sf[i];
        result[1] += q[qOffset + 1] * sf[i];
        result[2] += q[qOffset + 2] * sf[i];
    }
    return result;
}

//CObjectANCFThinPlate::
template<class TReal>
void ComputeKinematicsPure(
    const SlimVectorBase<TReal, 3>& r_x, const SlimVectorBase<TReal, 3>& r_y,
    const SlimVectorBase<TReal, 3>& r_xx, const SlimVectorBase<TReal, 3>& r_yy, const SlimVectorBase<TReal, 3>& r_xy,
    SlimVectorBase<TReal, 3>& eps_mid,
    SlimVectorBase<TReal, 3>& kappa) //const
{
    SlimVectorBase<TReal, 3> n3 = r_x.CrossProduct(r_y);
    TReal n3_norm = n3.GetL2Norm();
    // Assuming non-zero normal (checked in caller)

    // MATERIAL curvature measure (Gerstmayr-Irschik type, consistent with ANCFCable2D):
    //   kappa_xx = (n3 . r_xx) / (|n3| * |r_x|),  kappa_yy = (n3 . r_yy) / (|n3| * |r_y|),
    //   kappa_xy = 2 (n3 . r_xy) / (|n3| * sqrt(|r_x| |r_y|))
    // Strip limit (|r_y|=1): kappa_xx = (r' x r'') / |r'|^2 = Cable2D measure exactly.
    // Unlike the GEOMETRIC measure (n3 . r_ii)/|n3|^3, this measure makes pure bending
    // produce exactly zero membrane force (no parasitic strain eps = h^2 kappa^2 / 12).
    TReal rxNorm = r_x.GetL2Norm();
    TReal ryNorm = r_y.GetL2Norm();
    TReal invNx  = 1.0 / (n3_norm * rxNorm);
    TReal invNy  = 1.0 / (n3_norm * ryNorm);
    TReal invNxy = 1.0 / (n3_norm * sqrt(rxNorm * ryNorm));

    // Curvatures
    kappa[0] = (n3 * r_xx) * invNx;
    kappa[1] = (n3 * r_yy) * invNy;
    kappa[2] = 2. * (n3 * r_xy) * invNxy;// Factor 2 for engineering twist

    // --- Strains & Curvatures (Difference) ---
    // Green-Lagrange Strains
    eps_mid[0] = 0.5 * (r_x * r_x);
    eps_mid[1] = 0.5 * (r_y * r_y);
    eps_mid[2] = (r_x * r_y); // Gamma (2*eps12)
}


// Helper to transform parametric derivatives (xi, eta) to physical derivatives (x, y)
// utilizing the inverse Jacobian matrix A.
template<class TReal>
void TransformDerivatives(const Matrix2D& A,
    const SlimVectorBase<TReal, 3>& r_xi, const SlimVectorBase<TReal, 3>& r_eta,
    const SlimVectorBase<TReal, 3>& r_xixi, const SlimVectorBase<TReal, 3>& r_etaeta, const SlimVectorBase<TReal, 3>& r_xieta,
    SlimVectorBase<TReal, 3>& r_x, SlimVectorBase<TReal, 3>& r_y,
    SlimVectorBase<TReal, 3>& r_xx, SlimVectorBase<TReal, 3>& r_yy, SlimVectorBase<TReal, 3>& r_xy)
{
    // First derivatives
    r_x = r_xi * A(0, 0) + r_eta * A(1, 0);
    r_y = r_xi * A(0, 1) + r_eta * A(1, 1);

    // Second derivatives (Chain rule)
    // r_xx = r_xixi*(dxi/dx)^2 + 2*r_xieta*(dxi/dx)*(deta/dx) + r_etaeta*(deta/dx)^2
    r_xx = r_xixi * (A(0, 0) * A(0, 0)) + r_xieta * (2.0 * A(0, 0) * A(1, 0)) + r_etaeta * (A(1, 0) * A(1, 0));

    // r_yy = r_xixi*(dxi/dy)^2 + 2*r_xieta*(dxi/dy)*(deta/dy) + r_etaeta*(deta/dy)^2
    r_yy = r_xixi * (A(0, 1) * A(0, 1)) + r_xieta * (2.0 * A(0, 1) * A(1, 1)) + r_etaeta * (A(1, 1) * A(1, 1));

    // r_xy = r_xixi*(dxi/dx*dxi/dy) + r_xieta*(dxi/dx*deta/dy + deta/dx*dxi/dy) + r_etaeta*(deta/dx*deta/dy)
    r_xy = r_xixi * (A(0, 0) * A(0, 1)) + r_xieta * (A(0, 0) * A(1, 1) + A(1, 0) * A(0, 1)) + r_etaeta * (A(1, 0) * A(1, 1));

    // r_yy = r_xixi*(dxi/dy)^2 + 2*r_xieta*(dxi/dy)*(deta/dy) + r_etaeta*(deta/dy)^2
    r_yy = r_xixi * (A(0, 1) * A(0, 1))
        + r_xieta * (2.0 * A(0, 1) * A(1, 1))
        + r_etaeta * (A(1, 1) * A(1, 1));

}

template<class TReal>
void CObjectANCFThinPlate::ComputeKinematics(Real xi, Real eta,
    const ConstSizeVectorBase<Real, nODE2coordinates>& qANCFref,
    const ConstSizeVectorBase<TReal, nODE2coordinates>& qANCFtotal,
    SlimVectorBase<TReal, 3>& eps_mid,
    SlimVectorBase<TReal, 3>& kappa) const
{
    // Compute element dimensions from reference configuration
    // Node layout: 0=bottom-left, 1=bottom-right, 2=top-right, 3=top-left

    // Get shape functions and derivatives (SIZED, consistent with NodePointSlope12 slopes = dr/dx, dr/dy)
    Vector12D sf_x, sf_y, sf_xx, sf_yy, sf_xy;
    ComputeShapeFunctions_xy(xi, eta, sf_x, sf_y);
    ComputeShapeFunctions_xxyy(xi, eta, sf_xx, sf_yy, sf_xy);

    // from the reference coordinates at the current Gauss point.
    // These vectors represent dr/dxi and dr/deta in the reference configuration.
    SlimVectorBase<Real, 3> r_xi_ref = MapCoordinates(sf_x, qANCFref);
    SlimVectorBase<Real, 3> r_eta_ref = MapCoordinates(sf_y, qANCFref);
    SlimVectorBase<Real, 3> r_xixi_ref = MapCoordinates(sf_xx, qANCFref);
    SlimVectorBase<Real, 3> r_etaeta_ref = MapCoordinates(sf_yy, qANCFref);
    SlimVectorBase<Real, 3> r_xieta_ref = MapCoordinates(sf_xy, qANCFref);

    // Jacobian & transformation matrix
    SlimVectorBase<Real, 3> n0 = r_xi_ref.CrossProduct(r_eta_ref);
    Real n0_norm = n0.GetL2Norm();
    Matrix2D J0 = GetElementJacobian(r_xi_ref, r_eta_ref, n0 * (1. / n0_norm));
    Matrix2D J0inv = J0.GetInverse();

    // transform reference derivatives
    SlimVectorBase<Real, 3> r_x_ref, r_y_ref, r_xx_ref, r_yy_ref, r_xy_ref;
    TransformDerivatives(J0inv, r_xi_ref, r_eta_ref, r_xixi_ref, r_etaeta_ref, r_xieta_ref,
        r_x_ref, r_y_ref, r_xx_ref, r_yy_ref, r_xy_ref);

    //vectors in current configuration
    SlimVectorBase<TReal, 3> r_xi_cur = MapCoordinates(sf_x, qANCFtotal);
    SlimVectorBase<TReal, 3> r_eta_cur = MapCoordinates(sf_y, qANCFtotal);
    SlimVectorBase<TReal, 3> r_xixi_cur = MapCoordinates(sf_xx, qANCFtotal);
    SlimVectorBase<TReal, 3> r_etaeta_cur = MapCoordinates(sf_yy, qANCFtotal);
    SlimVectorBase<TReal, 3> r_xieta_cur = MapCoordinates(sf_xy, qANCFtotal);

    // transform current derivatives
    SlimVectorBase<TReal, 3> r_x_cur, r_y_cur, r_xx_cur, r_yy_cur, r_xy_cur;
    TransformDerivatives(J0inv, r_xi_cur, r_eta_cur, r_xixi_cur, r_etaeta_cur, r_xieta_cur,
        r_x_cur, r_y_cur, r_xx_cur, r_yy_cur, r_xy_cur);

    // compute kinematics (strains/curvatures) using physical vectors
    SlimVectorBase<Real, 3> eps_mid_ref, kappa_ref;
    SlimVectorBase<TReal, 3> eps_mid_cur, kappa_cur;
    ComputeKinematicsPure(r_x_ref, r_y_ref, r_xx_ref, r_yy_ref, r_xy_ref,
        eps_mid_ref, kappa_ref);
    ComputeKinematicsPure(r_x_cur, r_y_cur, r_xx_cur, r_yy_cur, r_xy_cur,
        eps_mid_cur, kappa_cur);

    for (Index i = 0; i < kappa.NumberOfItems(); i++)
    {
        eps_mid[i] = (TReal)(eps_mid_cur[i] - eps_mid_ref[i]);
        kappa[i] = (TReal)(kappa_cur[i] - kappa_ref[i]);
    }

}


