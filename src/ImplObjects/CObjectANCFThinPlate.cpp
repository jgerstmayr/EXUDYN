//! Precompute mass matrix terms
void CObjectANCFThinPlate::PreComputeMassTerms() const
{
    if (massMatrixComputed) { return; }  // Already computed
    
    // Initialize the mass matrix to zero
    precomputedMassMatrix.SetScalarMatrix(nODE2coordinates, 0.0);
    
    // Compute element dimensions from reference configuration
    // Node layout: 0=bottom-left, 1=bottom-right, 2=top-right, 3=top-left
    //Real jacDet = GetElementJacobian();

    Real rho = parameters.density;
    // CHANGED: thickness is now evaluated per Gauss point to support variable nodal thickness (MP/JG, 2026)
    // OLD: Real rhoThickness = rho * parameters.thickness;  // constant thickness

    ConstSizeVector<nODE2coordinates> qANCFref;
    ComputeReferenceObjectCoordinates(qANCFref);

    // Use 5-point Gauss integration for mass matrix (consistent with Python reference)
    // Note: SetGaussIntegrationRule valid orders are 1,3,5,7,9 (odd numbers)
    // order=9 gives 5 points, order=7 gives 4 points, order=5 gives 3 points
    ConstSizeVector<5> xiGP, xiW;
    EXUmath::SetGaussIntegrationRule(9, xiGP, xiW);  // order=9 gives 5-point Gauss
    
    Vector12D SV, sf_x, sf_y;
    for (Index iGP = 0; iGP < xiGP.NumberOfItems(); iGP++)
    {
        Real xi = xiGP[iGP];
        for (Index jGP = 0; jGP < xiGP.NumberOfItems(); jGP++)
        {
            Real eta = xiGP[jGP];

            ComputeShapeFunctions_xy(xi, eta, sf_x, sf_y);
            Vector3D dr_dxi = MapCoordinates(sf_x, qANCFref);
            Vector3D dr_deta = MapCoordinates(sf_y, qANCFref);

            // 3. Element Jacobian determinant (Surface Area scale factor)
            // This is the magnitude of the normal vector: ||dr/dxi x dr/deta||
            Real jacDet = (dr_dxi.CrossProduct(dr_deta)).GetL2Norm();

            // ADDED: compute thickness at current Gauss point for variable thickness support (MP/JG, 2026)
            Real h = ComputeThicknessAtPoint(xi, eta);
            Real w = xiW[iGP] * xiW[jGP] * jacDet * rho * h;

            // Consistent mass must use sized shape functions - refers to reference geometry!
            ComputeShapeFunctions(xi, eta, SV);
            
            // Mass matrix: M[i*3+k, j*3+k] += w * SV[i] * SV[j] for each spatial component k
            // where i, j are shape function indices (0-11), and k is spatial component (0-2)
            // Mapping: shape function i corresponds to node i/3, vector component i%3
            // DOF mapping: nodeIdx * 9 + vecIdx * 3 + spatialComp
            for (Index i = 0; i < 12; i++)
            {
                Index nodeI = i / 3;
                Index vecI = i % 3;
                Index dofI_base = nodeI * 9 + vecI * 3;
                
                for (Index j = 0; j < 12; j++)
                {
                    Index nodeJ = j / 3;
                    Index vecJ = j % 3;
                    Index dofJ_base = nodeJ * 9 + vecJ * 3;
                    
                    Real val = w * SV[i] * SV[j];
                    for (Index k = 0; k < 3; k++)
                    {
                        precomputedMassMatrix(dofI_base + k, dofJ_base + k) += val;
                    }
                }
            }
        }
    }
    
    massMatrixComputed = true;
}

//! the position Jacobian d(v)/d(q_t) at localPosition, 3 x n (#2744)
void CObjectANCFThinPlate::GetPositionJacobian(const Vector3D& localPosition, Matrix& value) const
{
    const Index dim = 3;		//3D finite element
    const Index ns = 12;		//number of shape functions
    //Real jacDet = GetElementJacobian();

    Vector12D SV;
    ComputeShapeFunctions(localPosition[0], localPosition[1], SV);

    value.SetNumberOfRowsAndColumns(dim, dim * ns); 

    CHECKandTHROW(localPosition[2] == 0,
        "CObjectANCFThinPlate: markers, forces and constraints can only act at the plate midsurface at Z=0; check your code", ExudynModelError);

    value.SetAll(0.);

    for (Index i = 0; i < 12; i++)
    {
        value(0, i*3  ) = SV[i];
        value(1, i*3+1) = SV[i];
        value(2, i*3+2) = SV[i];
    }
}

//! the mass-weighted position Jacobian int(rho J_pos dV), 3 x n (#2744)
void CObjectANCFThinPlate::GetMassWeightedPositionJacobian(Matrix& value) const
{
    const Index dim = 3;		//3D finite element
    const Index ns = 12;		//number of shape functions
    Real jacDet = GetElementJacobian();


    value.SetNumberOfRowsAndColumns(dim, dim * ns); //3D velocity, 12 coordinates qt
    value.SetAll(0.);

    Vector12D SVloc;
    Vector12D SV(0.);

    Real rho = parameters.density;
    // CHANGED: thickness evaluated per Gauss point for variable thickness support (MP/JG, 2026)
    // OLD: Real rhoThickness = rho * parameters.thickness;

    Index cntEta = 0;
    for (Real eta : EXUmath::gaussRuleOrder3Points)
    {
        Index cntXi = 0;
        for (Real xi : EXUmath::gaussRuleOrder3Points)
        {
            // ADDED: compute thickness at current Gauss point (MP/JG, 2026)
            Real h = ComputeThicknessAtPoint(xi, eta);
            ComputeShapeFunctions(xi, eta, SVloc);
            SVloc *= rho * h * jacDet * EXUmath::gaussRuleOrder3Weights[cntXi] * EXUmath::gaussRuleOrder3Weights[cntEta];
            SV += SVloc;
            cntXi++;
        }
    }

    for (Index i = 0; i < 12; i++)
    {
        value(0, i * 3) = SV[i];
        value(1, i * 3 + 1) = SV[i];
        value(2, i * 3 + 2) = SV[i];
    }
}


void CObjectANCFThinPlate::GetOutputVariableBody(OutputVariableType variableType, 
                                                  const Vector3D& localPosition, 
                                                  ConfigurationType configuration, 
                                                  Vector& value, 
                                                  Index objectNumber) const
{
    // localPosition is interpreted as (xi,eta,*) in [-1,1]x[-1,1] for this element
    Real xi = localPosition[0];
    Real eta = localPosition[1];

    // reference coordinates from nodes
    ConstSizeVector<nODE2coordinates> qANCFref;
    ComputeReferenceObjectCoordinates(qANCFref);

    // displacement coordinates (relative to reference) for requested configuration
    ConstSizeVector<nODE2coordinates> qANCFtotal;
    qANCFtotal.SetAll(0.);
    if (configuration != ConfigurationType::Reference)
    {
        for (Index i = 0; i < nNodes; i++)
        {
            LinkedDataVector qNodeU(qANCFtotal, i * nnc, nnc);
            qNodeU = ((CNodeODE2*)GetCNode(i))->GetCoordinateVector(configuration);
        }
        qANCFtotal += qANCFref;
    }
    // strains and curvatures are computed in the classical xi-aligned local frame
    // (GetElementJacobian); components map directly to physical quantities and
    // zeta=+-1 in localPosition[2] is the physical outer fibre.
    // REMOVED: useSymmetricFrame back-rotation (RotateToClassical) -- the bisector
    // frame option was removed (frame-invariant for isotropic material).  MP, 2026-06-10

    switch (variableType)
    {
    case OutputVariableType::StrainLocal:
    {
        // Through-thickness Green-Lagrange strains at localPosition[2] = zeta in [-1,1].
        // Kirchhoff-Love kinematics: eps(xi,eta,zeta) = eps_mid - (zeta*h/2)*kappa
        // where eps_mid = mid-surface membrane strains, kappa = curvature (physical, units 1/m),
        //       h = local thickness [m], zeta in [-1,1]: zeta=+1 -> outer fiber at z=+h/2 [m].
        // Factor h/2 converts the normalized zeta to physical distance z = zeta*(h/2).
        // Consistent with Cable2D: eps = eps_axial - y*kappa, where y = physical distance [m].
        // Consistent with StressLocal: s = N/h - zeta*(6*M/h^2) = E*(eps_mid - zeta*(h/2)*kappa)
        //   => StrainLocal = StressLocal/E (for nu=0) = eps_mid - zeta*(h/2)*kappa. (MP/JG, 2026)
        // Returns 6-component vector [e11, e22, e33, e23, e13, e12] (engineering strains).
        // e33=e23=e13=0 (plane-stress Kirchhoff-Love: no transverse normal/shear strains).
        // e12 = gamma_xy is the engineering shear strain (includes factor-2 from kappa[2]).
        SlimVectorBase<Real, 3> eps_mid, kappa;
        ComputeKinematics(xi, eta, qANCFref, qANCFtotal, eps_mid, kappa);
        Real zeta = localPosition[2];           // in [-1,1]: -1 = bottom, 0 = mid, +1 = top surface
        Real h = ComputeThicknessAtPoint(xi, eta);  // local thickness [m]; supports variable thickness
        Real halfH = 0.5 * h;                   // physical distance to outer fiber = h/2 [m]
        // Kirchhoff-Love: eps(zeta) = eps_mid - (zeta*halfH)*kappa; sign: kappa>0 -> concave-downward
        Real e11 = eps_mid[0] - zeta * halfH * kappa[0];  // normal strain xx (MP/JG, 2026)
        Real e22 = eps_mid[1] - zeta * halfH * kappa[1];  // normal strain yy
        Real e12 = eps_mid[2] - zeta * halfH * kappa[2];  // engineering shear strain gamma_xy
        // 6-component format [e11,e22,e33,e23,e13,e12] matches StressLocal output layout
        value.SetVector({ e11, e22, 0., 0., 0., e12 });
        break;
    }
    case OutputVariableType::CurvatureLocal:
    {
        SlimVectorBase<Real, 3> eps_mid, kappa;
        ComputeKinematics(xi, eta, qANCFref, qANCFtotal, eps_mid, kappa);
        value.SetVector({ -kappa[0], kappa[1], kappa[2] }); //[0]=-kappa_xx: sign matches Cable2D (kappa<0 for downward bending, M=EI*kappa<0), [1]=kappa_yy, [2]=kappa_xy
        break;
    }
    case OutputVariableType::Position:
    {
        value.CopyFrom(GetPosition(localPosition, configuration));
        break;
    }
    case OutputVariableType::Displacement:
    {
        value.CopyFrom(GetPosition(localPosition, configuration) - GetPosition(localPosition, ConfigurationType::Reference));
        break;
    }
    case OutputVariableType::Velocity:
    {
        value.CopyFrom(GetVelocity(localPosition, configuration));
        break;
    }
    case OutputVariableType::Acceleration:
    {
        value.CopyFrom(GetAcceleration(localPosition, configuration));
        break;
    }
    case OutputVariableType::StressLocal:
    {
        // Through-thickness engineering stress at localPosition[2] = zeta in [-1,1]
        // sigma(xi,eta,zeta) = N/h - zeta*(6*M/h^2)
        // where N = D_eps * Delta_eps_m  (membrane force resultant, 3 components)
        //       M = D_kappa * Delta_kappa  (moment resultant, 3 components)
        //       h = local thickness, zeta in [-1,1] is through-thickness coordinate
        // sign: kappa = n·r_xx uses opposite sign from Kirchhoff convention; minus compensates.
        SlimVectorBase<Real, 3> eps_mid, kappa;
        ComputeKinematics(xi, eta, qANCFref, qANCFtotal, eps_mid, kappa);

        SlimVectorBase<Real, 3> N, M;
        Real h = ComputeThicknessAtPoint(xi, eta);
        Matrix3D Deps, Dkappa;
        StiffnessAtPoint(*this, xi, eta, Deps, Dkappa);
        EXUmath::MultMatrixVectorTemplate(Deps, eps_mid, N);
        EXUmath::MultMatrixVectorTemplate(Dkappa, kappa, M);
        CHECKandTHROW(h > 0., "CObjectANCFThinPlate::GetOutputVariableBody: thickness h must be > 0 for StressLocal", ExudynValueError);
        Real zeta = localPosition[2];  // in [-1,1]: -1 = bottom, +1 = top surface
        Real s11 = N[0]/h - zeta*(6.*M[0]/(h*h));
        Real s22 = N[1]/h - zeta*(6.*M[1]/(h*h));
        Real s12 = N[2]/h - zeta*(6.*M[2]/(h*h));
        // return 6-component vector [s11,s22,s33,s23,s13,s12] with zero out-of-plane components
        // => component=-1 (norm flag) automatically computes plane-stress von Mises in the renderer
        value.SetVector({ s11, s22, 0., 0., 0., s12 });
        break;
    }
    case OutputVariableType::Director1:
    case OutputVariableType::Director2:
    {
        //the slope vectors at (xi,eta) (#2768)
        Vector3D slopeX, slopeY;
        GetSlopes(localPosition, slopeX, slopeY, configuration);
        value.CopyFrom(variableType == OutputVariableType::Director1 ? slopeX : slopeY);
        break;
    }
    case OutputVariableType::ForceLocal:
    {
        // Membrane force resultants N = [N11, N22, N12]  [N/m]
        // N = D_eps * Delta_eps_mid, integrated through thickness.
        // Comparable to Cable2D ForceLocal (axial force [N]) after dividing by plate width.
        // MP, 2026-05-26
        SlimVectorBase<Real, 3> eps_mid, kappa;
        ComputeKinematics(xi, eta, qANCFref, qANCFtotal, eps_mid, kappa);
        SlimVectorBase<Real, 3> N;
        Matrix3D Deps, Dkappa;
        StiffnessAtPoint(*this, xi, eta, Deps, Dkappa);
        EXUmath::MultMatrixVectorTemplate(Deps, eps_mid, N);
        value.SetVector({ N[0], N[1], N[2] });
        break;
    }
    case OutputVariableType::TorqueLocal:
    {
        // Bending moment resultants M = [M11, M22, M12]  [N*m/m = N]
        // M = D_kappa * Delta_kappa  (bending stiffness times curvature change).
        // Comparable to Cable2D TorqueLocal (bending moment [N*m]) after multiplying by plate width.
        // Sign convention: M[0] negated to match Cable2D (M<0 for downward bending),
        // consistent with CurvatureLocal[0] = -kappa[0].  MP, 2026-05-26
        SlimVectorBase<Real, 3> eps_mid, kappa;
        ComputeKinematics(xi, eta, qANCFref, qANCFtotal, eps_mid, kappa);
        SlimVectorBase<Real, 3> M;
        Matrix3D Deps, Dkappa;
        StiffnessAtPoint(*this, xi, eta, Deps, Dkappa);
        EXUmath::MultMatrixVectorTemplate(Dkappa, kappa, M);
        value.SetVector({ -M[0], M[1], M[2] }); // -M[0]: sign matches Cable2D TorqueLocal convention
        break;
    }
    case OutputVariableType::PotentialEnergy: {
        CheckEnergyLocalPosition(localPosition, "ObjectANCFThinPlate");
        value.SetVector({ ComputeElasticEnergy(configuration) }); break; }
    case OutputVariableType::KineticEnergy: {
        CheckEnergyLocalPosition(localPosition, "ObjectANCFThinPlate");
        value.SetVector({ ComputeKineticEnergyFromMassMatrix(configuration, objectNumber, "ObjectANCFThinPlate") }); break; }
    default:
        SysError("CObjectANCFThinPlate::GetOutputVariableBody failed"); // error should not occur, because types are checked!
    }
}

//! the integration rules of the elastic forces: the membrane and the bending virtual work, shared with the elastic
//! energy (#2202, #2857)
void CObjectANCFThinPlate::GetIntegrationRules(ConstSizeVector<5>& membranePoints, ConstSizeVector<5>& membraneWeights,
    ConstSizeVector<5>& gaussPoints, ConstSizeVector<5>& gaussWeights) const
{
    // Choose integration rules for membrane and bending integrals ─────────────────────────────
    // Mode 0: full Gauss (order 9, 5 points per direction) for both membrane and bending.
    //         Safe baseline; may exhibit membrane locking for very thin plates.
    // Mode 1: selective reduced integration (Ntarladima/Pieber/Gerstmayr, Nonlinear Dyn 2023, Table 1 scheme c):
    //         - membrane/strain:   Lobatto order 3 (3 points at {-1, 0, +1} per direction; 9 pts in 2D)
    //         - bending/curvature: Gauss  order 3 (2 points at {+-1/sqrt(3)} per direction; 4 pts in 2D)
    //         Key property: membrane and bending points are COMPLETELY DISJOINT (Lobatto {-1,0,+1}
    //         and Gauss-2pt {+-0.577} share no common value), which eliminates membrane locking.
    if (parameters.useReducedOrderIntegration == 0)
    {
        // full Gauss: order 9 (5 points per direction) for both membrane and bending
        EXUmath::SetGaussIntegrationRule(9, gaussPoints, gaussWeights);
        membranePoints.CopyFrom(gaussPoints);
        membraneWeights.CopyFrom(gaussWeights);
    }
    else if (parameters.useReducedOrderIntegration == 1)
    {
        // Lobatto SRI: membrane uses Lobatto order 3 (3 pts at {-1, 0, +1}),
        // bending uses Gauss order 3 (2 pts at {+-1/sqrt(3)}) -- completely disjoint
        EXUmath::SetGaussIntegrationRule(3, gaussPoints, gaussWeights);
        EXUmath::SetLobattoIntegrationRule(3, membranePoints, membraneWeights);
    }
    else if (parameters.useReducedOrderIntegration == 2)
    {
        // Mode 2 = same as Mode 1 (Lobatto SRI).
        // NOTE: cross-axis bending (points at (+-g,0) and (0,+-g)) was tested and found
        // incompatible with ANCF bicubic elements: the cross-derivative DOF shape function
        // S_cross = H1(xi)*H1(eta) evaluates to ZERO at all cross-axis points (H1(0)=0),
        // giving the cross-derivative DOF zero bending stiffness and creating a spurious
        // zero-energy mechanism.  Mode 2 therefore falls back to Mode 1.  MP, 2026-05-26
        EXUmath::SetGaussIntegrationRule(3, gaussPoints, gaussWeights);         // 2 pts at +-1/sqrt(3)
        EXUmath::SetLobattoIntegrationRule(3, membranePoints, membraneWeights); // 3 pts at {-1, 0, +1}
    }
    else
    {
        CHECKandTHROWstring("CObjectANCFThinPlate: useReducedOrderIntegration must be 0 (full Gauss), 1 (Lobatto SRI), or 2 (same as 1)", ExudynValueError);
    }
}

//! the elastic energy of the membrane strains and the curvatures, with the kinematics, stiffness and integration rules
//! of the elastic forces (#2202): membrane energy at the membrane points, bending energy at the bending points
Real CObjectANCFThinPlate::ComputeElasticEnergy(ConfigurationType configuration) const
{
    ConstSizeVector<nODE2coordinates> qANCFref, qANCFtotal;
    ComputeReferenceObjectCoordinates(qANCFref);
    qANCFtotal = qANCFref;
    if (configuration != ConfigurationType::Reference)
    {
        for (Index i = 0; i < nNodes; i++)
        {
            LinkedDataVector qNodeU(qANCFtotal, i * nnc, nnc);
            qNodeU += ((CNodeODE2*)GetCNode(i))->GetCoordinateVector(configuration);
        }
    }
    ConstSizeVector<5> membranePoints, membraneWeights, bendingPoints, bendingWeights;
    GetIntegrationRules(membranePoints, membraneWeights, bendingPoints, bendingWeights);
    Real energy = 0.;
    for (Index pass = 0; pass < 2; pass++) //0: membrane, 1: bending
    {
        const ConstSizeVector<5>& points = (pass == 0) ? membranePoints : bendingPoints;
        const ConstSizeVector<5>& weights = (pass == 0) ? membraneWeights : bendingWeights;
        for (Index iGP = 0; iGP < points.NumberOfItems(); iGP++)
        {
            for (Index jGP = 0; jGP < points.NumberOfItems(); jGP++)
            {
                Real xi = points[iGP];
                Real eta = points[jGP];
                //the area factor of the elastic forces, J0.GetDeterminant()
                Vector12D sf_x, sf_y;
                ComputeShapeFunctions_xy(xi, eta, sf_x, sf_y);
                SlimVectorBase<Real, 3> r_xi_ref = MapCoordinates(sf_x, qANCFref);
                SlimVectorBase<Real, 3> r_eta_ref = MapCoordinates(sf_y, qANCFref);
                SlimVectorBase<Real, 3> n0 = r_xi_ref.CrossProduct(r_eta_ref);
                Matrix2D J0 = GetElementJacobian(r_xi_ref, r_eta_ref, n0 * (1. / n0.GetL2Norm()));

                SlimVectorBase<Real, 3> eps_mid, kappa, resultant;
                ComputeKinematics(xi, eta, qANCFref, qANCFtotal, eps_mid, kappa);
                Matrix3D Deps, Dkappa;
                StiffnessAtPoint(*this, xi, eta, Deps, Dkappa);
                if (pass == 0)
                {
                    EXUmath::MultMatrixVectorTemplate(Deps, eps_mid, resultant);
                    energy += weights[iGP] * weights[jGP] * J0.GetDeterminant() * 0.5 * (eps_mid * resultant);
                }
                else
                {
                    EXUmath::MultMatrixVectorTemplate(Dkappa, kappa, resultant);
                    energy += weights[iGP] * weights[jGP] * J0.GetDeterminant() * 0.5 * (kappa * resultant);
                }
            }
        }
    }
    return energy;
}

void CObjectANCFThinPlate::GetSlopes(const Vector3D& localPosition, Vector3D& slopeX, Vector3D& slopeY,
    ConfigurationType configuration) const
{
    ConstSizeVector<nODE2coordinates> qANCFref;
    ComputeReferenceObjectCoordinates(qANCFref);

    //Real jacDet = GetElementJacobian();

    ConstSizeVector<nODE2coordinates> qANCFtotal;
    ComputeObjectCoordinates(qANCFtotal, configuration);
    qANCFtotal += qANCFref;

    Vector12D sf_x, sf_y;
    ComputeShapeFunctions_xy(localPosition[0], localPosition[1], sf_x, sf_y);

    // CHANGED: compute proper element Jacobian from reference geometry at (xi, eta) (MP/JG, 2026)
    // OLD: assumed rectangular element using slopesScalingX/Y[0] (wrong for distorted/curved elements)
    //   Real dxi_dx  = 2.0 / parameters.slopesScalingX[0];
    //   Real deta_dy = 2.0 / parameters.slopesScalingY[0];
    //   slopeX = dxi_dx  * MapCoordinates(sf_x, qANCFtotal);
    //   slopeY = deta_dy * MapCoordinates(sf_y, qANCFtotal);
    //
    // NEW: inverse Jacobian A maps parametric derivatives (d/dxi, d/deta) to physical (d/dx, d/dy),
    //      consistent with ComputeODE2LHStemplate.  J0 is built from the REFERENCE geometry.
    SlimVectorBase<Real, 3> r_xi_ref  = MapCoordinates(sf_x, qANCFref);
    SlimVectorBase<Real, 3> r_eta_ref = MapCoordinates(sf_y, qANCFref);
    SlimVectorBase<Real, 3> n0        = r_xi_ref.CrossProduct(r_eta_ref);
    Real n0_norm = n0.GetL2Norm();
    CHECKandTHROW(n0_norm > 0., "CObjectANCFThinPlate::GetSlopes: degenerate reference element (zero normal)");
    Matrix2D J0 = GetElementJacobian(r_xi_ref, r_eta_ref, n0 * (Real(1.) / n0_norm));
    Matrix2D A  = J0.GetInverse();

    // Transform current parametric derivatives to physical slopes
    // r_x = r_xi*A(0,0) + r_eta*A(1,0),  r_y = r_xi*A(0,1) + r_eta*A(1,1)
    SlimVectorBase<Real, 3> r_xi_cur  = MapCoordinates(sf_x, qANCFtotal);
    SlimVectorBase<Real, 3> r_eta_cur = MapCoordinates(sf_y, qANCFtotal);
    slopeX = r_xi_cur * A(0, 0) + r_eta_cur * A(1, 0);
    slopeY = r_xi_cur * A(0, 1) + r_eta_cur * A(1, 1);
}

Vector3D CObjectANCFThinPlate::GetNormal(const Vector3D& localPosition, ConfigurationType configuration) const
{
    Vector3D slopeX, slopeY;
    GetSlopes(localPosition, slopeX, slopeY, configuration);
    Vector3D n = slopeX.CrossProduct(slopeY);
    Real len = n.GetL2Norm(); 
    CHECKandTHROW(len != 0., "CObjectANCFThinPlate::GetNormal: normal has length zero; check model setup and solver convergence");
    n.Normalize();
    return n;
}

Vector3D CObjectANCFThinPlate::GetPosition(const Vector3D& localPosition,
                                            ConfigurationType configuration) const
{
    // includes through-thickness Z-offset via plate normal (MP/JG, 2026)
    // p(xi, eta, zeta) = p_mid(xi, eta) + zeta * h(xi,eta)/2 * n(xi, eta)
    // where zeta = localPosition[2] in [-1,1], h = interpolated thickness, n = unit normal
    ConstSizeVector<nODE2coordinates> qANCFref;
    ComputeReferenceObjectCoordinates(qANCFref);

    Vector12D SV;
    ComputeShapeFunctions(localPosition[0], localPosition[1], SV);

    // Compute mid-plane position
    Vector3D pMid;
    ConstSizeVector<nODE2coordinates> qANCFtotal;
    if (configuration != ConfigurationType::Reference)
    {
        ComputeObjectCoordinates(qANCFtotal, configuration);
        qANCFtotal += qANCFref;
        pMid = MapCoordinates(SV, qANCFtotal);
    }
    else
    {
        pMid = MapCoordinates(SV, qANCFref);
    }

    // ADDED: through-thickness offset p = p_mid + zeta * h/2 * n (MP/JG, 2026)
    Real zeta = localPosition[2];
    if (zeta != 0.)
    {
        Real h = ComputeThicknessAtPoint(localPosition[0], localPosition[1]);
        Vector3D n = GetNormal(localPosition, configuration);
        pMid += (zeta * 0.5 * h) * n;
    }
    return pMid;
}

Vector3D CObjectANCFThinPlate::GetDisplacement(const Vector3D& localPosition,
                                                ConfigurationType configuration) const
{
    // CHANGED: resolve TODO - derived from GetPosition to correctly include Z-offset (MP/JG, 2026)
    // u(xi, eta, zeta) = GetPosition(current) - GetPosition(reference)
    //   = u_mid + zeta*h/2 * (n_current - n_reference)
    // This reuses GetPosition which already handles the through-thickness normal offset.
    return GetPosition(localPosition, configuration) - GetPosition(localPosition, ConfigurationType::Reference);
}

Vector3D CObjectANCFThinPlate::GetVelocity(const Vector3D& localPosition,
                                            ConfigurationType configuration) const
{
    // CHANGED: resolve TODO - include through-thickness Z-offset for velocity (MP/JG, 2026)
    // v(xi, eta, zeta) = v_mid + zeta * h/2 * dn/dt
    // where dn/dt = (v_rx x r_y + r_x x v_ry) / |r_x x r_y|
    //              - (r_x x r_y) * dot(r_x x r_y, v_rx x r_y + r_x x v_ry) / |r_x x r_y|^3
    ConstSizeVector<nODE2coordinates> qANCF_t;
    ComputeObjectVelocities(qANCF_t, configuration);

    Vector12D SV;
    ComputeShapeFunctions(localPosition[0], localPosition[1], SV);
    Vector3D vMid = MapCoordinates(SV, qANCF_t);

    // ADDED: through-thickness velocity contribution dn/dt (MP/JG, 2026)
    Real zeta = localPosition[2];
    if (zeta != 0.)
    {
        Real xi = localPosition[0], eta = localPosition[1];
        Real h = ComputeThicknessAtPoint(xi, eta);

        // CHANGED: use proper reference-config Jacobian (MP/JG, 2026)
        // OLD: simplified rectangular scaling dxi_dx = 2/slopesScalingX[0]
        ConstSizeVector<nODE2coordinates> qANCFref, qANCFtotal;
        ComputeReferenceObjectCoordinates(qANCFref);
        ComputeObjectCoordinates(qANCFtotal, configuration);
        qANCFtotal += qANCFref;

        Vector12D sf_x, sf_y;
        ComputeShapeFunctions_xy(xi, eta, sf_x, sf_y);

        // Reference Jacobian A (same approach as ComputeODE2LHStemplate)
        SlimVectorBase<Real, 3> r_xi_ref  = MapCoordinates(sf_x, qANCFref);
        SlimVectorBase<Real, 3> r_eta_ref = MapCoordinates(sf_y, qANCFref);
        SlimVectorBase<Real, 3> n0_ref    = r_xi_ref.CrossProduct(r_eta_ref);
        Real n0_ref_norm = n0_ref.GetL2Norm();
        CHECKandTHROW(n0_ref_norm > 0., "CObjectANCFThinPlate::GetVelocity: degenerate reference element");
        Matrix2D J0 = GetElementJacobian(r_xi_ref, r_eta_ref, n0_ref * (Real(1.) / n0_ref_norm));
        Matrix2D A  = J0.GetInverse();

        // Physical slopes and slope-velocities via inverse Jacobian
        SlimVectorBase<Real, 3> r_xi_cur  = MapCoordinates(sf_x, qANCFtotal);
        SlimVectorBase<Real, 3> r_eta_cur = MapCoordinates(sf_y, qANCFtotal);
        SlimVectorBase<Real, 3> v_rxi     = MapCoordinates(sf_x, qANCF_t);
        SlimVectorBase<Real, 3> v_reta    = MapCoordinates(sf_y, qANCF_t);
        Vector3D r_x  = r_xi_cur  * A(0, 0) + r_eta_cur  * A(1, 0);  // current slope in x
        Vector3D r_y  = r_xi_cur  * A(0, 1) + r_eta_cur  * A(1, 1);  // current slope in y
        Vector3D v_rx = v_rxi     * A(0, 0) + v_reta     * A(1, 0);  // time derivative of r_x
        Vector3D v_ry = v_rxi     * A(0, 1) + v_reta     * A(1, 1);  // time derivative of r_y

        // dn/dt from time derivative of unit normal n = (r_x x r_y) / |r_x x r_y|
        Vector3D n_unnorm = r_x.CrossProduct(r_y);
        Real     len      = n_unnorm.GetL2Norm();
        CHECKandTHROW(len > 0., "CObjectANCFThinPlate::GetVelocity: degenerate element (zero normal)");

        Vector3D dn_unnorm_dt = v_rx.CrossProduct(r_y) + r_x.CrossProduct(v_ry);
        Real     d_len_dt     = (n_unnorm * dn_unnorm_dt) / len;  // dot product / len
        Vector3D dn_dt        = (Real(1.) / len) * dn_unnorm_dt
                                - (d_len_dt / (len * len)) * n_unnorm;

        vMid += (zeta * 0.5 * h) * dn_dt;
    }
    return vMid;
}

Vector3D CObjectANCFThinPlate::GetAcceleration(const Vector3D& localPosition,
                                                ConfigurationType configuration) const
{
    // CHANGED: resolve TODO - include through-thickness Z-offset for acceleration (MP/JG, 2026)
    // a(xi, eta, zeta) = a_mid + zeta * h/2 * d²n/dt²
    // Simplified: d²n/dt² uses acceleration DOFs only; velocity cross-terms in d²n/dt² are neglected
    // (these are second-order in velocity; exact expression requires dn/dt from GetVelocity context)
    ConstSizeVector<nODE2coordinates> qANCF_tt;
    ComputeObjectAccelerations(qANCF_tt, configuration);

    Vector12D SV;
    ComputeShapeFunctions(localPosition[0], localPosition[1], SV);
    Vector3D aMid = MapCoordinates(SV, qANCF_tt);

    // ADDED: through-thickness acceleration contribution (velocity cross-terms neglected) (MP/JG, 2026)
    Real zeta = localPosition[2];
    if (zeta != 0.)
    {
        Real xi = localPosition[0], eta = localPosition[1];
        Real h = ComputeThicknessAtPoint(xi, eta);

        // CHANGED: use proper reference-config Jacobian (MP/JG, 2026)
        // OLD: simplified rectangular scaling dxi_dx = 2/slopesScalingX[0]
        ConstSizeVector<nODE2coordinates> qANCFref, qANCFtotal;
        ComputeReferenceObjectCoordinates(qANCFref);
        ComputeObjectCoordinates(qANCFtotal, configuration);
        qANCFtotal += qANCFref;

        Vector12D sf_x, sf_y;
        ComputeShapeFunctions_xy(xi, eta, sf_x, sf_y);

        // Reference Jacobian A (same approach as ComputeODE2LHStemplate)
        SlimVectorBase<Real, 3> r_xi_ref  = MapCoordinates(sf_x, qANCFref);
        SlimVectorBase<Real, 3> r_eta_ref = MapCoordinates(sf_y, qANCFref);
        SlimVectorBase<Real, 3> n0_ref    = r_xi_ref.CrossProduct(r_eta_ref);
        Real n0_ref_norm = n0_ref.GetL2Norm();
        CHECKandTHROW(n0_ref_norm > 0., "CObjectANCFThinPlate::GetAcceleration: degenerate reference element");
        Matrix2D J0 = GetElementJacobian(r_xi_ref, r_eta_ref, n0_ref * (Real(1.) / n0_ref_norm));
        Matrix2D A  = J0.GetInverse();

        // Physical slopes and slope-accelerations via inverse Jacobian
        SlimVectorBase<Real, 3> r_xi_cur  = MapCoordinates(sf_x, qANCFtotal);
        SlimVectorBase<Real, 3> r_eta_cur = MapCoordinates(sf_y, qANCFtotal);
        SlimVectorBase<Real, 3> a_rxi     = MapCoordinates(sf_x, qANCF_tt);
        SlimVectorBase<Real, 3> a_reta    = MapCoordinates(sf_y, qANCF_tt);
        Vector3D r_x  = r_xi_cur  * A(0, 0) + r_eta_cur  * A(1, 0);  // current slope in x
        Vector3D r_y  = r_xi_cur  * A(0, 1) + r_eta_cur  * A(1, 1);  // current slope in y
        Vector3D a_rx = a_rxi     * A(0, 0) + a_reta     * A(1, 0);  // acceleration of r_x
        Vector3D a_ry = a_rxi     * A(0, 1) + a_reta     * A(1, 1);  // acceleration of r_y

        // Simplified d²n/dt² from acceleration DOFs only (velocity cross-terms neglected)
        // Same structure as dn/dt in GetVelocity, substituting velocities with accelerations
        Vector3D n_unnorm        = r_x.CrossProduct(r_y);
        Real     len             = n_unnorm.GetL2Norm();
        CHECKandTHROW(len > 0., "CObjectANCFThinPlate::GetAcceleration: degenerate element (zero normal)");

        Vector3D d2n_unnorm_dt2  = a_rx.CrossProduct(r_y) + r_x.CrossProduct(a_ry);
        Real     d_len_dt2       = (n_unnorm * d2n_unnorm_dt2) / len;
        Vector3D d2n_dt2         = (Real(1.) / len) * d2n_unnorm_dt2
                                   - (d_len_dt2 / (len * len)) * n_unnorm;

        aMid += (zeta * 0.5 * h) * d2n_dt2;
    }
    return aMid;
}

