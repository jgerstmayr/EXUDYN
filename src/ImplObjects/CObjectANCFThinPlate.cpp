//+++++++++++++++++++++++++++++++++++++++++
// Nodes odering (counter clockwise)
//
//          eta
//          ^
//      n3  |  n2
//   +1 +-------+
//      |   |   |
//      |   +---|--> xi
//      |       |
//   -1 +-------+ 
//      n0     n1
//      -1      +1
//


inline void CObjectANCFThinPlate::ScaleShapeFunctions(Vector12D& sf) const
{
    const Vector4D& scaleX = parameters.slopesScalingX;
    const Vector4D& scaleY = parameters.slopesScalingY;

    sf[1] *= scaleX[0];
    sf[2] *= scaleY[0];
    sf[4] *= scaleX[1];
    sf[5] *= scaleY[1];
    sf[7] *= scaleX[2];
    sf[8] *= scaleY[2];
    sf[10] *= scaleX[3];
    sf[11] *= scaleY[3];
}

//!original ANCF shape functions;
//!due to special design position/slopes, a cubic x cubic interpolation space is less optimal!
//!=>special shape functions design
inline void CObjectANCFThinPlate::ComputeShapeFunctions(Real xi, Real eta, Vector12D& sf, bool scaled) const
{
    
    //1D linear (Lagrange) basis
    // These handle the linear variation in the transverse direction
    Real Lx1 = 0.5 * (1.0 - xi);   Real Lx2 = 0.5 * (1.0 + xi);
    Real Ly1 = 0.5 * (1.0 - eta);  Real Ly2 = 0.5 * (1.0 + eta);

    Real xi2 = xi * xi; Real xi3 = xi2 * xi;
    Real eta2 = eta * eta; Real eta3 = eta2 * eta;

    //position cubic Hermite shape functions
    Real hx_pos_1 = 0.25 * (2.0 - 3.0 * xi + xi3);
    Real hx_pos_2 = 0.25 * (2.0 + 3.0 * xi - xi3);
    Real hy_pos_1 = 0.25 * (2.0 - 3.0 * eta + eta3);
    Real hy_pos_2 = 0.25 * (2.0 + 3.0 * eta - eta3);

    // Slope Cubics (Derivative 1..0..0)
    // Note: The factor 0.125 here combined with the linear terms (0.5) 
    // produces the 1/16 (0.0625) factor seen in your Old code.
    Real hx_slope_1 = 0.125 * (1.0 - xi - xi2 + xi3);
    Real hx_slope_2 = 0.125 * (-1.0 - xi + xi2 + xi3);
    Real hy_slope_1 = 0.125 * (1.0 - eta - eta2 + eta3);
    Real hy_slope_2 = 0.125 * (-1.0 - eta + eta2 + eta3);

    // --- 3. ACM Shape Function Assembly ---
    // rule for position: H(xi)L(eta) + H(eta)L(xi) - L(xi)L(eta)
    // rule for slopes: H_slope(primary) * L(transverse)

    //node 0 (Bottom-Left: -1, -1)
    sf[0] = hx_pos_1 * Ly1 + hy_pos_1 * Lx1 - Lx1 * Ly1;
    sf[1] = hx_slope_1 * Ly1;
    sf[2] = hy_slope_1 * Lx1;

    //node 1 (Bottom-Right: +1, -1)
    sf[3] = hx_pos_2 * Ly1 + hy_pos_1 * Lx2 - Lx2 * Ly1;
    sf[4] = hx_slope_2 * Ly1;
    sf[5] = hy_slope_1 * Lx2;

    //node 2 (Top-Right: +1, +1)
    sf[6] = hx_pos_2 * Ly2 + hy_pos_2 * Lx2 - Lx2 * Ly2;
    sf[7] = hx_slope_2 * Ly2;
    sf[8] = hy_slope_2 * Lx2;

    //node 3 (Top-Left: -1, +1)
    sf[9] = hx_pos_1 * Ly2 + hy_pos_2 * Lx1 - Lx1 * Ly2;
    sf[10] = hx_slope_1 * Ly2;
    sf[11] = hy_slope_2 * Lx1;

    if (scaled)
    {
        ScaleShapeFunctions(sf);
    }
}

//! Get first derivatives of shape functions - matches Python: shape_functions_xy_jax(xi, eta, size1, size2)
void CObjectANCFThinPlate::ComputeShapeFunctions_xy(Real xi, Real eta, Vector12D& sf_x, Vector12D& sf_y, bool scaled) const
{
    // --- 1. Precompute 1D Basis Values (Needed for Product Rule) ---
    Real xi2 = xi * xi; Real xi3 = xi2 * xi;
    Real eta2 = eta * eta; Real eta3 = eta2 * eta;

    // Linear Values
    Real Lx1 = 0.5 * (1.0 - xi);   Real Lx2 = 0.5 * (1.0 + xi);
    Real Ly1 = 0.5 * (1.0 - eta);  Real Ly2 = 0.5 * (1.0 + eta);

    // Cubic Values (Positions)
    Real hx_pos_1 = 0.25 * (2.0 - 3.0 * xi + xi3);
    Real hx_pos_2 = 0.25 * (2.0 + 3.0 * xi - xi3);
    Real hy_pos_1 = 0.25 * (2.0 - 3.0 * eta + eta3);
    Real hy_pos_2 = 0.25 * (2.0 + 3.0 * eta - eta3);

    // Cubic Values (Slopes)
    Real hx_slope_1 = 0.125 * (1.0 - xi - xi2 + xi3);
    Real hx_slope_2 = 0.125 * (-1.0 - xi + xi2 + xi3);
    Real hy_slope_1 = 0.125 * (1.0 - eta - eta2 + eta3);
    Real hy_slope_2 = 0.125 * (-1.0 - eta + eta2 + eta3);

    // --- 2. Precompute 1D First Derivatives (d/dxi or d/deta) ---

    // Linear Derivatives (constant)
    Real dLx1 = -0.5; Real dLx2 = 0.5;
    Real dLy1 = -0.5; Real dLy2 = 0.5;

    // Cubic Derivatives (Position)
    // d/dxi [0.25 * (2 - 3xi + xi^3)] = 0.25 * (-3 + 3xi^2)
    Real d_hx_pos_1 = 0.75 * (xi2 - 1.0);
    Real d_hx_pos_2 = 0.75 * (1.0 - xi2);
    Real d_hy_pos_1 = 0.75 * (eta2 - 1.0);
    Real d_hy_pos_2 = 0.75 * (1.0 - eta2);

    // Cubic Derivatives (Slope)
    // d/dxi [0.125 * (1 - xi - xi^2 + xi^3)] = 0.125 * (-1 - 2xi + 3xi^2)
    Real d_hx_slope_1 = 0.125 * (-1.0 - 2.0 * xi + 3.0 * xi2);
    Real d_hx_slope_2 = 0.125 * (-1.0 + 2.0 * xi + 3.0 * xi2);
    Real d_hy_slope_1 = 0.125 * (-1.0 - 2.0 * eta + 3.0 * eta2);
    Real d_hy_slope_2 = 0.125 * (-1.0 + 2.0 * eta + 3.0 * eta2);

    // --- 3. Compute Partial Derivatives ---
    // Rule for Pos d/dxi:  H'(xi)L(eta) + H(eta)L'(xi) - L'(xi)L(eta)
    // Rule for Pos d/deta: H(xi)L'(eta) + H'(eta)L(xi) - L(xi)L'(eta)

    // Node 0
    sf_x[0] = d_hx_pos_1 * Ly1 + hy_pos_1 * dLx1 - dLx1 * Ly1;
    sf_y[0] = hx_pos_1 * dLy1 + d_hy_pos_1 * Lx1 - Lx1 * dLy1;

    sf_x[1] = d_hx_slope_1 * Ly1; // rx0: Cubic(xi) * Linear(eta)
    sf_y[1] = hx_slope_1 * dLy1;

    sf_x[2] = hy_slope_1 * dLx1; // ry0: Linear(xi) * Cubic(eta)
    sf_y[2] = d_hy_slope_1 * Lx1;

    // Node 1
    sf_x[3] = d_hx_pos_2 * Ly1 + hy_pos_1 * dLx2 - dLx2 * Ly1;
    sf_y[3] = hx_pos_2 * dLy1 + d_hy_pos_1 * Lx2 - Lx2 * dLy1;

    sf_x[4] = d_hx_slope_2 * Ly1;
    sf_y[4] = hx_slope_2 * dLy1;

    sf_x[5] = hy_slope_1 * dLx2;
    sf_y[5] = d_hy_slope_1 * Lx2;

    // Node 2
    sf_x[6] = d_hx_pos_2 * Ly2 + hy_pos_2 * dLx2 - dLx2 * Ly2;
    sf_y[6] = hx_pos_2 * dLy2 + d_hy_pos_2 * Lx2 - Lx2 * dLy2;

    sf_x[7] = d_hx_slope_2 * Ly2;
    sf_y[7] = hx_slope_2 * dLy2;

    sf_x[8] = hy_slope_2 * dLx2;
    sf_y[8] = d_hy_slope_2 * Lx2;

    // Node 3
    sf_x[9] = d_hx_pos_1 * Ly2 + hy_pos_2 * dLx1 - dLx1 * Ly2;
    sf_y[9] = hx_pos_1 * dLy2 + d_hy_pos_2 * Lx1 - Lx1 * dLy2;

    sf_x[10] = d_hx_slope_1 * Ly2;
    sf_y[10] = hx_slope_1 * dLy2;

    sf_x[11] = hy_slope_2 * dLx1;
    sf_y[11] = d_hy_slope_2 * Lx1;

    if (scaled)
    {
        ScaleShapeFunctions(sf_x);
        ScaleShapeFunctions(sf_y);
    }
}

//! Get second derivatives of shape functions - matches Python: shape_functions_xxyy_jax(xi, eta, size1, size2)
void CObjectANCFThinPlate::ComputeShapeFunctions_xxyy(Real xi, Real eta, Vector12D& sf_xx, Vector12D& sf_yy, Vector12D& sf_xy, bool scaled) const
{
    Real Lx1 = 0.5 * (1.0 - xi);   Real Lx2 = 0.5 * (1.0 + xi);
    Real Ly1 = 0.5 * (1.0 - eta);  Real Ly2 = 0.5 * (1.0 + eta);
    Real dLx1 = -0.5; Real dLx2 = 0.5;
    Real dLy1 = -0.5; Real dLy2 = 0.5;

    Real xi2 = xi * xi; Real eta2 = eta * eta;
    Real d_hx_pos_1 = 0.75 * (xi2 - 1.0);  Real d_hx_pos_2 = 0.75 * (1.0 - xi2);
    Real d_hy_pos_1 = 0.75 * (eta2 - 1.0); Real d_hy_pos_2 = 0.75 * (1.0 - eta2);

    Real d_hx_slope_1 = 0.125 * (-1.0 - 2.0 * xi + 3.0 * xi2);
    Real d_hx_slope_2 = 0.125 * (-1.0 + 2.0 * xi + 3.0 * xi2);
    Real d_hy_slope_1 = 0.125 * (-1.0 - 2.0 * eta + 3.0 * eta2);
    Real d_hy_slope_2 = 0.125 * (-1.0 + 2.0 * eta + 3.0 * eta2);

    // Cubic Position 2nd Derivatives
    // d2/dxi2 [0.25 * (-3 + 3xi^2)] = 0.25 * 6xi = 1.5xi
    Real dd_hx_pos_1 = 1.5 * xi;
    Real dd_hx_pos_2 = -1.5 * xi;
    Real dd_hy_pos_1 = 1.5 * eta;
    Real dd_hy_pos_2 = -1.5 * eta;

    // Cubic Slope 2nd Derivatives
    // d2/dxi2 [0.125 * (-1 - 2xi + 3xi^2)] = 0.125 * (-2 + 6xi)
    Real dd_hx_slope_1 = 0.25 * (-1.0 + 3.0 * xi);
    Real dd_hx_slope_2 = 0.25 * (1.0 + 3.0 * xi);
    Real dd_hy_slope_1 = 0.25 * (-1.0 + 3.0 * eta);
    Real dd_hy_slope_2 = 0.25 * (1.0 + 3.0 * eta);

    // Note: Since L''(xi) = 0, terms like H(eta)L''(xi) vanish.

    // Node 0
    sf_xx[0] = dd_hx_pos_1 * Ly1; // Only H''(xi)L(eta) remains
    sf_yy[0] = dd_hy_pos_1 * Lx1; // Only H''(eta)L(xi) remains
    sf_xy[0] = d_hx_pos_1 * dLy1 + d_hy_pos_1 * dLx1 - dLx1 * dLy1;

    sf_xx[1] = dd_hx_slope_1 * Ly1;
    sf_yy[1] = 0.0; // Linear in eta -> 2nd deriv is 0
    sf_xy[1] = d_hx_slope_1 * dLy1;

    sf_xx[2] = 0.0; // Linear in xi -> 2nd deriv is 0
    sf_yy[2] = dd_hy_slope_1 * Lx1;
    sf_xy[2] = d_hy_slope_1 * dLx1;

    // Node 1
    sf_xx[3] = dd_hx_pos_2 * Ly1;
    sf_yy[3] = dd_hy_pos_1 * Lx2;
    sf_xy[3] = d_hx_pos_2 * dLy1 + d_hy_pos_1 * dLx2 - dLx2 * dLy1;

    sf_xx[4] = dd_hx_slope_2 * Ly1;
    sf_yy[4] = 0.0;
    sf_xy[4] = d_hx_slope_2 * dLy1;

    sf_xx[5] = 0.0;
    sf_yy[5] = dd_hy_slope_1 * Lx2;
    sf_xy[5] = d_hy_slope_1 * dLx2;

    // Node 2
    sf_xx[6] = dd_hx_pos_2 * Ly2;
    sf_yy[6] = dd_hy_pos_2 * Lx2;
    sf_xy[6] = d_hx_pos_2 * dLy2 + d_hy_pos_2 * dLx2 - dLx2 * dLy2;

    sf_xx[7] = dd_hx_slope_2 * Ly2;
    sf_yy[7] = 0.0;
    sf_xy[7] = d_hx_slope_2 * dLy2;

    sf_xx[8] = 0.0;
    sf_yy[8] = dd_hy_slope_2 * Lx2;
    sf_xy[8] = d_hy_slope_2 * dLx2;

    //node 3
    sf_xx[9] = dd_hx_pos_1 * Ly2;
    sf_yy[9] = dd_hy_pos_2 * Lx1;
    sf_xy[9] = d_hx_pos_1 * dLy2 + d_hy_pos_2 * dLx1 - dLx1 * dLy2;

    sf_xx[10] = dd_hx_slope_1 * Ly2;
    sf_yy[10] = 0.0;
    sf_xy[10] = d_hx_slope_1 * dLy2;

    sf_xx[11] = 0.0;
    sf_yy[11] = dd_hy_slope_2 * Lx1;
    sf_xy[11] = d_hy_slope_2 * dLx1;

    if (scaled)
    {
        ScaleShapeFunctions(sf_xx);
        ScaleShapeFunctions(sf_yy);
        ScaleShapeFunctions(sf_xy);
    }

}

