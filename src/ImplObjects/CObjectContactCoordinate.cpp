//! compute gap for given configuration (current, start of step, ...); gap <= 0 means contact, gap > 0 is no contact
Real CObjectContactCoordinate::ComputeGap(const MarkerDataStructure& markerData) const
{
	return (markerData.GetMarkerData(1).vectorValue[0] - markerData.GetMarkerData(0).vectorValue[0] - parameters.offset);
}

//! the contact force on marker 1 for gap and its time derivative (#2745); the contact state is the data variable
Real CObjectContactCoordinate::ComputeContactForce(Real gap, Real gap_t) const
{
	//decision upon contact is not gap, but the dataVariable ==> "active set strategy", needed for Newton solver to converge
	Real hasContact = 0; //1 for contact, 0 else
	if (GetCNode(0)->GetCurrentCoordinate(0) <= 0) { hasContact = 1; }; //this is the contact state: 1=contact/use contact force, 0=no contact

	//the contact law of ObjectContactSphereSphere (#2750): penetration delta = -gap, exponent, impact models;
	//as gap is negative in case of contact, the force needs to act in opposite direction
	Real fContact = 0.;
	if (hasContact)
	{
		const Real& k = parameters.contactStiffness;
		Real deltaExp = -gap;
		if (parameters.contactStiffnessExponent != 1.) { deltaExp = EXUstd::SignReal(deltaExp) * pow(fabs(deltaExp), parameters.contactStiffnessExponent); }
		Real fNormal = k * deltaExp - parameters.contactDamping * gap_t;
		if (parameters.impactModel != 0)
		{
			Real impactVelocity = EXUstd::Maximum(parameters.minimumImpactVelocity, GetCNode(0)->GetCurrentCoordinate(dataIndexImpactVelocity));
			if (impactVelocity > 0)
			{
				const Real& e = parameters.restitutionCoefficient;
				Real lambda = k / impactVelocity;
				if (parameters.impactModel == 1) { lambda *= 3. / 2. * (e - 1.); } //Hunt-Crossley
				else if (e > 1. / 3.) { lambda *= 3. / 2. * (e - 1.) * (11. - e) / (1. + 9. * e); } //Gonthier et al. / Carvalho-Martins
				else { lambda *= (e * e - 1.) / e; }
				fNormal += lambda * deltaExp * gap_t;
			}
		}
		fContact = -fNormal;
	}
	return fContact;
}

//! the force of the connector interface on coordinate markers (#2745), as ComputeODE2LHS: on marker 1, the reaction on marker 0
void CObjectContactCoordinate::ComputeConnectorForceCoordinate(const MarkerCoordinate<Real>* markers, Real t, Index itemIndex, Real& force) const
{
	force = 0.;
	if (!parameters.activeConnector) { return; } //an inactive connector adds no force (#2735)
	force = ComputeContactForce(markers[1].value - markers[0].value - parameters.offset, markers[1].value_t - markers[0].value_t);
}

