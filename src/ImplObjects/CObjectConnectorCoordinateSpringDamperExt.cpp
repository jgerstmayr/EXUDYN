//! the force of the connector from its relative position and velocity (#2745)
void CObjectConnectorCoordinateSpringDamperExt::ComputeSpringForceRelative(Real relPos, Real relVel, Real t, Index itemIndex, Real& force) const
{
	force = 0; //default; necessary, e.g. if computed in GetOutputVariable...
	if (parameters.activeConnector)
	{
		if (!parameters.springForceUserFunction)
		{   //compute resulting force vector:
			
            //spring-damper force:
			force = parameters.stiffness * (relPos - parameters.offset) + parameters.damping * (relVel - parameters.velocityOffset); //velocityOffset as documented (#2867)

            //friction:
            if (parameters.frictionProportionalZone != 0)
            {
                force += ExuPhysics::StribeckFunction(relVel, parameters.dynamicFrictionForce, 
                    parameters.staticFrictionOffsetForce, parameters.viscousFrictionFactor, 
                    parameters.exponentialDecayStatic, parameters.frictionProportionalZone);  
            }
            else
            {
                if (parameters.dynamicFrictionForce != 0 || parameters.staticFrictionOffsetForce != 0)
                {
                    CHECKandTHROW(parameters.nodeNumber != EXUstd::InvalidIndex, "CObjectConnectorCoordinateSpringDamperExt: needs valid data node for frictionProportionalZone != 0", ExudynModelError);
                    Real& currentStateFriction = ((CNodeData*)GetCNode(0))->GetCoordinateVector(ConfigurationType::Current)[0];
                    Real& currentStateLastStick = ((CNodeData*)GetCNode(0))->GetCoordinateVector(ConfigurationType::Current)[1];

                    Real newStateFriction;  //not used here
                    Real newStickPos;       //not used here
                    Real forceError;        //not used here
                    force += ComputeFrictionForce(relPos, relVel, currentStateLastStick, currentStateFriction,
                        currentStateLastStick, currentStateFriction, parameters, false,
                        newStateFriction, newStickPos, forceError); //these values are updated, only frictionForce used
                }
            }

            //limit stops:
            if (parameters.useLimitStops)
            {
                CHECKandTHROW(parameters.nodeNumber != EXUstd::InvalidIndex, "CObjectConnectorCoordinateSpringDamperExt: needs valid data node for useLimitStops=True", ExudynModelError);
                Real newContactState = 0; //unused
                Real discontinuousError = 0; //unused
                Real currentStateLS = ((CNodeData*)GetCNode(0))->GetCoordinateVector(ConfigurationType::Current)[2];
                force += ComputeLimitStops(relPos, relVel, currentStateLS, parameters, newContactState, discontinuousError);
            }
        }
		else
		{
			EvaluateUserFunctionForce(force, cSystemData->GetMainSystemBacklink(), t, 
                itemIndex, relPos, relVel);
		}
	}
}



//! Computational function: compute left-hand-side (LHS) of second order ordinary differential equations (ODE) to "ode2Lhs"
//  MODEL: f
//! the forces of the connector interface on coordinate markers (#2745), as ComputeODE2LHS: factor1 times the force on
//! marker 1, -factor0 times it on marker 0
void CObjectConnectorCoordinateSpringDamperExt::ComputeConnectorForcesCoordinate(const MarkerCoordinate<Real>* markers, Real t, Index itemIndex,
	Real* forces) const
{
	forces[0] = forces[1] = 0.;
	if (!parameters.activeConnector) { return; }
	Real relPos = parameters.factor1 * markers[1].value - parameters.factor0 * markers[0].value;
	Real relVel = parameters.factor1 * markers[1].value_t - parameters.factor0 * markers[0].value_t;
	Real force;
	ComputeSpringForceRelative(relPos, relVel, t, itemIndex, force);
	forces[1] = parameters.factor1 * force;
	forces[0] = -parameters.factor0 * force;
}

