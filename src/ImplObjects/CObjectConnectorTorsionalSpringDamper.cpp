//! the physics of the connector, for Real and AutoDiff (#2745); the user function is Real only
template<class TReal>
void CObjectConnectorTorsionalSpringDamper::ComputeSpringTorque(const MarkerRigid<TReal>* markers, Real t, Index itemIndex,
	ConstSizeMatrixBase<TReal, 9>& A0all, TReal& angle, TReal& omega, TReal& torque) const
{
	//spring is measured relative to marker0:

	const ConstSizeMatrixBase<TReal, 9>& A0 = markers[0].frame.GetRotation();
	const ConstSizeMatrixBase<TReal, 9>& A1 = markers[1].frame.GetRotation();
	A0all = ApplyRotationMarker(A0, parameters.rotationMarker0);
	ConstSizeMatrixBase<TReal, 9> A1all = ApplyRotationMarker(A1, parameters.rotationMarker1);

	//relative rotation
	ConstSizeMatrixBase<TReal, 9> relRot = A0all.GetTransposed() * A1all;
	SlimVectorBase<TReal, 3> vLocRot = RigidBodyMath::RotationMatrix2RotXYZTemplate(relRot);
	SlimVectorBase<TReal, 3> vLocAngVel = A0all.GetTransposed()*(A1*markers[1].angularVelocityLocal - A0 * markers[0].angularVelocityLocal);
	angle = vLocRot[2]; //z-component
	if (angle > EXUstd::pi) {angle -= 2. * EXUstd::pi; }
	omega = vLocAngVel[2]; //z-component

	if (parameters.nodeNumber != EXUstd::InvalidIndex)
	{ //Generic node for continuous rotation
		Real previousAngle = GetCNode(0)->GetCurrentCoordinate(0); //this is the continuous angle (of previous step during computation and of end of step for OutputVariable)
		if (fabs((Real)angle - previousAngle) > EXUstd::pi)
		{
			Real delta = previousAngle - (Real)angle;
			Real off2pi = round(delta / (2.*EXUstd::pi));
			angle += off2pi * 2.*EXUstd::pi;
		}
		//pout << "prev angle=" << previousAngle << ", angle=" << angle << "\n";
	}

	//+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
	//compute resulting torque:
	if (!parameters.springTorqueUserFunction)
	{
		torque = parameters.stiffness * (angle - parameters.offset) +
			parameters.damping * (omega - parameters.velocityOffset) + parameters.torque;
	}
	else
	{
		if constexpr (std::is_same<TReal, Real>::value)
		{
			EvaluateUserFunctionForce(torque, cSystemData->GetMainSystemBacklink(), t, itemIndex, angle, omega);
		}
		else
		{
			CHECKandTHROWstring("ObjectConnectorTorsionalSpringDamper: the user function has no Jacobian by automatic differentiation");
		}
	}
}

//! the torques of the connector interface on rigid markers (#2745): about the z-axis of the frame of marker 0, no forces
template<class TReal>
void CObjectConnectorTorsionalSpringDamper::ComputeConnectorForceRigidTemplate(const MarkerRigid<TReal>* markers, Real t, Index itemIndex,
	SlimVectorBase<TReal, 3>* forces, SlimVectorBase<TReal, 3>* torques) const
{
	for (Index k = 0; k < 2; k++) { forces[k].SetAll(0.); torques[k].SetAll(0.); }
	if (!parameters.activeConnector) { return; }

	TReal angle, omega, torque;
	ConstSizeMatrixBase<TReal, 9> A0all;
	ComputeSpringTorque(markers, t, itemIndex, A0all, angle, omega, torque);
	SlimVectorBase<TReal, 3> fRotLoc;
	fRotLoc.SetAll(0.);
	fRotLoc[2] = torque;
	torques[1] = A0all * fRotLoc;
	torques[0] = -torques[1];
}

