//! the generalized forces of the connector, one block per marker in the order of markerNumbers, of the size of the
//! coordinates the marker acts on - as the system composes the coordinates of a connector from its markers
void CObjectConnectorUser::ComputeODE2LHS(Vector& ode2Lhs, const MarkerDataStructure& markerData) const
{
	ArrayIndex blockSizes; //the coordinates of each marker, as CSystem composes the LTG of the connector
	blockSizes.SetNumberOfItems(parameters.markerNumbers.NumberOfItems());
	Index n = 0;
	ArrayIndex ltg;
	for (Index i = 0; i < parameters.markerNumbers.NumberOfItems(); i++)
	{
		GetCSystemData()->ComputeMarkerODE2LTGarray(parameters.markerNumbers[i], ltg, true);
		blockSizes[i] = ltg.NumberOfItems();
		n += blockSizes[i];
	}
	ode2Lhs.SetNumberOfItems(n);
	ode2Lhs.SetAll(0.);
	if (!parameters.activeConnector) { return; }
	if (parameters.forceUserFunction) { EvaluateUserFunctionForce(ode2Lhs, markerData, blockSizes); } //the forces of the marker states (#3119)
	else if (parameters.markerAccessUserFunction) { EvaluateUserFunctionMarkerAccess(ode2Lhs, markerData, blockSizes); }
}

//! the postNewtonStepUserFunction: the new data coordinates are stored, its error and its recommended step size go to
//! the solver; a switch updates the Jacobian, as the built-in contacts do (#3102)
Real CObjectConnectorUser::PostNewtonStep(const MarkerDataStructure& markerDataCurrent, PostNewtonFlags::Type& flags, Real& recommendedStepSize)
{
	flags = PostNewtonFlags::_None;
	if (!parameters.postNewtonStepUserFunction || !parameters.activeConnector || parameters.nodeNumber == EXUstd::InvalidIndex) { return 0.; }
	Vector newData;
	Real error = EvaluateUserFunctionPostNewtonStep(markerDataCurrent, newData, recommendedStepSize);
	LinkedDataVector data = ((CNodeData*)GetCNode(0))->GetCoordinateVector(ConfigurationType::Current);
	data.CopyFrom(newData);
	if (error != 0.) { flags = PostNewtonFlags::UpdateJacobian; }
	return error;
}

//! nothing but the number, at the first marker
void VisualizationObjectConnectorUser::UpdateGraphics(const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemNumber)
{
	if (!visualizationSettings.connectors.showNumbers) { return; }
	const CObjectConnectorUser* cItem = (const CObjectConnectorUser*)vSystem->systemData->GetCObjects()[itemNumber];
	const ArrayIndex& markerNumbers = cItem->GetParameters().markerNumbers;
	if (markerNumbers.NumberOfItems() == 0) { return; }
	const CMarker* marker = vSystem->systemData->GetCMarkers()[markerNumbers[0]];
	if (!EXUstd::IsOfType(marker->GetType(), Marker::Position)) { return; }
	Vector3D position;
	marker->GetPosition(*vSystem->systemData, position, ConfigurationType::Visualization);
	Index itemID = Index2ItemID(itemNumber, ItemType::Object, vSystem->GetSystemID());
	EXUvis::DrawItemNumber(position, vSystem, itemID, "", visualizationSettings.connectors.defaultColor);
}
