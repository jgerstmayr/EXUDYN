//! function provides the force, relative displacement and relative velocity of the connector; templated for the Jacobian
//! by automatic differentiation (#2745)
template<class TReal>
void CObjectConnectorCartesianSpringDamper::ComputeSpringForce(const SlimVectorBase<TReal, 3>& position0, const SlimVectorBase<TReal, 3>& position1,
	const SlimVectorBase<TReal, 3>& velocity0, const SlimVectorBase<TReal, 3>& velocity1, Real t, Index itemIndex,
	SlimVectorBase<TReal, 3>& vPos, SlimVectorBase<TReal, 3>& vVel, SlimVectorBase<TReal, 3>& fVec) const
{
	//relative position, spring length and inverse spring length
	vPos = (position1 - position0);
	for (Index i = 0; i < 3; i++) { vPos[i] -= parameters.offset[i]; } //the offset is Real, also with automatic differentiation

	//unit direction and relative velocity of spring-damper
	vVel = (velocity1 - velocity0);

	fVec.SetAll(0.);
	if (parameters.activeConnector)
	{
		//compute resulting force vector:
		if (!parameters.springForceUserFunction)
		{
			for (Index i = 0; i < 3; i++)
			{
				fVec[i] = parameters.stiffness[i] * vPos[i] + parameters.damping[i] * vVel[i];
			}
		}
		else if constexpr (std::is_same<TReal, Real>::value)
		{
			EvaluateUserFunctionForce(fVec, cSystemData->GetMainSystemBacklink(), t, itemIndex, vPos, vVel);
		}
		else
		{
			CHECKandTHROWstring("ObjectConnectorCartesianSpringDamper: no automatic differentiation of a springForceUserFunction");
		}
	}

}

