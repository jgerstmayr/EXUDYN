//! the equations of the joint at position level (#2745), as ComputeAlgebraicEquations: those of the relative frame of the
//! joint frames for the constrained axes (JointRelativeFrameEquations, #2884), the translations minus the offset of the
//! user function, lambda_i = 0 on the free axes; with derivatives their rows, zero for the free axes
static void JointGenericEquations(const CObjectJointGenericParameters& parameters, const Vector6D& userOffset,
	const MarkerRigid<Real>& marker0, const MarkerRigid<Real>& marker1, const LinkedDataVector& lambda,
	ConstSizeVector<maxConstraintEquations>& equations, RigidMarkersDerivatives* derivatives)
{
	Matrix3D A0all = ApplyRotationMarker(marker0.frame.GetRotation(), parameters.rotationMarker0);
	if (userOffset[3] != 0. || userOffset[4] != 0. || userOffset[5] != 0.)
	{
		A0all = A0all * RigidBodyMath::RotXYZ2RotationMatrix(Vector3D({ userOffset[3], userOffset[4], userOffset[5] }));
	}
	Matrix3D A1all = ApplyRotationMarker(marker1.frame.GetRotation(), parameters.rotationMarker1);
	const Index* constrainedAxes = parameters.constrainedAxes.GetDataPointer();
	Vector6D values;
	JointRelativeFrameEquations(constrainedAxes, parameters.alternativeConstraints, A0all, A1all,
		marker1.frame.GetTranslation() - marker0.frame.GetTranslation(), values, derivatives);
	equations.SetNumberOfItems(6);
	for (Index i = 0; i < 6; i++)
	{
		if (constrainedAxes[i] != 1) { equations[i] = lambda[i]; }
		else { equations[i] = (i < 3) ? values[i] - userOffset[i] : values[i]; }
	}
}

//! the equations on the connector interface (#2745); at velocity level (index 2) the time derivatives of those of the
//! relative frame, without the offset of the user function, lambda_i = 0 on the free axes
void CObjectJointGeneric::ComputeConstraintEquationsRigid(FlatArray<const MarkerRigid<Real>> markers, const LinkedDataVector& lambda, Real t, bool velocityLevel, ConstSizeVector<maxConstraintEquations>& equations) const
{
	if (!velocityLevel)
	{
		Vector6D userOffset(0.);
		if (parameters.offsetUserFunction) { EvaluateUserFunctionOffset(userOffset, cSystemData->GetMainSystemBacklink(), t); }
		JointGenericEquations(parameters, userOffset, markers[0], markers[1], lambda, equations, nullptr);
	}
	else
	{
		if (parameters.offsetUserFunction_t)
		{
			PyError("ObjectJointGeneric: offsetUserFunction_t not implemented for velocity level constraints!", PyErrorType::notImplementedError);
		}
		const Matrix3D& A0 = markers[0].frame.GetRotation();
		const Matrix3D& A1 = markers[1].frame.GetRotation();
		const Index* constrainedAxes = parameters.constrainedAxes.GetDataPointer();
		Vector6D values;
		JointRelativeFrameEquations_t(constrainedAxes, parameters.alternativeConstraints, ApplyRotationMarker(A0, parameters.rotationMarker0),
			ApplyRotationMarker(A1, parameters.rotationMarker1), markers[1].frame.GetTranslation() - markers[0].frame.GetTranslation(),
			markers[0].velocity, A0 * markers[0].angularVelocityLocal, markers[1].velocity, A1 * markers[1].angularVelocityLocal, values);
		equations.SetNumberOfItems(6);
		for (Index i = 0; i < 6; i++) { equations[i] = (constrainedAxes[i] == 1) ? values[i] : lambda[i]; }
	}
}

bool CObjectJointGeneric::ComputeConstraintEquationsRigidDerivatives(FlatArray<const MarkerRigid<Real>> markers, const LinkedDataVector& lambda,
	Real t, ConstSizeVector<maxConstraintEquations>& equations, RigidMarkersDerivatives& derivatives) const
{
	Vector6D userOffset(0.);
	if (parameters.offsetUserFunction) { EvaluateUserFunctionOffset(userOffset, cSystemData->GetMainSystemBacklink(), t); }
	JointGenericEquations(parameters, userOffset, markers[0], markers[1], lambda, equations, &derivatives);
	return true;
}

void CObjectJointGeneric::ComputeJacobianAE_AE(ResizableMatrix& jacobian_AE) const
{
	jacobian_AE.SetScalarMatrix(nConstraints, 0.);
	for (Index i = 0; i < nConstraints; i++)
	{
		if (parameters.constrainedAxes[i] == 0) { jacobian_AE(i, i) = 1.; }
	}
}

JacobianType::Type CObjectJointGeneric::GetAvailableJacobians() const
{
	if (parameters.activeConnector)
	{
		return (JacobianType::Type)(JacobianType::AE_ODE2 + JacobianType::AE_ODE2_function + JacobianType::AE_AE + JacobianType::AE_AE_function); //all AE_AE terms needed, because of free axes
	}
	else //deactivated constraint means that only the lagrange multiplier needs to be set to zero
	{
		return (JacobianType::Type)(JacobianType::AE_AE + JacobianType::AE_AE_function);
	}
}

//! provide according output variable in "value"
void CObjectJointGeneric::GetOutputVariableConnector(OutputVariableType variableType, const MarkerDataStructure& markerData, Vector& value) const
{
	//const LinkedDataVector& lambda = markerData.GetLagrangeMultipliers();

	const Matrix3D& A0 = markerData.GetMarkerData(0).orientation;
	const Matrix3D& A0off = parameters.rotationMarker0;
	Matrix3D A0all = (A0*A0off);

	const Matrix3D& A1 = markerData.GetMarkerData(1).orientation;
	const Matrix3D& A1off = parameters.rotationMarker1;
	Matrix3D A1all = (A1*A1off);

	//use difference of positions in local joint J0 coordinates
	Vector3D vPosLocal = A0all.GetTransposed()*(markerData.GetMarkerData(1).position - markerData.GetMarkerData(0).position); 
	Vector3D vVelLocal = A0all.GetTransposed()*(markerData.GetMarkerData(1).velocity - markerData.GetMarkerData(0).velocity);

	Vector3D angVelLocal = A0all.GetTransposed()*(A1*markerData.GetMarkerData(1).angularVelocityLocal - A0 * markerData.GetMarkerData(0).angularVelocityLocal); //difference of global angular velocities, projected into J0

	//compute relative rotation, J0-fixed:
	Matrix3D relRot = A0all.GetTransposed() * A1all;
	Vector3D vLocRot = RigidBodyMath::RotationMatrix2RotXYZ(relRot);

	if (vLocRot[0] > EXUstd::pi) { vLocRot[0] -= 2.*EXUstd::pi; }
	if (vLocRot[1] > EXUstd::pi) { vLocRot[1] -= 2.*EXUstd::pi; }
	if (vLocRot[2] > EXUstd::pi) { vLocRot[2] -= 2.*EXUstd::pi; }

	switch (variableType)
	{
	case OutputVariableType::Position: value.CopyFrom(markerData.GetMarkerData(0).position); break;
	case OutputVariableType::Velocity: value.CopyFrom(markerData.GetMarkerData(0).velocity); break;
	case OutputVariableType::DisplacementLocal: value.CopyFrom(vPosLocal); break;
	case OutputVariableType::HomogeneousTransformation: //the joint frame J0 (#2870)
		ConnectorOutputVariableFrame(A0all, markerData.GetMarkerData(0).position, value); break;
	case OutputVariableType::HomogeneousTransformationLocal: //the joint frame J1 in J0 (#2870)
		ConnectorOutputVariableFrameLocal(A0all, markerData.GetMarkerData(0).position, A1all, markerData.GetMarkerData(1).position, value); break;
	case OutputVariableType::Rotation: value.CopyFrom(vLocRot); break;
	case OutputVariableType::VelocityLocal: value.CopyFrom(vVelLocal); break;
	case OutputVariableType::AngularVelocityLocal: value.CopyFrom(angVelLocal); break;
	case OutputVariableType::ForceLocal:
	{
		Vector3D force({ GetCurrentAEcoordinate(0), GetCurrentAEcoordinate(1), GetCurrentAEcoordinate(2) }); 
		if (parameters.constrainedAxes[0] == 1 && parameters.constrainedAxes[1] == 1 && parameters.constrainedAxes[2] == 1) //then force is global!
		{
			force = A0all.GetTransposed()*force;
		}
		value.CopyFrom(force);
		break;
	}
	case OutputVariableType::TorqueLocal:
	{
		Vector3D torque({ GetCurrentAEcoordinate(3), GetCurrentAEcoordinate(4), GetCurrentAEcoordinate(5) });
		value.CopyFrom(torque);
		break;
	}
	default:
		SysError("CObjectJointGeneric::GetOutputVariable failed"); //error should not occur, because types are checked!
	}

}

