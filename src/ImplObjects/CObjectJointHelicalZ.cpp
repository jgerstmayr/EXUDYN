//! the angle phi of J1 about z of J0 from c = x0*x1, s = y0*x1, taken on the branch nearest to psi = dz/h (phiTilde),
//! and the coupling dz - h*phiTilde = -h*atan2(sin(phi-psi), cos(phi-psi)); for h = 0 the coupling is dz and phiTilde
//! the angle in (-pi, pi]
static Real HelicalJointCoupling(Real pitch, Real c, Real s, Real dz, Real& phiTilde)
{
	if (pitch == 0.)
	{
		phiTilde = EM::Atan2(s, c);
		return dz;
	}
	const Real psi = dz / pitch;
	const Real cosPsi = EM::Cos(psi);
	const Real sinPsi = EM::Sin(psi);
	const Real error = EM::Atan2(s*cosPsi - c * sinPsi, c*cosPsi + s * sinPsi); //phi - psi in (-pi, pi]
	phiTilde = psi + error;
	return -pitch * error;
}

//! the 5 equations and, if derivatives is given, their rows in the 12 variations of the two frames; lambda_i on a free
//! equation, whose row is zero
static void HelicalJointEquations(const CObjectJointHelicalZParameters& parameters, const MarkerRigid<Real>& marker0,
	const MarkerRigid<Real>& marker1, const LinkedDataVector& lambda, ConstSizeVector<maxConstraintEquations>& equations,
	RigidMarkersDerivatives* derivatives)
{
	const Matrix3D& A0 = marker0.frame.GetRotation();
	const Matrix3D& A1 = marker1.frame.GetRotation();
	const Vector3D x0 = A0.GetColumnVector<3>(0), y0 = A0.GetColumnVector<3>(1), z0 = A0.GetColumnVector<3>(2);
	const Vector3D x1 = A1.GetColumnVector<3>(0), y1 = A1.GetColumnVector<3>(1);
	const Vector3D relativePosition = marker1.frame.GetTranslation() - marker0.frame.GetTranslation();
	const Real h = parameters.pitch;

	equations.SetNumberOfItems(5);
	if (derivatives)
	{
		derivatives->SetNumberOfRowsAndColumns(5, 12);
		derivatives->SetAll(0.);
	}

	//the translations along a = x0, y0, z0: d(a*(p1-p0)) = a*(dp1 - dp0) + (a x (p1-p0))*dtheta0
	const Vector3D* translationAxes[3] = { &x0, &y0, &z0 };
	for (Index i = 0; i < 3; i++)
	{
		const Vector3D& a = *translationAxes[i];
		equations[i] = a * relativePosition;
		if (derivatives)
		{
			Vector3D w = a.CrossProduct(relativePosition);
			for (Index k = 0; k < 3; k++)
			{
				(*derivatives)(i, k) = -a[k];
				(*derivatives)(i, 3 + k) = w[k];
				(*derivatives)(i, 6 + k) = a[k];
			}
		}
	}

	//the coupling: equation 2 holds dz and becomes dz - h*phiTilde; d(phi) = (c ds - s dc)/(c^2+s^2) with
	//d(a*b) = (a x b)*(dtheta0 - dtheta1) for c = x0*x1, s = y0*x1
	const Real c = x0 * x1;
	const Real s = y0 * x1;
	Real phiTilde;
	equations[2] = HelicalJointCoupling(h, c, s, equations[2], phiTilde);
	if (derivatives && h != 0.)
	{
		const Real cs2 = c * c + s * s;
		CHECKandTHROW(cs2 != 0., "ObjectJointHelicalZ: the x-axis of marker 1 is parallel to the joint axis; the angle is undefined");
		Vector3D wPhi = (1. / cs2) * (c * y0.CrossProduct(x1) - s * x0.CrossProduct(x1)); //d(phi) = wPhi*(dtheta0 - dtheta1)
		for (Index k = 0; k < 3; k++)
		{
			(*derivatives)(2, 3 + k) -= h * wPhi[k];
			(*derivatives)(2, 9 + k) += h * wPhi[k];
		}
	}

	//the tilts about x and y of J0
	equations[3] = JointAxesEquation(z0, y1, 3, derivatives);
	equations[4] = JointAxesEquation(z0, x1, 4, derivatives);

	for (Index i = 0; i < 5; i++)
	{
		if (parameters.constrainedAxes[i] != 1)
		{
			equations[i] = lambda[i];
			if (derivatives) { for (Index j = 0; j < 12; j++) { (*derivatives)(i, j) = 0.; } }
		}
	}
}

//! the equations on the connector interface; at velocity level (index 2) their rows times the twists of the frames
void CObjectJointHelicalZ::ComputeConstraintEquationsRigid(FlatArray<const MarkerRigid<Real>> markers, const LinkedDataVector& lambda, Real t, bool velocityLevel, ConstSizeVector<maxConstraintEquations>& equations) const
{
	if (!velocityLevel)
	{
		HelicalJointEquations(parameters, markers[0], markers[1], lambda, equations, nullptr);
	}
	else
	{
		RigidMarkersDerivatives derivatives;
		HelicalJointEquations(parameters, markers[0], markers[1], lambda, equations, &derivatives);
		const Vector3D omega0 = markers[0].frame.GetRotation() * markers[0].angularVelocityLocal;
		const Vector3D omega1 = markers[1].frame.GetRotation() * markers[1].angularVelocityLocal;
		const Vector3D* twist[4] = { &markers[0].velocity, &omega0, &markers[1].velocity, &omega1 };
		for (Index i = 0; i < 5; i++)
		{
			if (parameters.constrainedAxes[i] != 1) { continue; } //lambda_i
			Real value = 0.;
			for (Index k = 0; k < 4; k++)
			{
				for (Index c = 0; c < 3; c++) { value += derivatives(i, 3 * k + c) * (*twist[k])[c]; }
			}
			equations[i] = value;
		}
	}
}

bool CObjectJointHelicalZ::ComputeConstraintEquationsRigidDerivatives(FlatArray<const MarkerRigid<Real>> markers, const LinkedDataVector& lambda,
	Real t, ConstSizeVector<maxConstraintEquations>& equations, RigidMarkersDerivatives& derivatives) const
{
	HelicalJointEquations(parameters, markers[0], markers[1], lambda, equations, &derivatives);
	return true;
}

void CObjectJointHelicalZ::ComputeJacobianAE_AE(ResizableMatrix& jacobian_AE) const
{
	jacobian_AE.SetScalarMatrix(nConstraints, 0.);
	for (Index i = 0; i < nConstraints; i++)
	{
		if (parameters.constrainedAxes[i] != 1) { jacobian_AE(i, i) = 1.; }
	}
}

JacobianType::Type CObjectJointHelicalZ::GetAvailableJacobians() const
{
	if (parameters.activeConnector)
	{
		return (JacobianType::Type)(JacobianType::AE_ODE2 + JacobianType::AE_ODE2_function + JacobianType::AE_AE + JacobianType::AE_AE_function); //AE_AE for the free equations
	}
	else //deactivated constraint means that only the lagrange multiplier needs to be set to zero
	{
		return (JacobianType::Type)(JacobianType::AE_AE + JacobianType::AE_AE_function);
	}
}

//! provide according output variable in "value"
void CObjectJointHelicalZ::GetOutputVariableConnector(OutputVariableType variableType, const MarkerDataStructure& markerData, Vector& value) const
{
	const Matrix3D& A0 = markerData.GetMarkerData(0).orientation;
	const Matrix3D& A1 = markerData.GetMarkerData(1).orientation;
	const Vector3D& p0 = markerData.GetMarkerData(0).position;
	const Vector3D& p1 = markerData.GetMarkerData(1).position;

	Vector3D vPosLocal = Transposed(A0) *(p1 - p0);
	Vector3D vVelLocal = Transposed(A0) *(markerData.GetMarkerData(1).velocity - markerData.GetMarkerData(0).velocity);
	Vector3D angVelLocal = Transposed(A0) *(A1*markerData.GetMarkerData(1).angularVelocityLocal - A0 * markerData.GetMarkerData(0).angularVelocityLocal);

	switch (variableType)
	{
	case OutputVariableType::Position: value.CopyFrom(p0); break;
	case OutputVariableType::Velocity: value.CopyFrom(markerData.GetMarkerData(0).velocity); break;
	case OutputVariableType::DisplacementLocal: value.CopyFrom(vPosLocal); break;
	case OutputVariableType::HomogeneousTransformation: //the joint frame J0
		ConnectorOutputVariableFrame(A0, p0, value); break;
	case OutputVariableType::HomogeneousTransformationLocal: //the joint frame J1 in J0
		ConnectorOutputVariableFrameLocal(A0, p0, A1, p1, value); break;
	case OutputVariableType::Rotation:
	{
		//Tait-Bryan angles for the tilts, the angle on the turn of the axial position about z
		Vector3D vLocRot = RigidBodyMath::RotationMatrix2RotXYZ(Transposed(A0) * A1);
		if (vLocRot[0] > EXUstd::pi) { vLocRot[0] -= 2.*EXUstd::pi; }
		if (vLocRot[1] > EXUstd::pi) { vLocRot[1] -= 2.*EXUstd::pi; }
		const Vector3D x1 = A1.GetColumnVector<3>(0);
		Real phiTilde;
		HelicalJointCoupling(parameters.pitch, A0.GetColumnVector<3>(0) * x1, A0.GetColumnVector<3>(1) * x1, vPosLocal[2], phiTilde);
		vLocRot[2] = phiTilde;
		value.CopyFrom(vLocRot);
		break;
	}
	case OutputVariableType::VelocityLocal: value.CopyFrom(vVelLocal); break;
	case OutputVariableType::AngularVelocityLocal: value.CopyFrom(angVelLocal); break;
	case OutputVariableType::ForceLocal:
	{
		Vector3D force({ GetCurrentAEcoordinate(0), GetCurrentAEcoordinate(1), GetCurrentAEcoordinate(2) }); //along x0, y0, z0
		value.CopyFrom(force);
		break;
	}
	case OutputVariableType::TorqueLocal:
	{
		Vector3D torque({ GetCurrentAEcoordinate(3), GetCurrentAEcoordinate(4), -parameters.pitch*GetCurrentAEcoordinate(2) });
		value.CopyFrom(torque);
		break;
	}
	default:
		SysError("CObjectJointHelicalZ::GetOutputVariable failed"); //error should not occur, because types are checked!
	}
}

