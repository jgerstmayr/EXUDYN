//! the force with automatic differentiation, for the Jacobian of the connector interface (#2745)
void CObjectConnectorSpringDamper::ComputeConnectorForcePositionDiff(const MarkerPosition<DRealPositionMarkers>* markers, Real t, Index itemIndex,
	SlimVectorBase<DRealPositionMarkers, 3>& force) const
{
	SlimVectorBase<DRealPositionMarkers, 3> relPos, relVel, forceDirection;
	DRealPositionMarkers forceScalar;
	ComputeSpringForce(markers[0].position, markers[1].position, markers[0].velocity, markers[1].velocity, t, itemIndex,
		relPos, relVel, forceScalar, forceDirection);
	force = forceScalar * forceDirection;
	if (relPos.GetL2NormSquared() == 0. && parameters.activeConnector)
	{
		//at zero length the direction has no derivative; the Jacobian is k I and d I, as on the legacy path
		force += parameters.stiffness * relPos + parameters.damping * (relVel - (relVel * forceDirection) * forceDirection);
	}
}

template<class TReal>
void CObjectConnectorSpringDamper::ComputeSpringForce(const SlimVectorBase<TReal, 3>& position0, const SlimVectorBase<TReal, 3>& position1,
	const SlimVectorBase<TReal, 3>& velocity0, const SlimVectorBase<TReal, 3>& velocity1, Real t, Index itemIndex,
	SlimVectorBase<TReal, 3>& relPos, SlimVectorBase<TReal, 3>& relVel, TReal& force, SlimVectorBase<TReal, 3>& forceDirection) const
{
	using std::sqrt;
	relPos = (position1 - position0);
	//sqrt only of a nonzero length: its derivative at zero is not defined
	TReal springLength2 = relPos.GetL2NormSquared();
	TReal springLength = 0.;
	if (springLength2 != 0.) { springLength = sqrt(springLength2); }
	TReal springLengthInv;

	//unit direction and relative velocity of spring-damper
	forceDirection = relPos;
	relVel = (velocity1 - velocity0);

	if (springLength != 0.) 
	{ 
		springLengthInv = 1. / springLength; 
		forceDirection *= springLengthInv;
	}
	else 
	{ 
		springLengthInv = 1.; 
		//not marked as error since issue #1686
		//SysError("CObjectConnectorSpringDamper::ComputeODE2LHS: springLength = 0"); 

		//compute alternative force-direction for zero distance; alternatively, forceDirection could be [0,0,0]
		forceDirection = relVel;
		TReal relVelNorm = relVel.GetL2Norm();
		if (relVelNorm != 0.)
		{
			forceDirection *= 1. / relVelNorm;
		}
		if constexpr (!std::is_same<TReal, Real>::value)
		{
			for (Index i = 0; i < 3; i++) { forceDirection[i] = forceDirection[i].Value(); } //a constant direction, as on the legacy path
		}
	}


	//stiffness term; this is the term without the jacobian [delta l_vec]; compare Shabana MultibodyDynamics1998, page 119:
	force = 0;
	if (parameters.activeConnector)
	{
		if (!parameters.springForceUserFunction)
		{
			// delta W_spring = k*(l-l0)*(1/l)*l_vec* [delta l_vec]
			force += (parameters.stiffness * (springLength - parameters.referenceLength));

			//damping term  + force:
			force += (parameters.damping * (relVel*forceDirection - parameters.velocityOffset)) + parameters.force;
		}
		else if constexpr (std::is_same<TReal, Real>::value)
		{
			Real forceAdd;
			EvaluateUserFunctionForce(forceAdd, cSystemData->GetMainSystemBacklink(), t, itemIndex,
				springLength - parameters.referenceLength, relVel*forceDirection - parameters.velocityOffset);
			force += forceAdd;
		}
		else
		{
			CHECKandTHROWstring("ObjectConnectorSpringDamper: no automatic differentiation of a springForceUserFunction");
		}
	}
}

//! Computational function: compute left-hand-side (LHS) of second order ordinary differential equations (ODE) to "ode2Lhs"
//  MODEL: f
void CObjectConnectorSpringDamper::ComputeODE2LHS(Vector& ode2Lhs, const MarkerDataStructure& markerData, Index objectNumber) const
{
	//relative position, spring length and inverse spring length
	CHECKandTHROW(markerData.GetMarkerData(1).velocityAvailable && markerData.GetMarkerData(0).velocityAvailable,
		"CObjectConnectorSpringDamper::ComputeODE2LHS: marker do not provide velocityLevel information");

	//link separate vectors to result (ode2Lhs) vector
	ode2Lhs.SetNumberOfItems(markerData.GetMarkerData(0).positionJacobian.NumberOfColumns() + markerData.GetMarkerData(1).positionJacobian.NumberOfColumns());
	ode2Lhs.SetAll(0.); //this is the default; used if !activeConnector

	if (parameters.activeConnector)
	{
		Real force;
		Vector3D relPos, relVel, forceDirection;
		ComputeConnectorProperties(markerData, objectNumber, relPos, relVel, force, forceDirection);
		Vector3D fVec = force * forceDirection;

		//now link ode2Lhs Vector to partial result using the two jacobians
		if (markerData.GetMarkerData(1).positionJacobian.NumberOfColumns()) //special case: COGround has (0,0) Jacobian
		{
			LinkedDataVector ldv1(ode2Lhs, markerData.GetMarkerData(0).positionJacobian.NumberOfColumns(), markerData.GetMarkerData(1).positionJacobian.NumberOfColumns());

			//ldv1 = (1.)*(markerData.GetMarkerData(1).positionJacobian.GetTransposed()*f); //slow version		
			EXUmath::MultMatrixTransposedVector(markerData.GetMarkerData(1).positionJacobian, fVec, ldv1);
		}

		if (markerData.GetMarkerData(0).positionJacobian.NumberOfColumns()) //special case: COGround has (0,0) Jacobian
		{
			LinkedDataVector ldv0(ode2Lhs, 0, markerData.GetMarkerData(0).positionJacobian.NumberOfColumns());

			//ldv0 = (-1.)*(jacobian0.GetTransposed()*f); //SLOW version
			EXUmath::MultMatrixTransposedVector(markerData.GetMarkerData(0).positionJacobian, fVec, ldv0);
			ldv0 *= -1.;
		}
	}
}





//! compute global 6D force and torque which is used for computation of derivative of jacobian; used only in combination with ComputeJacobianODE2_ODE2
