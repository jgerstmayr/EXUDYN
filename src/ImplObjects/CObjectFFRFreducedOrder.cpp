//! compute coordinates for nodeNumber(without reference coordinates) from modeBasis(= multiplication of according part of mode Basis with modal coordinates)
Vector3D CObjectFFRFreducedOrder::GetMeshNodeCoordinates(Index nodeNumber, const Vector& coordinates) const
{
	Vector3D u({ 0.,0.,0. }); //can be displacements and velocities, depending on coordinates!
	const Matrix& Psi = parameters.modeBasis;
	Index nModes = Psi.NumberOfColumns();
	Index nOffset = nodeNumber*3; //offset in modeBasis, giving according x-coordinates of node

	for (Index i = 0; i < 3; i++) //node coordinates x,y,z
	{
		for (Index j = 0; j < nModes; j++) //iteration over all modes / modal coordinates
		{
			u[i] += Psi(nOffset + i, j) * coordinates[j];
		}
	}
	return u;
}

//+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
//THE INTERFACE OF THE SUPERELEMENT MARKERS: the sums over the mesh nodes are linear in the modal coordinates q,
//sum_i w_i u_i = Pm q and the weighted rotation = Rm q, with Pm and Rm computed once (#2184)

//! the part of CObjectSuperElement, and with precomputeMarkerModes the matrices
//! Pm = sum_i w_i Psi_i and Rm = W^{-1} (sum_i w_i tilde(p_i) Psi_i - tilde(sum_i w_i p_i) Pm), p_i = p_i^ref - p_0
void CObjectFFRFreducedOrder::InitializeMarkerInterface(const ArrayIndex& meshNodeNumbers, const Vector& weightingFactors, bool computeRotation,
	bool alternativeApproach, SuperElementMarkerInterface& markerInterface) const
{
	CObjectSuperElement::InitializeMarkerInterface(meshNodeNumbers, weightingFactors, computeRotation, alternativeApproach, markerInterface);
	if (!parameters.precomputeMarkerModes) { return; }

	const Matrix& modeBasis = parameters.modeBasis;
	const Index nModes = modeBasis.NumberOfColumns();
	Matrix& positionModes = markerInterface.positionModes;
	Matrix& rotationModes = markerInterface.rotationModes;
	positionModes.SetNumberOfRowsAndColumns(nDim3D, nModes);
	positionModes.SetAll(0.);
	if (computeRotation)
	{
		rotationModes.SetNumberOfRowsAndColumns(nDim3D, nModes);
		rotationModes.SetAll(0.);
	}

	Vector3D weightedPositions(0.); //sum_i w_i p_i, zero if the weights sum up to 1
	for (Index i = 0; i < meshNodeNumbers.NumberOfItems(); i++)
	{
		const Real w = weightingFactors[i];
		const Index offset = meshNodeNumbers[i] * 3;
		const Vector3D p = GetMeshNodeLocalPosition(meshNodeNumbers[i], ConfigurationType::Reference) - markerInterface.referencePosition;
		weightedPositions += w * p;
		for (Index m = 0; m < nModes; m++)
		{
			const Vector3D psi({ modeBasis(offset, m), modeBasis(offset + 1, m), modeBasis(offset + 2, m) });
			for (Index k = 0; k < 3; k++) { positionModes(k, m) += w * psi[k]; }
			if (computeRotation)
			{
				const Vector3D rotation = w * p.CrossProduct(psi);
				for (Index k = 0; k < 3; k++) { rotationModes(k, m) += rotation[k]; }
			}
		}
	}

	if (computeRotation)
	{
		for (Index m = 0; m < nModes; m++)
		{
			Vector3D column({ rotationModes(0, m), rotationModes(1, m), rotationModes(2, m) });
			column -= weightedPositions.CrossProduct(Vector3D({ positionModes(0, m), positionModes(1, m), positionModes(2, m) }));
			column = markerInterface.ApplyRotationWeighting(column);
			for (Index k = 0; k < 3; k++) { rotationModes(k, m) = column[k]; }
		}
	}
}

//! Pm * q or Rm * q for the modal coordinates of configuration (coordinates) or their velocities (coordinates_t)
static Vector3D MultiplyModes(const Matrix& modes, const VectorBase<Real>& coordinates)
{
	Vector3D result(0.);
	const Index nModes = modes.NumberOfColumns();
	for (Index k = 0; k < 3; k++)
	{
		const Real* row = &modes.GetDataPointer()[k*nModes];
		Real value = 0.;
		for (Index m = 0; m < nModes; m++) { value += row[m] * coordinates[m]; }
		result[k] = value;
	}
	return result;
}

Vector3D CObjectFFRFreducedOrder::GetMarkerLocalPosition(const SuperElementMarkerInterface& markerInterface, const ArrayIndex& meshNodeNumbers,
	const Vector& weightingFactors, ConfigurationType configuration) const
{
	if (!markerInterface.HasModes())
	{
		return CObjectSuperElement::GetMarkerLocalPosition(markerInterface, meshNodeNumbers, weightingFactors, configuration);
	}
	if (configuration == ConfigurationType::Reference) { return markerInterface.referencePosition; } //the reference coordinates are zero
	return markerInterface.referencePosition +
		MultiplyModes(markerInterface.positionModes, ((const CNodeODE2*)GetCNode(genericNodeNumber))->GetCoordinateVector(configuration));
}

Vector3D CObjectFFRFreducedOrder::GetMarkerLocalVelocity(const SuperElementMarkerInterface& markerInterface, const ArrayIndex& meshNodeNumbers,
	const Vector& weightingFactors, ConfigurationType configuration) const
{
	if (!markerInterface.HasModes())
	{
		return CObjectSuperElement::GetMarkerLocalVelocity(markerInterface, meshNodeNumbers, weightingFactors, configuration);
	}
	return MultiplyModes(markerInterface.positionModes, ((const CNodeODE2*)GetCNode(genericNodeNumber))->GetCoordinateVector_t(configuration));
}

Vector3D CObjectFFRFreducedOrder::GetMarkerLocalRotation(const SuperElementMarkerInterface& markerInterface, const ArrayIndex& meshNodeNumbers,
	const Vector& weightingFactors, ConfigurationType configuration) const
{
	if (!markerInterface.HasModes())
	{
		return CObjectSuperElement::GetMarkerLocalRotation(markerInterface, meshNodeNumbers, weightingFactors, configuration);
	}
	CHECKandTHROW(markerInterface.hasRotation, "CObjectFFRFreducedOrder::GetMarkerLocalRotation: the marker interface has no rotation");
	if (configuration == ConfigurationType::Reference) { return Vector3D(0.); }
	return MultiplyModes(markerInterface.rotationModes, ((const CNodeODE2*)GetCNode(genericNodeNumber))->GetCoordinateVector(configuration));
}

Vector3D CObjectFFRFreducedOrder::GetMarkerLocalAngularVelocity(const SuperElementMarkerInterface& markerInterface, const ArrayIndex& meshNodeNumbers,
	const Vector& weightingFactors, ConfigurationType configuration) const
{
	if (!markerInterface.HasModes())
	{
		return CObjectSuperElement::GetMarkerLocalAngularVelocity(markerInterface, meshNodeNumbers, weightingFactors, configuration);
	}
	CHECKandTHROW(markerInterface.hasRotation, "CObjectFFRFreducedOrder::GetMarkerLocalAngularVelocity: the marker interface has no rotation");
	return MultiplyModes(markerInterface.rotationModes, ((const CNodeODE2*)GetCNode(genericNodeNumber))->GetCoordinateVector_t(configuration));
}

//! for definition see CObjectSuperElement; the columns of the modal coordinates are A*Pm and A*Rm (A*T*Rm in the
//! alternative approach), or the sums over the mesh nodes without precomputeMarkerModes
void CObjectFFRFreducedOrder::GetAccessFunctionSuperElement(AccessFunctionType accessType, const SuperElementMarkerInterface& markerInterface,
	const ArrayIndex& meshNodeNumbers, const Vector& weightingFactors, const Vector3D& localOffset, const Matrix3D& rotTangentCorrection, Matrix& value) const
{
	const CNodeRigidBody* cNode = (const CNodeRigidBody*)GetCNode(rigidBodyNodeNumber);
	const Index nODE2rigid = cNode->GetNumberOfODE2Coordinates();
	const Matrix& modeBasis = parameters.modeBasis;
	const Index nModes = modeBasis.NumberOfColumns();
	const Matrix3D A = cNode->GetRotationMatrix();

	value.SetNumberOfRowsAndColumns(nDim3D, GetODE2Size());
	value.SetAll(0.);

	//add jac * Psi_i, the rows of mesh node i of the mode basis, to the columns of the modal coordinates
	auto AddNodeJacobian = [&](const Matrix3D& jac, Index meshNodeNumber)
	{
		const Index offset = meshNodeNumber * 3;
		for (Index j = 0; j < 3; j++)
		{
			for (Index k = 0; k < 3; k++)
			{
				for (Index m = 0; m < nModes; m++)
				{
					value(j, nODE2rigid + m) += jac(j, k) * modeBasis(offset + k, m);
				}
			}
		}
	};
	//set jac * modes, modes = Pm or Rm, as the columns of the modal coordinates
	auto SetModalJacobian = [&](const Matrix3D& jac, const Matrix& modes)
	{
		for (Index j = 0; j < 3; j++)
		{
			for (Index m = 0; m < nModes; m++)
			{
				value(j, nODE2rigid + m) = jac(j, 0) * modes(0, m) + jac(j, 1) * modes(1, m) + jac(j, 2) * modes(2, m);
			}
		}
	};

	switch ((Index)accessType)
	{
	case (Index)AccessFunctionType::TranslationalVelocity_qt + (Index)AccessFunctionType::SuperElement:
	//\partial vMarker / \partial q_t = [I, -A * pLocalTilde * Glocal, A*(w0*Psi_0 + w1*Psi_1 + ...)]
	{
		if (markerInterface.HasModes()) { SetModalJacobian(A, markerInterface.positionModes); }
		else
		{
			for (Index i = 0; i < meshNodeNumbers.NumberOfItems(); i++) { AddNodeJacobian(weightingFactors[i] * A, meshNodeNumbers[i]); }
		}

		//the reference frame node: [I, -A * pLocalTilde * Glocal]
		Vector3D localPosition = localOffset + GetMarkerLocalPosition(markerInterface, meshNodeNumbers, weightingFactors, ConfigurationType::Current);
		ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates*CNodeRigidBody::nDim3D> ApLocalTildeGlocal;
		cNode->GetGlocal(ApLocalTildeGlocal);
		EXUmath::ApplyTransformation33(RigidBodyMath::Vector2SkewMatrixTemplate(-localPosition), ApLocalTildeGlocal);
		EXUmath::ApplyTransformation33(A, ApLocalTildeGlocal);

		//posJac0 needs its size before it is linked
		ConstSizeMatrix<CNodeRigidBody::nDim3D * (CNodeRigidBody::maxDisplacementCoordinates + CNodeRigidBody::maxRotationCoordinates)> posJac0(nDim3D, nODE2rigid);
		LinkedDataMatrix linkedPosJac0(posJac0);
		cNode->GetPositionJacobian(linkedPosJac0); //usually identity, because node does not include localPosition

		value.SetSubmatrix(posJac0, 0, 0);
		value.SetSubmatrix(ApLocalTildeGlocal, 0, CNodeRigidBody::maxDisplacementCoordinates);
		break;
	}
	case (Index)AccessFunctionType::AngularVelocity_qt + (Index)AccessFunctionType::SuperElement:
	//\partial omegaMarker / \partial q_t = [0, A * Glocal, A*W^{-1}*(w0*pRefTilde0*Psi_0 + w1*pRefTilde1*Psi_1 + ...)]
	{
		CHECKandTHROW(markerInterface.hasRotation, "CObjectFFRFreducedOrder::GetAccessFunctionSuperElement: the marker interface has no rotation");

		if (markerInterface.HasModes())
		{
			if (markerInterface.alternativeApproach) { SetModalJacobian(A * rotTangentCorrection, markerInterface.rotationModes); }
			else { SetModalJacobian(A, markerInterface.rotationModes); }
		}
		else
		{
			Matrix3D weighting = A; //A*rotTangentCorrection*W^{-1} or A*W^{-1}
			if (markerInterface.alternativeApproach) { weighting = A * (rotTangentCorrection * markerInterface.rotationMatrixInverse); }
			else { weighting *= 1. / markerInterface.rotationFactor; }
			for (Index i = 0; i < meshNodeNumbers.NumberOfItems(); i++)
			{
				Vector3D p = GetMeshNodeLocalPosition(meshNodeNumbers[i], ConfigurationType::Reference) - markerInterface.referencePosition;
				AddNodeJacobian(weightingFactors[i] * weighting * RigidBodyMath::Vector2SkewMatrix(p), meshNodeNumbers[i]);
			}
		}

		//the reference frame node: [0, A * Glocal]
		ConstSizeMatrix<CNodeRigidBody::maxRotationCoordinates*CNodeRigidBody::nDim3D> Glocal;
		cNode->GetGlocal(Glocal);
		EXUmath::ApplyTransformation33(A, Glocal);
		value.SetSubmatrix(Glocal, 0, CNodeRigidBody::maxDisplacementCoordinates);
		break;
	}
	default:
		CHECKandTHROWstring("CObjectFFRFreducedOrder:GetAccessFunctionSuperElement illegal accessType");
	}
}

//! get extended output variable types for multi-nodal objects with mesh nodes
OutputVariableType CObjectFFRFreducedOrder::GetOutputVariableTypesSuperElement(Index meshNodeNumber) const
{
	CHECKandTHROW(meshNodeNumber < GetNumberOfMeshNodes(), "CObjectFFRFreducedOrder::GetOutputVariableSuperElement: meshNodeNumber out of range ", ExudynIndexError);
	//independent of meshNodeNumber!!!
	OutputVariableType ovt = (OutputVariableType)(
		(Index64)OutputVariableType::Position +
		(Index64)OutputVariableType::Displacement +
		(Index64)OutputVariableType::Velocity +
		(Index64)OutputVariableType::Acceleration +
		(Index64)OutputVariableType::DisplacementLocal +
		(Index64)OutputVariableType::VelocityLocal);
	if (parameters.outputVariableTypeModeBasis == OutputVariableType::StressLocal) 
	{
		ovt = (OutputVariableType)((Index64)ovt + (Index64)OutputVariableType::StressLocal);
	}
	else if (parameters.outputVariableTypeModeBasis == OutputVariableType::StrainLocal)
	{
		ovt = (OutputVariableType)((Index64)ovt + (Index64)OutputVariableType::StrainLocal);
	}

	return ovt;
}

//! get extended output variables for multi-nodal objects with mesh nodes
void CObjectFFRFreducedOrder::GetOutputVariableSuperElement(OutputVariableType variableType, Index meshNodeNumber, ConfigurationType configuration, Vector& value) const
{
	switch (variableType)
	{
	case OutputVariableType::Position:	value.CopyFrom(GetMeshNodePosition(meshNodeNumber, configuration));	break;
	case OutputVariableType::Displacement:	value.CopyFrom(GetMeshNodePosition(meshNodeNumber, configuration) - GetMeshNodePosition(meshNodeNumber, ConfigurationType::Reference));	break;
	case OutputVariableType::Velocity:	value.CopyFrom(GetMeshNodeVelocity(meshNodeNumber, configuration));	break;
	case OutputVariableType::Acceleration:	value.CopyFrom(GetMeshNodeAcceleration(meshNodeNumber, configuration));	break;

	case OutputVariableType::DisplacementLocal:	value.CopyFrom(GetMeshNodeLocalPosition(meshNodeNumber, configuration) - GetMeshNodeLocalPosition(meshNodeNumber, ConfigurationType::Reference));	break;
	case OutputVariableType::VelocityLocal:	value.CopyFrom(GetMeshNodeLocalVelocity(meshNodeNumber, configuration));	break;
	case OutputVariableType::StressLocal:
	{
		value.SetNumberOfItems(6);
		value.SetAll(0);
		const Matrix& PsiS = parameters.outputVariableModeBasis;

		//stresses are based on modal displacements only
		LinkedDataVector coordinates = ((CNodeODE2*)GetCNode(genericNodeNumber))->GetCoordinateVector(configuration);

		Index nModes = parameters.modeBasis.NumberOfColumns();

		for (Index i = 0; i < 6; i++) //stress component
		{
			for (Index j = 0; j < nModes; j++) //iteration over all modes / modal coordinates
			{
				value[i] += PsiS(meshNodeNumber, j * 6 + i) * coordinates[j];
			}
		}
		break;
	}
	case OutputVariableType::StrainLocal:
	{
		value.SetNumberOfItems(6);
		value.SetAll(0);
		const Matrix& PsiS = parameters.outputVariableModeBasis;

		//stresses are based on modal displacements only
		LinkedDataVector coordinates = ((CNodeODE2*)GetCNode(genericNodeNumber))->GetCoordinateVector(configuration);

		Index nModes = parameters.modeBasis.NumberOfColumns();

		for (Index i = 0; i < 6; i++) //strain component
		{
			for (Index j = 0; j < nModes; j++) //iteration over all modes / modal coordinates
			{
				value[i] += PsiS(meshNodeNumber, j*6+i) * coordinates[j];
			}
		}
		break;
	}
	default:
		SysError("CObjectFFRFreducedOrder::GetOutputVariableSuperElement failed"); //error should not occur, because types are checked!
	}

}

//! return the mesh node pointer; for consistency checks
CNodeODE2* CObjectFFRFreducedOrder::GetMeshNode(Index meshNodeNumber) const
{
	CHECKandTHROW(meshNodeNumber < GetNumberOfMeshNodes(), "CObjectFFRFreducedOrder::GetMeshNode: meshNodeNumber out of range", ExudynIndexError);

	return nullptr; //there is no meshnode, its only virtual ...
}

//! return the (local) position of a mesh node according to configuration type; use Configuration.Reference to access the mesh reference position; meshNodeNumber is the local node number of the (underlying) mesh
Vector3D CObjectFFRFreducedOrder::GetMeshNodeLocalPosition(Index meshNodeNumber, ConfigurationType configuration) const
{
	CHECKandTHROW(meshNodeNumber < GetNumberOfMeshNodes(), "CObjectFFRFreducedOrder::GetMeshNodeLocalPosition: meshNodeNumber out of range (mesh node 0 is node 1 in ObjectFFRFreducedOrder)", ExudynIndexError);

	if (configuration == ConfigurationType::Reference) {
		return Vector3D({ parameters.referencePositions[meshNodeNumber * 3],
			parameters.referencePositions[meshNodeNumber * 3 + 1],
			parameters.referencePositions[meshNodeNumber * 3 + 2] });
		//note that GetCoordinateVector(ConfigurationType::Reference) is all zero, guaranteed by checkPReAssembleConsistencies()
	}
	else
	{
		return GetMeshNodeCoordinates(meshNodeNumber, ((CNodeODE2*)GetCNode(genericNodeNumber))->GetCoordinateVector(configuration))
		+ Vector3D({ parameters.referencePositions[meshNodeNumber * 3],
			parameters.referencePositions[meshNodeNumber * 3 + 1],
			parameters.referencePositions[meshNodeNumber * 3 + 2] });
	}
}

//! return the (local) velocity of a mesh node according to configuration type; meshNodeNumber is the local node number of the (underlying) mesh
Vector3D CObjectFFRFreducedOrder::GetMeshNodeLocalVelocity(Index meshNodeNumber, ConfigurationType configuration) const
{
	CHECKandTHROW(meshNodeNumber < GetNumberOfMeshNodes(), "CObjectFFRFreducedOrder::GetMeshNodeLocalVelocity: meshNodeNumber out of range (mesh node 0 is node 1 in ObjectFFRFreducedOrder)", ExudynIndexError);

	return GetMeshNodeCoordinates(meshNodeNumber, ((CNodeODE2*)GetCNode(genericNodeNumber))->GetCoordinateVector_t(configuration));
}

//! return the (local) acceleration of a mesh node according to configuration type; meshNodeNumber is the local node number of the (underlying) mesh
Vector3D CObjectFFRFreducedOrder::GetMeshNodeLocalAcceleration(Index meshNodeNumber, ConfigurationType configuration) const
{
	CHECKandTHROW(meshNodeNumber < GetNumberOfMeshNodes(), "CObjectFFRFreducedOrder::GetMeshNodeLocalAcceleration: meshNodeNumber out of range (mesh node 0 is node 1 in ObjectFFRFreducedOrder)", ExudynIndexError);

	return GetMeshNodeCoordinates(meshNodeNumber, ((CNodeODE2*)GetCNode(genericNodeNumber))->GetCoordinateVector_tt(configuration));
}

//! return the (global) position of a mesh node according to configuration type; this is the node position transformed by the motion of the reference frame; meshNodeNumber is the local node number of the (underlying) mesh
Vector3D CObjectFFRFreducedOrder::GetMeshNodePosition(Index meshNodeNumber, ConfigurationType configuration) const
{
	CHECKandTHROW(meshNodeNumber < GetNumberOfMeshNodes(), "CObjectFFRFreducedOrder::GetMeshNodePosition: meshNodeNumber out of range (mesh node 0 is node 1 in ObjectFFRFreducedOrder)", ExudynIndexError);

	Matrix3D refRot = ((const CNodeRigidBody*)GetCNode(rigidBodyNodeNumber))->GetRotationMatrix(configuration);
	Vector3D refPos = ((const CNodeRigidBody*)GetCNode(rigidBodyNodeNumber))->GetPosition(configuration);

	return refPos + refRot * GetMeshNodeLocalPosition(meshNodeNumber, configuration); //no "+1", because it is already the mesh function
}

//! return the (global) velocity of a mesh node according to configuration type; this is the node position transformed by the motion of the reference frame; meshNodeNumber is the local node number of the (underlying) mesh
Vector3D CObjectFFRFreducedOrder::GetMeshNodeVelocity(Index meshNodeNumber, ConfigurationType configuration) const
{
	CHECKandTHROW(meshNodeNumber < GetNumberOfMeshNodes(), "CObjectFFRFreducedOrder::GetMeshNodeVelocity: meshNodeNumber out of range (mesh node 0 is node 1 in ObjectFFRFreducedOrder)", ExudynIndexError);

	// \dot R + A * \localOmega x \localPosition
	return ((CNodeRigidBody*)GetCNode(rigidBodyNodeNumber))->GetVelocity(configuration) +
		((CNodeRigidBody*)GetCNode(rigidBodyNodeNumber))->GetRotationMatrix(configuration) *
		((CNodeRigidBody*)GetCNode(rigidBodyNodeNumber))->GetAngularVelocityLocal(configuration).CrossProduct(GetMeshNodeLocalPosition(meshNodeNumber, configuration)) +
		((CNodeRigidBody*)GetCNode(rigidBodyNodeNumber))->GetRotationMatrix(configuration) * GetMeshNodeLocalVelocity(meshNodeNumber, configuration);
}

//! return the (global) velocity of a mesh node according to configuration type; this is the node position transformed by the motion of the reference frame; meshNodeNumber is the local node number of the (underlying) mesh
Vector3D CObjectFFRFreducedOrder::GetMeshNodeAcceleration(Index meshNodeNumber, ConfigurationType configuration) const
{
	CHECKandTHROW(meshNodeNumber < GetNumberOfMeshNodes(), "CObjectFFRFreducedOrder::GetMeshNodeAcceleration: meshNodeNumber out of range (mesh node 0 is node 1 in ObjectFFRF)", ExudynIndexError);

	Matrix3D A = ((CNodeRigidBody*)GetCNode(rigidBodyNodeNumber))->GetRotationMatrix(configuration);
	Vector3D xloc = GetMeshNodeLocalPosition(meshNodeNumber, configuration);
	Vector3D xglob = A * xloc;
	Vector3D vloc = GetMeshNodeLocalVelocity(meshNodeNumber, configuration);
	Vector3D aloc = GetMeshNodeLocalAcceleration(meshNodeNumber, configuration);
	Vector3D vglob = A * vloc;
	Vector3D omega = ((CNodeRigidBody*)GetCNode(rigidBodyNodeNumber))->GetAngularVelocity(configuration);
	Vector3D alpha = ((CNodeRigidBody*)GetCNode(rigidBodyNodeNumber))->GetAngularAcceleration(configuration);

	// \ddot R + A * \ddot xloc + 2*omega x vglob + alpha x xglob + omega x omega x xglob
	return ((CNodeRigidBody*)GetCNode(rigidBodyNodeNumber))->GetAcceleration(configuration) +
		A * aloc + 2 * omega.CrossProduct(vglob) + alpha.CrossProduct(xglob) + omega.CrossProduct(omega.CrossProduct(xglob));
}






