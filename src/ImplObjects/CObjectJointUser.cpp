//! the step of the central difference of dc/dt at velocity level, relative to the size of t
const Real jointUserDifferenceStep = 1e-6;

//! dc/d[p0, theta0, p1, theta1], n_c x 12, theta the global rotation increment of A(theta) = (I + skew(theta)) A: the
//! jacobianUserFunction, which an active joint must have; a constraint Jacobian is never approximated numerically in
//! Exudyn, as it gives artifacts (#3101)
void CObjectJointUser::ComputeJacobianIncrements(Matrix& jacobian, Real t, const Vector3D* positions, const Matrix3D* rotations) const
{
	CHECKandTHROW(parameters.jacobianUserFunction, "ObjectJointUser: jacobianUserFunction is not given", ExudynModelError);
	EvaluateUserFunctionJacobian(jacobian, t, positions[0], rotations[0], positions[1], rotations[1]);
}

//! the equations of the constraintUserFunction; at velocity level C [v0, omega0, v1, omega1] + dc/dt, the angular
//! velocities global and dc/dt by central differences
void CObjectJointUser::ComputeConstraintEquationsRigid(FlatArray<const MarkerRigid<Real>> markers, const LinkedDataVector& lambda, Real t,
	bool velocityLevel, ConstSizeVector<maxConstraintEquations>& equations) const
{
	const Index n = parameters.numberOfConstraints;
	Vector3D positions[2] = { markers[0].frame.GetTranslation(), markers[1].frame.GetTranslation() };
	Matrix3D rotations[2] = { markers[0].frame.GetRotation(), markers[1].frame.GetRotation() };
	Vector values;
	equations.SetNumberOfItems(n);
	if (!velocityLevel)
	{
		EvaluateUserFunctionConstraint(values, t, positions[0], rotations[0], positions[1], rotations[1]);
		for (Index i = 0; i < n; i++) { equations[i] = values[i]; }
		return;
	}

	Matrix jacobian;
	ComputeJacobianIncrements(jacobian, t, positions, rotations);
	Vector3D velocities[4] = { markers[0].velocity, rotations[0] * markers[0].angularVelocityLocal,
		markers[1].velocity, rotations[1] * markers[1].angularVelocityLocal };
	Real step = jointUserDifferenceStep * EXUstd::Maximum(1., fabs(t));
	Vector plus, minus;
	EvaluateUserFunctionConstraint(plus, t + step, positions[0], rotations[0], positions[1], rotations[1]);
	EvaluateUserFunctionConstraint(minus, t - step, positions[0], rotations[0], positions[1], rotations[1]);
	for (Index i = 0; i < n; i++)
	{
		Real value = (plus[i] - minus[i]) / (2. * step);
		for (Index l = 0; l < 12; l++) { value += jacobian(i, l) * velocities[l / 3][l % 3]; }
		equations[i] = value;
	}
}

//! the equations with their derivatives in the directions the markers are seeded with: per direction the increments of
//! the translations and the rotation increments theta, skew(dtheta) = dA A^T, times dc/d[p0, theta0, p1, theta1]
void CObjectJointUser::ComputeConstraintEquationsRigidDiff(FlatArray<const MarkerRigid<DRealRigidMarkers>> markers, const LinkedDataVector& lambda,
	Real t, ConstSizeVectorBase<DRealRigidMarkers, maxConstraintEquations>& equations) const
{
	const Index n = parameters.numberOfConstraints;
	const int nDirections = 12;
	Vector3D positions[2];
	Matrix3D rotations[2];
	ConstSizeMatrix<12 * 12> increments(12, nDirections); //increment l in direction j
	for (Index k = 0; k < 2; k++)
	{
		const SlimVectorBase<DRealRigidMarkers, 3>& position = markers[k].frame.GetTranslation();
		const ConstSizeMatrixBase<DRealRigidMarkers, 9> rotation = markers[k].frame.GetRotation();
		rotations[k].SetNumberOfRowsAndColumns(3, 3);
		for (Index i = 0; i < 3; i++)
		{
			positions[k][i] = position[i].Value();
			for (Index m = 0; m < 3; m++) { rotations[k](i, m) = rotation(i, m).Value(); }
		}
		for (int j = 0; j < nDirections; j++)
		{
			Matrix3D dA(3, 3);
			for (Index i = 0; i < 3; i++)
			{
				increments(6 * k + i, j) = position[i].DValue(j);
				for (Index m = 0; m < 3; m++) { dA(i, m) = rotation(i, m).DValue(j); }
			}
			Matrix3D W = dA * rotations[k].GetTransposed(); //skew(dtheta)
			increments(6 * k + 3, j) = W(2, 1);
			increments(6 * k + 4, j) = W(0, 2);
			increments(6 * k + 5, j) = W(1, 0);
		}
	}

	Vector values;
	EvaluateUserFunctionConstraint(values, t, positions[0], rotations[0], positions[1], rotations[1]);
	Matrix jacobian;
	ComputeJacobianIncrements(jacobian, t, positions, rotations);

	equations.SetNumberOfItems(n);
	for (Index i = 0; i < n; i++)
	{
		equations[i] = values[i];
		for (int j = 0; j < nDirections; j++)
		{
			Real value = 0.;
			for (Index l = 0; l < 12; l++) { value += jacobian(i, l) * increments(l, j); }
			equations[i].DValue(j) = value;
		}
	}
}

//! provide according output variable in "value"
void CObjectJointUser::GetOutputVariableConnector(OutputVariableType variableType, const MarkerDataStructure& markerData, Vector& value) const
{
	switch (variableType)
	{
	case OutputVariableType::Position: value.CopyFrom(markerData.GetMarkerData(0).position); break;
	case OutputVariableType::Displacement: value.CopyFrom(markerData.GetMarkerData(1).position - markerData.GetMarkerData(0).position); break;
	case OutputVariableType::Force:
	{
		value.SetNumberOfItems(parameters.numberOfConstraints);
		for (Index i = 0; i < parameters.numberOfConstraints; i++) { value[i] = GetCurrentAEcoordinate(i); }
		break;
	}
	default:
		SysError("CObjectJointUser::GetOutputVariable failed"); //error should not occur, because types are checked!
	}
}

//! nothing but the number, at marker 0
void VisualizationObjectJointUser::UpdateGraphics(const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemNumber)
{
	if (!visualizationSettings.connectors.showNumbers) { return; }
	const CObjectJointUser* cItem = (const CObjectJointUser*)vSystem->systemData->GetCObjects()[itemNumber];
	Vector3D position;
	vSystem->systemData->GetCMarkers()[cItem->GetParameters().markerNumbers[0]]->GetPosition(*vSystem->systemData, position, ConfigurationType::Visualization);
	Index itemID = Index2ItemID(itemNumber, ItemType::Object, vSystem->GetSystemID());
	EXUvis::DrawItemNumber(position, vSystem, itemID, "", visualizationSettings.connectors.defaultColor);
}
