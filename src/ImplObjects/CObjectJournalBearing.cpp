//! the eccentricity, its rate, the radial direction and the force on marker 0, the journal
void CObjectJournalBearing::ComputeBearingForce(const MarkerDataStructure& markerData, Vector3D& eccentricity, Vector3D& eccentricity_t,
	Vector3D& radial, Vector3D& force) const
{
	const MarkerData& journal = markerData.GetMarkerData(0);
	const MarkerData& bearing = markerData.GetMarkerData(1);
	const Matrix3D& A1 = bearing.orientation;
	Vector3D axis({ A1(0, 2), A1(1, 2), A1(2, 2) });
	Vector3D d = journal.position - bearing.position;
	eccentricity = d - (d * axis) * axis;
	//the relative velocity of the centers, the bearing turning with its marker
	Vector3D omega0 = journal.orientation * journal.angularVelocityLocal;
	Vector3D omega1 = A1 * bearing.angularVelocityLocal;
	Vector3D v = journal.velocity - (bearing.velocity + omega1.CrossProduct(d));
	eccentricity_t = v - (v * axis) * axis;
	Real angularVelocity = (omega0 + omega1) * axis;

	Real e = eccentricity.GetL2Norm();
	if (e > 0.) { radial = (1. / e) * eccentricity; }
	else { radial = Vector3D({ A1(0, 0), A1(1, 0), A1(2, 0) }); }
	force.SetAll(0.);
	if (!parameters.activeConnector) { return; }
	if (parameters.forceUserFunction)
	{
		EvaluateUserFunctionForce(force, cSystemData->GetMainSystemBacklink(), markerData.GetTime(), eccentricity, eccentricity_t,
			angularVelocity, axis);
		return;
	}
	Vector3D tangent = axis.CrossProduct(radial);
	Real c = parameters.bearingRadius - parameters.journalRadius;
	Real R = parameters.journalRadius;
	Real L = parameters.bearingLength;
	Real mu = parameters.viscosity;
	Real epsilon = EXUstd::Minimum(e / c, parameters.maximumEccentricityRatio);
	Real e_t = eccentricity_t * radial;
	Real epsilon_t = e_t / c;
	Real gamma_t = e > 0. ? (eccentricity_t * tangent) / e : 0.;
	Real w = angularVelocity - 2. * gamma_t;
	//the film in the gap converging in the direction of rotation, on either side: the wedge term of Fr with |w|, which
	//pulls the journal in for both directions; Ft changes its sign with w (#3345)
	Real wAbs = fabs(w);
	Real e2 = epsilon * epsilon;
	Real s = 1. - e2;
	Real pi = EXUstd::pi;
	Real Fr, Ft;
	if (parameters.bearingModel == JournalBearingModel::Short)
	{
		Real K = mu * R * L * L * L / (2. * c * c);
		Fr = -K * (2. * e2 * wAbs / (s * s) + pi * (1. + 2. * e2) * epsilon_t / (s * s * sqrt(s)));
		Ft = K * (pi * epsilon * w / (2. * s * sqrt(s)) + 4. * epsilon * epsilon_t / (s * s));
	}
	else
	{
		Real K = 12. * mu * L * R * R * R / (c * c);
		Fr = -K * (e2 * wAbs / ((2. + e2) * s) + epsilon_t / (s * sqrt(s)) * (0.5 * pi - 8. / (pi * (2. + e2))));
		Ft = K * (pi * epsilon * w / (2. * (2. + e2) * sqrt(s)) + 2. * epsilon * epsilon_t / ((2. + e2) * s));
	}
	force = Fr * radial + Ft * tangent;
	if (e > c) //the contact beyond the clearance
	{
		force -= (parameters.contactStiffness * (e - c) + parameters.contactDamping * e_t) * radial;
	}
}

//! the forces and torques of the connector interface (#2745): the force on the journal at its center, its negative on
//! the bearing on the same line of action
void CObjectJournalBearing::ComputeConnectorForceRigid(const MarkerRigid<Real>* markers, Real t, Vector3D* forces, Vector3D* torques) const
{
	for (Index k = 0; k < 2; k++) { forces[k].SetAll(0.); torques[k].SetAll(0.); }
	if (!parameters.activeConnector) { return; }
	TemporaryMarkerDataStructure temporary; //the physics read a marker data structure, without Jacobians
	MarkerDataStructure& markerData = temporary.Get();
	MarkerDataFromKinematics(markers, t, markerData);
	Vector3D eccentricity, eccentricity_t, radial, force;
	ComputeBearingForce(markerData, eccentricity, eccentricity_t, radial, force);
	forces[0] = -1. * force;
	forces[1] = force;
	torques[1] = (markerData.GetMarkerData(0).position - markerData.GetMarkerData(1).position).CrossProduct(force);
}

//! provide according output variable in "value"
void CObjectJournalBearing::GetOutputVariableConnector(OutputVariableType variableType, const MarkerDataStructure& markerData, Vector& value) const
{
	Vector3D eccentricity, eccentricity_t, radial, force;
	ComputeBearingForce(markerData, eccentricity, eccentricity_t, radial, force);
	switch (variableType)
	{
	case OutputVariableType::Displacement: value.CopyFrom(eccentricity); break;
	case OutputVariableType::Velocity: value.CopyFrom(eccentricity_t); break;
	case OutputVariableType::Distance: value.CopyFrom(Vector1D({ parameters.bearingRadius - parameters.journalRadius - eccentricity.GetL2Norm() })); break;
	case OutputVariableType::Director1: value.CopyFrom(radial); break;
	case OutputVariableType::Force: value.CopyFrom(force); break;
	default:
		SysError("CObjectJournalBearing::GetOutputVariableConnector failed"); //error should not occur, because types are checked!
	}
}

void VisualizationObjectJournalBearing::UpdateGraphics(const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemNumber)
{
	Index itemID = Index2ItemID(itemNumber, ItemType::Object, vSystem->GetSystemID());
	CObjectJournalBearing* cItem = (CObjectJournalBearing*)vSystem->systemData->GetCObjects()[itemNumber];
	const auto& parameters = cItem->GetParameters();
	if (DrawContactForces(visualizationSettings, parameters.forceUserFunction) && parameters.activeConnector)
	{
		//the force of the film on the journal, marker 0, at the journal surface towards the eccentricity (#3339)
		MarkerDataStructure markerData;
		VisualizationMarkerData(*vSystem->systemData, cItem->GetMarkerNumbers(), markerData);
		Vector3D eccentricity, eccentricity_t, radial, force;
		cItem->ComputeBearingForce(markerData, eccentricity, eccentricity_t, radial, force);
		DrawContactForce(visualizationSettings, vSystem, itemID, markerData.GetMarkerData(0).position + parameters.journalRadius * radial, force);
	}
	if (!visualizationSettings.contact.show.cylinders) { return; }
	Float4 cylinderColor = visualizationSettings.contact.color.cylinders;
	if (color[0] != -1.f) { cylinderColor = color; }
	for (Index i = 0; i < 2; i++)
	{
		Vector3D position;
		Matrix3D A;
		vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[i]]->GetPosition(*vSystem->systemData, position, ConfigurationType::Visualization);
		vSystem->systemData->GetCMarkers()[cItem->GetMarkerNumbers()[1]]->GetRotationMatrix(*vSystem->systemData, A, ConfigurationType::Visualization);
		Vector3D axis = parameters.bearingLength * Vector3D({ A(0, 2), A(1, 2), A(2, 2) });
		if (i == 0) //the journal, a bit longer than the bearing
		{
			EXUvis::DrawCylinder(position - 0.6 * axis, 1.2 * axis, parameters.journalRadius, cylinderColor, vSystem->graphicsData, itemID,
				visualizationSettings.general.cylinderTiling);
		}
		else //the bearing as a tube
		{
			EXUvis::DrawCylinder(position - 0.5 * axis, axis, 1.2 * parameters.bearingRadius, cylinderColor, vSystem->graphicsData, itemID,
				visualizationSettings.general.cylinderTiling, parameters.bearingRadius);
		}
	}
}
