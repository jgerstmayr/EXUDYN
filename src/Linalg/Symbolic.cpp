//the copies of a recording for the threads of the parallel loops (#2978)

//! a leaf of values: a number, a vector or a matrix, named or not
static bool IsValueLeaf(const FlatNode& node)
{
	switch (node.kind)
	{
	case FlatKind::Real: return dynamic_cast<const ExpressionReal*>((const ExpressionBase*)node.node) != nullptr;
	case FlatKind::Vector: return dynamic_cast<const VectorExpressionReal*>((const VectorExpressionBase*)node.node) != nullptr;
	default: return dynamic_cast<const MatrixExpressionReal*>((const MatrixExpressionBase*)node.node) != nullptr;
	}
}

bool SymbolicFunction::ThreadCopiesPossible() const
{
	if (flatProgram.IsBuilt())
	{
		for (Index k = 0; k < flatProgram.NumberOfOperations(); k++)
		{
			if (flatProgram.NumberOfOperationOperands(k) == 0 && !IsValueLeaf(flatProgram.OperationNode(k))) { return false; }
		}
		return true;
	}
	FlatNode root = ResultNode();
	if (root.node == nullptr) { return true; } //a constant
	if (!IsValueLeaf(root)) { return false; }
	for (Index i = 0; i < argRealList.NumberOfItems(); i++) //an argument is written by each evaluation
	{
		const SymbolicGeneric& argument = argRealList[i];
		if ((argument.IsReal() && argument.GetReal() && (const void*)argument.GetReal()->GetExpression() == root.node)
			|| (argument.IsVector() && argument.GetVector() && (const void*)argument.GetVector()->GetExpression() == root.node)
			|| (argument.IsMatrix() && argument.GetMatrix() && (const void*)argument.GetMatrix()->GetExpression() == root.node)) { return false; }
	}
	return true;
}

void SymbolicFunction::DeleteThreadCopies()
{
	for (ThreadCopy* copy : threadCopies)
	{
		copy->flatProgram.Clear();
		copy->symbolicProgram.Clear();
		if (copy->root.node) { Optimizer::Release(copy->root); } //its operations; the leaves of its arguments stay referenced by the copy
		for (const FlatNode& argument : copy->arguments) { if (argument.node) { Optimizer::Release(argument); } }
		delete copy;
	}
	threadCopies.clear();
}

void SymbolicFunction::PrepareThreads(Index numberOfThreads)
{
	if (!CanEvaluateInThreads()) { return; }
	//the leaves of the arguments in the recording, which each copy replaces by its own
	std::unordered_map<const void*, Index> argumentOfLeaf;
	for (Index i = 0; i < argRealList.NumberOfItems(); i++)
	{
		const SymbolicGeneric& argument = argRealList[i];
		if (argument.IsReal() && argument.GetReal()) { argumentOfLeaf[argument.GetReal()->GetExpression()] = i; }
		else if (argument.IsVector() && argument.GetVector()) { argumentOfLeaf[argument.GetVector()->GetExpression()] = i; }
		else if (argument.IsMatrix() && argument.GetMatrix()) { argumentOfLeaf[argument.GetMatrix()->GetExpression()] = i; }
	}
	Index n = flatProgram.NumberOfOperations();
	std::vector<FlatNode> nodes(n);
	std::vector<FlatNode> operands;
	while ((Index)threadCopies.size() < numberOfThreads - 1)
	{
		ThreadCopy* copy = new ThreadCopy();
		copy->arguments.assign(argRealList.NumberOfItems(), FlatNode());
		if (!flatProgram.IsBuilt()) { threadCopies.push_back(copy); continue; } //a constant result: no arguments, the result read
for (Index k = 0; k < n; k++) //in the order of the program: the operands before their users
		{
			const FlatNode& node = flatProgram.OperationNode(k);
			Index m = flatProgram.NumberOfOperationOperands(k);
			if (m == 0)
			{
				auto found = argumentOfLeaf.find(node.node);
				if (found == argumentOfLeaf.end()) { nodes[k] = node; continue; } //a number or a variable: shared
				//a new leaf of the same name and value, as the other nodes referenced by its users, and by the copy
				switch (node.kind)
				{
				case FlatKind::Real:
				{
					const ExpressionNamedReal* leaf = (const ExpressionNamedReal*)node.node;
					ExpressionNamedReal* newLeaf = new ExpressionNamedReal(leaf->GetName(), leaf->GetValue());
					ExpressionBase::NewCount()++;
					nodes[k] = FlatNode((const ExpressionBase*)newLeaf);
					break;
				}
				case FlatKind::Vector:
				{
					const VectorExpressionNamedReal* leaf = (const VectorExpressionNamedReal*)node.node;
					VectorExpressionNamedReal* newLeaf = new VectorExpressionNamedReal(leaf->GetVector(), leaf->GetName());
					VectorExpressionBase::NewCount()++;
					nodes[k] = FlatNode((const VectorExpressionBase*)newLeaf);
					break;
				}
				default:
				{
					const MatrixExpressionNamedReal* leaf = (const MatrixExpressionNamedReal*)node.node;
					MatrixExpressionNamedReal* newLeaf = new MatrixExpressionNamedReal(leaf->GetMatrix(), leaf->GetName());
					MatrixExpressionBase::NewCount()++;
					nodes[k] = FlatNode((const MatrixExpressionBase*)newLeaf);
					break;
				}
				}
				copy->arguments[found->second] = nodes[k]; //the reference of its constructor is the one of the copy
				continue;
			}
			operands.resize(m);
			for (Index i = 0; i < m; i++) { operands[i] = nodes[flatProgram.OperandSlot(k, i)]; }
			switch (node.kind)
			{
			case FlatKind::Real: nodes[k] = ((const ExpressionBase*)node.node)->NewWithOperands(operands.data()); ExpressionBase::NewCount()++; break;
			case FlatKind::Vector: nodes[k] = ((const VectorExpressionBase*)node.node)->NewWithOperands(operands.data()); VectorExpressionBase::NewCount()++; break;
			default: nodes[k] = ((const MatrixExpressionBase*)node.node)->NewWithOperands(operands.data()); MatrixExpressionBase::NewCount()++; break;
			}
			CHECKandTHROW(nodes[k].node != nullptr, "symbolic user function " + functionName + ": the expression class cannot be copied for a thread: "
				+ FlatProgramData::ToString(node));
			for (const FlatNode& operand : operands) { Optimizer::Reference(operand); }
		}
		copy->root = nodes[flatProgram.ResultSlot(0)];
		Optimizer::Reference(copy->root);
		copy->flatProgram.Build({ copy->root });
		copy->symbolicProgram.Build(copy->flatProgram);
		threadCopies.push_back(copy);
	}
}


//! esym.Optimize(expressions, level, mergeDuplicates) (#3085): the same structure as expressions, with new expressions
py::object OptimizeExpressions(const py::object& expressions, Index level, bool mergeDuplicates)
{
	bool isList = py::isinstance<py::list>(expressions) || py::isinstance<py::tuple>(expressions);
	std::vector<py::object> objects = FlatProgramRoots(expressions);
	bool recording = SReal::recordExpressions;
	SReal::recordExpressions = true; //a vector argument without size gives no error, as while recording
	Optimizer optimizer(level, mergeDuplicates);
	py::list results;
	try
	{
		std::vector<FlatNode> roots;
		for (const py::object& x : objects)
		{
			FlatNode root;
			if (py::isinstance<SReal>(x)) { root = FlatNode(py::cast<const SReal&>(x).GetExpression()); }
			else if (py::isinstance<SymbolicRealVector>(x)) { root = FlatNode(py::cast<const SymbolicRealVector&>(x).GetExpression()); }
			else if (py::isinstance<SymbolicRealMatrix>(x)) { root = FlatNode(py::cast<const SymbolicRealMatrix&>(x).GetExpression()); }
			else { throw py::type_error("Optimize: expected exudyn.symbolic.Real, Vector or Matrix, but received " + py::cast<STDstring>(py::str(x))); }
			roots.push_back(root.node ? optimizer.Optimized(root) : root);
		}
		for (Index i = 0; i < (Index)roots.size(); i++)
		{
			const FlatNode& root = roots[i];
			Real value;
			if (root.node == nullptr) { results.append(objects[i]); } //a number, which has no expression
			else if (Optimizer::IsNumberLeaf(root, value)) { results.append(py::cast(SReal(value))); }
			else if (root.kind == FlatKind::Real) { results.append(py::cast(SReal((ExpressionBase*)root.node))); }
			else if (root.kind == FlatKind::Vector) { results.append(py::cast(SymbolicRealVector((VectorExpressionBase*)root.node))); }
			else { results.append(py::cast(SymbolicRealMatrix((MatrixExpressionBase*)root.node))); }
		}
		optimizer.RemoveUnused();
	}
	catch (...)
	{
		SReal::recordExpressions = recording;
		throw;
	}
	SReal::recordExpressions = recording;
	return isList ? py::object(results) : py::object(results[0]);
}

//! ToString(format) of esym.Real, Vector, Matrix: 'Python' is the text of the tree, the others one expression of the writer
template<class TSymbolic>
STDstring SymbolicToString(const TSymbolic& x, const STDstring& format)
{
	if (format == "Python") { return x.ToString(); }
	py::object object = py::cast(x, py::return_value_policy::reference);
	return WriteFlatProgramFormat(FlatProgramDataOfExpressions(object, py::none(), py::none()), format, false, "", true);
}

//! the node of a named vector variable and the checked component, for Diff (#3115)
static const void* NamedVectorOfDiff(const SymbolicRealVector& variable, Index component, Index& size)
{
	if (!variable.IsExpressionNamedReal()) { PyError("symbolic Diff: the variable must be a named symbolic.Vector", PyErrorType::valueError); }
	const VectorExpressionNamedReal& named = variable.GetExpressionNamedReal();
	size = named.NumberOfItems();
	if (component < 0 || component >= size) { PyError("symbolic Diff: the component " + EXUstd::ToString(component)
		+ " is out of range of the vector variable of size " + EXUstd::ToString(size), PyErrorType::indexError); }
	return &named;
}

//! Diff of an expression: its derivatives by component of a variable with n components, at the current values, by the
//! one-pass derivative of the table (#3171); an expression without node - a number - gives zeros of its size
static std::vector<Real> DiffOfExpression(const FlatNode& root, Index size, const void* variable, Index n, Index component)
{
	std::vector<Real> result(size, 0.);
	if (root.node == nullptr) { return result; }
	std::vector<Real> derivatives;
	OnePassDerivative(root, variable, n, derivatives);
	for (Index c = 0; c < size; c++) { result[c] = derivatives[c*n + component]; }
	return result;
}

//! SReal.Diff, by a named Real or the component of a named vector
Real PyRealDiff(const SReal& item, const void* variable, Index n, Index component)
{
	return DiffOfExpression(FlatNode(item.GetExpression()), 1, variable, n, component)[0];
}

//! Vector.Diff: the derivative at the current values, as numpy array; a vector without expression gives zeros (#3115)
py::array_t<Real> PyVectorDiff(const SymbolicRealVector& item, const void* variable, Index n, Index component)
{
	Index size = item.GetExpression() ? item.NumberOfItems() : (Index)item.PyEvaluate().size();
	return EPyUtils::ToPython(ResizableConstVector(DiffOfExpression(FlatNode(item.GetExpression()), size, variable, n, component)));
}

//! Matrix.Diff, as PyVectorDiff (#3115)
py::array_t<Real> PyMatrixDiff(const SymbolicRealMatrix& item, const void* variable, Index n, Index component)
{
	py::array_t<Real> value = item.PyEvaluate();
	Index rows = (Index)value.shape(0), columns = (Index)value.shape(1);
	std::vector<Real> derivative = DiffOfExpression(FlatNode(item.GetExpression()), rows*columns, variable, n, component);
	ResizableMatrix result(rows, columns, 0.);
	for (Index c = 0; c < rows*columns; c++) { result.GetDataPointer()[c] = derivative[c]; }
	return EPyUtils::ToPython(result);
}

