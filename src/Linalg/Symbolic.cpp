{
	delete pyObject;
}

template <typename UFT>
PythonUserFunctionBase<UFT>::PythonUserFunctionBase() : pyObject(new PyUFobject()), ufType(UserFunctionType::_None), symbolicFunction(nullptr)
{
	*pyObject = py::cast((Index)0);
}

template <typename UFT>
void PythonUserFunctionBase<UFT>::SetPythonObject(const PyUFobject& pyObjectInit)
{
	symbolicFunction = nullptr; //set again by SetPythonUserFunction for a symbolic function
	if (py::isinstance<py::dict>(pyObjectInit))
	{
		py::dict pyDict = py::cast<py::dict>(pyObjectInit);
		CHECKandTHROW(pyDict.contains("function") && pyDict.contains("type"), "PythonUserFunctionBase::SetPythonObject: invalid function dictionary");

		STDstring typeString = py::cast<STDstring>(pyDict["type"]);

		//the dictionary of a symbolic user function, as GetDictionary writes it, sets it as symbolic again (#1888)
		if (typeString == "Symbolic" && py::isinstance<Symbolic::PySymbolicUserFunction>(pyDict["function"]))
		{
			SetPythonUserFunction(pyDict["function"]);
			return;
		}

		*pyObject = pyDict["function"];
		if (typeString == "Python") { ufType = UserFunctionType::Python; }
		else if (typeString == "Symbolic")
		{
			ufType = UserFunctionType::Symbolic;
			PyWarning("PythonUserFunctionBase::SetPythonObject: symbolic user functions are currently only copied as regular Python functions!");
		}
		else { PyError(STDstring("PythonUserFunctionBase::SetPythonObject: invalid function type: ") + typeString, PyErrorType::valueError); }
		userFunction = PythonUserFunctionToStdFunction(pyDict["function"], (UFT*)nullptr);

	}
	else if (py::isinstance<py::function>(pyObjectInit)) //old-style or first initialization
	{
		*pyObject = pyObjectInit;
		ufType = UserFunctionType::Python;
		userFunction = PythonUserFunctionToStdFunction(pyObjectInit, (UFT*)nullptr); //numpy arguments (#3008)
	}
	else if (EPyUtils::IsPyTypeInteger(pyObjectInit))
	{
		if (py::cast<int>(pyObjectInit) != 0)
		{
			PyError(STDstring("PythonUserFunction: Failed to convert PyFunction: must be either valid Python function or 0, but got ") + EXUstd::ToString(pyObjectInit), PyErrorType::typeError);
		}
		ufType = UserFunctionType::_None;
		*pyObject = py::cast<py::int_>(pyObjectInit); //cast for other int types
		userFunction = 0;
	}
	else //unknown
	{
		//this branch fires for ANYTHING that is not a function, not an integer and not a symbolic
		//function - a string, a list, a dict. That is a TypeError, whatever the message says; the
		//reference of parameterConversionTest showed it reporting NotImplementedFeatureError for
		//a list, which would be caught by "except NotImplementedError" (#2528)
		PyError(STDstring("PythonUserFunction: user function type currently not supported (only pure Python function)"), PyErrorType::typeError);
	}
}

//! set Python user function using PySymbolicFunction
template <typename UFT>
void PythonUserFunctionBase<UFT>::SetPythonUserFunction(const PyUFobject& pyObjectInit)
{
	if (py::isinstance<Symbolic::PySymbolicUserFunction>(pyObjectInit))
	{
		const auto& symUF = py::cast<Symbolic::PySymbolicUserFunction>(pyObjectInit);
		userFunction = symUF.GetSTDfunction<UFT>();

		*pyObject = pyObjectInit;
		ufType = UserFunctionType::Symbolic;
		symbolicFunction = py::cast<Symbolic::PySymbolicUserFunction*>(pyObjectInit); //the object pyObject holds
	}
	else //all other cases
	{
		SetPythonObject(pyObjectInit); //<UFT>
	}
}

