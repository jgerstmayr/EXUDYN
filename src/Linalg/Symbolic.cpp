//! the functions mbs.Get...Output calls, without Python and without the checks, which the recording did
const ResizableConstVector& VectorExpressionItemOutput::EvaluateRef() const
{
	if (mainSystem == nullptr) { return buffer; } //outside an evaluation of its function: the value at recording
	const CSystemData& data = mainSystem->GetCSystem().GetSystemData();
	OutputVariableType type = (OutputVariableType)variableType;
	ConfigurationType configurationType = (ConfigurationType)configuration;
	switch (kind)
	{
	case Kind::Node: data.GetCNodes()[itemNumber]->GetOutputVariable(type, configurationType, buffer); break;
	case Kind::Object:
	{
		const CObject* object = data.GetCObjects()[itemNumber];
		if ((Index)object->GetType() & (Index)CObjectType::Connector)
		{
			TemporaryMarkerDataStructure temporary; //as MainSystem::PyGetObjectOutputVariable
			MarkerDataStructure& markerDataStructure = temporary.Get();
			data.ComputeMarkerDataStructure((const CObjectConnector*)object, false, markerDataStructure);
			GetConnectorOutputVariable(*(const CObjectConnector*)object, type, markerDataStructure, buffer);
		}
		else { object->GetOutputVariable(type, buffer, configurationType); }
		break;
	}
	case Kind::ObjectBody: ((const CObjectBody*)data.GetCObjects()[itemNumber])->GetOutputVariableBody(type, localPosition, configurationType, buffer); break;
	case Kind::Marker: data.GetCMarkers()[itemNumber]->GetOutputVariable(data, type, configurationType, buffer); break;
	default: data.GetCSensors()[itemNumber]->GetSensorValues(data, buffer, configurationType); break;
	}
	return buffer;
}

STDstring VectorExpressionItemOutput::ToString() const
{
	const char* functions[] = { "GetNodeOutput", "GetObjectOutput", "GetObjectOutputBody", "GetMarkerOutput", "GetSensorValues" };
	STDstring text = STDstring("mbs.") + functions[(Index)kind] + "(" + EXUstd::ToString(itemNumber);
	if (kind != Kind::Sensor) { text += STDstring(", ") + GetOutputVariableTypeString((OutputVariableType)variableType); }
	if (kind == Kind::ObjectBody) { text += ", [" + EXUstd::ToString(localPosition[0]) + ", " + EXUstd::ToString(localPosition[1]) + ", " + EXUstd::ToString(localPosition[2]) + "]"; }
	const char* configurations[] = { "_None", "Initial", "Current", "Reference", "StartOfStep", "Visualization" };
	if ((ConfigurationType)configuration != ConfigurationType::Current && configuration >= 0 && configuration < 6) { text += STDstring(", ") + configurations[configuration]; }
	return text + ")";
}

//! esym._ItemOutput, for the MainSystem of CreateSymbolicUserFunction: the node of an output, with its value at recording
SymbolicRealVector ItemOutputExpression(const STDstring& kind, Index itemNumber, OutputVariableType variableType,
	ConfigurationType configuration, const std::vector<Real>& localPosition, const std::vector<Real>& valueAtRecording)
{
	const STDstring kinds[] = { "Node", "Object", "ObjectBody", "Marker", "Sensor" };
	Index k = 0;
	while (k < 5 && kinds[k] != kind) { k++; }
	CHECKandTHROW(k < 5, "symbolic._ItemOutput: invalid kind " + kind);
	CHECKandTHROW(localPosition.size() == 3, "symbolic._ItemOutput: localPosition must have 3 components");
	VectorExpressionBase::NewCount()++;
	return SymbolicRealVector(new VectorExpressionItemOutput((VectorExpressionItemOutput::Kind)k, itemNumber, (Index64)variableType,
		(Index)configuration, Vector3D({ localPosition[0], localPosition[1], localPosition[2] }), Vector(valueAtRecording)));
}

//! esym.GetDepth(expressions): the depth of each, in the structure of expressions (#3090)
py::object DepthOfExpressions(const py::object& expressions)
{
	bool isList = py::isinstance<py::list>(expressions) || py::isinstance<py::tuple>(expressions);
	std::vector<py::object> objects = isList ? py::cast<std::vector<py::object>>(expressions) : std::vector<py::object>{ expressions };
	py::list results;
	for (const py::object& x : objects)
	{
		FlatNode node;
		if (py::isinstance<SReal>(x)) { node = FlatNode(py::cast<const SReal&>(x).GetExpression()); }
		else if (py::isinstance<SymbolicRealVector>(x)) { node = FlatNode(py::cast<const SymbolicRealVector&>(x).GetExpression()); }
		else if (py::isinstance<SymbolicRealMatrix>(x)) { node = FlatNode(py::cast<const SymbolicRealMatrix&>(x).GetExpression()); }
		else { throw py::type_error("GetDepth: expected exudyn.symbolic.Real, Vector or Matrix, but received " + py::cast<STDstring>(py::str(x))); }
		results.append(node.node ? RecordedDepth(node) : 0);
	}
	return isList ? py::object(results) : py::object(results[0]);
}

//! VariableSet.Add(name, value) of a list or array: a named esym.Vector (1D) or esym.Matrix (2D) (#3149)
py::object AddArrayVariable(VariableSet& set, const STDstring& name, const py::object& value)
{
	py::array_t<Real> array = py::array_t<Real>::ensure(value);
	CHECKandTHROW(array && (array.ndim() == 1 || array.ndim() == 2), "VariableSet.Add: the value of '" + name + "' must be a number, a list or 1D array (a Vector) or a 2D array (a Matrix)", ExudynValueError);
	py::object variable = (array.ndim() == 1) ? py::cast(SymbolicRealVector(name, Vector(py::cast<std::vector<Real>>(value))))
		: py::cast(SymbolicRealMatrix(name, array));
	set.AddArray(name, variable);
	return variable;
}

//! VariableSet.Add(variable): a named esym.Real, Vector or Matrix under its name (#3149)
py::object AddNamedVariable(VariableSet& set, const py::object& variable)
{
	if (py::isinstance<SReal>(variable)) { set.AddVariable(py::cast<const SReal&>(variable)); return py::cast(set.GetVariable(py::cast<const SReal&>(variable).GetExpressionNamedReal().GetName())); }
	STDstring name;
	if (py::isinstance<SymbolicRealVector>(variable) && py::cast<const SymbolicRealVector&>(variable).IsExpressionNamedReal()) { name = py::cast<const SymbolicRealVector&>(variable).GetExpressionNamedReal().GetName(); }
	else if (py::isinstance<SymbolicRealMatrix>(variable) && py::cast<const SymbolicRealMatrix&>(variable).IsExpressionNamedReal()) { name = py::cast<const SymbolicRealMatrix&>(variable).GetExpressionNamedReal().GetName(); }
	else { throw py::type_error("VariableSet.Add: expected a named esym.Real, Vector or Matrix, but received " + py::cast<STDstring>(py::str(variable))); }
	set.AddArray(name, variable);
	return variable;
}

//! VariableSet.Set(name, value): a number for a Real, a list or array for a Vector or Matrix; a new name is added
void SetSetVariable(VariableSet& set, const STDstring& name, const py::object& value)
{
	if (!set.HasVariable(name))
	{
		if (py::isinstance<py::float_>(value) || py::isinstance<py::int_>(value)) { set.AddVariable(name, py::cast<Real>(value)); }
		else { AddArrayVariable(set, name, value); }
		return;
	}
	if (!set.IsArray(name)) { set.SetVariable(name, py::cast<Real>(value)); return; }
	const py::object& variable = set.GetArray(name);
	if (py::isinstance<SymbolicRealVector>(variable)) { py::cast<SymbolicRealVector&>(variable).SetExpressionNamedVector(ResizableConstVector(py::cast<std::vector<Real>>(value))); }
	else { py::cast<SymbolicRealMatrix&>(variable).SetSymbolicMatrix(py::array_t<Real>::ensure(value)); }
}

//! exudyn.special.deprecations.symbolicVariablesWithoutScope: a named variable of no scope, as before #3208
static bool VariablesWithoutScope()
{
	if (!pySpecial.deprecations.symbolicVariablesWithoutScope) { return false; }
	if (!pySpecial.deprecations.symbolicVariablesWithoutScopeReported)
	{
		pySpecial.deprecations.symbolicVariablesWithoutScopeReported = true;
		PyDeprecated("settings", "special.deprecations.symbolicVariablesWithoutScope", "exudyn.special.deprecations.symbolicVariablesWithoutScope: "
			"a named symbolic variable belongs to a scope, esym.variables or mbs.symbolicVariables; create those of a symbolic user function with esym.Real(name, value, scope=mbs)");
	}
	return true;
}

//! the scope of a named variable created in Python (#3208): esym.variables for None, the scope of a MainSystem, or a VariableSet
static VariableSet& ScopeOfNamedVariable(const py::object& scope, const STDstring& name)
{
	if (SReal::recordingFunction) { PyError("exudyn.symbolic: the named variable '" + name + "' is created while a user function is "
		"recorded; a named variable belongs to the model: create it before the recording, esym.Real(name, value, scope=mbs)", PyErrorType::valueError); }
	if (scope.is_none()) { return py::module_::import("exudyn").attr("symbolic").attr("variables").cast<VariableSet&>(); }
	if (py::isinstance<VariableSet>(scope)) { return py::cast<VariableSet&>(scope); }
	if (py::isinstance<MainSystem>(scope)) { return py::cast<MainSystem&>(scope).GetSymbolicVariables().cast<VariableSet&>(); }
	throw py::type_error("exudyn.symbolic: the scope of the named variable '" + name + "' must be None (esym.variables), a MainSystem "
		"(its symbolicVariables) or an esym.VariableSet, but received " + py::cast<STDstring>(py::str(scope)));
}

//! esym.Real(name, value, scope) (#3208): the variable of that name in its scope - a new one, or the one there, with the value set;
//! one of another kind of that name is replaced
SReal NamedRealInScope(const STDstring& name, Real value, const py::object& scope)
{
	if (!SReal::GetRecording() || VariablesWithoutScope()) { return SReal(name, value); } //without recording a number, as before
	VariableSet& set = ScopeOfNamedVariable(scope, name);
	if (set.HasVariable(name) && set.IsArray(name)) { set.RemoveVariable(name); }
	if (!set.HasVariable(name)) { set.AddVariable(name, value); }
	else { set.SetVariable(name, value); }
	return set.GetVariable(name);
}

//! esym.Vector(name, values, scope) and esym.Matrix(name, values, scope) (#3208), as NamedRealInScope
py::object NamedArrayInScope(const STDstring& name, const py::object& value, const py::object& scope, bool isMatrix)
{
	if (!SReal::GetRecording() || VariablesWithoutScope()) //without recording numbers, as before
	{
		return isMatrix ? py::cast(SymbolicRealMatrix(name, py::array_t<Real>::ensure(value))) : py::cast(SymbolicRealVector(name, Vector(py::cast<std::vector<Real>>(value))));
	}
	VariableSet& set = ScopeOfNamedVariable(scope, name);
	py::array_t<Real> array = py::array_t<Real>::ensure(value);
	CHECKandTHROW(array && array.ndim() == (isMatrix ? 2 : 1), STDstring("esym.") + (isMatrix ? "Matrix" : "Vector") + ": the value of '"
		+ name + "' must be a " + (isMatrix ? "2D" : "1D") + " list or array", ExudynValueError);
	bool sameKind = set.IsArray(name) && (isMatrix ? py::isinstance<SymbolicRealMatrix>(set.GetArray(name)) : py::isinstance<SymbolicRealVector>(set.GetArray(name)));
	if (sameKind) //and of the same size
	{
		py::array_t<Real> present = py::array_t<Real>::ensure(set.GetArray(name).attr("Evaluate")());
		sameKind = py::cast<py::tuple>(present.attr("shape")).equal(py::cast<py::tuple>(array.attr("shape")));
	}
	if (set.HasVariable(name) && !sameKind) { set.RemoveVariable(name); } //one of another kind or size is replaced
	if (!set.HasVariable(name)) { return AddArrayVariable(set, name, value); }
	SetSetVariable(set, name, value);
	return set.GetArray(name);
}

static void NamedVariablesOf(const py::object& x, std::vector<std::pair<const void*, STDstring>>& named);

//! true, if the named variable of this node is the variable of its name in the scope (#3208)
static bool IsVariableOfScope(VariableSet& scope, const void* node, const STDstring& name)
{
	return scope.HasVariable(name) && (scope.IsArray(name) ? FlatProgramData::NamedNode(scope.GetArray(name))
		: (const void*)scope.GetVariable(name).GetExpression()) == node;
}

//! the named variables of one or a list of esym.Real, Vector and Matrix, each name once, in the order found (#3208)
static void NamedVariablesOfList(const py::object& expressions, std::vector<std::pair<const void*, STDstring>>& namedVariables)
{
	if (py::isinstance<py::list>(expressions) || py::isinstance<py::tuple>(expressions))
	{
		for (const auto& item : expressions) { NamedVariablesOf(py::reinterpret_borrow<py::object>(item), namedVariables); }
	}
	else { NamedVariablesOf(expressions, namedVariables); }
}

//! esym._VariablesNotInScope (#3208): the names of the named variables of the expressions that are not those of the scope
py::list VariablesNotInScope(const py::object& expressions, VariableSet& scope)
{
	std::vector<std::pair<const void*, STDstring>> namedVariables;
	NamedVariablesOfList(expressions, namedVariables);
	py::list names;
	std::unordered_set<const void*> found; //each variable once, also if several expressions have it
	for (const auto& [node, name] : namedVariables)
	{
		if (found.insert(node).second && !IsVariableOfScope(scope, node, name)) { names.append(name); }
	}
	return names;
}

//! the check of a recording of CreateSymbolicUserFunction (#3208): every named variable of the result is an argument or a
//! variable of the scope of the MainSystem, the same node
void CheckVariablesOfRecording(const py::object& returnValue, const py::list& arguments, MainSystem& mainSystem, const STDstring& name)
{
	if (VariablesWithoutScope()) { return; }
	std::vector<const void*> argumentNodes;
	for (const auto& argument : arguments)
	{
		const void* node = FlatProgramData::NamedNode(py::reinterpret_borrow<py::object>(argument));
		if (node) { argumentNodes.push_back(node); }
	}
	std::vector<std::pair<const void*, STDstring>> namedVariables;
	NamedVariablesOfList(returnValue, namedVariables);
	VariableSet& scope = mainSystem.GetSymbolicVariables().cast<VariableSet&>();
	for (const auto& [node, variableName] : namedVariables)
	{
		if (std::find(argumentNodes.begin(), argumentNodes.end(), node) != argumentNodes.end()) { continue; }
		if (!IsVariableOfScope(scope, node, variableName)) { PyError("CreateSymbolicUserFunction " + name + ": the function reads the named variable '" + variableName
			+ "', which is not in mbs.symbolicVariables, the scope of the model; create it with esym.Real('" + variableName
			+ "', value, scope=mbs) - or esym.Vector, esym.Matrix - before the recording", PyErrorType::valueError); }
	}
}

//! esym.Function(result, inputs, name) (#3149): a recording of an expression in declared inputs, without an item;
//! a UserFunction whose arguments are the inputs, in their order, and which needs no MainSystem
//! the named variables of an esym.Real, Vector or Matrix, each node with its name, by a traversal without recursion (#3198)
static void NamedVariablesOf(const py::object& x, std::vector<std::pair<const void*, STDstring>>& named)
{
	FlatNode root;
	if (py::isinstance<SReal>(x)) { root = FlatNode(py::cast<const SReal&>(x).GetExpression()); }
	else if (py::isinstance<SymbolicRealVector>(x)) { root = FlatNode(py::cast<const SymbolicRealVector&>(x).GetExpression()); }
	else if (py::isinstance<SymbolicRealMatrix>(x)) { root = FlatNode(py::cast<const SymbolicRealMatrix&>(x).GetExpression()); }
	if (root.node == nullptr) { return; }
	std::unordered_set<const void*> visited{ root.node };
	std::vector<FlatNode> stack{ root };
	while (stack.size())
	{
		FlatNode node = stack.back();
		stack.pop_back();
		Index n = FlatProgramData::NumberOfOperands(node);
		for (Index i = 0; i < n; i++)
		{
			FlatNode operand = FlatProgramData::GetOperand(node, i);
			if (visited.insert(operand.node).second) { stack.push_back(operand); }
		}
		if (n != 0) { continue; }
		if (node.kind == FlatKind::Real)
		{
			const ExpressionNamedReal* variable = dynamic_cast<const ExpressionNamedReal*>((const ExpressionBase*)node.node);
			if (variable) { named.push_back({ node.node, variable->GetName() }); }
		}
		else if (node.kind == FlatKind::Vector)
		{
			const VectorExpressionNamedReal* variable = dynamic_cast<const VectorExpressionNamedReal*>((const VectorExpressionBase*)node.node);
			if (variable) { named.push_back({ node.node, variable->GetName() }); }
		}
		else
		{
			const MatrixExpressionNamedReal* variable = dynamic_cast<const MatrixExpressionNamedReal*>((const MatrixExpressionBase*)node.node);
			if (variable) { named.push_back({ node.node, variable->GetName() }); }
		}
	}
}

py::object FunctionOfExpression(const py::object& result, const py::object& inputs, const STDstring& name)
{
	std::vector<py::object> inputList;
	if (py::isinstance<VariableSet>(inputs))
	{
		VariableSet& set = py::cast<VariableSet&>(inputs);
		for (const STDstring& key : set.GetNames()) { inputList.push_back(set.IsArray(key) ? set.GetArray(key) : py::cast(set.GetVariable(key))); }
	}
	else if (py::isinstance<py::list>(inputs) || py::isinstance<py::tuple>(inputs)) { inputList = py::cast<std::vector<py::object>>(inputs); }
	else { inputList = { inputs }; }
	py::list argList, argTypeList, argNameList;
	argList.append(py::none()); argTypeList.append("MainSystem"); argNameList.append("mbs"); //skipped as for every user function
	std::vector<const void*> inputNodes;
	std::vector<STDstring> names;
	for (const py::object& input : inputList)
	{
		const void* node = FlatProgramData::NamedNode(input);
		//user input: PyError, which the fast module keeps (#3293)
		if (node == nullptr) { PyError("esym.Function: an input must be a named variable, esym.Real('x', 1.), esym.Vector('v', [...]) or esym.Matrix('M', [[...]]), but received " + py::cast<STDstring>(py::str(input)), PyErrorType::valueError); }
		STDstring inputName = py::isinstance<SReal>(input) ? py::cast<const SReal&>(input).GetExpressionNamedReal().GetName()
			: (py::isinstance<SymbolicRealVector>(input) ? py::cast<const SymbolicRealVector&>(input).GetExpressionNamedReal().GetName()
			: py::cast<const SymbolicRealMatrix&>(input).GetExpressionNamedReal().GetName());
		if (std::find(names.begin(), names.end(), inputName) != names.end()) { PyError("esym.Function: two inputs are named '" + inputName + "'", PyErrorType::valueError); }
		names.push_back(inputName);
		inputNodes.push_back(node);
		argList.append(input);
		argTypeList.append(py::isinstance<SReal>(input) ? "Real" : (py::isinstance<SymbolicRealVector>(input) ? "StdVector" : "NumpyMatrix"));
		argNameList.append(inputName);
	}
	py::object returnValue = result;
	if (py::isinstance<py::float_>(result) || py::isinstance<py::int_>(result)) { returnValue = py::cast(SReal(py::cast<Real>(result))); }
	if (!(py::isinstance<SReal>(returnValue) || py::isinstance<SymbolicRealVector>(returnValue) || py::isinstance<SymbolicRealMatrix>(returnValue))) { PyError("esym.Function: the result must be an esym.Real, Vector or Matrix, but received " + py::cast<STDstring>(py::str(result)), PyErrorType::valueError); }
	//every named variable of the result is an input, or a variable of esym.variables, which the function reads at every call;
	//found by a traversal of the nodes, not by the entries of GetFlatProgramData, which cost 80 percent of the call (#3198)
	std::vector<std::pair<const void*, STDstring>> namedVariables;
	NamedVariablesOf(returnValue, namedVariables);
	VariableSet& globalVariables = py::module_::import("exudyn").attr("symbolic").attr("variables").cast<VariableSet&>();
	for (const auto& [node, variableName] : namedVariables)
	{
		if (std::find(inputNodes.begin(), inputNodes.end(), node) != inputNodes.end()) { continue; }
		bool global = globalVariables.HasVariable(variableName) && !globalVariables.IsArray(variableName)
			&& (const void*)globalVariables.GetVariable(variableName).GetExpression() == node;
		if (!global) { PyError("esym.Function " + name + ": the result depends on the variable '" + variableName
			+ "', which is no input and not in esym.variables", PyErrorType::valueError); }
	}
	py::dict functionDict;
	functionDict["functionName"] = name;
	functionDict["argList"] = argList;
	functionDict["argTypeList"] = argTypeList;
	functionDict["argNameList"] = argNameList;
	functionDict["returnValue"] = returnValue;
	functionDict["returnType"] = py::isinstance<SReal>(returnValue) ? "Real" : (py::isinstance<SymbolicRealVector>(returnValue) ? "StdVector" : "NumpyMatrix");
	functionDict["withoutMainSystem"] = true;
	PySymbolicUserFunction* function = new PySymbolicUserFunction();
	function->SetupUserFunction(functionDict, "Function", name);
	return py::cast(function, py::return_value_policy::take_ownership);
}

//! the name of a node in the counts of GetStatistics: the FlatName of an operation, number, variable or itemOutput of a leaf
static const char* StatisticsName(const FlatNode& node)
{
	if (FlatProgramData::NumberOfOperands(node) != 0)
	{
		const char* name = OperationName(node); //of the table, or of the node (#3153)
		return name[0] ? name : "unnamed";
	}
	switch (node.kind)
	{
	case FlatKind::Real:
	{
		const ExpressionBase* e = (const ExpressionBase*)node.node;
		if (dynamic_cast<const ExpressionNamedReal*>(e)) { return "variable"; }
		return dynamic_cast<const ExpressionReal*>(e) ? "number" : "leaf";
	}
	case FlatKind::Vector:
	{
		const VectorExpressionBase* e = (const VectorExpressionBase*)node.node;
		if (dynamic_cast<const VectorExpressionNamedReal*>(e)) { return "variable"; }
		if (dynamic_cast<const VectorExpressionItemOutput*>(e)) { return "itemOutput"; }
		return dynamic_cast<const VectorExpressionReal*>(e) ? "number" : "leaf";
	}
	default:
	{
		const MatrixExpressionBase* e = (const MatrixExpressionBase*)node.node;
		if (dynamic_cast<const MatrixExpressionNamedReal*>(e)) { return "variable"; }
		return dynamic_cast<const MatrixExpressionReal*>(e) ? "number" : "leaf";
	}
	}
}

//! the counts of esym.GetStatistics and UserFunction.GetStatistics (#3142), from the flat program of the roots - one
//! traversal without recursion -; numbers: results that are no expression, each counted as a leaf
py::dict StatisticsOfNodes(const std::vector<FlatNode>& roots, Index numbers, bool detailed)
{
	FlatProgram program;
	if (roots.size()) { program.Build(roots); }
	Index n = roots.size() ? program.NumberOfOperations() : 0;
	std::vector<Index> uses(n, 0);
	std::vector<Index> depth(n, 0);
	std::vector<Real> treeSize(n, 1.);	//a float: with shared nodes it grows exponentially
	std::map<STDstring, Index> byOperation;
	std::map<STDstring, Index> byKind;
	Index leaves = numbers;
	for (Index k = 0; k < n; k++)
	{
		Index m = program.NumberOfOperationOperands(k);
		leaves += (m == 0);
		for (Index i = 0; i < m; i++)
		{
			Index operand = program.OperandSlot(k, i);
			uses[operand]++;
			depth[k] = EXUstd::Maximum(depth[k], depth[operand] + 1);
			treeSize[k] += treeSize[operand];
		}
		if (detailed)
		{
			const FlatNode& node = program.OperationNode(k);
			byOperation[StatisticsName(node)]++;
			byKind[FlatProgramData::KindName(node.kind)]++;
		}
	}
	Index shared = 0;
	for (Index k = 0; k < n; k++) { shared += (uses[k] > 1); }
	Real totalTreeSize = (Real)numbers;
	Index maximumDepth = 0;
	for (Index i = 0; i < (Index)roots.size(); i++)
	{
		totalTreeSize += treeSize[program.ResultSlot(i)];
		maximumDepth = EXUstd::Maximum(maximumDepth, depth[program.ResultSlot(i)]);
	}
	py::dict statistics;
	statistics["nodes"] = n + numbers;
	statistics["operations"] = n + numbers - leaves;
	statistics["leaves"] = leaves;
	statistics["shared"] = shared;
	statistics["depth"] = maximumDepth;
	statistics["treeSize"] = totalTreeSize;
	statistics["flatOperations"] = roots.size() ? program.NumberOfComputations() : 0;
	SymbolicProgram tableProgram; //the operations computed by the table (#3153)
	if (roots.size() && program.NumberOfOperations()) { tableProgram.Build(program); }
	statistics["tableOperations"] = tableProgram.NumberOfTableSteps();
	if (detailed)
	{
		if (numbers) { byOperation["number"] += numbers; byKind["Real"] += numbers; }
		py::dict operationCounts, kindCounts;
		for (const auto& item : byOperation) { operationCounts[py::str(item.first)] = item.second; }
		for (const auto& item : byKind) { kindCounts[py::str(item.first)] = item.second; }
		statistics["byOperation"] = operationCounts;
		statistics["byKind"] = kindCounts;
	}
	return statistics;
}

//! esym.GetStatistics(expressions, detailed), and GetStatistics() of esym.Real, Vector and Matrix (#3142)
py::dict StatisticsOfExpressions(const py::object& expressions, bool detailed)
{
	bool isList = py::isinstance<py::list>(expressions) || py::isinstance<py::tuple>(expressions);
	std::vector<py::object> objects = isList ? py::cast<std::vector<py::object>>(expressions) : std::vector<py::object>{ expressions };
	std::vector<FlatNode> roots;
	Index numbers = 0;
	for (const py::object& x : objects)
	{
		FlatNode node;
		if (py::isinstance<SReal>(x)) { node = FlatNode(py::cast<const SReal&>(x).GetExpression()); }
		else if (py::isinstance<SymbolicRealVector>(x)) { node = FlatNode(py::cast<const SymbolicRealVector&>(x).GetExpression()); }
		else if (py::isinstance<SymbolicRealMatrix>(x)) { node = FlatNode(py::cast<const SymbolicRealMatrix&>(x).GetExpression()); }
		else if (py::isinstance<py::float_>(x) || py::isinstance<py::int_>(x)) {}
		else { throw py::type_error("GetStatistics: expected exudyn.symbolic.Real, Vector or Matrix, or a number, but received " + py::cast<STDstring>(py::str(x))); }
		if (node.node) { roots.push_back(node); }
		else { numbers++; }
	}
	return StatisticsOfNodes(roots, numbers, detailed);
}

//! UserFunction.GetStatistics(detailed): the counts of its recorded result (#3142)
py::dict StatisticsOfUserFunction(const PySymbolicUserFunction& function, bool detailed)
{
	const SymbolicGeneric& returnValue = function.GetReturnValue();
	FlatNode node;
	if (returnValue.IsReal() && returnValue.GetReal()) { node = FlatNode(returnValue.GetReal()->GetExpression()); }
	else if (returnValue.IsVector() && returnValue.GetVector()) { node = FlatNode(returnValue.GetVector()->GetExpression()); }
	else if (returnValue.IsMatrix() && returnValue.GetMatrix()) { node = FlatNode(returnValue.GetMatrix()->GetExpression()); }
	else { throw py::value_error("UserFunction.GetStatistics: the user function has no recorded result"); }
	if (node.node) { return StatisticsOfNodes({ node }, 0, detailed); }
	return StatisticsOfNodes({}, 1, detailed); //a constant result
}

//! the expressions: one esym.Real, Vector or Matrix, or a list or tuple of them
std::vector<py::object> FlatProgramRoots(const py::object& expressions)
{
	if (py::isinstance<py::list>(expressions) || py::isinstance<py::tuple>(expressions)) { return py::cast<std::vector<py::object>>(expressions); }
	return { expressions };
}

//! the names of the results: given, or result for one, result[i] for several, as FlatProgram::ToString
std::vector<STDstring> FlatProgramResultNames(const py::object& resultNames, Index numberOfResults)
{
	std::vector<STDstring> names;
	if (!resultNames.is_none()) { names = py::cast<std::vector<STDstring>>(resultNames); }
	CHECKandTHROW(resultNames.is_none() || (Index)names.size() == numberOfResults, "GetFlatProgramData: resultNames must have one name per expression");
	if (resultNames.is_none())
	{
		for (Index i = 0; i < numberOfResults; i++) { names.push_back(numberOfResults == 1 ? "result" : "result[" + EXUstd::ToString(i) + "]"); }
	}
	return names;
}

//! esym.GetFlatProgramData(expressions, arguments, resultNames) (#3087)
py::dict FlatProgramDataOfExpressions(const py::object& expressions, const py::object& arguments, const py::object& resultNames)
{
	FlatProgramData data;
	std::vector<py::object> roots = FlatProgramRoots(expressions);
	std::vector<STDstring> names = FlatProgramResultNames(resultNames, (Index)roots.size());
	py::list results;
	for (Index i = 0; i < (Index)roots.size(); i++)
	{
		Index slot = data.Add(roots[i]);
		py::dict result;
		result["name"] = names[i];
		result["node"] = slot;
		result["kind"] = data.Entry(slot)["kind"];
		results.append(result);
	}
	py::list argumentList;
	if (arguments.is_none()) //the named variables, in the order of their first appearance
	{
		for (Index i = 0; i < (Index)data.NamedNodes().size(); i++) { argumentList.append(FlatProgramData::ArgumentEntry(data.NamedEntry(i))); }
	}
	else
	{
		std::vector<const void*> given;
		for (const py::object& argument : FlatProgramRoots(arguments))
		{
			argumentList.append(data.ArgumentEntry(argument));
			given.push_back(FlatProgramData::NamedNode(argument));
		}
		for (Index i = 0; i < (Index)data.NamedNodes().size(); i++)
		{
			if (std::find(given.begin(), given.end(), data.NamedNodes()[i]) == given.end())
			{
				throw py::value_error("GetFlatProgramData: the expressions depend on the variable '" + py::cast<STDstring>(data.NamedEntry(i)["name"])
					+ "', which is not in arguments");
			}
		}
	}
	py::dict dict;
	dict["arguments"] = argumentList;
	dict["operations"] = data.Operations();
	dict["results"] = results;
	return dict;
}

//! UserFunction.GetFlatProgramData() (#3087): the arguments of the Python signature, the variables of
//! exudyn.symbolic.variables that the recording reads, the operations and the result
py::dict FlatProgramDataOfUserFunction(const PySymbolicUserFunction& function)
{
	FlatProgramData data;
	const SymbolicGeneric& returnValue = function.GetReturnValue();
	Index slot = -1;
	if (returnValue.IsReal() && returnValue.GetReal()) { slot = data.Add(*returnValue.GetReal()); }
	else if (returnValue.IsVector() && returnValue.GetVector()) { slot = data.Add(*returnValue.GetVector()); }
	else if (returnValue.IsMatrix() && returnValue.GetMatrix()) { slot = data.Add(*returnValue.GetMatrix()); }
	CHECKandTHROW(slot >= 0, "UserFunction.GetFlatProgramData: the user function has no recorded result");

	const py::dict& functionDict = function.GetFunctionDict();
	py::list argList = functionDict["argList"];
	py::list argTypeList = functionDict["argTypeList"];
	py::list argNameList = functionDict.contains("argNameList") ? py::list(functionDict["argNameList"]) : py::list();
	py::list argumentList;
	std::vector<const void*> argumentNodes;
	for (Index i = 0; i < (Index)py::len(argList); i++)
	{
		py::object argument = argList[i];
		STDstring type = py::cast<STDstring>(argTypeList[i]);
		py::dict entry;
		if (type == "MainSystem" && functionDict.contains("withoutMainSystem")) { continue; } //esym.Function (#3149)
		if (type == "MainSystem") { entry["name"] = "mbs"; entry["kind"] = "MainSystem"; }
		else { entry = data.ArgumentEntry(argument); argumentNodes.push_back(FlatProgramData::NamedNode(argument)); }
		if (i < (Index)py::len(argNameList)) { entry["name"] = argNameList[i]; }
		entry["type"] = type;
		argumentList.append(entry);
	}
	py::list variables; //named variables that are no arguments: exudyn.symbolic.variables
	for (Index i = 0; i < (Index)data.NamedNodes().size(); i++)
	{
		if (std::find(argumentNodes.begin(), argumentNodes.end(), data.NamedNodes()[i]) == argumentNodes.end())
		{
			variables.append(FlatProgramData::ArgumentEntry(data.NamedEntry(i)));
		}
	}
	py::list results;
	py::dict result;
	result["name"] = "result";
	result["node"] = slot;
	result["kind"] = data.Entry(slot)["kind"];
	results.append(result);

	py::dict dict;
	dict["name"] = function.GetFunctionName();
	dict["arguments"] = argumentList;
	dict["variables"] = variables;
	dict["operations"] = data.Operations();
	dict["results"] = results;
	return dict;
}

