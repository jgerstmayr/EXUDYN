template <typename UFT>
PyUFobject PythonUserFunctionBase<UFT>::GetPythonDictionary() const
{
	switch (ufType)
	{
	case UserFunctionType::_None:
	{
		//CHECKandTHROW(py::isinstance<py::int_>(*pyObject) && py::cast<Index>(*pyObject) == 0, "PythonUserFunctionBase::GetPythonDictionary: 0 expected!");
		return py::cast((Index)0); //must be 0
	}
	case UserFunctionType::Python: //same as symbolic
	{
		auto d = py::dict();
		d["function"] = py::cast<py::function>(*pyObject);
		d["type"] = py::cast((STDstring)GetUserFunctionTypeString(ufType));
		return d;
	};
	case UserFunctionType::Symbolic:
	{
		auto d = py::dict();
		d["function"] = *pyObject;
		d["type"] = py::cast((STDstring)GetUserFunctionTypeString(ufType));
		return d;
	};
	//case UserFunctionType::InternalCpp: return "InternalCpp";
	//case UserFunctionType::Jit: return "Jit";

	default:
		CHECKandTHROWstring("PythonUserFunctionBase::GetPythonDictionary(): failed: invalid function type");
	}
	return py::cast((Index)(-1));
}

