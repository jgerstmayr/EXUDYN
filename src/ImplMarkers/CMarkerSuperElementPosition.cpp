//! position = framePosition + frameRotation * sum_i w_i (local position of mesh node i)
void CMarkerSuperElementPosition::GetPosition(const CSystemData& cSystemData, Vector3D& position, ConfigurationType configuration) const
{
	const CObjectSuperElement& cObject = (const CObjectSuperElement&)(cSystemData.GetCObjectBody(GetObjectNumber())); //always possible
	SuperElementMarkerInterface temp;
	const SuperElementMarkerInterface& markerInterfaceValid = ValidMarkerInterface(cObject, temp);

	Vector3D framePosition, frameVelocity, frameAngularVelocityLocal;
	Matrix3D frameRotationMatrix;
	cObject.GetReferenceFrame(framePosition, frameRotationMatrix, frameVelocity, frameAngularVelocityLocal, configuration);
	position = framePosition + frameRotationMatrix * cObject.GetMarkerLocalPosition(markerInterfaceValid, parameters.meshNodeNumbers, parameters.weightingFactors, configuration);
}

//! velocity = frameVelocity + frameRotation * (sum_i w_i v_i + frameAngularVelocityLocal x sum_i w_i x_i)
void CMarkerSuperElementPosition::GetVelocity(const CSystemData& cSystemData, Vector3D& velocity, ConfigurationType configuration) const
{
	const CObjectSuperElement& cObject = (const CObjectSuperElement&)(cSystemData.GetCObjectBody(GetObjectNumber())); //always possible
	SuperElementMarkerInterface temp;
	const SuperElementMarkerInterface& markerInterfaceValid = ValidMarkerInterface(cObject, temp);

	Vector3D framePosition, frameVelocity, frameAngularVelocityLocal;
	Matrix3D frameRotationMatrix;
	cObject.GetReferenceFrame(framePosition, frameRotationMatrix, frameVelocity, frameAngularVelocityLocal, configuration);
	Vector3D localVelocity = cObject.GetMarkerLocalVelocity(markerInterfaceValid, parameters.meshNodeNumbers, parameters.weightingFactors, configuration);
	localVelocity += frameAngularVelocityLocal.CrossProduct(cObject.GetMarkerLocalPosition(markerInterfaceValid, parameters.meshNodeNumbers, parameters.weightingFactors, configuration));
	velocity = frameVelocity + frameRotationMatrix * localVelocity;
}

