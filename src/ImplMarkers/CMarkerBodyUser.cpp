//! the coordinates of the nodes of the bodies, body by body in the order of bodyNumbers and of the nodes of each body - the
//! order in which the system composes the coordinates of the marker (ComputeMarkerODE2LTGarray)
void CMarkerBodyUser::GatherCoordinates(const CSystemData& cSystemData, ConfigurationType configuration, Vector& qRef, Vector& q, Vector& q_t) const
{
	Index n = 0;
	for (Index body : parameters.bodyNumbers) { n += ((const CObjectBody*)cSystemData.GetCObjects()[body])->GetODE2Size(); }
	qRef.SetNumberOfItems(n);
	q.SetNumberOfItems(n);
	q_t.SetNumberOfItems(n);
	ResizableVector bodyRef, bodyRef_t, bodyQ, bodyQ_t;
	Index offset = 0;
	for (Index body : parameters.bodyNumbers)
	{
		const CObjectBody* cBody = (const CObjectBody*)cSystemData.GetCObjects()[body];
		cBody->GatherCoordinates(bodyRef, bodyRef_t, ConfigurationType::Reference, true);
		cBody->GatherCoordinates(bodyQ, bodyQ_t, configuration, true);
		for (Index i = 0; i < bodyQ.NumberOfItems(); i++)
		{
			qRef[offset + i] = bodyRef[i];
			q[offset + i] = bodyQ[i];
			q_t[offset + i] = bodyQ_t[i];
		}
		offset += bodyQ.NumberOfItems();
	}
}

Index CMarkerBodyUser::GetMarkerNumber(const CSystemData& cSystemData) const
{
	const ResizableArray<CMarker*>& markers = cSystemData.GetCMarkers();
	for (Index i = 0; i < markers.NumberOfItems(); i++) { if (markers[i] == this) { return i; } }
	return EXUstd::InvalidIndex;
}

//! false in another thread than the main thread, where no Python call is possible (#3003)
static bool MarkerBodyUserPythonCallPossible(ConfigurationType configuration)
{
	if (configuration != ConfigurationType::Visualization || IsExudynMainThread()) { return true; }
	ReportUserFunctionCallOutsideMainThread();
	return false;
}

//! a Jacobian times the velocity coordinates
static Vector3D MarkerBodyUserJacobianTimesVector(const Matrix& jacobian, const Vector& vector)
{
	Vector3D result(0.);
	for (Index i = 0; i < 3; i++)
	{
		for (Index j = 0; j < vector.NumberOfItems(); j++) { result[i] += jacobian(i, j) * vector[j]; }
	}
	return result;
}

void CMarkerBodyUser::GetPosition(const CSystemData& cSystemData, Vector3D& position, ConfigurationType configuration) const
{
	position.SetAll(0.);
	if (!MarkerBodyUserPythonCallPossible(configuration)) { return; }
	Vector qRef, q, q_t;
	GatherCoordinates(cSystemData, configuration, qRef, q, q_t);
	EvaluatePosition(cSystemData, position, cSystemData.GetConfigurationTime(configuration), qRef, q, q_t);
}

void CMarkerBodyUser::GetVelocity(const CSystemData& cSystemData, Vector3D& velocity, ConfigurationType configuration) const
{
	velocity.SetAll(0.);
	if (configuration == ConfigurationType::Reference || !MarkerBodyUserPythonCallPossible(configuration)) { return; }
	Vector qRef, q, q_t;
	GatherCoordinates(cSystemData, configuration, qRef, q, q_t);
	Matrix jacobian;
	EvaluatePositionJacobian(cSystemData, jacobian, cSystemData.GetConfigurationTime(configuration), qRef, q, q_t);
	velocity = MarkerBodyUserJacobianTimesVector(jacobian, q_t);
}

void CMarkerBodyUser::GetRotationMatrix(const CSystemData& cSystemData, Matrix3D& rotationMatrix, ConfigurationType configuration) const
{
	rotationMatrix = EXUmath::unitMatrix3D;
	if (!MarkerBodyUserPythonCallPossible(configuration)) { return; }
	Vector qRef, q, q_t;
	GatherCoordinates(cSystemData, configuration, qRef, q, q_t);
	EvaluateRotationMatrix(cSystemData, rotationMatrix, cSystemData.GetConfigurationTime(configuration), qRef, q, q_t);
}

void CMarkerBodyUser::GetAngularVelocity(const CSystemData& cSystemData, Vector3D& angularVelocity, ConfigurationType configuration) const
{
	angularVelocity.SetAll(0.);
	if (configuration == ConfigurationType::Reference || !MarkerBodyUserPythonCallPossible(configuration)) { return; }
	Vector qRef, q, q_t;
	GatherCoordinates(cSystemData, configuration, qRef, q, q_t);
	Matrix jacobian;
	EvaluateRotationJacobian(cSystemData, jacobian, cSystemData.GetConfigurationTime(configuration), qRef, q, q_t);
	angularVelocity = MarkerBodyUserJacobianTimesVector(jacobian, q_t);
}

void CMarkerBodyUser::GetAngularVelocityLocal(const CSystemData& cSystemData, Vector3D& angularVelocity, ConfigurationType configuration) const
{
	Matrix3D rotationMatrix;
	Vector3D omega;
	GetRotationMatrix(cSystemData, rotationMatrix, configuration);
	GetAngularVelocity(cSystemData, omega, configuration);
	angularVelocity = Transposed(rotationMatrix) * omega;
}

//! position, velocity and position Jacobian; with a rotationMatrixUserFunction also rotation, angular velocity and rotation
//! Jacobian; no Jacobian derivative: connectors on the marker compute their Jacobian numerically
void CMarkerBodyUser::ComputeMarkerData(const CSystemData& cSystemData, bool computeJacobian, MarkerData& markerData) const
{
	Vector qRef, q, q_t;
	GatherCoordinates(cSystemData, ConfigurationType::Current, qRef, q, q_t);
	Real t = cSystemData.GetConfigurationTime(ConfigurationType::Current);
	EvaluatePosition(cSystemData, markerData.position, t, qRef, q, q_t);
	EvaluatePositionJacobian(cSystemData, markerData.positionJacobian, t, qRef, q, q_t);
	markerData.velocity = MarkerBodyUserJacobianTimesVector(markerData.positionJacobian, q_t);
	if (parameters.rotationMatrixUserFunction)
	{
		EvaluateRotationMatrix(cSystemData, markerData.orientation, t, qRef, q, q_t);
		EvaluateRotationJacobian(cSystemData, markerData.rotationJacobian, t, qRef, q, q_t);
		markerData.angularVelocityLocal = Transposed(markerData.orientation) * MarkerBodyUserJacobianTimesVector(markerData.rotationJacobian, q_t);
	}
	markerData.velocityAvailable = true;
	if (!computeJacobian)
	{
		markerData.positionJacobian.SetNumberOfRowsAndColumns(0, 0);
		markerData.rotationJacobian.SetNumberOfRowsAndColumns(0, 0);
	}
}

//! a point at the position, as the other markers
void VisualizationMarkerBodyUser::UpdateGraphics(const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemNumber)
{
	Float4 currentColor = visualizationSettings.markers.defaultColor;
	Index itemID = Index2ItemID(itemNumber, ItemType::Marker, vSystem->GetSystemID());
	const CMarker* cMarker = vSystem->systemData->GetCMarkers()[itemNumber];
	Vector3D position;
	cMarker->GetPosition(*vSystem->systemData, position, ConfigurationType::Visualization);
	float radius = 0.5f * visualizationSettings.markers.defaultSize;
	if (visualizationSettings.markers.defaultSize == -1.f) { radius = 0.5f * visualizationSettings.openGL.advanced.initialMaxSceneSize * 0.002f; }
	EXUvis::DrawMarker(position, radius, currentColor, vSystem->graphicsData, itemID, !visualizationSettings.markers.drawSimplified && drawNodesMarkersLoadsWithFaces);
	if (visualizationSettings.markers.showNumbers) { EXUvis::DrawItemNumber(position, vSystem, itemID, "M", currentColor); }
}
