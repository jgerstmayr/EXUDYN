void VisualizationMarkerBodiesRelativeRotationCoordinate::UpdateGraphics(const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemNumber)
{
	Index itemID = Index2ItemID(itemNumber, ItemType::Marker, vSystem->GetSystemID());
	Float4 currentColor = visualizationSettings.markers.defaultColor;

	CMarkerBodiesRelativeRotationCoordinate* cMarker = (CMarkerBodiesRelativeRotationCoordinate*)vSystem->systemData->GetCMarkers()[itemNumber];
	CObjectBody* cBody1 = &vSystem->systemData->GetCObjectBody(cMarker->GetObjectNumber(1));

	Vector3D pos0; //global marker position
	cMarker->GetPosition(*vSystem->systemData, pos0, ConfigurationType::Visualization); //position of body0

	Matrix3D A0;
	cMarker->GetRotationMatrix(*vSystem->systemData, A0, ConfigurationType::Visualization); //rotation of body0
	Vector3D pos1 = cBody1->GetPosition(cMarker->GetParameters().localPosition1, ConfigurationType::Visualization);

	float radius = 0.5f * visualizationSettings.markers.defaultSize;
	if (visualizationSettings.markers.defaultSize == -1.f) { radius = 0.5f * visualizationSettings.openGL.advanced.initialMaxSceneSize * 0.002f; }

	//draw 2 markers with line connecting both!

	EXUvis::DrawMarker(pos0, radius, currentColor, vSystem->graphicsData, itemID, !visualizationSettings.markers.drawSimplified && drawNodesMarkersLoadsWithFaces);
	EXUvis::DrawMarker(pos1, radius, currentColor, vSystem->graphicsData, itemID, !visualizationSettings.markers.drawSimplified && drawNodesMarkersLoadsWithFaces);
	//draw axis depending on marker size
	Vector3D v = (radius * 10.) * (A0 * cMarker->GetParameters().axis0);
	vSystem->graphicsData.AddLine(pos0 - v, pos0 + v, currentColor, currentColor, itemID);

	if (visualizationSettings.markers.showNumbers)
	{
		EXUvis::DrawItemNumber(pos0, vSystem, itemID, "M", currentColor);
		EXUvis::DrawItemNumber(pos1, vSystem, itemID, "M", currentColor);
	}
}
