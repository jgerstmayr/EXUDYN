//the coordinates go into local ResizableConstVectors: up to 7 items without memory allocation, and no buffer that a
//nested call - a user function that asks for an output of the node - could overwrite (#2995)

void CNodeUser::TotalCoordinates(ResizableConstVector& q, ConfigurationType configuration) const
{
	LinkedDataVector reference(GetReferenceCoordinateVector());
	q.CopyFrom(reference);
	if (configuration != ConfigurationType::Reference)
	{
		LinkedDataVector u(GetCoordinateVector(configuration));
		for (Index k = 0; k < q.NumberOfItems(); k++) { q[k] += u[k]; }
	}
}

//! the velocity coordinates of a configuration, zero in the reference configuration (#3056)
void CNodeUser::Velocities(ResizableConstVector& q_t, ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Reference)
	{
		q_t.SetNumberOfItems(GetNumberOfODE2Coordinates());
		q_t.SetAll(0.);
	}
	else { q_t.CopyFrom(GetCoordinateVector_t(configuration)); }
}

Index CNodeUser::GetNodeNumber() const
{
	if (cSystemData == nullptr) { return EXUstd::InvalidIndex; }
	const ResizableArray<CNode*>& nodes = cSystemData->GetCNodes();
	for (Index i = 0; i < nodes.NumberOfItems(); i++) { if (nodes[i] == this) { return i; } }
	return EXUstd::InvalidIndex;
}

Vector3D CNodeUser::GetPosition(ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	ResizableConstVector q, q_t;
	TotalCoordinates(q, configuration);
	Velocities(q_t, configuration);
	LinkedDataVector qRef(GetReferenceCoordinateVector());
	Vector3D position;
	EvaluatePosition(position, cSystemData->GetConfigurationTime(configuration), qRef, q, q_t);
	return position;
}

void CNodeUser::GetPositionJacobian(Matrix& value) const
{
	ResizableConstVector q, q_t;
	TotalCoordinates(q, ConfigurationType::Current);
	Velocities(q_t, ConfigurationType::Current);
	LinkedDataVector qRef(GetReferenceCoordinateVector());
	EvaluatePositionJacobian(value, cSystemData->GetConfigurationTime(ConfigurationType::Current), qRef, q, q_t);
}

void CNodeUser::GetRotationJacobian(Matrix& value) const
{
	ResizableConstVector q, q_t;
	TotalCoordinates(q, ConfigurationType::Current);
	Velocities(q_t, ConfigurationType::Current);
	LinkedDataVector qRef(GetReferenceCoordinateVector());
	EvaluateRotationJacobian(value, cSystemData->GetConfigurationTime(ConfigurationType::Current), qRef, q, q_t);
}

//! a Jacobian, of the position or the rotation, times the velocity coordinates of a configuration
Vector3D NodeUserJacobianTimesVector(const Matrix& jacobian, const VectorBase<Real>& vector)
{
	Vector3D result(0.);
	for (Index i = 0; i < 3; i++)
	{
		for (Index j = 0; j < vector.NumberOfItems(); j++) { result[i] += jacobian(i, j)*vector[j]; }
	}
	return result;
}

Vector3D CNodeUser::GetVelocity(ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	if (configuration == ConfigurationType::Reference) { return Vector3D(0.); }
	ResizableConstVector q, q_t;
	TotalCoordinates(q, configuration);
	Velocities(q_t, configuration);
	LinkedDataVector qRef(GetReferenceCoordinateVector());
	Matrix jacobian;
	EvaluatePositionJacobian(jacobian, cSystemData->GetConfigurationTime(configuration), qRef, q, q_t);
	return NodeUserJacobianTimesVector(jacobian, GetCoordinateVector_t(configuration));
}

//! J q_tt + J_t q_t: with positionJacobianUserFunction, J_t q_t by central differences of J along q_t; without, as
//! the second derivative of the position along q_t, (p(q + h q_t) - 2 p(q) + p(q - h q_t))/h^2, as the first
//! differences of a numerical J would amplify its rounding
Vector3D CNodeUser::GetAcceleration(ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	if (configuration == ConfigurationType::Reference) { return Vector3D(0.); }
	ResizableConstVector q, q_t;
	TotalCoordinates(q, configuration);
	Velocities(q_t, configuration);
	LinkedDataVector qRef(GetReferenceCoordinateVector());
	Real t = cSystemData->GetConfigurationTime(configuration);
	Matrix jacobian;
	EvaluatePositionJacobian(jacobian, t, qRef, q, q_t);
	Vector3D acceleration = NodeUserJacobianTimesVector(jacobian, GetCoordinateVector_tt(configuration));

	Real velocityNorm = q_t.GetL2Norm();
	if (velocityNorm == 0.) { return acceleration; }
	ResizableConstVector qVaried(q);
	if (parameters.positionJacobianUserFunction)
	{
		const Real eps = 1e-7*EXUstd::Maximum(1., q.GetL2Norm())/velocityNorm;
		for (Index k = 0; k < q.NumberOfItems(); k++) { qVaried[k] = q[k] + eps*q_t[k]; }
		EvaluatePositionJacobian(jacobian, t, qRef, qVaried, q_t);
		Vector3D plus = NodeUserJacobianTimesVector(jacobian, q_t);
		for (Index k = 0; k < q.NumberOfItems(); k++) { qVaried[k] = q[k] - eps*q_t[k]; }
		EvaluatePositionJacobian(jacobian, t, qRef, qVaried, q_t);
		Vector3D minus = NodeUserJacobianTimesVector(jacobian, q_t);
		return acceleration + (1./(2.*eps))*(plus - minus);
	}
	const Real h = 1e-4*EXUstd::Maximum(1., q.GetL2Norm())/velocityNorm;
	Vector3D position, plus, minus;
	EvaluatePosition(position, t, qRef, q, q_t);
	for (Index k = 0; k < q.NumberOfItems(); k++) { qVaried[k] = q[k] + h*q_t[k]; }
	EvaluatePosition(plus, t, qRef, qVaried, q_t);
	for (Index k = 0; k < q.NumberOfItems(); k++) { qVaried[k] = q[k] - h*q_t[k]; }
	EvaluatePosition(minus, t, qRef, qVaried, q_t);
	return acceleration + (1./(h*h))*(plus - 2.*position + minus);
}

Matrix3D CNodeUser::GetRotationMatrix(ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return EXUmath::unitMatrix3D; }
	ResizableConstVector q, q_t;
	TotalCoordinates(q, configuration);
	Velocities(q_t, configuration);
	LinkedDataVector qRef(GetReferenceCoordinateVector());
	Matrix3D rotation;
	EvaluateRotationMatrix(rotation, cSystemData->GetConfigurationTime(configuration), qRef, q, q_t);
	return rotation;
}

Vector3D CNodeUser::GetAngularVelocity(ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	if (configuration == ConfigurationType::Reference) { return Vector3D(0.); }
	ResizableConstVector q, q_t;
	TotalCoordinates(q, configuration);
	Velocities(q_t, configuration);
	LinkedDataVector qRef(GetReferenceCoordinateVector());
	Matrix jacobian;
	EvaluateRotationJacobian(jacobian, cSystemData->GetConfigurationTime(configuration), qRef, q, q_t);
	return NodeUserJacobianTimesVector(jacobian, GetCoordinateVector_t(configuration));
}

Vector3D CNodeUser::GetAngularVelocityLocal(ConfigurationType configuration) const
{
	if (configuration == ConfigurationType::Visualization && !PythonCallPossible()) { return Vector3D(0.); }
	return GetRotationMatrix(configuration).GetTransposed()*GetAngularVelocity(configuration);
}

//! d(J_rot^T v)/dq by central differences of the rotation Jacobian; the step follows the rule of
//! newton.numericalDifferentiation with its defaults, as for ObjectUserBody (#2995)
void CNodeUser::GetRotationJacobianTTimesVector_q(const Vector3D& vector, Matrix& jacobian_q) const
{
	ResizableConstVector q, q_t;
	TotalCoordinates(q, ConfigurationType::Current);
	Velocities(q_t, ConfigurationType::Current);
	LinkedDataVector qRef(GetReferenceCoordinateVector());
	Index n = q.NumberOfItems();
	Real t = cSystemData->GetConfigurationTime(ConfigurationType::Current);
	jacobian_q.SetNumberOfRowsAndColumns(n, n);
	Matrix jacobian;
	Vector plus(n), minus(n);
	auto Projected = [&](Vector& result)
	{
		EvaluateRotationJacobian(jacobian, t, qRef, q, q_t);
		for (Index j = 0; j < n; j++) { result[j] = jacobian(0, j)*vector[0] + jacobian(1, j)*vector[1] + jacobian(2, j)*vector[2]; }
	};
	const Real relativeEpsilon = 1e-7;
	const Real minimumCoordinateSize = 1e-2;
	for (Index k = 0; k < n; k++)
	{
		Real qk = q[k];
		Real eps = relativeEpsilon*EXUstd::Maximum(minimumCoordinateSize, fabs(qk));
		q[k] = qk + eps;
		Projected(plus);
		q[k] = qk - eps;
		Projected(minus);
		q[k] = qk;
		for (Index j = 0; j < n; j++) { jacobian_q(j, k) = (plus[j] - minus[j])/(2.*eps); }
	}
}

void CNodeUser::GetOutputVariable(OutputVariableType variableType, ConfigurationType configuration, Vector& value) const
{
	switch (variableType)
	{
	case OutputVariableType::Position: value.CopyFrom(GetPosition(configuration)); break;
	case OutputVariableType::Displacement: value.CopyFrom(GetPosition(configuration) - GetPosition(ConfigurationType::Reference)); break;
	case OutputVariableType::Velocity: value.CopyFrom(GetVelocity(configuration)); break;
	case OutputVariableType::Acceleration: value.CopyFrom(GetAcceleration(configuration)); break;
	case OutputVariableType::RotationMatrix: {
		Matrix3D rotation = GetRotationMatrix(configuration);
		value.SetVector(9, rotation.GetDataPointer());
		break;
	}
	case OutputVariableType::AngularVelocity: value.CopyFrom(GetAngularVelocity(configuration)); break;
	case OutputVariableType::AngularVelocityLocal: value.CopyFrom(GetAngularVelocityLocal(configuration)); break;
	case OutputVariableType::CoordinatesTotal: {
		ResizableConstVector q;
		TotalCoordinates(q, configuration);
		value.CopyFrom(q);
		break;
	}
	case OutputVariableType::Coordinates: value.CopyFrom(GetCoordinateVector(configuration)); break;
	case OutputVariableType::Coordinates_t: value.CopyFrom(GetCoordinateVector_t(configuration)); break;
	case OutputVariableType::Coordinates_tt: value.CopyFrom(GetCoordinateVector_tt(configuration)); break;
	default:
		SysError("CNodeUser::GetOutputVariable failed"); //error should not occur, because types are checked!
	}
}

//! a point, and the frame with nodes.showBasis if the node has a rotationMatrixUserFunction; drawn in the main thread
void VisualizationNodeUser::UpdateGraphics(const VisualizationSettings& visualizationSettings, VisualizationSystem* vSystem, Index itemNumber)
{
	Index itemID = Index2ItemID(itemNumber, ItemType::Node, vSystem->GetSystemID());
	Float4 currentColor = visualizationSettings.nodes.defaultColor;
	if (color[0] != -1.f) { currentColor = color; }

	CNodeUser* cNode = (CNodeUser*)vSystem->systemData->GetCNodes()[itemNumber];

	float radius = 0.5f*drawSize; //drawSize represents diameter/cube edge length
	if (drawSize == -1.f) {
		radius = 0.5f*visualizationSettings.nodes.defaultSize;
		if (visualizationSettings.nodes.defaultSize == -1.f) { radius = 0.5f*visualizationSettings.openGL.advanced.initialMaxSceneSize * 0.002f; }
	}

	Vector3D pos(cNode->GetPosition(ConfigurationType::Visualization));
	Index tiling = visualizationSettings.nodes.drawNodesAsPoint ? 0 : visualizationSettings.nodes.tiling;
	EXUvis::DrawNode(pos, radius, currentColor, vSystem->graphicsData, itemID, drawNodesMarkersLoadsWithFaces, tiling);

	if (visualizationSettings.nodes.showBasis && cNode->GetParameters().rotationMatrixUserFunction.IsValid())
	{
		Index nn = visualizationSettings.nodes.showNumbers ? itemNumber : EXUstd::InvalidIndex;
		Matrix3D A(cNode->GetRotationMatrix(ConfigurationType::Visualization));
		EXUvis::DrawOrthonormalBasis(pos, A, visualizationSettings.nodes.basisSize, 0.025*visualizationSettings.nodes.basisSize,
			vSystem->graphicsData, itemID, 1.f, drawNodesMarkersLoadsWithFaces && !visualizationSettings.nodes.drawNodesAsPoint,
			visualizationSettings.general.axesTiling, 2.5, nn, visualizationSettings.nodes.showNumbers ? "N" : "");
	}
	if (visualizationSettings.nodes.showNumbers) { EXUvis::DrawItemNumber(pos, vSystem, itemID, "N", visualizationSettings.nodes.defaultColor); }
}
