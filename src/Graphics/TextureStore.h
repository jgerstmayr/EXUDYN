#include <vector>
#include <atomic>

//! one texture: the pixels row by row, from the bottom row of the image (texture coordinate v=0) to the top, with the
//! channels of the interpretation (1, 3 or 4 bytes per pixel)
class Texture
{
public:
	STDstring name;
	Index width = 0;
	Index height = 0;
	Index channels = 0;
	TextureInterpretation interpretation = TextureInterpretation::RGBA;
	Index flags = 0;				//!< bits of TextureFlags
	std::vector<unsigned char> data;
	uint64_t version = 0;			//!< changes with every new image; the renderers upload the texture again
	bool valid = false;				//!< false: removed; the number stays reserved for the name

	bool HasFlag(TextureFlags flag) const { return (flags & (Index)flag) != 0; }

	//! the channels of an interpretation
	static Index Channels(TextureInterpretation interpretation)
	{
		if (interpretation == TextureInterpretation::Grey) { return 1; }
		if (interpretation == TextureInterpretation::RGB) { return 3; }
		return 4;
	}
};

//! the textures by number; a number is never given to another name, so the graphics data keeps the numbers it resolved
//! from the names; the renderer thread reads the store while Python adds to it, which the lock protects
class TextureStore
{
	std::vector<Texture> textures;
	uint64_t versionCounter = 0;
	mutable std::atomic_flag lock = ATOMIC_FLAG_INIT;
public:
	void LockData() const { EXUstd::WaitAndLockSemaphore(lock); }
	void ClearLock() const { EXUstd::ReleaseSemaphore(lock); }

	//! the number of a name, or -1 for an unknown or removed one
	Index GetID(const STDstring& name) const
	{
		LockData();
		Index id = FindName(name);
		if (id != -1 && !textures[id].valid) { id = -1; }
		ClearLock();
		return id;
	}

	//! add a texture or replace the image of a name; the pixels are given as described for Texture; returns the number
	Index Set(const STDstring& name, Index width, Index height, TextureInterpretation interpretation, Index flags,
		std::vector<unsigned char>&& data)
	{
		LockData();
		Index id = FindName(name);
		if (id == -1)
		{
			id = (Index)textures.size();
			textures.emplace_back();
		}
		Texture& texture = textures[id];
		texture.name = name;
		texture.width = width;
		texture.height = height;
		texture.channels = Texture::Channels(interpretation);
		texture.interpretation = interpretation;
		texture.flags = flags;
		texture.data = std::move(data);
		texture.version = ++versionCounter;
		texture.valid = true;
		ClearLock();
		return id;
	}

	//! remove a texture; triangles that refer to it are drawn without texture; returns false for an unknown name
	bool Remove(const STDstring& name)
	{
		LockData();
		Index id = FindName(name);
		bool found = (id != -1 && textures[id].valid);
		if (found)
		{
			textures[id].valid = false;
			textures[id].data = std::vector<unsigned char>();
			textures[id].version = ++versionCounter;
		}
		ClearLock();
		return found;
	}

	//! the name of a number, also of a removed texture; empty for an unknown number
	STDstring GetName(Index id) const
	{
		LockData();
		STDstring name = (id >= 0 && id < (Index)textures.size()) ? textures[id].name : STDstring();
		ClearLock();
		return name;
	}

	//! the names of the textures, in the order they were added
	std::vector<STDstring> GetNames() const
	{
		LockData();
		std::vector<STDstring> names;
		for (const Texture& texture : textures) { if (texture.valid) { names.push_back(texture.name); } }
		ClearLock();
		return names;
	}

	//! the number of entries, including the removed ones; the renderers iterate over them with the lock held
	Index NumberOfEntries() const { return (Index)textures.size(); }
	//! an entry, with LockData() held by the caller
	const Texture& GetTexture(Index id) const { return textures[id]; }

private:
	Index FindName(const STDstring& name) const
	{
		for (Index i = 0; i < (Index)textures.size(); i++) { if (textures[i].name == name) { return i; } }
		return -1;
	}
};

//! the one store of the module, defined in VisualizationSystemContainer.cpp
extern TextureStore textureStore;

#endif
