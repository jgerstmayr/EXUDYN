#+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
# Exudyn: the enumeration type registrator
#
# One entry per enumeration type shared by C++ and Python (except OutputVariableType, which has
# its own registrator in outputVariableTypes.py). This is the ONLY place where the values are
#
#           DESCRIPTIONS: read definitions/README.md, section "Writing a
#           description", before writing or changing one - what the text may
#           contain, and how it is checked.
#
# declared: tools/generators/enumEmitter.py generates the C++ enums with their string functions
# into src/Autogenerated/EnumTypes.h, and definitions/pybindEnums.py hands the same table to the
# pybind11 / stub / documentation side. Before this file existed, the C++ enum, its string
# function and the Python list were kept in step by hand ("keep this list synchronized with ...")
# and had drifted.
#
# EnumType:
#   pythonName       name in the exudyn module, e.g. 'NodeType'
#   cppName          C++ name: 'ConfigurationType' for an enum class, 'Node::Type' for a plain enum
#                    inside a namespace (these allow bit combinations, e.g. Node::Position + ...)
#   description      shown in Python and in the documentation; None: not exposed to Python
#   bits             True: the value of an EnumValue is a bit position, rendered as 1 << value
#   stringFunction   None, 'operator<<' (switch over the values), 'GetTypeString' or another
#                    function name returning STDstring; with bits, the names of all set bits
#   stringPrefix     removed from the value names in the string function
# EnumValue:
#   value            integer (bit position with bits=True) or a C++ expression string
#   python           False: the value exists in C++ only
#   stringText       text in a bit string function instead of the name; '' omits the value there
#   stringIf         additional C++ condition for that text, e.g. '!(var & Body)'
# Author:   Johannes Gerstmayr
#+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++


class EnumValue:
    def __init__(self, name, value, description, python=True, stringText=None, stringIf=''):
        self.name = name
        self.value = value
        self.description = description
        self.python = python
        self.stringText = stringText
        self.stringIf = stringIf


class EnumType:
    def __init__(self, pythonName, cppName, description, values, bits=False, stringFunction=None,
                 stringPrefix='', cppNote=''):
        self.pythonName = pythonName
        self.cppName = cppName
        self.description = description
        self.values = values
        self.bits = bits
        self.stringFunction = stringFunction
        self.stringPrefix = stringPrefix
        self.cppNote = cppNote

    def Namespace(self):
        """the namespace of a plain enum ('Node' for 'Node::Type'), or '' for an enum class"""
        return self.cppName.split('::')[0] if '::' in self.cppName else ''

    def EnumName(self):
        return self.cppName.split('::')[-1]


