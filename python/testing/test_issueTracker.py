def OpenIssueNumber(module):
    return int([issue for issue in module.GetIssues() if issue['status'] == 'RAISED'][-1]['number'])


def ClosedIssueNumber(module):
    return int([issue for issue in module.GetIssues()
                if issue['status'] in module.closedStatuses][-1]['number'])


def testExtendAppendsAndChangesNothingElse(tracker):
    number = OpenIssueNumber(tracker)
    before = tracker.GetIssue(number)
    count = tracker.NumberOfIssues()

    tracker.ExtendIssue(number, 'the parser also fails on an empty file', author='Claude-JG')

