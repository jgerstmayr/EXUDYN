#the characters that make an issue description into Markdown instead of text
markdownSpecials = ['`', '*', '_', '[', ']', '<', '>', '#', '|', '$', '\\']


@pytest.mark.parametrize('character', markdownSpecials)
def testEverySpecialCharacterIsEscaped(character):
    text = IssueTracker().ToMarkdown('a' + character + 'b')
    assert text == 'a\\' + character + 'b' or text == 'a\\\\b', text


def testRealIssueTextStaysText():
    """three shapes that actually occur in the tracker and each of which is markup if it is not
    escaped: a star that opens emphasis, a word ending in an underscore, an unpaired backtick"""
    toMarkdown = IssueTracker().ToMarkdown
    assert toMarkdown('rename *.md files') == 'rename \\*.md files'
    assert toMarkdown('the CIBW_ variable') == 'the CIBW\\_ variable'
    assert toMarkdown('use `pip install') == 'use \\`pip install'


def testBackslashIsEscapedFirst():
    """a backslash that arrives escaped would otherwise escape the escape of the next rule and
    the text would lose it"""
    assert IssueTracker().ToMarkdown('C:\\temp') == 'C:\\\\temp'
    assert IssueTracker().ToMarkdown('\\#tag') == '\\\\\\#tag'


def testNothingElseIsTouched():
    """escaping is total for the specials and silent for everything else - an issue author writes
    ordinary sentences and they have to arrive as they were written"""
    text = 'solver fails after 3 steps; tolerance 1e-8 (see issue 2401), 50% slower'
    assert IssueTracker().ToMarkdown(text) == text


def testGeneratedPageIsThere():
    """the page the tracker writes; its first line says that it is generated"""
    path = os.path.normpath(os.path.join(trackerDirectory, '..', '..', 'docs', 'generated',
                                         'trackerlog.md'))
    assert os.path.exists(path), path
    with open(path, encoding='utf-8') as file:
        assert 'GENERATED by tools/issueTracker/issueTracker.py' in file.readline()


