#ExtendIssue and the triage notes (revision2026 steps R8.3.3 and R8.5.2)

@pytest.fixture
def tracker(tmp_path, monkeypatch):
    """the tracker working on a COPY of the log in a temporary directory: it reads and writes
    trackerlog.txt relative to the current directory, and the three files it updates afterwards
    (the version files, the HTML and the Markdown page) live outside it"""
    import shutil
    module = IssueTracker()
    shutil.copy(os.path.join(trackerDirectory, 'trackerlog.txt'),
                os.path.join(str(tmp_path), 'trackerlog.txt'))
    monkeypatch.chdir(str(tmp_path))
    monkeypatch.setattr(module, 'UpdateDateAndVersion', lambda *args, **kwargs: None)
    monkeypatch.setattr(module, 'ConvertToHTML', lambda *args, **kwargs: None)
    monkeypatch.setattr(module, 'ConvertToMarkdown', lambda *args, **kwargs: None)
    return module


def OpenIssueNumber(module):
    return int([issue for issue in module.GetIssues() if issue['status'] == 'RAISED'][-1]['number'])


def ClosedIssueNumber(module):
    return int([issue for issue in module.GetIssues()
                if issue['status'] in module.closedStatuses][-1]['number'])


def testExtendAppendsAndChangesNothingElse(tracker):
    number = OpenIssueNumber(tracker)
    before = tracker.GetIssue(number)
    count = tracker.NumberOfIssues()

    tracker.ExtendIssue(number, 'the parser also fails on an empty file', author='Claude-JG')

    after = tracker.GetIssue(number)
    assert after['description'].startswith(before['description'].rstrip()[:40])
    assert after['description'].endswith('the parser also fails on an empty file')
    assert 'Claude-JG' in after['description']
    #everything else is untouched - above all the status, which is what the version counts
    for field in ['issue', 'status', 'type', 'date raised', 'releaseNotes', 'workingRemarks']:
        assert after[field] == before[field], field
    assert tracker.NumberOfIssues() == count


def testExtendRefusesAClosedIssue(tracker):
    """a closed issue has been published in the release notes; it is reopened or superseded,
    not rewritten"""
    with pytest.raises(ValueError):
        tracker.ExtendIssue(ClosedIssueNumber(tracker), 'more analysis')


def testExtendRefusesEmptyText(tracker):
    with pytest.raises(ValueError):
        tracker.ExtendIssue(OpenIssueNumber(tracker), '   ')


def testResolveWritesTheReleaseNoteAndClearsTheRemarks(tracker):
    """the working remarks of an open issue ("duplicate of #2134") are worthless once it closes
    and must not reach the release notes, which is what releaseNotes is"""
    number = OpenIssueNumber(tracker)
    tracker.RemarkIssue(number, 'duplicate of #2134, check before starting')

    tracker.ResolveIssue(number, notes='fixed by the new parser', author='Claude-JG')

    issue = tracker.GetIssue(number)
    assert issue['releaseNotes'] == 'fixed by the new parser'
    assert issue['workingRemarks'] == ''
    assert issue['status'] == 'RESOLVED'


def testAbandonAlsoClearsTheRemarks(tracker):
    number = OpenIssueNumber(tracker)
    tracker.RemarkIssue(number, 'marked for deprecation')

    tracker.AbandonIssue(number, reason='superseded by the new solver', author='Claude-JG')

    issue = tracker.GetIssue(number)
    assert issue['releaseNotes'] == 'superseded by the new solver'
    assert issue['workingRemarks'] == ''
    assert issue['status'] == 'ABANDONED'


def testRemarkAppendsAndReplaces(tracker):
    number = OpenIssueNumber(tracker)
    tracker.RemarkIssue(number, 'part A solved')
    tracker.RemarkIssue(number, 'B still open')
    assert tracker.GetIssue(number)['workingRemarks'] == 'part A solved; B still open'

    tracker.RemarkIssue(number, 'all of it is the parser', replace=True)
    assert tracker.GetIssue(number)['workingRemarks'] == 'all of it is the parser'


def testRemarkRefusesAClosedIssue(tracker):
    """the remarks of a closed issue are gone by design"""
    with pytest.raises(ValueError):
        tracker.RemarkIssue(ClosedIssueNumber(tracker), 'something')


def testRaiseRefusesAReleaseNote(tracker):
    """the release note is written when the issue closes; what is known now is a working remark"""
    with pytest.raises(ValueError):
        tracker.RaiseIssueDict({'issue': 'x', 'description': 'y', 'type': 'FIX',
                                'releaseNotes': 'not yet'})


def testUnknownEffortAndPriorityAreRefused(tracker):
    """one spelling per value, at both places that write one"""
    with pytest.raises(ValueError):
        tracker.RaiseIssueDict({'issue': 'x', 'description': 'y', 'type': 'FIX',
                                'effort': 'SMALL'})
    with pytest.raises(ValueError):
        tracker.ChangeIssue(OpenIssueNumber(tracker), 'effort', 'quick')
    with pytest.raises(ValueError):
        tracker.ChangeIssue(OpenIssueNumber(tracker), 'priority', 'med')


def testEffortIsKeptAndNormalized(tracker):
    number = tracker.RaiseIssue('an issue with an effort', 'description', issueType='FIX',
                                author='Claude-JG')
    tracker.ChangeIssue(number, 'effort', 'medium')
    assert tracker.GetIssue(number)['effort'] == 'MEDIUM'


def testTheSchemaIsTheOneOfTheFile(tracker):
    """the 16 columns of trackerlog.txt and the names the module reads them under are one list;
    they went out of step once already (the status column is padded to 8 characters, #2519)"""
    with open(os.path.join(trackerDirectory, 'trackerlog.txt'), encoding='utf-8') as file:
        header = [next(file) for _ in range(tracker.nHeaderLines)]
    formatLine = [line for line in header if line.startswith('# line format:')]
    assert len(formatLine) == 1
    for name in ['releaseNotes', 'workingRemarks', 'effort']:
        assert name in formatLine[0], name
    assert header[-1].strip() == '# end of comment (' + str(tracker.nHeaderLines) + ' lines)'
    assert len(tracker.trackerItems) == tracker.numberOfItems == 16
