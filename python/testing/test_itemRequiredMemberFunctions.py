import os
import sys

repositoryRoot = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(repositoryRoot, 'tools', 'generators'))
sys.path.insert(0, os.path.join(repositoryRoot, 'definitions'))
import itemHeaderEmitter                                                    # noqa: E402
import itemDefsNodes                                                        # noqa: E402
import itemDefsObjects                                                      # noqa: E402
import itemDefsMarkers                                                      # noqa: E402

allDefinitions = itemDefsNodes.definitions + itemDefsObjects.definitions + itemDefsMarkers.definitions


def _Required(className):
    definition = [d for d in allDefinitions if d['className'] == className][0]
    return {function: (baseClass, declaration) for (function, baseClass, declaration) in itemHeaderEmitter.RequiredMemberFunctions(definition)}


def test_aRigidBodyNodeRequiresItsKinematicsAndItsGMatrices():
    required = _Required('NodeRigidBodyEP')
    assert required['GetPosition'] == ('CNodeODE2', 'Position')
    assert required['GetAngularVelocityLocal'] == ('CNodeODE2', 'Orientation')
    assert required['GetGlocal'] == ('CNodeRigidBody', 'RigidBody')
    assert required['GetOutputVariable'] == ('CNode', 'output variables')


def test_a2DRigidBodyNodeRequiresNoGMatrices():
    #NodeRigidBody2D declares RigidBody, but is no CNodeRigidBody
    required = _Required('NodeRigidBody2D')
    assert 'GetRotationMatrix' in required and 'GetG' not in required


def test_aBodyRequiresWhatItsAccessFunctionsServe():
    required = _Required('ObjectBeamGeometricallyExact2D')
    assert required['GetAngularVelocityLocal'] == ('CObjectBody', 'AngularVelocity_qt') #missing before #3406
    assert required['GetOutputVariableBody'] == ('CObjectBody', 'output variables')
    assert _Required('ObjectANCFBeam')['GetLocalCenterOfMass'] == ('CObjectBody', 'DisplacementMassIntegral_q') #missing before #3406
    assert _Required('ObjectFFRF')['GetMeshNode'] == ('CObjectSuperElement', 'SuperElement')


def test_anObjectWithOwnMarkersOnlyRequiresNoBodyFunctions():
    for className in ['ObjectGenericODE2', 'ObjectKinematicTree']:
        assert 'GetPosition' not in _Required(className)


def test_aConnectorRequiresItsOutputFunction():
    assert _Required('ObjectConnectorSpringDamper') == {'GetOutputVariableConnector': ('CObjectConnector', 'output variables')}


def test_markersRequireTheFunctionsOfTheirTypes():
    required = _Required('MarkerBodyRigid')
    assert required['ComputeMarkerData'] == ('CMarker', 'Position')
    assert required['GetAngularVelocityLocal'] == ('CMarker', 'Orientation')
    assert required['ComputeMarkerDataJacobianDerivative'] == ('CMarker', 'JacobianDerivativeAvailable')


def test_everyGeneratedHeaderAssertsItsRequirements():
    missing = []
    for (definitions, folder) in [(itemDefsNodes.definitions, 'nodes'), (itemDefsObjects.definitions, 'objects'), (itemDefsMarkers.definitions, 'markers')]:
        for definition in definitions:
            className = 'C' + definition['className']
            text = open(os.path.join(repositoryRoot, 'src', 'Autogenerated', folder, className + '.h'), encoding='utf-8').read()
            for (function, baseClass, declaration) in itemHeaderEmitter.RequiredMemberFunctions(definition):
                if 'decltype(&' + className + '::' + function + '), decltype(&' + baseClass + '::' + function + ')' not in text:
                    missing.append(className + '::' + function)
    assert missing == []
